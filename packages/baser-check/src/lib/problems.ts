/**
 * Отказы ПРОВЕРКИ — данные, а не исключения.
 *
 * Форма отказа взята у контрактов целиком (`FormProblem`: код, адрес, текст) и
 * не переизобретается: проверка складывает в один список отказы формы и свои
 * собственные, а потребитель ветвится по коду. Разные формы на один предмет
 * заставили бы гейт разбирать два языка вместо одного (`tasker:BASER2-20`).
 *
 * Здесь объявлены ТОЛЬКО коды, которых нет у формы. Всё, что умеет назвать
 * соседняя зона, проверка пробрасывает её кодом: своей семантики поверх чужой
 * она не изобретает — иначе `duplicate-dest` от контрактов и `duplicate-dest`
 * от проверки стали бы двумя правдами об одном событии.
 */

import type { FormProblem, FormProblemCode } from '@omnifield/baser-contracts';

/**
 * Что не так с ПОСТАВКОЙ обвеса — то, чего форма сказать не может.
 *
 * Форма разбирает объявление и ничего не читает с диска: файлов у неё нет.
 * Поэтому «объявлено, но не приехало» — вопрос этой зоны и только её.
 */
export type SupplyProblemCode =
  /** Каталога обвеса нет вовсе — проверять нечего. */
  | 'root-missing'
  /** В каталоге нет `package.json` — это не пакет. */
  | 'manifest-missing'
  /** `package.json` есть, но не читается или не разбирается как JSON. */
  | 'manifest-unreadable'
  /** Пакет без имени поставить нельзя: потребитель зовёт обвес по имени. */
  | 'package-name-missing'
  /** `contentRoot` объявлен, но такого каталога в поставке нет. */
  | 'content-root-missing'
  /** Запись раскладки ссылается на файл, которого в поставке нет. */
  | 'content-missing'
  /** Файл в поставке есть, но не читается — права, битая ссылка. */
  | 'content-unreadable'
  /** Модуль вычисляемого дефолта объявлен, но в поставке его нет. */
  | 'resolver-missing'
  /**
   * Файл в каталоге есть, но `files` манифеста его не увезёт.
   *
   * Отдельный код, а не оттенок `content-missing`: чинится он в другом месте
   * (список `files`, а не раскладка) и ловится ТОЛЬКО до выдачи. У потребителя
   * такой обвес выглядит как «шаблон пропал», хотя у автора всё на месте.
   */
  | 'not-shipped';

/**
 * Код отказа проверки: свой либо формы, но всегда машинный.
 *
 * Коды контрактов принимаются КАК ЕСТЬ: `form-version-unsupported` и
 * `content-missing` — это разные починки в разных местах, и склеить их в один
 * «обвес непригоден» значило бы сказать «что-то не так» (`tasker:BASER2-24`).
 */
export type CheckProblemCode = SupplyProblemCode | FormProblemCode;

/**
 * Отказ в ответе проверки.
 *
 * Структурно совместим с `FormProblem` контрактов — отказы формы ложатся сюда
 * без переупаковки.
 */
export interface CheckProblem extends Omit<FormProblem, 'code'> {
  readonly code: CheckProblemCode;
}

/**
 * Копилка отказов.
 *
 * Проверка идёт дальше, а не встаёт на первом: три беды в обвесе это три
 * строки, а не три прогона. Бросок на первой заставлял бы чинить их по одной
 * штуке за прогон — ровно то, от чего форма ушла в `ProblemLog` контрактов.
 */
export class CheckProblemLog {
  readonly #problems: CheckProblem[] = [];

  add(code: CheckProblemCode, at: string, message: string): void {
    this.#problems.push({ code, at, message });
  }

  /**
   * Принимает отказы как есть — код и адрес уже машинные.
   *
   * Принимает и `FormProblem` соседней зоны, и собственные: коды проверки шире
   * кодов формы, поэтому чужой отказ ложится сюда без переупаковки.
   */
  addAll(problems: readonly (FormProblem | CheckProblem)[]): void {
    this.#problems.push(...problems);
  }

  get empty(): boolean {
    return this.#problems.length === 0;
  }

  list(): readonly CheckProblem[] {
    return this.#problems;
  }
}
