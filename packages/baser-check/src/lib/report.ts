/**
 * ОТВЕТ ПРОВЕРКИ — данные. Текст поверх них рисует дверь, а не эта зона.
 *
 * Потребитель ответа — гейт в CI, следующее звено цепи (`baser-pack`) и пульт,
 * а человек в терминале только один из них (`tasker:BASER2-20`). Поэтому
 * проверка отдаёт структуру и НИЧЕГО не печатает: своей семантики поверх кодов
 * отказа она не изобретает, а человеческий текст — рендер поверх этих же
 * данных, живущий у двери (`tasker:BASER2-29`).
 *
 * В ответе есть не только отказы, но и ПЕРЕЧЕНЬ ТОГО, ЧТО СВЕРЕНО. Причина
 * прозаическая: зелёная проба, которая ничего не сверила, хуже отсутствующей.
 * «Годен» без объёма проверки читается одинаково и когда сверили десять файлов,
 * и когда не смогли сверить ни одного, — поэтому объём и пропуски названы
 * данными, а не подразумеваются.
 */

import type { SourceDeclaration } from '@omnifield/baser-contracts';
import type { CheckProblem } from './problems.js';
import type { ShippingList } from './shipping.js';

/**
 * Версия формы ОТВЕТА проверки.
 *
 * Отдельная от `FORM_VERSION` контрактов: форма объявления обвеса и форма
 * ответа проверки едут по разным причинам и в разном темпе. Причина иметь
 * версию та же — несовместимость обязана быть видимой, а не выясняться по
 * симптомам у потребителя, который по ответу ветвится.
 */
export const CHECK_SCHEMA_VERSION = 1;

/** Какой слой сверялся. */
export type CheckStageName =
  /** Каталог, `package.json`, имя пакета. */
  | 'manifest'
  /** Разбор блока `baser` формой — версия, поля, столкновения `dest`. */
  | 'declaration'
  /** Объявленное лежит на диске: `contentRoot`, `src`, модули резолверов. */
  | 'content'
  /** Объявленное уедет потребителю: белый список `files`. */
  | 'shipping'
  /** Рендеримые шаблоны написаны на языке формы. */
  | 'templates';

export type CheckStageStatus =
  /** Сверено, отказов нет. */
  | 'ok'
  /** Сверено, отказы названы. */
  | 'failed'
  /** НЕ сверено — и сказано почему. Не то же самое, что «сверено и чисто». */
  | 'skipped';

export interface CheckStage {
  readonly name: CheckStageName;
  readonly status: CheckStageStatus;
  /** Сколько единиц сверено: файлов, записей раскладки, шаблонов. */
  readonly counted: number;
  /** Почему пропущен. Обязателен при `skipped` — иначе это молчание. */
  readonly reason?: string;
}

/**
 * Один замер (perf-лог), тремя полями.
 *
 * Форма намеренно совпадает с `TraceSpan` движка, чтобы дверь могла сложить
 * спаны своих зон в один список. Зависимости на движок ради записи из трёх
 * полей проверка не берёт: цепь идёт снизу вверх (`check → pack → дверь`), и
 * тянуть соседа вниз значило бы её замкнуть.
 */
export interface CheckSpan {
  readonly name: string;
  readonly ms: number;
  readonly detail?: Readonly<Record<string, unknown>>;
}

export interface CheckReport {
  /** Версия формы этого ответа. */
  readonly checkSchemaVersion: number;
  /** Версия формы объявления, против которой сверяли, — из контрактов. */
  readonly formVersion: number;
  /**
   * Годен ли обвес: ни одного отказа.
   *
   * Производная от `problems`, а не отдельный признак: два источника правды о
   * пригодности разошлись бы на первой же ветке.
   */
  readonly ok: boolean;
  /** Абсолютный корень каталога, который проверяли. */
  readonly root: string;
  readonly packageName: string | null;
  readonly packageVersion: string | null;
  /**
   * Разобранное объявление — следующему звену цепи.
   *
   * Отдаётся ровно потому, что оно УЖЕ разобрано: заставлять `pack` разбирать
   * тот же манифест второй раз значило бы поставить рядом второй разбор,
   * который однажды разойдётся с первым.
   */
  readonly declaration: SourceDeclaration | null;
  /** Что известно про состав поставки — включая «неизвестно, и вот почему». */
  readonly shipping: ShippingList;
  readonly stages: readonly CheckStage[];
  readonly problems: readonly CheckProblem[];
  /** Телеметрия слоёв. Данные вне ответа человеку — их печатает не проверка. */
  readonly trace: readonly CheckSpan[];
}
