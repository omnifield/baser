/**
 * СЛОВО ОБВЕСА — что он говорит человеку про своё применение В ЭТОЙ ЛОКАЦИИ.
 *
 * Резолвер поля `warningFrom` (форма 7, `tasker:BASER2-235`). Заявку на канал
 * поднял этот обвес и по этому самому случаю (`tasker:BASER2-208`): хук ложится
 * в `.git/hooks`, git смотрит туда САМ — но у локации с заданным
 * `core.hooksPath` он смотрит ТОЛЬКО в названный каталог, и положенный файл
 * остаётся лежать мёртвым. **Прогон при этом верный, отказывать не за что, а
 * человек обязан услышать.** Прежде сказать было нечем: единственная громкость
 * обвеса — бросок резолвера — валит весь прогон локации у всех обвесов сразу.
 *
 * Форма канал завела (`baser-contracts`, `warning.ts`), движок его несёт,
 * консоль печатает — и до этого файла шов был декоративен: механизм выпущен, а
 * обвес им не пользовался, то есть человек в живой локации по-прежнему не слышал
 * ничего.
 *
 * ## Пакет впервые содержит код — и ровно столько, сколько нужно
 *
 * До сих пор обвес был содержимым без кода (`README.md`). Резолвер — не мотор и
 * не второй `pr-title.mjs`: он ничего не кладёт, ничего не меняет и никуда не
 * записывается. Его ответ живёт один прогон и адресован глазам.
 *
 * ## Спрашиваем САМ git, а не читаем `.git/config`
 *
 * Разница не стилистическая. `core.hooksPath` живёт не только в конфиге
 * локации: он бывает глобальным, системным и приехавшим через `include` —
 * и во всех трёх случаях git его слушается. Свой разбор INI увидел бы лишь
 * первый, а в остальных **промолчал бы**, то есть дал бы ровно то молчание,
 * против которого поле и заведено. Правда о конфиге одна, и она у git'а.
 *
 * Сверка с рынком (2026-08-07): `pre-commit` спрашивает так же —
 * `git config core.hooksPath` и «пусто значит не задано»
 * (`pre_commit/git.py`, `has_core_hookpaths_set`), — и, увидев настройку,
 * УСТАНОВКУ ОТМЕНЯЕТ («Cowardly refusing to install hooks with `core.hooksPath`
 * set», issue #1298); `lefthook` обсуждает снятие настройки за человека
 * (issue #1248). Мы не делаем ни того, ни другого: отказ уронил бы прогон всей
 * локации ради одного артефакта, а снятие чужой настройки — правка территории
 * потребителя, о которой он не просил. Мы говорим. Живой случай глобальной
 * настройки, из-за которой отказ «везде», в их же беклоге (issue #1198) — он же
 * и причина спрашивать git'а, а не файл.
 *
 * ## Окружение чистится, и это не перестраховка
 *
 * `GIT_DIR` в окружении переопределяет поиск репозитория, и `git -C <локация>`
 * ответит про ЧУЖОЙ репозиторий, не сказав об этом. Случай наш собственный:
 * положенный этим обвесом `pre-commit` гоняет команду готовности, у которой
 * `GIT_DIR` выставлен git'ом, — и прогон двери из-под хука спросил бы не про ту
 * локацию. Поэтому все `GIT_*` снимаются целиком, а `HOME` остаётся: без него
 * git не нашёл бы глобальный конфиг, за которым мы сюда и пришли.
 *
 * ## Молчание — рабочий ответ, и оно НИКОГДА не бросок
 *
 * Локация без git, настройка не задана, `.git` — мусор, git не установлен вовсе:
 * всё это нормальные состояния обстановки, а не беда. Сказать нечего
 * выражается ПУСТОТОЙ (`null`): пустую строку печатать некуда, и от исправной
 * работы она неотличима (`baser-contracts`, `warning.ts`). Бросок прогон не
 * уронит — дверь и движок это держат, — но резолвер, роняющий себя на пустом
 * месте, лишает человека слова ровно там, где оно нужнее всего.
 */

import { spawnSync } from 'node:child_process';
import { existsSync, realpathSync } from 'node:fs';
import { homedir } from 'node:os';
import { isAbsolute, join, resolve } from 'node:path';

/**
 * Адрес хука — тот же, что стоит в раскладке объявления.
 *
 * Второе место для одного факта, и держит их вместе ПРОБА (`warning.spec.mjs`):
 * назвать в тексте не тот файл, который кладём, — соврать человеку адресом,
 * причём соврать молча. Прочитать раскладку прямо здесь было бы дороже: манифест
 * пришлось бы разбирать в резолвере, у которого нет права упасть.
 */
export const HOOK_DEST = '.git/hooks/pre-commit';

/** Каталог, в который git смотрит САМ, пока его не увели настройкой. */
const OUR_HOOKS_DIR = '.git/hooks';

const SETTING = 'core.hooksPath';

/**
 * Сколько ждём ответа git'а.
 *
 * `git config` не ходит в сеть и не ждёт блокировок, поэтому порог здесь не про
 * медленную машину, а про «процесс не вернулся вообще»: прогон локации не имеет
 * права стоять из-за фразы. Вышло время — считаем, что спросить не удалось.
 */
const ASK_TIMEOUT_MS = 5_000;

/**
 * Что этот обвес говорит про своё применение здесь.
 *
 * @param {{ repo?: { root?: string } }} ctx обстановка от двери (`ResolverContext`)
 * @returns {string | null} текст для человека либо пустота — «сказать нечего»
 */
export function hooksPath(ctx) {
  const root = ctx?.repo?.root;
  if (typeof root !== 'string' || root === '') {
    return null;
  }

  // Локации без git сказать нечего, и спрашивать не о чем: глобальная настройка
  // тут есть у половины машин, а хука, который она гасит, нет вовсе — говорить о
  // ней значило бы пугать человека тем, что его не касается.
  if (!existsSync(join(root, '.git'))) {
    return null;
  }

  const asked = askGit(root);
  if (asked === null) {
    return null;
  }

  // Настройка, указывающая ТУДА ЖЕ, куда мы кладём, ничего не ломает: git
  // смотрит в наш каталог, просто названный явно.
  if (samePlace(placeOf(root, asked.value), join(root, OUR_HOOKS_DIR))) {
    return null;
  }

  const where = asked.origin === null ? '' : ` (написано в "${asked.origin}")`;

  // ПЕРЕНОСЫ СВОИ, и это обязанность автора текста: консоль печатает слово
  // обвеса ДОСЛОВНО и по своей ширине его не ломает — она не знает ни причины,
  // ни цены этой фразы (`baser-cli`, `report.ts`). Не разбив строку здесь, я
  // получил бы в терминале человека одну строку на четверть экрана.
  return [
    `хук лёг в "${HOOK_DEST}", но git этой локации туда не смотрит:`,
    `у неё задан ${SETTING} = "${asked.value}"${where},`,
    'и запускается только то, что лежит ТАМ. Положенный файл останется мёртвым —',
    'эту проверку git не позовёт ни на одном коммите и не скажет об этом ни слова.',
    '',
    `Сними настройку там, где она написана ("git config --unset-all ${SETTING}"`,
    'правит конфиг локации, а не глобальный), либо не рассчитывай на машинный хук',
    'отсюда: укладка верная — расходятся адреса, а не содержимое, и чинить в',
    'обвесе нечего.',
  ].join('\n');
}

/**
 * Ответ git'а про настройку: значение и файл, где оно написано.
 *
 * `-z` вместо разбора строк: значение конфига вправе содержать и таб, и перевод
 * строки, а поля, разделённые нулём, разобрать однозначно. `--show-origin` — не
 * украшение: без имени файла человек с ГЛОБАЛЬНОЙ настройкой пойдёт снимать её
 * в локации, ничего не добьётся и решит, что мы соврали.
 *
 * @returns {{ value: string, origin: string | null } | null} пустота — спросить
 *   не удалось либо настройки нет
 */
function askGit(root) {
  let asked;
  try {
    asked = spawnSync(
      'git',
      ['-C', root, 'config', '-z', '--show-origin', '--get', SETTING],
      {
        encoding: 'utf-8',
        env: envWithoutGit(process.env),
        timeout: ASK_TIMEOUT_MS,
        windowsHide: true,
      },
    );
  } catch {
    // Сюда попадают только беды самого запуска. Наружу они не летят: человеку
    // нужно слово про хук, а не наша ошибка вместо него.
    return null;
  }

  // `error` — git не нашёлся или не уложился в срок; `status: 1` — настройки
  // нет; `128` — спрашивать не у кого (`.git` не репозиторий). Все три —
  // обстановка, а не беда: молчим.
  if (asked.error || asked.status !== 0) {
    return null;
  }

  const fields = String(asked.stdout ?? '').split('\0');
  const value = (fields[1] ?? '').trim();
  if (value === '') {
    // Пустое значение git слушается (хуки уезжают в корень дерева), но сказать
    // про него нечего внятного, а рынок считает пустоту незаданностью
    // (`pre-commit`, сверка выше). Держим одну правду с ним.
    return null;
  }

  const origin = fields[0] ?? '';
  return {
    value,
    // Происхождение бывает не файлом («command line:», «blob:»): называть его
    // человеку как файл значило бы послать его править то, чего нет.
    origin: origin.startsWith('file:') ? origin.slice('file:'.length) : null,
  };
}

/**
 * Окружение без всего, чем git переопределяют снаружи.
 *
 * Снимается ПРЕФИКС целиком, а не перечень имён: `GIT_DIR`, `GIT_WORK_TREE`,
 * `GIT_CONFIG`, `GIT_CONFIG_GLOBAL`, `GIT_CONFIG_PARAMETERS` — их больше, чем
 * помнит человек, и забытое имя дало бы не отказ, а ТИХО ЧУЖОЙ ответ.
 */
function envWithoutGit(env) {
  const clean = {};
  for (const [name, value] of Object.entries(env)) {
    if (!name.startsWith('GIT_') && value !== undefined) {
      clean[name] = value;
    }
  }
  return clean;
}

/**
 * Куда указывает значение настройки.
 *
 * Относительное git отсчитывает от корня рабочего дерева, тильду разворачивает
 * сам. Форму `~пользователь` не разворачиваем: она указывает в чужой дом, то
 * есть заведомо не в наш `.git/hooks`, и сравнение и без разворота даст «не
 * туда» — то есть человек услышит, а не промолчим.
 */
function placeOf(root, value) {
  if (value === '~') {
    return homedir();
  }
  if (value.startsWith('~/')) {
    return join(homedir(), value.slice(2));
  }
  return isAbsolute(value) ? resolve(value) : resolve(root, value);
}

/**
 * Один ли это каталог — с точностью до ссылок.
 *
 * Сравнение строк даёт ложную ТРЕВОГУ там, где путь ведёт через симлинк
 * (`/tmp` на macOS — живой пример), поэтому спорный случай доспрашивается у ФС.
 * Несуществующий каталог до `realpathSync` не доживает и остаётся «не тем»: если
 * настройка уводит в никуда, хук тем более не сработает.
 */
function samePlace(a, b) {
  if (a === b) {
    return true;
  }
  try {
    return realpathSync(a) === realpathSync(b);
  } catch {
    return false;
  }
}
