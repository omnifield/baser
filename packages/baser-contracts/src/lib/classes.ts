/**
 * КЛАСС АРТЕФАКТА — чем станок держит положенный файл.
 *
 * Станок даёт инструменту руки, а не решения (`kb:BASER2-2` §4): он замечает и
 * называет, а что делать с файлом при обновлении — знает обвес. Класс и есть то
 * слово, которым обвес это говорит: он один знает, где у него кор, где конфиг, а
 * где скелет, в котором человек уже месяц работает.
 *
 * **Перечисление, а не флаг.** `once: true` выразил бы ровно два состояния, а
 * третий класс уже описан у соседей (`kb:WEBER-4`) — и его приезд ломал бы форму
 * второй раз. Перечисление принимает новое слово, не трогая уже выпущенные
 * обвесы.
 */

export type ArtifactClass =
  /**
   * Артефакт наш и перегенерируется целиком (`kb:BASER2-2` §4, модель A).
   * Правка руками не переводит владение — она поднимает флаг, а план называет
   * будущее затирание вслух.
   */
  | 'regenerated'
  /**
   * Станок кладёт файл в объявленном месте и дальше его не трогает.
   *
   * Семантика (исполнение — `tasker:BASER2-51`): хеш не пишется вовсе · правка
   * человека флага не поднимает и расхождением не называется · пропала запись из
   * раскладки — артефакт НЕ уходит сиротой, а называется вслух и снимается явной
   * командой · пропал сам артефакт — кладём заново, потому что объявленное место
   * пустое.
   *
   * Зачем: выпиленная строка шаблона иначе молча уносила бы файл, в котором
   * человек месяц работал.
   */
  | 'placed-once';

/** Перечень классов — для сообщений и для проверки объявления. */
export const ARTIFACT_CLASSES: readonly ArtifactClass[] = [
  'regenerated',
  'placed-once',
];

/**
 * Умолчание: не назвал класс — артефакт наш.
 *
 * Проставляется ПРИ РАЗБОРЕ, как и `render`: умолчание живёт в одном месте, а не
 * в каждом читателе формы. Оно же делает форму 1 разбираемой по существу —
 * старая раскладка означала ровно `regenerated`.
 */
export const DEFAULT_ARTIFACT_CLASS: ArtifactClass = 'regenerated';

export function isArtifactClass(value: unknown): value is ArtifactClass {
  return (
    typeof value === 'string' &&
    (ARTIFACT_CLASSES as readonly string[]).includes(value)
  );
}
