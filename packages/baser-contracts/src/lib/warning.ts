/**
 * ВЫЧИСЛЯЕМОЕ ПРЕДУПРЕЖДЕНИЕ — обвес говорит человеку, НЕ ломая прогон.
 *
 * До формы 7 громкость у обвеса была ровно одна: бросок резолвера, который
 * валит весь прогон локации у всех обвесов сразу. Выбор в форме был между
 * «промолчать» и «сломать всё», третьего не существовало
 * (`tasker:BASER2-226`).
 *
 * Живой случай: локация с заданным `core.hooksPath` получает хук в
 * `.git/hooks` — он ляжет и не сработает. **Прогон при этом верный, отказывать
 * не за что, но человек обязан услышать** (`tasker:BASER2-208`). Причину знает
 * только обвес: движок про конкретные обвесы не знает по построению
 * (`kb:BASER3-34`), а дверь про `core.hooksPath` знать не должна. Значит текст и
 * условие объявляет обвес, а печатает дверь.
 *
 * ## Это НЕ свойство артефакта — и поэтому поле не на записи раскладки
 *
 * Развилка формы 7, решение владельца зоны (`tasker:BASER2-232`): предупреждение
 * — не свойство артефакта и не состояние движка, а **то, что обвес говорит про
 * своё применение в ЭТОЙ локации**. Отсюда и место поля: верхний уровень
 * объявления, рядом с `source`.
 *
 * - `executable` описывает САМ артефакт: он программа, и это верно всюду, куда
 *   его ни положи. Предупреждение не описывает артефакт — файл один и тот же
 *   при любом `core.hooksPath`, меняется только то, СРАБОТАЕТ ли он здесь.
 * - На записи раскладки резолверу нечего было бы дать сверх того же
 *   `ResolverContext` — адрес записи стал бы декорацией, а не входом.
 *
 * **Цена названа честно:** предупреждение про один файл из пяти автоматического
 * адреса не получит — имя файла обвес пишет в своём тексте сам. Взамен обвес,
 * говорящий про применение целиком («пересоздай контейнер»), не обязан вешать
 * свою фразу на произвольный артефакт и врать адресом.
 *
 * ## Вторая громкость не имеет права вести себя как первая
 *
 * Ни одна беда ВНУТРИ этого механизма не отказ: резолвер не нашёлся, бросил,
 * вернул обещание, вернул не строку, вернул пустоту — прогон продолжается, а
 * случившееся называется ДАННЫМИ (`SourceWarning`), с обычным кодом и адресом.
 * Иначе мы завели бы вторую громкость, которая ведёт себя как первая, и
 * обвес, попытавшийся сказать, ронял бы локацию сильнее молчащего.
 *
 * Отказом остаётся ровно одно, и оно приходит РАНЬШЕ — при разборе объявления
 * (`declaration.ts`): непригодная сама ссылка `<файл>#<экспорт>` и поле под
 * старым номером формы. Там непригоден обвес, а не обстановка.
 */

import type { ResolverRef, SourceDeclaration } from './declaration.js';
import type { FormProblem, FormProblemCode } from './problems.js';
import { describeCause, isThenable } from './resolvers.js';
import { describeValue } from './values.js';

/**
 * Порт вызова резолвера предупреждения: найти модуль обвеса и позвать экспорт.
 *
 * Загрузка — дело двери, поэтому контракт её не делает, а требует; бросок
 * наружу ловится здесь и называется данными.
 *
 * **Порт свой, а не `ComputeDefault`, хотя реализация у двери одна.** Механизм
 * загрузки общий (`resolvers.ts`), обещания разные:
 *
 * | | резолвер дефолта | резолвер предупреждения |
 * | --- | --- | --- |
 * | куда едет ответ | в артефакт у потребителя | человеку, на этом прогоне |
 * | смотреть на посадочное место | нельзя: сломает воспроизводимость коммита | НУЖНО: ради этого и заведён |
 *
 * Сложив их в один порт, мы стёрли бы ровно то различение, ради которого поле
 * заводилось: автор обвеса не смог бы прочитать по типу, чего от его функции
 * ждут. Синхронность и запрет на сеть при этом общие — прогон не имеет права
 * зависеть от сети ни в одном из двух случаев.
 */
export type ComputeWarning = (ref: ResolverRef) => unknown;

/**
 * Что обвес сказал про своё применение здесь.
 *
 * Состояний три, и `failed` — не отказ прогона, а НАЗВАННАЯ беда самого
 * предупреждения: дверь её печатает и кладёт в машинный ответ, но прогон от неё
 * не останавливается.
 */
export type SourceWarning =
  /** Обвес предупреждения не объявлял либо резолвер вернул пустоту. */
  | { readonly kind: 'none' }
  /** Обвесу есть что сказать — вот его текст, дословно. */
  | { readonly kind: 'said'; readonly text: string }
  /**
   * Сказать не вышло, и это названо, а не проглочено.
   *
   * Проглотить было бы хуже отказа: автор обвеса считал бы, что его
   * предупреждение работает, а оно молчит — то самое молчание, против которого
   * поле и заведено.
   */
  | { readonly kind: 'failed'; readonly problem: FormProblem };

const NOTHING: SourceWarning = { kind: 'none' };

/**
 * Зовёт резолвер предупреждения и разбирает то, что он вернул.
 *
 * **Никогда не отказывает.** Возвращает состояние, а не `FormResult`, и это не
 * стилистика: `FormResult` с `ok: false` читается всеми зонами как «прогон не
 * поедет», а предупреждение права останавливать прогон не имеет.
 *
 * @param computeWarning порт двери; не передан — беда называется данными, а не
 *   тихо превращается в «сказать нечего»: разница между «обвес молчит» и «мы не
 *   умеем его спросить» видна только здесь
 */
export function resolveWarning(
  declaration: SourceDeclaration,
  computeWarning?: ComputeWarning,
): SourceWarning {
  const ref = declaration.warningFrom;
  if (ref === undefined) {
    return NOTHING;
  }

  // Адрес — личность обвеса и поле: предупреждение принадлежит применению
  // ОБВЕСА, а не какому-то одному артефакту, и адрес обязан это показывать.
  const at = `${declaration.source.id}.warningFrom`;
  const named = `"${ref.module}#${ref.member}"`;
  const failed = (code: FormProblemCode, message: string): SourceWarning => ({
    kind: 'failed',
    problem: { code, at, message },
  });

  if (!computeWarning) {
    return failed(
      'resolver-failed',
      `обвес объявил предупреждение ${named}, а звать резолверы некому — ` +
        'дверь обязана передать computeWarning',
    );
  }

  let value: unknown;
  try {
    value = computeWarning(ref);
  } catch (cause) {
    // Ради этой строки поле и заводилось: упавший резолвер предупреждения не
    // имеет права уронить прогон — иначе вторая громкость ведёт себя как первая.
    return failed(
      'resolver-failed',
      `резолвер предупреждения ${named} не отработал: ${describeCause(cause)}. ` +
        'Прогон это не остановило: предупреждение не отказ',
    );
  }

  if (isThenable(value)) {
    return failed(
      'resolver-async',
      `резолвер предупреждения ${named} вернул обещание. Он обязан быть ` +
        'синхронным: дверь считает предупреждение вместе с планом, до применения, ' +
        'и ждать чужого обещания там нечем',
    );
  }

  // Пустота — рабочий ответ, а не беда: «сказать нечего» это самый частый
  // случай, и обвес обязан уметь выразить его, не заводя условий у двери.
  if (value === null || value === undefined) {
    return NOTHING;
  }

  if (typeof value !== 'string') {
    return failed(
      'wrong-type',
      `резолвер предупреждения ${named} вернул ${describeValue(value)} — ` +
        'ожидался текст для человека либо null («сказать нечего»). ' +
        'Печатать это некуда: жанр двери — строка, которую читают глазами',
    );
  }

  if (value.trim() === '') {
    // Пустая строка — не «сказать нечего», а сказанное ничем: ходовое `return
    // условие ? текст : ''` даёт ровно то молчание, против которого поле
    // заведено, и отличить его от исправной работы было бы нечем.
    return failed(
      'empty-string',
      `резолвер предупреждения ${named} вернул пустую строку. ` +
        '«Сказать нечего» выражается null, а не пустотой: пустую строку ' +
        'печатать некуда, и от исправной работы она неотличима',
    );
  }

  // Текст отдаётся ДОСЛОВНО: форма не переписывает того, что обвес сказал
  // человеку. Обрезка тут была бы редактурой чужой фразы.
  return { kind: 'said', text: value };
}
