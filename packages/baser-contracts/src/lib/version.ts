/**
 * ВЕРСИЯ ФОРМЫ ОБЪЯВЛЕНИЯ.
 *
 * Обвесы пишут третьи лица (`kb:BASER2-7`), поэтому форма поедет, а выпущенные
 * обвесы останутся в проде. Без признака версии старый обвес при изменившейся
 * форме сломался бы молча или, хуже, был бы разобран наполовину — то самое
 * молчание, которое канон называет дефектом (`kb:BASER2-2` §4).
 *
 * Причина та же, по которой у движка есть `OUTPUT_SCHEMA_VERSION`:
 * несовместимость обязана быть ВИДИМОЙ, а не выясняться по симптомам.
 *
 * Версия поднимается при НЕСОВМЕСТИМОМ изменении формы (поле удалено,
 * переименовано, сменило смысл). Новое необязательное поле версию не поднимает:
 * старый обвес продолжает разбираться.
 *
 * **1** — первая форма (`tasker:BASER2-19`): `source` · `settings` · `presets` ·
 * `layout`; настройки и пресеты потребитель писал в `baser.json`.
 *
 * **2** — форма нескольких инструментов (`tasker:BASER2-10`): у записи раскладки
 * появился `class` (`regenerated` · `placed-once`), а настройки и пресеты
 * потребителя уехали из `baser.json` в файл на инструмент
 * (`.omnifield/<поставщик>-<обвес>.yaml`). Версия обвеса вторым полем не
 * заводится: она уже есть в манифесте пакета.
 *
 * **3** — форма составного типа (`tasker:BASER2-116`): у настройки появился тип
 * `map` со словом `of`. Прибавление чистое — ни одно поле не снято, не
 * переименовано и не сменило смысл, — и версия поднята НЕ поэтому.
 *
 * Поднята она затем, что старый baser иначе врёт про причину. Обвес с
 * `type: "map"`, поданный разборщику формы 2, получил бы «ожидался один из типов
 * string · number · boolean · list» — то есть человека отправили бы искать
 * опечатку там, где её нет: он написал не опечатку, а тип, которого у ЭТОГО
 * baser'а ещё нет. С поднятой версией он получает `form-version-unsupported` и
 * ровно то указание, которое ему нужно: **обнови baser**.
 *
 * **4** — форма закреплённой поставки (`tasker:BASER2-145`): у записи перечня
 * поставленного (`sources[]` в `baser.json`) появилось необязательное поле
 * `version`. Объявление обвеса не изменилось НИ НА ОДНО ПОЛЕ — прибавление
 * целиком на стороне потребителя, — но номер у формы один на обе половины
 * (`config.ts`), потому что дверь склеивает их в одну декларацию.
 *
 * Причина подъёма та же, что у формы 3, и она не про «поле добавилось». Старый
 * baser, увидев `version`, назвал бы его `unknown-field` — «конфиг такого поля
 * не знает, опечатка либо надежда на поведение, которого нет». Человек при этом
 * написал не опечатку, а закрепление, которого у ЭТОГО baser'а ещё нет. С
 * поднятой версией конфиг называется формой 4, и старый baser говорит
 * единственное, что тут уместно: **обнови baser**.
 *
 * **5** — форма названного канала (`tasker:BASER2-177`, контракт `kb:BASER3-26`):
 * у записи перечня поставленного появилось необязательное поле `channel` —
 * метка склада («дай последнее из дев-канала»), которой локация говорит, ЧТО
 * брать, не зная номера. Объявление обвеса опять не изменилось ни на одно поле:
 * прибавление целиком на стороне потребителя.
 *
 * **Канал — отдельное поле, а НЕ значение поля версии.** Номер это адрес
 * содержимого: под ним лежит ровно одна сборка, и она не меняется. Метка —
 * указатель, который двигается. Сложив оба обещания в одно поле, мы потеряли бы
 * различение ровно там, где оно несущее: читающий перечень не смог бы сказать,
 * воспроизводим он, не разбирая строку.
 *
 * Причина подъёма номера — та же, что у форм 3 и 4, и она не про «поле
 * добавилось»: старый baser, увидев `channel`, назвал бы его `unknown-field`,
 * то есть опечаткой. Человек написал не опечатку, а метку, которой у ЭТОГО
 * baser'а ещё нет, и сказать ему надо **обнови baser**.
 */
export const FORM_VERSION = 5;

/**
 * Самая старая форма, которую этот baser ещё разбирает.
 *
 * **Осталась на 2, хотя текущая уже 5, и это решение, а не забывчивость.**
 * Граница проходит там, где поля ПЕРЕЕХАЛИ: форма 1 держала настройки и пресеты
 * в `baser.json`, форма 2 — в файле на инструмент, и разобрать первую по
 * правилам второй значит **молча потерять всё, что человек настроил** — ключи
 * лежат там, где вторая форма их не ищет. Поэтому объявление и конфиг первой
 * формы получают названный отказ целиком, а не частичный разбор.
 *
 * Ни между 2 и 3, ни между 3 и 4, ни между 4 и 5 такого переезда нет: третья
 * форма только ДОБАВИЛА тип, четвёртая и пятая — по необязательному полю записи
 * перечня, и ни одна ничего не сдвинула. Объявление формы 2 читается пятой без
 * единой потери — просто составного типа в нём не встретится; конфиг формы 3
 * читается ею же, просто ни закрепления, ни метки канала в нём нет, а их
 * отсутствие законно. Опустить эту границу значило бы потребовать правки от
 * каждого выпущенного обвеса ради возможности, которой он не пользуется, — и
 * заставить живых потребителей мигрировать лишний раз.
 *
 * **Два живых перечня формы 2 у нас есть прямо сейчас** (`tasker:BASER2-177`),
 * и подъём до 5 их не касается.
 *
 * Цена перехода 1 → 2 была нулевой: живых `baser.json` не существовало ни одного
 * (`tasker:BASER2-10`, «момент менять — сейчас»). Второй раз так дёшево не
 * будет, и поэтому граница двигается только за переездом полей.
 */
export const MIN_FORM_VERSION = 2;

/**
 * Форма, в которой у настройки появился составной тип (`values.ts`).
 *
 * Названа отдельным словом, потому что по ней ВЕТВИТСЯ РАЗБОР: `type: "map"` в
 * объявлении, назвавшемся формой 2, — отказ, а не тихое согласие. Версия формы
 * говорит, по каким правилам читать остальное; принимать по ней то, чего в той
 * форме не было, значит превратить её в украшение.
 */
export const MAP_TYPE_SINCE = 3;

/**
 * Форма, в которой у записи перечня поставленного появилось закрепление версии
 * (`config.ts`, поле `version`).
 *
 * Названа отдельным словом ровно по той же причине, что и `MAP_TYPE_SINCE`: по
 * ней ВЕТВИТСЯ РАЗБОР. `version` в конфиге, назвавшемся формой 3, — отказ, а не
 * тихое согласие. **Метка, по которой ничего не ветвится, — украшение:** приняв
 * закрепление в конфиге формы 3, мы дали бы двери записать файл, который старый
 * baser назовёт опечаткой вместо «обнови baser», — то есть сами испортили бы тот
 * единственный признак, ради которого версия формы и существует.
 */
export const PINNED_VERSION_SINCE = 4;

/**
 * Форма, в которой у записи перечня поставленного появилась метка канала
 * (`config.ts`, поле `channel`).
 *
 * Названа отдельным словом по той же причине, что `MAP_TYPE_SINCE` и
 * `PINNED_VERSION_SINCE`: по ней ВЕТВИТСЯ РАЗБОР. `channel` в перечне,
 * назвавшемся формой 4, — отказ «подними formVersion», а не «неизвестное поле»:
 * приняв метку под старым номером, мы дали бы двери записать файл, который
 * прежний baser назовёт опечаткой, — то есть сами испортили бы тот единственный
 * признак, ради которого версия формы и существует.
 */
export const CHANNEL_SINCE = 5;

export type FormVersion = typeof FORM_VERSION;
