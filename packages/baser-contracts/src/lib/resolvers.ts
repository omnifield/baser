/**
 * ОБЩЕЕ ДЛЯ ВЫЗОВА РЕЗОЛВЕРОВ ОБВЕСА — механизм один, обещания разные.
 *
 * Резолверов у формы два, и оба грузит дверь по одной и той же ссылке
 * `<файл>#<экспорт>` (`ResolverRef`): вычисляемый дефолт настройки
 * (`settings.ts`) и вычисляемое предупреждение (`warning.ts`). Загрузка —
 * дело двери, у которой есть файловая система и распакованный пакет; форма
 * только зовёт порт и разбирает то, что вернулось.
 *
 * **Обещания при этом РАЗНЫЕ, и складывать их в один порт нельзя** — см.
 * `warning.ts`. Общее у них ровно то, что здесь: как отличить обещание от
 * значения и как пересказать чужой бросок человеком.
 *
 * Модуль внутренний: наружу из него не уходит ни одного имени. Заведён он не
 * ради красоты, а против дубля — две копии этих двух проверок разъехались бы
 * молча, потому что обе половины остались бы зелёными.
 */

/**
 * Резолвер вернул обещание.
 *
 * Проверяется по `then`, а не `instanceof Promise`: обещание чужого рантайма
 * (или thenable из старой библиотеки) — то же самое нарушение, и пропустить его
 * значило бы поймать только свой случай.
 */
export function isThenable(value: unknown): boolean {
  return (
    typeof value === 'object' &&
    value !== null &&
    typeof (value as { then?: unknown }).then === 'function'
  );
}

/** Чужой бросок — человеческим текстом: у резолвера бросают чем угодно. */
export function describeCause(cause: unknown): string {
  return cause instanceof Error ? cause.message : String(cause);
}
