/**
 * Отказы формы — данные, а не исключения.
 *
 * Объявление обвеса и конфиг потребителя часто непригодны СРАЗУ В НЕСКОЛЬКИХ
 * местах: три опечатки в конфиге это три опечатки, а не одна. Бросок на первой
 * заставил бы пользователя чинить их по очереди, по одному прогону на штуку,
 * поэтому разбор собирает все и отдаёт списком.
 *
 * Форма ответа машинночитаема в первую очередь (`tasker:BASER2-20`): у отказа
 * есть код для ветвления, адрес и человеческий текст. `describeProblems` —
 * рендер поверх тех же данных, а не отдельная правда.
 */

/** Что именно не так. Ветвиться потребителю — по коду, не по тексту. */
export type FormProblemCode =
  /** На месте объекта пришло не то — строка, массив, `null`. */
  | 'not-an-object'
  /** Обязательного поля нет. */
  | 'missing-field'
  /** Поле есть, но другого типа. */
  | 'wrong-type'
  /** Строка есть, но пустая — имя, которого нет. */
  | 'empty-string'
  /**
   * Поле, которого форма этой версии не знает.
   *
   * Названо, а не пропущено молча: в пределах объявленной версии формы лишнее
   * поле — это опечатка либо надежда на поведение, которого нет (был `mode`).
   * Приезд новых полей закрывает не молчание разбора, а `formVersion`.
   */
  | 'unknown-field'
  /** Обвес не объявил версию формы. */
  | 'form-version-missing'
  /** Версия формы объявлена, но не целым положительным числом. */
  | 'form-version-invalid'
  /** Обвес рассчитан на форму, которой этот baser не знает. */
  | 'form-version-unsupported'
  /** `source.id` не похож на идентичность вида `<поставщик>/<обвес>`. */
  | 'invalid-source-id'
  /** `src`/`dest`/`contentRoot` непригодны как путь. */
  | 'invalid-path'
  /** У настройки нет дефолта — а это вопрос пользователю, которого не бывает. */
  | 'setting-no-default'
  /** У настройки сразу `default` и `defaultFrom` — неизвестно, что победит. */
  | 'setting-two-defaults'
  /**
   * Слово `of` не на месте: у карты его нет, у не-карты оно есть либо оно
   * незнакомое.
   *
   * Отдельный код, а не `missing-field`/`unknown-field`: у карты тип НЕПОЛОН без
   * `of` — «просто карта» приняла бы значение любой глубины, то есть ровно то,
   * от чего форма уводит. Читателю формы это надо отличать от обычного пропуска
   * поля, потому что чинится оно не дописыванием значения, а выбором слова из
   * закрытого словаря (`values.ts`).
   */
  | 'map-value-type'
  /**
   * Закрепление версии поставки непригодно: это не точная версия.
   *
   * Отдельный код, а не `wrong-type`: строка на месте и типом она верна —
   * непригодно её СОДЕРЖАНИЕ. Диапазон (`^1.2.0`) и метка (`latest`) не
   * закрепляют ничего, то есть чинится это не другим типом, а другим решением:
   * назвать точную версию либо не писать поле вовсе (`config.ts`).
   */
  | 'invalid-version'
  /**
   * Метка канала непригодна: меткой это не является.
   *
   * Отдельный код, а не `invalid-version` и не `wrong-type`: у канала и у
   * закрепления РАЗНЫЕ обещания — номер это адрес содержимого, метка это
   * указатель, который двигается, — и чинятся они разным. Номер, написанный в
   * канал, чинится переносом в `version`, а не другой меткой.
   *
   * Чего этот код НЕ значит: «такого канала нет на складе». Про наличие метки
   * знает только склад, и отвечает на это дверь (`config.ts`).
   */
  | 'invalid-channel'
  /** `defaultFrom` не разбирается как `<файл>#<экспорт>`. */
  | 'invalid-resolver-ref'
  /** Резолвер дефолта не нашёлся или бросил. */
  | 'resolver-failed'
  /** Резолвер вернул обещание: он обязан быть синхронным и не ходить наружу. */
  | 'resolver-async'
  /** Запись раскладки объявила класс, которого форма не знает. */
  | 'unknown-artifact-class'
  /**
   * Настройки или пресеты остались в `baser.json` — форма 1.
   *
   * Отдельный код, а не `unknown-field`: человеку надо сказать не «поля нет», а
   * КУДА оно уехало, иначе он ищет опечатку там, где её нет.
   */
  | 'consumer-settings-moved'
  /** Два обвеса считают из своих личностей одно имя файла настроек. */
  | 'source-config-shared'
  /**
   * Артефакт объявлен по адресу файла настроек — своего или соседского.
   *
   * Файл настроек заполняет ЧЕЛОВЕК, и владеть им станок не может: он не запись
   * раскладки и в паспорте укладки не числится. Молчаливое совпадение адресов
   * означало бы, что обновление обвеса затирает то, что человек настроил.
   */
  | 'artifact-over-source-config'
  /**
   * Артефакт объявлен по адресу перечня поставленного (`baser.json`).
   *
   * Отдельный код, а не общее «путь непригоден»: причина у него своя — файл ведут
   * дверь и человек, владеть им нечем, а перегенерация снесла бы перечень, по
   * которому обвес и нашли, — и подсказка поэтому своя.
   *
   * Ловится при разборе ОДНОГО объявления, в отличие от соседнего
   * `artifact-over-source-config`: имя конфига потребителя знает сама форма, и
   * чужое объявление для этого не нужно.
   */
  | 'artifact-over-consumer-config'
  /**
   * Перечня поставленного нет — ни в указанном каталоге, ни выше по дереву.
   *
   * Отказ входа `locate` (`locate.ts`), а не разбора: разбору перечень подают
   * уже прочитанным. Читает его тот вход сам, потому что исполняется у
   * потребителя, и «не туда позвали» обязано называться отдельно от «конфиг
   * непригоден» — чинятся они разным.
   */
  | 'consumer-config-missing'
  /** Перечень поставленного есть, но не разбирается как JSON. */
  | 'consumer-config-unreadable'
  /** Обвеса с такой личностью среди поставленных нет. */
  | 'source-not-installed'
  /**
   * Пакета с таким именем у потребителя нет — от его корня он не резолвится.
   *
   * Отказ резолва ПО ИМЕНИ (`locatePackage`), и он не то же самое, что
   * `source-not-installed`: тот отвечает на «обвеса с такой ЛИЧНОСТЬЮ среди
   * поставленных нет» и называет поставленных, а этот — на «пакета нет вовсе»,
   * и перечислять ему нечего. Имя приходит извне — из перечня поставленного, из
   * зависимостей манифеста потребителя, — а не из нашего разбора.
   */
  | 'package-not-installed'
  /**
   * Пакет на месте, но его манифест непригоден — а объявление обвеса живёт в нём.
   *
   * Отдельно от «пакета нет», потому что чинится это правкой файла, а не
   * установкой. Резолвер Node на непригодном манифесте отказывает ТАК ЖЕ, как на
   * отсутствующем пакете, и без этого кода единственным ответом на обе беды было
   * бы «не поставлен» — правдоподобно неверное про пакет, лежащий на диске.
   */
  | 'package-manifest-unreadable'
  /**
   * Обвес поставлен, но его содержимого на месте нет.
   *
   * Либо каталог `contentRoot` не уехал в пакет, либо запрошенного файла в нём
   * не оказалось. Отказ приходит СРАЗУ, а не путём к несуществующему файлу:
   * иначе он назвался бы ниже по цепочке и хуже.
   */
  | 'content-missing'
  /** Значение не того типа, который объявила настройка. */
  | 'value-type-mismatch'
  /** Речь про настройку, которой обвес не объявлял. */
  | 'unknown-setting'
  /** Потребитель просит пресет, которого у обвеса нет. */
  | 'unknown-preset'
  /** Два `layout` одного обвеса целятся в один `dest`. */
  | 'duplicate-dest'
  /** Два РАЗНЫХ обвеса целятся в один `dest` (`kb:BASER2-6`). */
  | 'artifact-shared'
  /** Два обвеса объявили одну и ту же идентичность. */
  | 'duplicate-source-id'
  /** Один и тот же пакет перечислен в конфиге дважды. */
  | 'duplicate-consumer-entry'
  /** Шаблон использует экранирующую форму вывода — кавычка станет `&#34;`. */
  | 'template-html-escape'
  /** Шаблон объявлен рендеримым, но ни одного тега подстановки в нём нет. */
  | 'template-not-ejs'
  /** Шаблон тянет содержимое мимо объявленной раскладки. */
  | 'template-include'
  /**
   * Шаблон тянется наружу: `process`, `require`, `import(`, сеть.
   *
   * Область видимости шаблона — значения настроек, и только они. Всё, что обвесу
   * нужно вычислить, вычисляет его резолвер и приезжает настройкой: иначе один и
   * тот же коммит раскладывается по-разному на разных машинах.
   */
  | 'template-escapes-scope'
  /** Теги подстановки не сходятся — шаблон оборван. */
  | 'template-unbalanced';

export interface FormProblem {
  readonly code: FormProblemCode;
  /** Адрес в разбираемом документе: `baser.settings.name.default`. */
  readonly at: string;
  /** Человеческим текстом и самодостаточно — без «см. выше». */
  readonly message: string;
}

/** Разбор: либо пригодное значение, либо перечень названных отказов. */
export type FormResult<T> =
  | { readonly ok: true; readonly value: T }
  | { readonly ok: false; readonly problems: readonly FormProblem[] };

/** Копилка отказов — чтобы разбор шёл дальше, а не останавливался на первом. */
export class ProblemLog {
  readonly #problems: FormProblem[] = [];

  add(code: FormProblemCode, at: string, message: string): void {
    this.#problems.push({ code, at, message });
  }

  get empty(): boolean {
    return this.#problems.length === 0;
  }

  list(): readonly FormProblem[] {
    return this.#problems;
  }

  /** Пригодное значение отдаём, только если не набралось ни одного отказа. */
  result<T>(value: () => T): FormResult<T> {
    return this.empty
      ? { ok: true, value: value() }
      : { ok: false, problems: this.list() };
  }
}

/** Текстовый рендер поверх тех же данных — для человека в терминале. */
export function describeProblems(problems: readonly FormProblem[]): string {
  if (problems.length === 0) {
    return 'отказов нет';
  }
  return problems
    .map((problem) => `${problem.at}: ${problem.message} [${problem.code}]`)
    .join('\n');
}
