/**
 * ЯЗЫК ПОДСТАНОВКИ — часть формы, а не подробность примера.
 *
 * Шаблон обвеса пишется на **EJS** (пакет `ejs`) — том же, на котором работает
 * `generateFiles` у генераторов Nx, по форме которых устроен движок. Дверь не
 * выбирает шаблонизатор и не приносит второй: язык назван здесь, и оба читателя
 * формы — автор двери и автор обвеса — понимают под ним одно.
 *
 * Пересказа документации EJS тут нет. Есть граница: что обвесу разрешено и на
 * что он опираться НЕ должен.
 *
 * ## Что обвесу доступно
 *
 * | | |
 * |---|---|
 * | `<%- значение %>` | подстановка значения настройки, **как есть** |
 * | `<% … %>` | ветвление и перебор: `if`, `for`, локальные переменные |
 * | `<% … -%>` | то же, со срезанием переноса строки за тегом |
 *
 * **Ветвление — несущая часть контракта, а не удобство.** Именно им выражается
 * третий слой обвеса: без пресета блок не разворачивается вовсе (`kb:BASER2-6` —
 * второго обвеса поверх первого не бывает, уровни живут внутри одного). Форма,
 * дающая только подстановку, не выражает девбокс.
 *
 * ## Чего нельзя
 *
 * - **`<%= … %>` — запрещено.** Это экранирующая форма вывода: кавычка
 *   превращается в `&#34;`, и валидный `devcontainer.json` перестаёт быть JSON.
 *   Артефакты — это JSON и shell, а не разметка страницы. Всегда `<%-`.
 * - **`include(…)` — запрещено.** Шаблон тянул бы содержимое мимо объявленной
 *   раскладки: дверь не знает, откуда его резолвить, а `layout` перестал бы
 *   описывать то, что реально приезжает.
 *
 * ## Что внутри тега разрешено
 *
 * **Обычный JavaScript.** Локальные переменные, стрелочные функции, методы
 * массивов и строк, `JSON.stringify`, шаблонные литералы — всё это несущая
 * часть контракта, а не поблажка: эталонный шаблон девбокса собирает `runArgs`
 * и `mounts` из настроек именно так, и без этого форма не выражает девбокс.
 *
 * Прежняя редакция доки обещала «только разрешённые значения настроек, по
 * именам» — это было **неправдой в обе стороны** (`tasker:BASER2-70` §2):
 * собственный эталонный шаблон зоны обещание нарушал, а проверка не судила ни
 * его, ни настоящие нарушения. Обещание приведено к поведению.
 *
 * ## Чего нельзя: ходов наружу
 *
 * **Данные шаблона — значения настроек, и только они.** Обращения к окружению и
 * загрузка чужого кода — отказ (`template-escapes-scope`): `process`,
 * `require`, `import(`, `globalThis`, `eval`, `new Function`, `fetch`,
 * `__dirname`, `__filename`.
 *
 * Причина та же, по которой резолвер не ходит в сеть (`settings.ts`): дефолт,
 * взятый из окружения машины, ломает воспроизводимость коммита — один и тот же
 * код раскладывается по-разному у автора и у потребителя. Всё, что обвесу нужно
 * вычислить, вычисляет его резолвер и приезжает настройкой.
 *
 * ## Чего проверка НЕ обещает — и это сказано вслух
 *
 * Форма не разбирает JavaScript и потому **не может обещать «в области видимости
 * только имена настроек»**: технически рендерер видит и глобали (`ejs` рендерит
 * через `with(locals)` внутри обычной функции). Держатся ДВЕРИ НАРУЖУ, а не
 * список имён, — по именам их отличить можно, по смыслу код разбирать нечем.
 *
 * Ищутся имена в КОДЕ тега: строковые литералы и комментарии из проверки
 * вырезаны, поэтому слово `process` в подставляемой строке отказом не будет, а
 * `${process.env.HOME}` внутри шаблонного литерала — будет.
 *
 * ## Артефакт, которому подстановка не нужна
 *
 * `render: false` — файл копируется байт в байт и НЕ проверяется: это уже не
 * шаблон, а содержимое.
 */

import type { FormProblem } from './problems.js';
import { ProblemLog } from './problems.js';

/** Открывающий тег любого вида. */
const OPEN = /<%/g;
/** Закрывающий тег любого вида, включая срезающий перенос. */
const CLOSE = /-?%>/g;
/** Экранирующая форма вывода. */
const ESCAPING = /<%=/;
/** Тело тега целиком — чтобы искать запрещённое ВНУТРИ него, а не в содержимом. */
const TAG_BODY = /<%([^]*?)%>/g;
/** Подключение чужого содержимого. */
const INCLUDE = /\binclude\s*\(/;

/**
 * Ходы наружу: имя → чем оно является для шаблона.
 *
 * Список — про ДВЕРИ, а не про полный периметр (см. докблок): форма не разбирает
 * JavaScript и обещает ровно то, что проверяет.
 */
const OUTSIDE_SCOPE: ReadonlyArray<readonly [RegExp, string]> = [
  [/\bprocess\b/, 'process — окружение машины, на которой запущена дверь'],
  [/\brequire\s*\(/, 'require( — загрузка чужого кода мимо объявления'],
  [/\bimport\s*\(/, 'import( — загрузка чужого кода мимо объявления'],
  [/\bglobalThis\b/, 'globalThis — обход области видимости целиком'],
  [/\beval\s*\(/, 'eval( — исполнение строки как кода'],
  [/\bnew\s+Function\b/, 'new Function — исполнение строки как кода'],
  [/\bfetch\s*\(/, 'fetch( — сеть; артефакт перестал бы быть воспроизводимым'],
  [/\b__dirname\b/, '__dirname — файловая система машины'],
  [/\b__filename\b/, '__filename — файловая система машины'],
];

/**
 * Проверяет, что содержимое рендеримого артефакта написано на языке формы.
 *
 * Читает и рендерит дверь — но **что разрешено, решает форма**: инвариант,
 * который держит только соседняя зона, не инвариант. Дверь зовёт эту проверку
 * до рендера и получает те же данные отказа, что и у остального разбора.
 *
 * @param content содержимое шаблона (текст, не путь — файлов пакет не читает)
 * @param at адрес для сообщений, обычно `<src> → <dest>`
 */
export function checkTemplate(
  content: string,
  at: string,
): readonly FormProblem[] {
  const log = new ProblemLog();

  const opens = count(content, OPEN);
  const closes = count(content, CLOSE);

  if (opens === 0) {
    // Единственный сомнительный случай — файл БЕЗ подстановок, помеченный
    // рендеримым. Он и должен быть назван: либо в нём ничего не подставляется и
    // ему место под `render: false`, либо он написан на чужом языке (`{{name}}`,
    // `{% if %}`) и молча ляжет к потребителю с неподставленными местами.
    log.add(
      'template-not-ejs',
      at,
      'артефакт объявлен рендеримым, но ни одного тега подстановки в нём нет. ' +
        'Шаблоны обвесов пишутся на EJS (`<%- значение %>`, `<% if … %>`); ' +
        'если подставлять нечего — объяви запись с "render": false, и файл ляжет байт в байт',
    );
    return log.list();
  }

  if (opens !== closes) {
    log.add(
      'template-unbalanced',
      at,
      `теги подстановки не сходятся: открывающих ${opens}, закрывающих ${closes} — шаблон оборван`,
    );
  }

  if (ESCAPING.test(content)) {
    log.add(
      'template-html-escape',
      at,
      'шаблон использует "<%=" — экранирующую форму вывода: кавычка превратится в "&#34;", ' +
        'и артефакт перестанет быть валидным JSON. Артефакты — это JSON и shell, ' +
        'а не разметка страницы; выводи через "<%-"',
    );
  }

  // Ищем внутри тегов, а не по всему тексту: `include(` в содержимом артефакта
  // (скрипт, конфиг) — обычная строка, а не обращение к шаблонизатору.
  const code = tagBodies(content).map(codeOnly);

  if (code.some((body) => INCLUDE.test(body))) {
    log.add(
      'template-include',
      at,
      'шаблон тянет содержимое через include(): дверь не знает, откуда его резолвить, ' +
        'а раскладка перестала бы описывать то, что реально приезжает потребителю',
    );
  }

  for (const [pattern, what] of OUTSIDE_SCOPE) {
    if (code.some((body) => pattern.test(body))) {
      log.add(
        'template-escapes-scope',
        at,
        `шаблон тянется наружу: ${what}. Данные шаблона — значения настроек, и только они; ` +
          'всё остальное вычисляет резолвер обвеса и приезжает настройкой. ' +
          'Иначе один и тот же коммит раскладывается по-разному у автора и у потребителя',
      );
    }
  }

  return log.list();
}

function count(content: string, pattern: RegExp): number {
  return content.match(pattern)?.length ?? 0;
}

function tagBodies(content: string): string[] {
  return [...content.matchAll(TAG_BODY)].map((match) => match[1]);
}

/** В каком состоянии разбирается тело тега. */
type Mode = 'code' | 'single' | 'double' | 'tpl' | 'line' | 'block';

/**
 * Оставляет от тела тега только КОД: строковые литералы и комментарии гасит.
 *
 * Иначе `<%- "не трогай process" %>` был бы отказом, а отказ на слове в строке —
 * это ложная тревога, из-за которой перестают верить настоящим.
 *
 * Нутро `${…}` в шаблонных литералах при этом остаётся кодом: именно там ход
 * наружу и прячется (`${process.env.HOME}`), и погасить литерал целиком значило
 * бы завести дыру ровно в проверке, ради которой всё делается.
 *
 * Регулярные литералы формой не разбираются — кавычка внутри `/['"]/` собьёт
 * разбор строк. Случай экзотический (подстановка в JSON и shell), и цена его —
 * лишний отказ или пропущенный ход, а не молчаливо неверный артефакт.
 */
function codeOnly(body: string): string {
  const chars = body.split('');
  /** Глубина фигурных скобок на входе в каждое незакрытое `${…}`. */
  const interpolation: number[] = [];
  let mode: Mode = 'code';
  let braces = 0;

  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    const next = chars[i + 1] ?? '';

    if (mode === 'code') {
      if (ch === '/' && next === '/') {
        mode = 'line';
      } else if (ch === '/' && next === '*') {
        mode = 'block';
      } else if (ch === "'") {
        mode = 'single';
      } else if (ch === '"') {
        mode = 'double';
      } else if (ch === '`') {
        mode = 'tpl';
      } else if (ch === '{') {
        braces++;
        continue;
      } else if (ch === '}') {
        if (interpolation.at(-1) === braces) {
          interpolation.pop();
          mode = 'tpl';
          chars[i] = ' ';
        } else {
          braces--;
        }
        continue;
      } else {
        continue;
      }
      chars[i] = ' ';
      continue;
    }

    chars[i] = ' ';

    if (mode === 'line') {
      if (ch === '\n') {
        chars[i] = '\n';
        mode = 'code';
      }
      continue;
    }
    if (mode === 'block') {
      if (ch === '*' && next === '/') {
        chars[++i] = ' ';
        mode = 'code';
      }
      continue;
    }
    if (ch === '\\') {
      chars[++i] = ' ';
      continue;
    }
    if (mode === 'single') {
      if (ch === "'") mode = 'code';
      continue;
    }
    if (mode === 'double') {
      if (ch === '"') mode = 'code';
      continue;
    }
    if (ch === '`') {
      mode = 'code';
      continue;
    }
    if (ch === '$' && next === '{') {
      chars[++i] = ' ';
      interpolation.push(braces);
      mode = 'code';
    }
  }

  return chars.join('');
}
