/**
 * Вычисляемое предупреждение обвеса-фикстуры (форма 7).
 *
 * Отдельный файл, а не второй экспорт в `defaults.mjs`, — и это не аккуратность.
 * Резолверы у формы два, механизм загрузки у них один, а ОБЕЩАНИЯ разные:
 *
 * - резолвер ДЕФОЛТА считает значение, которое уедет в артефакт у потребителя, и
 *   потому смотреть на посадочное место ему нельзя — сломается воспроизводимость
 *   коммита;
 * - резолвер ПРЕДУПРЕЖДЕНИЯ говорит человеку про ЭТОТ прогон, и смотреть на
 *   посадочное место ему ровно затем и положено. Его ответ никуда не
 *   записывается.
 *
 * Общее у них — синхронность и запрет на сеть: прогон не имеет права зависеть
 * от того, поднят ли интернет.
 */

import { existsSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Хук набора ляжет верно и не сработает, если локация его не позвала.
 *
 * Форма фикстуры повторяет живой случай, ради которого форма 7 и заведена
 * (`tasker:BASER2-208`): обвес git кладёт `pre-commit` в `.git/hooks`, а локация
 * с заданным `core.hooksPath` смотрит в другое место — файл на месте, машина не
 * работает, и **прогон при этом верный, отказывать не за что**.
 *
 * Про посадочное место знает только обвес: движок про конкретные обвесы не знает
 * по построению, а дверь про чужие перечни хуков знать не должна.
 */
export function hookNotWired(ctx) {
  if (existsSync(join(ctx.repo.root, 'fixture/hooks.list'))) {
    // Сказать нечего — и это выражается ПУСТОТОЙ, а не пустой строкой: пустую
    // строку печатать некуда, и от исправной работы она неотличима.
    return null;
  }

  return (
    'хук набора лёг в fixture/hook.sh, но в локации нет fixture/hooks.list — ' +
    'раннер его не позовёт. Пропиши хук в перечень либо зови его сам; ' +
    'укладка при этом верная, чинить в наборе нечего.'
  );
}
