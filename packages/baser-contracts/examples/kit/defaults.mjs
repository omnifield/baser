/**
 * Вычисляемые дефолты обвеса-фикстуры.
 *
 * Резолвер — функция САМОГО обвеса, станок её только зовёт и не знает, что она
 * считает (`kb:BASER2-4`: станок держит хвостовик, не инструмент). Контекст даёт
 * дверь. Вернуть обязан КОНКРЕТНОЕ значение — «последнее на сегодня» в артефакт
 * не попадает (`kb:BASER2-5`).
 *
 * Резолверы СИНХРОННЫЕ и наружу не ходят: репозиторий, пакет, файлы рядом.
 * Дефолт, ездящий по календарю, ломал бы воспроизводимость коммита.
 */

/** Имя набора: `<репозиторий>-kit`. Пользователь не вводит ничего. */
export function nameFromRepo(ctx) {
  return `${ctx.repo.name}-kit`;
}

/**
 * Отметка выпуска: личность обвеса и его версия.
 *
 * Версия приезжает из манифеста пакета и по форме бывает ОТСУТСТВУЮЩЕЙ
 * (`tasker:BASER2-69`): подставить `null` в артефакт нельзя, а выдать вместо
 * версии `0.0.0` значит соврать правдоподобно. Поэтому отсутствие называется.
 */
export function sourceStamp(ctx) {
  return `${ctx.source.id}@${ctx.source.version ?? 'версия не объявлена'}`;
}
