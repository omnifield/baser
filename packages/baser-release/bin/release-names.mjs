#!/usr/bin/env node
/**
 * Карта имён репозитория — печать для того, кто публикует.
 *
 * ```
 * node packages/baser-release/bin/release-names.mjs [--root <каталог>] > names.json
 * ```
 *
 * В stdout — ДЖЕЙСОН вида `{"<внутреннее имя>": "<публичное имя>"}` по всем
 * пакетам монорепы (`kb:MECH-15`). Целиком, а не по одному: вместе с именем
 * пакета переписываются имена его межпакетных зависимостей.
 *
 * ПОЧЕМУ ПЕЧАТЬ, А НЕ ИМПОРТ. Конвейеру выпуска нужен ФАКТ, а не наш модуль:
 * связав шаг публикации с внутренним API зоны, мы сделали бы переименование
 * функции здесь поломкой выпуска наружу. Джейсон читается чем угодно, переживает
 * смену языка шага и не требует установки пакетов — зависимостей у инструмента
 * нет и здесь тоже (`tests/run.spec.mjs`).
 *
 * ФОРМА — ТА, КОТОРУЮ ЖДЁТ ПОТРЕБИТЕЛЬ: `--names <файл>` шага переименования
 * (`.github/scripts/public-rename.mjs`, зона git) читает ровно этот объект.
 * Обернули бы мы его в свою структуру — между двумя зонами появилась бы
 * переходная логика в YAML, а её тут и вычищают (`tasker:BASER2-261`).
 *
 * ПОЧЕМУ КОМАНДА, А НЕ ЧТЕНИЕ ОБЪЯВЛЕНИЯ НАПРЯМУЮ. Объявление — файл нашей зоны:
 * в нём живут пояснения (ключ `//`), и лежит он там, где решили мы. Команда
 * отдаёт не копию файла, а СВЕРЕННУЮ с раскладкой карту — и отказывается, если
 * они разошлись.
 *
 * Выход `0` — карта полна и напечатана; `1` — карта неполна или противоречива,
 * причина названа в stderr, а stdout ПУСТ: половина карты хуже её отсутствия,
 * потому что по ней доезжают до `npm publish`. `2` — неверно позван.
 */

import { publicNames } from '../lib/repo.mjs';

const args = process.argv.slice(2);
const rootFlag = args.indexOf('--root');
const root = rootFlag === -1 ? process.cwd() : args[rootFlag + 1];

if (rootFlag !== -1 && !root) {
  console.error('release-names: у --root не назван каталог');
  process.exit(2);
}

let names;
try {
  names = publicNames(root);
} catch (error) {
  console.error(
    'КАРТА ИМЁН НЕ ОТДАНА: имя, под которым пакет уезжает наружу, неизвестно\n',
  );
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}

console.log(JSON.stringify(Object.fromEntries(names), null, 2));
