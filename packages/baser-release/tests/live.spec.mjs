import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { judge } from '../lib/guard.mjs';
import { allTags, breakingSince, readPackages, releases } from '../lib/repo.mjs';
import { compare, parse } from '../lib/version.mjs';

/**
 * ГЕЙТ НА ВЫПУЩЕННОЙ ИСТОРИИ — на наших тегах и наших коммитах, а не на выдуманных.
 *
 * Выдуманный набор проверяет правило, но не проверяет, что правило вообще
 * встретится с действительностью: тег `<имя>@<номер>` со скоупом внутри имени,
 * коммит-сквош с номером PR в заголовке, многозонный заход, СМЕНА ИМЕНИ ПАКЕТА.
 * Здесь всё это живое.
 *
 * ЧТО ИМЕННО ЖИВОЕ — РАЗЛИЧЕНИЕ, КУПЛЕННОЕ КРАСНЫМ ПРОГОНОМ (`BASER2-176`,
 * 2026-08-04). Живое здесь — **выпущенная история**: теги, которые уже уехали, и
 * коммиты между ними. Это исторические факты, они больше не меняются. Рабочее
 * дерево — НЕ факт, а состояние: номера в манифестах двигаются каждым выпуском,
 * список тегов растёт каждым выпуском. Прежние пробы читали и то и другое, и
 * подъём номера красил пять из девяти — ни одна не про дефект. Проба, которая
 * падает от выпуска, не защищает, а мешает выпускать.
 *
 * Отсюда форма каждой пробы — МОМЕНТ ИСТОРИИ, закрытый с обеих сторон:
 *   - номер-кандидат называет сама проба (вход), из дерева он не читается;
 *   - теги берутся ПО СОСТОЯНИЮ НА названный выпуск — то, что уехало позже,
 *     тогда ещё не существовало;
 *   - окно коммитов закрыто сверху тегом, а не `HEAD`, — иначе завтрашний
 *     ломающий коммит перепишет вчерашний вердикт.
 *
 * ПРОПУСК ЗДЕСЬ ГРОМКИЙ, И ЭТО ТРЕБОВАНИЕ, А НЕ ВЕЖЛИВОСТЬ (`BASER2-260`).
 * Прогон требует полной истории с тегами (`fetch-depth: 0`); нет её — сценарные
 * пробы пропускаются, но прогон об этом ГОВОРИТ. Молчаливый `runIf` уже снял
 * восемь проб разом (2026-08-09, после переименования пакетов история под новым
 * именем оказалась пуста) — зелёный прогон, минус восемь проверок, ни одного
 * слова человеку. Поэтому:
 *   - тегов нет вовсе (мелкий клон) — пропуск, названный вслух;
 *   - теги есть, а истории пакета нет — КРАСНОЕ: это и есть ослепший гейт.
 */
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const IS_REPO = existsSync(join(ROOT, '.git'));

/**
 * Пакет, на котором стоят пробы: `@baser/cli` — единственный наш, у
 * которого между тегами лежит ЖИВОЙ ломающий коммит.
 *
 * Имя, каталог и зона названы здесь, а не вычитаны из дерева: в пробах о
 * выпуске `0.1.0` должна стоять раскладка ТОГО выпуска. На всех тегах, которых
 * касаются пробы, она одна и та же (сверено `git ls-tree` 2026-08-04).
 *
 * Прежнее имя названо здесь по той же причине — и оно не декорация: вся история
 * этого пакета уехала под ним, под нынешним именем не выпускалось ничего.
 * Настоящее объявление, по которому работает гейт, лежит в `former-names.json`;
 * что оно совпадает с этим — держит проба «каждый тег принадлежит объявленному
 * имени» ниже.
 */
const CLI = {
  name: '@baser/cli',
  formerNames: ['@omnifield/baser-cli'],
  dir: 'packages/baser-cli',
  zone: 'cli',
  private: false,
};

/**
 * Зоны репозитория в этих окнах истории — нужны гейту, чтобы отличить ломающее
 * СОСЕДА от своего. Тоже названы, а не собраны с диска: сегодняшняя раскладка
 * не должна решать, как судился выпуск, который уже уехал.
 */
const ZONES = new Set([
  'check',
  'cli',
  'contracts',
  'devbox',
  'materialize',
  'pack',
  'release',
]);

/** Все теги репозитория — по ним видно, полная история в клоне или мелкая. */
const ТЕГИ = IS_REPO ? allTags(ROOT) : [];

/** Выпуски пакета — под нынешним именем и под прежними, как их видит гейт. */
const ИСТОРИЯ = IS_REPO ? releases(ROOT, CLI.name, CLI.formerNames) : [];

/** Номера, без которых сценарным пробам не о чем судить. */
const НУЖНЫ = [
  '0.0.4',
  '0.1.0',
  '0.2.0-dev.1',
  '0.8.0-dev.1',
  '0.9.0-dev.1',
];
const ЕСТЬ_ИСТОРИЯ = НУЖНЫ.every((raw) =>
  ИСТОРИЯ.some((выпуск) => выпуск.version === raw),
);

/**
 * Пропуск, который слышно. Печатается один раз на файл — до того, как vitest
 * покажет вереницу серых галочек, по которым причины не видно.
 */
if (!IS_REPO || ТЕГИ.length === 0) {
  console.warn(
    [
      '[release/live] СЦЕНАРНЫЕ ПРОБЫ ЖИВОЙ ИСТОРИИ ПРОПУЩЕНЫ.',
      `  Причина: ${IS_REPO ? 'в клоне нет тегов выпуска — нужен fetch-depth: 0' : 'запуск не из репозитория (нет .git)'}.`,
      '  Пропущено: суждение на живых тегах и живом ломающем коммите cli,',
      '  включая случай переименования пакета. Прогон зелёный, но НЕ полный.',
    ].join('\n'),
  );
}

/**
 * Суждение о номере в НАЗВАННЫЙ момент истории пакета.
 *
 * @param {string} version номер-кандидат — вход пробы
 * @param {object} moment
 * @param {string|null} moment.released старший номер, УЖЕ выпущенный к этому
 *   моменту; что старше — тогда ещё не уехало. `null` — не выпускался ни разу
 * @param {string} [moment.until] верх окна коммитов — тег момента
 */
function asOf(version, { released, until }) {
  const ceiling = released === null ? null : parse(released);
  const tags =
    ceiling === null
      ? []
      : ИСТОРИЯ.filter((выпуск) => {
          const parsed = parse(выпуск.version);
          return parsed !== null && compare(parsed, ceiling) <= 0;
        });

  return judge({
    packages: [{ ...CLI, version }],
    releases: () => tags,
    breakingSince: (tag, pkg) => breakingSince(ROOT, tag, pkg, ZONES, until),
  });
}

/**
 * Момент перед выпуском минора: выпущен `0.0.4`, а в дереве уже лежит ломающий
 * `feat(cli)!: дверь зовёт резолв контрактов …`. Ровно тот PR, каким он приезжал
 * на гейт; за него и был взят `0.1.0`. На нём же проверяется, что предвыпускной
 * номер судится по той же цене.
 */
const ПЕРЕД_МИНОРОМ = {
  released: '0.0.4',
  until: '@omnifield/baser-cli@0.1.0',
};

/** Момент после выпуска минора: выпущены `0.0.4` и `0.1.0`, ломающего с них нет. */
const ПОСЛЕ_МИНОРА = {
  released: '0.1.0',
  until: '@omnifield/baser-cli@0.2.0-dev.1',
};

/** Момент после первой дев-сборки: старший выпущенный — предвыпускной. */
const ПОСЛЕ_ДЕВ_СБОРКИ = {
  released: '0.2.0-dev.1',
  until: '@omnifield/baser-cli@0.2.0-dev.1',
};

/**
 * Момент переименования: вся история уехала под прежним именем, старший
 * выпущенный — `0.9.0-dev.1`, и под нынешним именем не выпущено ничего.
 */
const ПОСЛЕ_ПЕРЕИМЕНОВАНИЯ = {
  released: '0.9.0-dev.1',
  until: '@omnifield/baser-cli@0.9.0-dev.1',
};

/**
 * ОСНОВАНИЕ ОСТАЛЬНЫХ ПРОБ. Если этот раздел красный — сценарные ниже не просто
 * упали, они ОТКЛЮЧИЛИСЬ, и красное здесь единственный способ об этом узнать.
 */
describe('живая история — основание сценарных проб', () => {
  it.runIf(ТЕГИ.length > 0)(
    'история пакета видна гейту — под нынешним именем или под прежним',
    () => {
      const пропали = НУЖНЫ.filter(
        (raw) => !ИСТОРИЯ.some((выпуск) => выпуск.version === raw),
      );
      expect(
        пропали,
        [
          `История ${CLI.name} не найдена: ${пропали.join(', ')}.`,
          `Искали под именами: ${[CLI.name, ...CLI.formerNames].join(', ')}.`,
          'Теги в репозитории есть, значит клон полный — это ослепший гейт,',
          'а не мелкий clone: проверь объявление в former-names.json.',
        ].join(' '),
      ).toEqual([]);
    },
  );

  it.runIf(ТЕГИ.length > 0)(
    'объявление знает прежнее имя cli — то самое, на котором стоят пробы',
    () => {
      // Прежнее имя названо в пробах константой (момент истории не читается из
      // дерева), а гейт судит по объявлению. Разойдись они — пробы проверяли бы
      // не то, чем работает гейт, и остались бы зелёными.
      const объявлено =
        readPackages(ROOT).find((pkg) => pkg.name === CLI.name)?.formerNames ??
        [];

      expect(
        объявлено,
        `former-names.json не объявляет ${CLI.formerNames.join(', ')} для ${CLI.name} — гейт этой истории не видит, а пробы ниже видят.`,
      ).toEqual(expect.arrayContaining(CLI.formerNames));
    },
  );

  it.runIf(ТЕГИ.length > 0)(
    'каждый тег выпуска принадлежит объявленному имени — переименование не прячет историю',
    () => {
      // Здесь рабочее дерево читается НАМЕРЕННО: проба не про давний выпуск, а
      // про сегодняшнее объявление против сегодняшнего реестра тегов. Тег, чьё
      // имя никем не объявлено, — это история, которую гейт больше не видит.
      const объявленные = readPackages(ROOT).flatMap((pkg) => [
        pkg.name,
        ...pkg.formerNames,
      ]);
      const ничьи = ТЕГИ.filter(
        (tag) => !объявленные.some((name) => tag.startsWith(`${name}@`)),
      );

      expect(
        ничьи,
        [
          `Теги без владельца: ${ничьи.join(', ')}.`,
          'Пакет переименовали и не объявили прежнее имя в former-names.json —',
          'его выпущенные номера для гейта больше не существуют.',
        ].join(' '),
      ).toEqual([]);
    },
  );
});

describe.runIf(ЕСТЬ_ИСТОРИЯ)('живой ломающий коммит cli', () => {
  it('патч поверх 0.0.4 ломающее не покрывает', () => {
    const { problems } = asOf('0.0.5', ПЕРЕД_МИНОРОМ);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('ЭТОГО МАЛО');
    expect(problems[0]).toContain('feat(cli)!:');
  });

  it('минор 0.1.0 покрывает — так и было выпущено', () => {
    const { problems, said } = asOf('0.1.0', ПЕРЕД_МИНОРОМ);
    expect(problems).toEqual([]);
    expect(said).toContain(
      `${CLI.name}: 0.0.4 → 0.1.0, ломающих коммитов 1 — минор набран`,
    );
  });

  it('предвыпускной 0.0.5-dev.1 не покрывает — как и обычный патч', () => {
    const { problems } = asOf('0.0.5-dev.1', ПЕРЕД_МИНОРОМ);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('судится тройка перед суффиксом (0.0.5)');
  });

  it('предвыпускной 0.1.0-dev.1 покрывает — база 0.1.0 берёт минор', () => {
    const { problems, said } = asOf('0.1.0-dev.1', ПЕРЕД_МИНОРОМ);
    expect(problems).toEqual([]);
    expect(said).toContain(
      `${CLI.name}: 0.0.4 → 0.1.0-dev.1 (предвыпускной, база 0.1.0), ломающих коммитов 1 — минор набран`,
    );
  });
});

describe.runIf(ЕСТЬ_ИСТОРИЯ)('живые теги cli', () => {
  it('номер равен старшему выпущенному — гейту сказать нечего', () => {
    const { problems, said } = asOf('0.1.0', ПОСЛЕ_МИНОРА);
    expect(problems).toEqual([]);
    expect(said).toEqual([]);
  });

  it('уже выпущенный номер не переиспользуется', () => {
    const { problems } = asOf('0.0.4', ПОСЛЕ_МИНОРА);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain(
      `уже выпущен тегом ${CLI.formerNames[0]}@0.0.4`,
    );
  });

  it('дев-сборка поверх выпущенного минора судится с него же', () => {
    const { problems, said } = asOf('0.2.0-dev.1', ПОСЛЕ_МИНОРА);
    expect(problems).toEqual([]);
    expect(said).toContain(
      `${CLI.name}: 0.1.0 → 0.2.0-dev.1 (предвыпускной, база 0.2.0), ломающего с прошлого выпуска нет`,
    );
  });

  it('следующая дев-сборка мерится со СТАБИЛЬНОГО, а не с предыдущей', () => {
    const { problems, said } = asOf('0.2.0-dev.2', ПОСЛЕ_ДЕВ_СБОРКИ);
    expect(problems).toEqual([]);
    expect(said).toContain(
      `${CLI.name}: 0.1.0 → 0.2.0-dev.2 (предвыпускной, база 0.2.0), ломающего с прошлого выпуска нет`,
    );
    // Мерили бы против черновика — в строке стояло бы `0.2.0-dev.1 →`, и каждая
    // итерация той же работы сжигала бы ещё один минор.
    expect(said.some((line) => line.includes('0.2.0-dev.1 →'))).toBe(false);
  });
});

/**
 * ПЕРЕИМЕНОВАНИЕ — НАСТОЯЩЕЕ, НАШЕ И НЕОБРАТИМОЕ. `@omnifield/baser-cli` стал
 * `@baser/cli` 2026-08-09 (`kb:MECH-15`), десять выпусков остались под прежним
 * именем, и переписывать их нельзя: тег — факт того, что уехало.
 *
 * Здесь проверяется весь исход целиком: история видна, занятый номер отвергнут
 * с НАСТОЯЩИМ тегом в отказе, откат назад отвергнут, а окно ломающих коммитов
 * открывается тегом, который существует.
 */
describe.runIf(ЕСТЬ_ИСТОРИЯ)('пакет со сменённым именем', () => {
  it('история видна — и она вся под прежним именем', () => {
    const под_прежним = ИСТОРИЯ.filter(
      (выпуск) => выпуск.name === CLI.formerNames[0],
    ).map((выпуск) => выпуск.version);

    expect(под_прежним).toEqual(expect.arrayContaining(НУЖНЫ));
  });

  it('номер, уехавший под прежним именем, занят — и тег в отказе настоящий', () => {
    const { problems } = asOf('0.8.0-dev.1', ПОСЛЕ_ПЕРЕИМЕНОВАНИЯ);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain(
      `уже выпущен тегом ${CLI.formerNames[0]}@0.8.0-dev.1 (прежнее имя пакета)`,
    );
    // Тега `@baser/cli@0.8.0-dev.1` в репозитории нет — назови гейт его,
    // человек пошёл бы искать несуществующее.
    expect(problems[0]).not.toContain(`${CLI.name}@0.8.0-dev.1`);
  });

  it('откат назад отвергнут — выпуски прежнего имени считаются уехавшими', () => {
    const { problems } = asOf('0.7.0', ПОСЛЕ_ПЕРЕИМЕНОВАНИЯ);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain(
      'не старше выпущенной 0.9.0-dev.1 (прежнее имя пакета)',
    );
  });

  it('цена изменения мерится от стабильного выпуска под прежним именем', () => {
    // Тот самый поход в git: окно открывается тегом `@omnifield/baser-cli@0.1.0`.
    // Собери гейт тег из нынешнего имени — `git log` упал бы на несуществующей
    // ревизии, и это уже не слепота, а падение прямо на PR.
    const { problems, said } = asOf('0.10.0-dev.1', ПОСЛЕ_ПЕРЕИМЕНОВАНИЯ);
    expect(problems).toEqual([]);
    expect(
      said.some((line) =>
        line.startsWith(
          `${CLI.name}: 0.1.0 → 0.10.0-dev.1 (предвыпускной, база 0.10.0)`,
        ),
      ),
    ).toBe(true);
  });
});

describe.runIf(IS_REPO)('пакет до первого выпуска', () => {
  it('невыпускавшийся назван, а не пропущен молча', () => {
    const { problems, said } = asOf('0.0.1', { released: null });
    expect(problems).toEqual([]);
    expect(said).toContain(
      `${CLI.name}: тегов выпуска нет — пакет не выпускался, сравнивать не с чем`,
    );
  });
});
