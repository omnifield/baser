/**
 * ВЫЧИСЛЯЕМЫЕ ДЕФОЛТЫ ОБВЕСА ДЕВБОКСА.
 *
 * Резолвер — функция САМОГО обвеса: станок её только зовёт и не знает, что она
 * считает (`kb:BASER2-4` — станок держит хвостовик, не инструмент). Контекст
 * даёт дверь: `{ repo: { name, root }, source: { id, packageName, version } }`.
 *
 * Три обязательства, и они не стилистические
 * (`packages/baser-contracts/README.md` §3):
 *
 * 1. **Синхронно.** Вернувший обещание резолвер — отказ `resolver-async`.
 * 2. **Локальный контекст: репозиторий, пакет, файлы рядом. В сеть не ходит.**
 *    Дефолт, ездящий по календарю или по ответу реестра, ломает
 *    воспроизводимость коммита: один и тот же код поднимался бы по-разному
 *    завтра и в оффлайне.
 * 3. **Конкретное значение, а не `latest`** (`kb:BASER2-5`). В артефакт
 *    попадает число.
 *
 * Файл публикуется В СОСТАВЕ ПАКЕТА как есть (`files: ["defaults.mjs"]`) и
 * ничего не собирает: `defaultFrom` дверь резолвит путём внутри распакованного
 * пакета, а не через `exports`, поэтому «собранный dist» здесь означал бы, что
 * обвес не работает до сборки — то есть не работает у потребителя.
 *
 * ── РАДИУС ПРАВА НА ЧТЕНИЕ ──────────────────────────────────────────────────
 *
 * До 0.3.0 модуль не импортировал ничего вовсе, и «не ходит наружу» держалось
 * по построению: дотягиваться было нечем. С 0.3.0 модуль читает ОДИН файл
 * репозитория (`.git/config`) — форма это право даёт прямым текстом, но
 * гарантия «нечем» им потрачена, поэтому она заменена узкой и проверяемой:
 *
 * - импорт разрешён только из `node:fs` и `node:path` — ни сети, ни
 *   подпроцесса, ни окружения, ни часов (`test/defaults.spec.mjs`);
 * - чтение только внутри `ctx.repo.root`, вверх по дереву не ходим (той же
 *   причины, по которой не ходит дверь: один вызов из разных мест обязан
 *   раскладывать одинаково);
 * - НИ ОДИН резолвер не бросает. Отказ резолвера — это `resolver-failed` на
 *   весь прогон, а «не смогли прочитать конфиг git» такой цены не стоит:
 *   нечитаемое просто не участвует, и в ответе остаётся запасной вариант.
 */

import { readFileSync, statSync } from 'node:fs';
import { isAbsolute, join, resolve } from 'node:path';

/**
 * Имя репозитория — базис для остальных имён; он же алиас в docker-сети.
 *
 * ── ПОЧЕМУ НЕ ИМЯ КАТАЛОГА (это и есть починка `tasker:BASER2-32`) ──────────
 *
 * Каталог — это то, как ЧЕЛОВЕК назвал клон, а не то, как называется
 * репозиторий. Два клона одного репозитория (`weber` и `weber-live`) давали два
 * разных имени и два разных алиаса в общей сети, а в ручной установке через
 * докер имя приезжало и вовсе от точки монтирования (`-v "$PWD":/repo`).
 *
 * Для имени контейнера это неудобство, для алиаса — поломка: алиас есть
 * ОБЕЩАНИЕ СОСЕДЯМ. Сосед ходит на `http://weber:3000`, и от того, что человек
 * клонировал в другую папку, адрес меняться не должен.
 *
 * ── ПОЧЕМУ НЕ `name` ИЗ `package.json` ──────────────────────────────────────
 *
 * Манифест отвечает на другой вопрос — как называется ПАКЕТ. Два живых
 * контрпримера, и оба наши:
 *
 * 1. Корень этого репозитория объявлен `@omnifield/baser-source` — репозиторий
 *    называется `baser`. Имя из манифеста дало бы `baser-source-devbox`, то
 *    есть разошлось бы с живым `.devcontainer`, который и есть эталон приёмки.
 * 2. В ручной установке манифест бывает НАШ СОБСТВЕННЫЙ: в репозитории без
 *    `package.json` (Go, Python) установщик бандла создаёт его на время прогона
 *    с именем-заглушкой `repo` (`tasker:BASER2-32`, ловушка). Резолвер, верящий
 *    манифесту, положил бы `repo-devbox` — хуже, чем имя каталога.
 *
 * Обе беды — один класс: манифест отвечает не на тот вопрос. Поэтому он не
 * читается ВОВСЕ, и заглушка перестаёт быть опасной по построению, а не
 * по списку признаков «настоящего манифеста», который пришлось бы держать
 * синхронно с чужой зоной.
 *
 * ── ЧТО ЧИТАЕТСЯ ВМЕСТО НЕГО ────────────────────────────────────────────────
 *
 * `origin` из `.git/config` — адрес, по которому репозиторий клонировали. Это
 * ровно его идентичность: одинакова у всех клонов, не зависит ни от имени
 * папки, ни от точки монтирования, есть у любого стека (Go, Python, что
 * угодно), и в CI та же, что у человека. `omnifield/weber` → `weber`.
 *
 * Нет `.git`, нет `origin`, нечитаемый конфиг — берётся имя каталога, то есть
 * ровно сегодняшнее поведение. Запасной вариант, а не отказ: имя девбокса не
 * стоит того, чтобы уронить прогон.
 */
export function repoName(ctx) {
  return repository(ctx);
}

/** Имя девбокса: `<репозиторий>-devbox`. Пользователь не вводит ничего. */
export function devboxName(ctx) {
  return `${repository(ctx)}-devbox`;
}

/**
 * Версия Node в базовом образе — ПИН, поставленный при выпуске этого обвеса.
 *
 * ── ОТКУДА ВЗЯЛОСЬ ЧИСЛО ────────────────────────────────────────────────────
 *
 * `24`. Решение owner-devbox на выпуск 0.1.0 (2026-07-27), два независимых
 * основания, и оба проверяемы:
 *
 * 1. **Node 24 «Krypton» — Active LTS на дату выпуска.** По графику релизов
 *    Node.js: 24 в Active LTS с 2025-10-28 по 2026-10-20, дальше maintenance до
 *    2028-04. Линия 22 ушла в maintenance 2025-10-21 — выпускать сегодня обвес
 *    с дефолтом на maintenance-линии значило бы отдавать новому потребителю
 *    заведомо стареющий рантайм. Линия 26 вышла в апреле 2026, но Active LTS
 *    станет только 2026-10-20: «последняя стабильная» — это LTS, не Current.
 * 2. **Тег реально опубликован семейством образа.** У
 *    `mcr.microsoft.com/devcontainers/typescript-node` на 2026-07-27 есть теги
 *    `18`/`20`/`22`/`24` и НЕТ `26` — семейство само идёт за LTS. Дефолт,
 *    указывающий на несуществующий тег, — сломанный девбокс, а не смелый.
 *
 * ── ПОЧЕМУ ЭТО ПИН, А НЕ ЗАПРОС ─────────────────────────────────────────────
 *
 * «Последняя стабильная» вычисляется НЕ в момент установки: за версией ходят в
 * сеть, а резолверу в сеть нельзя (см. шапку). Поэтому версия двигается вместе
 * с версией обвеса — видно в диффе, видно в ревью, одинаково на любой машине и
 * в оффлайне. Пользовательская модель при этом та же (`kb:BASER2-5`): не
 * заполнил — идёшь за нами; «за нами» означает «за нашим выпуском», а не «за
 * календарём».
 *
 * ── КОГДА ЭТО ЧИСЛО ПОРА ДВИГАТЬ ────────────────────────────────────────────
 *
 * Когда следующая чётная линия входит в Active LTS (ближайшая точка —
 * 2026-10-20, Node 26) И семейство образа опубликовало соответствующий тег.
 * Движение дефолта дверь назовёт потребителю до применения («подниму версию с
 * 24 на 26») — спрашивать она не будет и не должна.
 */
export function latestStableNode() {
  return '24';
}

