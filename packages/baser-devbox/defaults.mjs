/**
 * ВЫЧИСЛЯЕМЫЕ ДЕФОЛТЫ ОБВЕСА ДЕВБОКСА.
 *
 * Резолвер — функция САМОГО обвеса: станок её только зовёт и не знает, что она
 * считает (`kb:BASER2-4` — станок держит хвостовик, не инструмент). Контекст
 * даёт дверь: `{ repo: { name, root }, source: { id, packageName, version } }`.
 *
 * Три обязательства, и они не стилистические
 * (`packages/baser-contracts/README.md` §3):
 *
 * 1. **Синхронно.** Вернувший обещание резолвер — отказ `resolver-async`.
 * 2. **Чисто и без сети.** Дефолт, ездящий по календарю или по ответу реестра,
 *    ломает воспроизводимость коммита: один и тот же код поднимался бы
 *    по-разному завтра и в оффлайне.
 * 3. **Конкретное значение, а не `latest`** (`kb:BASER2-5`). В артефакт
 *    попадает число.
 *
 * Файл публикуется В СОСТАВЕ ПАКЕТА как есть (`files: ["defaults.mjs"]`) и
 * ничего не собирает: `defaultFrom` дверь резолвит путём внутри распакованного
 * пакета, а не через `exports`, поэтому «собранный dist» здесь означал бы, что
 * обвес не работает до сборки — то есть не работает у потребителя.
 */

/** Имя репозитория — базис для остальных имён; он же алиас в docker-сети. */
export function repoName(ctx) {
  return ctx.repo.name;
}

/** Имя девбокса: `<репозиторий>-devbox`. Пользователь не вводит ничего. */
export function devboxName(ctx) {
  return `${ctx.repo.name}-devbox`;
}

/**
 * Версия Node в базовом образе — ПИН, поставленный при выпуске этого обвеса.
 *
 * ── ОТКУДА ВЗЯЛОСЬ ЧИСЛО ────────────────────────────────────────────────────
 *
 * `24`. Решение owner-devbox на выпуск 0.1.0 (2026-07-27), два независимых
 * основания, и оба проверяемы:
 *
 * 1. **Node 24 «Krypton» — Active LTS на дату выпуска.** По графику релизов
 *    Node.js: 24 в Active LTS с 2025-10-28 по 2026-10-20, дальше maintenance до
 *    2028-04. Линия 22 ушла в maintenance 2025-10-21 — выпускать сегодня обвес
 *    с дефолтом на maintenance-линии значило бы отдавать новому потребителю
 *    заведомо стареющий рантайм. Линия 26 вышла в апреле 2026, но Active LTS
 *    станет только 2026-10-20: «последняя стабильная» — это LTS, не Current.
 * 2. **Тег реально опубликован семейством образа.** У
 *    `mcr.microsoft.com/devcontainers/typescript-node` на 2026-07-27 есть теги
 *    `18`/`20`/`22`/`24` и НЕТ `26` — семейство само идёт за LTS. Дефолт,
 *    указывающий на несуществующий тег, — сломанный девбокс, а не смелый.
 *
 * ── ПОЧЕМУ ЭТО ПИН, А НЕ ЗАПРОС ─────────────────────────────────────────────
 *
 * «Последняя стабильная» вычисляется НЕ в момент установки: за версией ходят в
 * сеть, а резолверу в сеть нельзя (см. шапку). Поэтому версия двигается вместе
 * с версией обвеса — видно в диффе, видно в ревью, одинаково на любой машине и
 * в оффлайне. Пользовательская модель при этом та же (`kb:BASER2-5`): не
 * заполнил — идёшь за нами; «за нами» означает «за нашим выпуском», а не «за
 * календарём».
 *
 * ── КОГДА ЭТО ЧИСЛО ПОРА ДВИГАТЬ ────────────────────────────────────────────
 *
 * Когда следующая чётная линия входит в Active LTS (ближайшая точка —
 * 2026-10-20, Node 26) И семейство образа опубликовало соответствующий тег.
 * Движение дефолта дверь назовёт потребителю до применения («подниму версию с
 * 24 на 26») — спрашивать она не будет и не должна.
 */
export function latestStableNode() {
  return '24';
}
