/**
 * Имя репозитория: сначала его собственная идентичность, потом — как назвали.
 *
 * Порядок и есть решение: `origin` знает репозиторий, каталог знает только
 * человек с его клоном.
 */
function repository(ctx) {
  const root = typeof ctx?.repo?.root === 'string' ? ctx.repo.root : null;
  const folder = typeof ctx?.repo?.name === 'string' ? ctx.repo.name : null;
  return (
    (root === null ? null : token(fromGitOrigin(root))) ??
    token(folder) ??
    // Сюда попадают только имена, из которых не осталось ни одного пригодного
    // символа (корень тома, каталог из одних пробелов). Пустое имя контейнера
    // — сломанный артефакт, поэтому у ответа есть дно, и оно названо.
    'workspace'
  );
}

/** Последний сегмент URL `origin` — или `null`, если его нечем узнать. */
function fromGitOrigin(root) {
  const config = gitConfigPath(root);
  if (config === null) {
    return null;
  }
  const url = originUrl(read(config));
  return url === null ? null : lastSegment(url);
}

/**
 * Путь к общему `config` репозитория — или `null`.
 *
 * `.git` бывает каталогом (обычный клон) и файлом (`git worktree`, submodule).
 * Во втором случае в нём лежит адрес служебного каталога, а настройки — общие,
 * и живут в общем каталоге, на который указывает `commondir`. Разбирать это
 * руками, а не звать `git`, — потому что резолвер не запускает подпроцессов:
 * право читать файлы рядом форма даёт, право исполнять — нет.
 */
function gitConfigPath(root) {
  const dotGit = join(root, '.git');
  const stat = statOf(dotGit);
  if (stat === null) {
    return null;
  }
  if (stat.isDirectory()) {
    return join(dotGit, 'config');
  }

  const pointer = /^gitdir:\s*(.+)$/m.exec(read(dotGit) ?? '');
  if (pointer === null) {
    return null;
  }
  const gitdir = absolute(root, pointer[1].trim());
  const common = read(join(gitdir, 'commondir'));
  return join(
    common === null ? gitdir : absolute(gitdir, common.trim()),
    'config',
  );
}

/**
 * URL удалённого `origin` из текста `.git/config`.
 *
 * Разбор ровно на ту глубину, которая нужна: имена секций и ключей git считает
 * без учёта регистра, имя подсекции — с учётом. Всё остальное в файле нас не
 * касается — чужие внутренности не судим и не переписываем.
 */
function originUrl(text) {
  if (text === null) {
    return null;
  }

  let inside = false;
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line === '' || line.startsWith('#') || line.startsWith(';')) {
      continue;
    }
    if (line.startsWith('[')) {
      inside = /^\[remote\s+"origin"\]$/i.test(line);
      continue;
    }
    if (!inside) {
      continue;
    }
    const url = /^url\s*=\s*(.+)$/i.exec(line);
    if (url !== null) {
      return url[1].trim().replace(/^"(.*)"$/, '$1');
    }
  }
  return null;
}

/**
 * Имя репозитория внутри адреса: `git@host:omnifield/weber.git` → `weber`.
 *
 * Разделителем работает и `:` — в scp-подобном адресе (`host:owner/repo`) пути
 * как такового нет. Хвост `.git` снимается: это суффикс адреса, а не часть
 * имени.
 */
function lastSegment(url) {
  const trimmed = url
    .replace(/[/\\]+$/, '')
    .replace(/\.git$/i, '')
    .replace(/[/\\]+$/, '');
  const cut = Math.max(
    trimmed.lastIndexOf('/'),
    trimmed.lastIndexOf('\\'),
    trimmed.lastIndexOf(':'),
  );
  return cut === -1 ? trimmed : trimmed.slice(cut + 1);
}

/**
 * Пригодное имя контейнера и сетевого алиаса — или `null`.
 *
 * Значение едет в `--network-alias`, то есть становится ИМЕНЕМ В DNS: docker
 * принимает `[a-zA-Z0-9][a-zA-Z0-9_.-]*`, метка DNS не длиннее 63 символов.
 * Непригодное значение — это не «некрасиво», это контейнер, который не
 * поднимется, поэтому чистка здесь, а не в шаблоне: артефакт обязан приезжать
 * рабочим.
 *
 * Scope снимается отдельным правилом, а не общей заменой символов:
 * `@omnifield/weber` должен стать `weber`, а не `omnifield-weber` (в имени
 * контейнера и в алиасе scope не значит ничего). Манифест мы не читаем, но
 * scope-подобная форма приходит и из адреса, и из имени каталога.
 */
function token(value) {
  if (typeof value !== 'string') {
    return null;
  }
  const cleaned = value
    .trim()
    .replace(/^@[^/\\]+[/\\]/, '')
    .replace(/[^a-zA-Z0-9_.-]+/g, '-')
    .replace(/^[^a-zA-Z0-9]+/, '')
    .slice(0, 63)
    .replace(/[^a-zA-Z0-9]+$/, '');
  return cleaned === '' ? null : cleaned;
}

function absolute(base, path) {
  return isAbsolute(path) ? path : resolve(base, path);
}

/** Чтение, которое не бросает: нечитаемое просто не участвует в ответе. */
function read(path) {
  try {
    return readFileSync(path, 'utf-8');
  } catch {
    return null;
  }
}

function statOf(path) {
  try {
    return statSync(path);
  } catch {
    return null;
  }
}
