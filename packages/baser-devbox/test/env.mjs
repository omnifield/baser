/**
 * ОКРУЖЕНИЕ ФИКСТУР ЭТОЙ ЗОНЫ: СОБРАННОЕ, А НЕ УНАСЛЕДОВАННОЕ.
 *
 * Пробы зоны исполняют настоящие команды — установку зависимостей, `pnpm store path`,
 * проверку доступа к реестру, — и все они изображают КОНТЕЙНЕР. Постсоздание девбокса
 * выполняется не из-под прогона тестов, и наследовать ему от прогона нечего.
 *
 * ── ЗА ЧТО ЭТО ЗАПЛАЧЕНО ────────────────────────────────────────────────────
 *
 * Раньше в каждой пробе стоял свой ЧЁРНЫЙ СПИСОК: взять `process.env` и вычистить
 * `npm_config_*`. Он держал ровно то, о чём мы успели подумать, — и потому не удержал.
 * В GitHub Actions в окружении лежит `CI=true`; pnpm, увидев его, подтверждений не
 * спрашивает ВОВСЕ. Негативный контроль постсоздания (`post-create-install.spec.mjs`)
 * требует, чтобы вопрос прозвучал, — и в CI он позеленел на пустом месте, при зелёном
 * локальном verify (`tasker:BASER2-125`, PR #51 красным).
 *
 * Утверждение, которое из этого следует и стоит того, чтобы стоять здесь текстом:
 * **фикстура, унаследовавшая чужое окружение, перестаёт мерить то, ради чего заведена**
 * — и заметно это становится не там, где её писали. Чёрный список тут не «недостаточно
 * полный», он неверен по устройству: перечислять приходится ЧУЖОЕ, которого мы не
 * видели, а машина прогона меняется без нашего участия.
 *
 * Тот же список уже подводил и раньше, другой стороной (`registry.spec.mjs`): прогон
 * идёт из-под `npx`, а тот экспортирует `npm_config_*` — в том числе `npm_config_prefix`
 * и `npm_config_globalconfig`, указывающие на общий npmrc машины. Строчные `npm_config_*`
 * БЬЮТ одноимённые UPPERCASE-переменные, поэтому клетка из `NPM_CONFIG_PREFIX` выглядела
 * клеткой и не держала: мутация «`--location=user` → `--location=global`» всё равно
 * писала приватный реестр на машину. Белый список закрывает обе стороны разом.
 *
 * ── БЕЛЫЙ СПИСОК ────────────────────────────────────────────────────────────
 *
 * Поэтому наследуется только то, без чего команду не запустить вовсе, и каждый пункт
 * назван причиной:
 *
 * - `PATH` — где лежит менеджер пакетов (его же ищет `/bin/sh -c`);
 * - `HOME` — кэш менеджера и его пин версии (`packageManager`); без него pnpm тянул бы
 *   пин заново в несуществующий каталог.
 *
 * Всё остальное, что пробе нужно, она называет САМА — и видно это в её коде, а не в
 * окружении машины. `npmrc` пользователя, приезжающий вместе с `HOME`, пробы шпилят
 * своим `NPM_CONFIG_USERCONFIG` — клетка вокруг конфига остаётся на них.
 */

/** Переменные прогона, которые фикстуре зоны действительно нужны. */
const INHERITED = ['PATH', 'HOME'];

/**
 * Окружение для команды, изображающей контейнер: белый список + названное пробой.
 *
 * @param {Record<string, string>} named переменные, которые проба задаёт осознанно
 */
export function containerEnv(named = {}) {
  const base = {};
  for (const key of INHERITED) {
    if (process.env[key] !== undefined) {
      base[key] = process.env[key];
    }
  }
  return { ...base, ...named };
}
