/**
 * Версия схемы вывода ДВЕРИ.
 *
 * У движка уже есть `OUTPUT_SCHEMA_VERSION`, у формы — `FORM_VERSION`. Третий
 * номер здесь не дублирует их, а версионирует то, чего нет ни у кого из них:
 * **обёртку прогона** — что дверь прочитала, какие значения разрешила, какое
 * движение дефолта назвала и что сбросила на диск.
 *
 * Три номера, а не один, потому что зоны выпускаются порознь: движок может
 * поднять свою схему, не тронув форму ответа двери, и наоборот. Один общий
 * номер заставлял бы потребителя перепроверять всё при движении любой части —
 * то есть не значил бы ничего.
 *
 * Все три едут в ответе вместе (`DoorResult`): потребитель обязан видеть, по
 * какой версии каждой зоны собран этот конкретный ответ, а не выяснять это по
 * симптомам.
 *
 * **2 — дверь проходит по ВСЕМ обвесам** (`tasker:BASER2-55`). Обвесов в
 * репозитории может быть сколько угодно (`kb:BASER2-4`), а прогон движка идёт по
 * одной декларации — поэтому прогонов столько же, сколько обвесов, и они уехали
 * в `runs` по одному на обвес. Сняты `source`, `settings`, `plan`, `applied` на
 * верхнем уровне: поля, называвшие ОДИН обвес, при двух отвечали бы про первый и
 * молчали про второй. Снят и код отказа `multiple-sources` — вместе с причиной, а
 * не подавлением: движок научился вести владение по каждому обвесу отдельно
 * (`tasker:BASER2-7`). Потребитель, читавший снятые поля, обязан это увидеть, а
 * не промахнуться молча.
 *
 * **3 — прогон несёт ЦЕНУ движения** (`tasker:BASER2-98`, `tasker:BASER2-112`).
 * У прогона появились два списка: `derived` — слова артефакта, переезжающие
 * вместе с названным значением (адрес тома считается от настройки, а в томе
 * лежит положенное руками), и `differences` — построчное расхождение с ЧУЖИМ
 * файлом там, где он лежит на пути обвеса. Изменение ДОБАВЛЯЮЩЕЕ: ни одно поле
 * не снято и не переименовано, читавший прежние поля читает их как прежде.
 * Номер поднят всё равно — по нему потребитель узнаёт, есть ли в ответе эти
 * списки вовсе, а не выясняет это по их пустоте (пустой список законен и у
 * двери, которая умеет их считать).
 *
 * **4 — ответ несёт ВОПРОС, который ему задали** (`tasker:BASER2-135`). Поле
 * `difference` говорит, снят ли предел показа (`--difference`). Оно отвечает
 * двум читателям на один вопрос: гейту — полны ли списки `gone` и `comes` или
 * усечены (счётчики говорят, сколько строк ВСЕГО, но не говорят, усекали ли), а
 * человеку — почему прогон с флагом выглядит ровно так же, как без него.
 * Расхождение считается только для ЧУЖОГО файла, и там, где чужого нет, флаг
 * получал в ответ молчание — то есть читался как невыполненное обещание.
 * Ответить дверь может лишь тем, что есть в ответе: чего здесь нет, того рендеру
 * показать нечем.
 *
 * **Тем же номером едет третий код отказа — `unrecorded-dest`**
 * (`tasker:BASER2-134`). Состояний «файлы оказались чужими» три, а называла
 * дверь два: оба прежних кода привязаны к репозиторию, и там, где запись есть и
 * верна, а спорных путей в ней нет, не срабатывал ни один. Номер один на оба
 * изменения, потому что один и выпуск: потребитель, читающий схему, узнаёт по
 * нему и про поле, и про новое слово в перечислении кодов.
 *
 * Оба изменения ДОБАВЛЯЮЩИЕ: ни одно поле и ни один код не сняты и не
 * переименованы, и ни у одного не сменился смысл. Читавший прежнюю схему читает
 * её как прежде.
 *
 * **5 — прогон несёт ПОСТАВКУ: откуда она и почему эта версия**
 * (`tasker:BASER2-146`). Обвес больше не ищется среди того, что положил пакетный
 * менеджер потребителя, — поставку достаёт сама дверь, в кэш снаружи локации
 * (`kb:BASER2-22`). Значит выбор версии стал РЕШЕНИЕМ ДВЕРИ, а решение, о котором
 * читатель ответа узнаёт постфактум, ничем не лучше молча поднятого дефолта:
 * `runs[].source.supply` называет, чем версия определилась (закреплена в
 * перечне · записана паспортом укладки · последняя доступная · названный каталог
 * дев-петли), ходили ли за ней на склад и где она лежит в кэше.
 *
 * Тем же номером едут пять новых кодов отказа — `supply-unreachable`,
 * `supply-not-published`, `supply-fetch-failed`, `supply-local-missing`,
 * `package-manager-missing`. Доставание — единственная фаза двери, которая ходит
 * по сети, и раньше отказать на ней было нечем: пакет либо лежал у потребителя,
 * либо нет. Пять кодов, а не один, потому что чинятся они в пяти разных местах —
 * токен, перечень, среда, командная строка и «склад сказал что-то ещё».
 *
 * **Поле `supply` ОБЯЗАТЕЛЬНОЕ**, и это ЛОМАЮЩЕЕ изменение формы ответа: у
 * прогона, дошедшего до объявления обвеса, поставка есть всегда — «не знаю,
 * откуда взял» здесь не состояние, а дефект. Читатель, собиравший `SourceReport`
 * сам (гейт, проба соседа), узнаёт об этом красным при сборке, а не молчаливым
 * `undefined` в ответе.
 *
 * **6 — поставка берётся ПО МЕТКЕ КАНАЛА** (`tasker:BASER2-178`, контракт
 * `kb:BASER3-26`). Локация вправе сказать «дай последнее из дев-канала», не
 * зная номера: у записи перечня появилось поле `channel` (форма 5), и у
 * `runs[].source.supply.origin` — новое состояние `channel` с двумя концами,
 * меткой и номером, который за ней стоит СЕГОДНЯ. Оба обязательны: одной
 * меткой не сказать, чем разложили, одним номером — что укладка движущаяся.
 *
 * Тем же номером у состояния `pinned` появилось необязательное поле
 * `beatsChannel`: номер и метка в одной записи законны вместе, номер бьёт
 * метку, и проигравшая метка НАЗЫВАЕТСЯ. Без неё выбор между двумя словами
 * человека делался бы молча — то есть ровно так, как этой зоне запрещено.
 *
 * И тем же номером едет код отказа `supply-channel-unknown`: склад знает
 * пакет, а метки у него нет. Отдельный код, потому что тихий откат на
 * стабильную здесь запрещён — он разложил бы локацию не тем, что у неё
 * написано, и назвал бы это успехом.
 *
 * Изменение ДОБАВЛЯЮЩЕЕ: ни одно поле не снято и не переименовано, ни у одного
 * не сменился смысл. Читатель, разбирающий `origin` по `kind`, обязан узнать
 * про новое состояние — иначе он промахнётся молча, и узнаёт он про него по
 * этому номеру, а не по первой встреченной незнакомой метке.
 *
 * **7 — у консоли появился ВТОРОЙ ответ: привязка поставки** (`tasker:BASER2-201`).
 * Команда `add` объявляет поставку и применяет её, и отвечает она `AddResult` —
 * обёрткой над двумя ответами: `declared` от способности движка и `door` от
 * прогона. Прогон при этом не тронут ни на поле: `DoorResult` шестой версии
 * читается седьмой как прежде.
 *
 * Номер поднят всё равно, и не ради порядка: по нему читатель узнаёт, отвечает
 * ли эта консоль на `add` вовсе. Иначе единственный способ выяснить — позвать
 * команду и разобрать «неизвестная команда» из потока, то есть ветвиться по
 * тексту там, где для этого есть число.
 *
 * Тем же номером в перечень кодов отказа входят коды СПОСОБНОСТЕЙ движка
 * (`CapabilityProblemCode`, `pin-ambiguous` в их числе): консоль их не
 * переупаковывает — своего слова про названное дважды закрепление у неё нет.
 *
 * **8 — у записи на диск появилось ЧЕТВЁРТОЕ слово: `CHMOD`**
 * (`tasker:BASER2-223`, решение `kb:BASER3-36`). Паспорт укладки помнит теперь и
 * то, что baser сделал с файлом, поэтому расхождение бывает ТОЛЬКО по режиму:
 * содержимое сошлось, а бит разошёлся. Такая работа состоялась — и называется
 * своим словом, а не `UPDATE`: «обновлён» на файле, содержимое которого не
 * менялось, отправляет человека искать правку, которой нет.
 *
 * Изменение ДОБАВЛЯЮЩЕЕ: ни одно поле не снято и не переименовано. Но читатель,
 * ветвящийся по `writes[].kind`, обязан узнать про новое слово — и узнаёт он про
 * него по этому номеру, а не по первому встреченному незнакомому виду записи.
 */
export const DOOR_SCHEMA_VERSION = 8;

export type DoorSchemaVersion = typeof DOOR_SCHEMA_VERSION;
