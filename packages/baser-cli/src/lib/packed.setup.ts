/**
 * ОБВЕС СОБИРАЕТСЯ ОДИН РАЗ НА ПРОГОН, а не в первой пробе каждого файла.
 *
 * Приёмка зоны берёт обвес из ТАРБОЛА настоящего пакета (`npm pack`), и это
 * решение не пересматривается: между «файл лежит в репозитории» и «файл приехал
 * потребителю» стоит `files` из `package.json` (`devbox.fixture.ts`). Пересмотру
 * подлежало другое — КОГДА этот тарбол собирается.
 *
 * ## Что было и чем это стоило (`tasker:BASER2-189`)
 *
 * Сборка была ленивой и памятилась на модуль. Модульный реестр у vitest свой на
 * КАЖДЫЙ файл проб (изоляция включена), значит память не переживала файл: из
 * десяти файлов зоны, которые ставят девбокс, каждый собирал тарбол заново — и
 * платила за это ПЕРВАЯ проба файла, потому что позвали её первой.
 *
 * Замерено 2026-08-05 в девбоксе (4 ядра):
 *
 * ```
 * первая installDevbox = 264 мс, вторая = 1 мс     ← вся цена в первом вызове
 * npm pack + tar в одиночку   = 254 · 274 · 255 мс
 * то же самое, 8 одновременно = 480 … 739 мс       ← цена растёт с нагрузкой
 * ```
 *
 * Конвейер поймал ровно это (PR #88, 2026-08-05): три пробы упали по таймауту, и
 * все три — ПЕРВАЯ проба своего файла (`acceptance.spec.ts:90`,
 * `many-tools.spec.ts:158`, `supply.spec.ts:151`). Перезапуск того же коммита
 * прошёл зелёным.
 *
 * ## Почему это снятие общего ресурса, а не ускорение
 *
 * Тот же класс дефекта зона уже лечила (`tasker:BASER2-156`), и лечила так же:
 * не сроком ожидания, а тем, что общего ресурса не остаётся. Здесь общий ресурс
 * — сама подготовка: один и тот же тарбол собирался десять раз, каждый раз в
 * чужом бюджете. Теперь он собирается один раз на прогон, до первой пробы,
 * снаружи всякого теста — и в бюджете проб его нет вовсе, ни у первой, ни у
 * десятой.
 *
 * Прибавка в том, что цена перестала быть СЛУЧАЙНОЙ: раньше её платил тот, кому
 * не повезло начаться первым, и по одной пробе на файл вело себя иначе, чем все
 * остальные, — а различие такого рода в пробе читается как её собственная
 * дороговизна.
 */

import { mkdtempSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { TestProject } from 'vitest/node';
import { runSealed } from './sealed.fixture.js';

declare module 'vitest' {
  interface ProvidedContext {
    /** Каталог с содержимым тарбола обвеса: то и только то, что уедет. */
    packedDevbox: string;
  }
}

const here = dirname(fileURLToPath(import.meta.url));
const DEVBOX_SOURCE = resolve(here, '../../..', 'baser-devbox');

/**
 * Собирает обвес до первой пробы и отдаёт каталог всем файлам прогона.
 *
 * Внешние процессы идут через герметичный вход зоны (`sealed.fixture.ts`) — то
 * же правило, что и у проб: `npm`, унаследовавший окружение хука, ушёл бы
 * работать в чужой репозиторий (`tasker:BASER2-179`). Подготовка стоит раньше
 * проб, но снаружи их бюджета — значит правило к ней применимо ровно так же.
 *
 * `--ignore-scripts`: обвес это содержимое, а не код, собирать ему нечего, и
 * молчаливо исполнить чужой lifecycle-скрипт ради фикстуры мы не согласны.
 */
export default function setup(project: TestProject): () => void {
  const box = mkdtempSync(join(tmpdir(), 'baser-cli-pack-'));

  runSealed(
    'npm',
    ['pack', '--ignore-scripts', '--pack-destination', box, DEVBOX_SOURCE],
    { cwd: DEVBOX_SOURCE, stdio: 'pipe' },
  );

  const tarball = readdirSync(box).find((name) => name.endsWith('.tgz'));
  if (tarball === undefined) {
    throw new Error(`npm pack не оставил тарбол в ${box}`);
  }
  runSealed('tar', ['-xzf', join(box, tarball), '-C', box], { stdio: 'pipe' });

  project.provide('packedDevbox', join(box, 'package'));

  return () => rmSync(box, { force: true, recursive: true });
}
