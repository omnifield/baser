/**
 * `add` — ОБЪЯВИТЬ ПОСТАВКУ И ПРИМЕНИТЬ. Обёртка, а не механика.
 *
 * Первая поверхность пользователя, которой у консоли не было (`kb:BASER3-33`):
 * `plan` и `apply` работают против УЖЕ написанного `baser.json`, а в пустой
 * локации его нечем создать — первый шаг любого сценария делался руками
 * (`kb:SANDBOX-4`). Способность, которая его закрывает, живёт в ДВИЖКЕ
 * (`declareSupply`), и выбор этот не про удобство раскладки: консоль — один из фронтов, и
 * написанное в ней интерфейсу не достанется.
 *
 * Здесь поэтому нет ни одного решения. Две вещи, которые делает этот файл, —
 * работа раннера и больше ничья: **дать способности дерево** (движок файловой
 * системы не касается вовсе) и **сбросить объявление на диск**, чтобы применение
 * увидело его там же, где увидит человек.
 *
 * ```
 * declareSupply.run(дерево, {use, channel?, version?})   ← движок, Э1
 *          ↓ сброс объявления на диск                     ← консоль, единственная её работа
 * run({command: 'apply'})                                 ← существующее применение
 * ```
 *
 * ## Объявить И ПРИМЕНИТЬ — одной командой, а не двумя
 *
 * Решение user (`tasker:BASER2-201`): привязка модуля означает, что он
 * заработал. Объявление, после которого человек обязан позвать вторую команду,
 * оставляет локацию в состоянии «сказано, но не сделано» — и это состояние
 * ничем не лучше того, от которого уходит вся работа.
 *
 * ## Объявление ОСТАЁТСЯ, даже когда применение отказало
 *
 * Соблазн честный: применение проходит целиком либо никак, значит и объявление
 * надо бы откатить. Откат здесь неверен, и вот чем это доказывается — конфликтом
 * владения. Применение отказало `foreign-dest`, чинится это подтверждением
 * (`baser apply --confirm <путь>`), а подтверждение адресуется поставке, которая
 * ОБЪЯВЛЕНА. Откатив запись, консоль сделала бы починку невозможной: человек
 * вернулся бы к `add`, который снова объявил бы и снова откатил.
 *
 * Поэтому объявление на диске остаётся, а текст называет это вслух — молчаливо
 * оставленная запись читалась бы как след неудавшегося прогона.
 *
 * ## Отказ способности назван ДО применения — по построению, а не по порядку
 *
 * Способность пишет в ВИРТУАЛЬНОЕ дерево (`tree.ts`), а на диск его сбрасывает
 * этот файл. Значит отказавшая способность не оставляет за собой ничего: сброса
 * не было, применения не было, локация не тронута. Двойное закрепление
 * (`--channel` и `--version` разом) отказывает именно так — и отказывает СЛОВОМ
 * ДВИЖКА (`pin-ambiguous`), а не вторым таким же решением, принятым здесь.
 */

import {
  createTrace,
  declareSupply,
  type DeclareSupplyInput,
  type DeclareSupplyOutcome,
  type TraceSpan,
} from '@omnifield/baser-materialize';
import type { DoorProblem } from './problems.js';
import { readRepo } from './repo.js';
import { exitCodeOf, type DoorResult } from './result.js';
import { run } from './run.js';
import { DOOR_SCHEMA_VERSION } from './schema.js';
import { createRepoTree } from './tree.js';

export interface AddOptions {
  /** Имя пакета поставки — уезжает способности как есть, консоль его не читает. */
  readonly use: string;
  /** Метка канала; взаимоисключающа с номером — решает это движок, не консоль. */
  readonly channel?: string;
  /** Точный номер; взаимоисключающ с меткой. */
  readonly version?: string;
  /** Корень локации: откуда позвали либо `--cwd`. */
  readonly cwd: string;
  /**
   * Корень кэша поставок — тот же вход, что и у прогона.
   *
   * Уезжает применению нетронутым: своего кэша у `add` нет и быть не может.
   */
  readonly cache?: string;
}

/**
 * Ответ `add` — ДВА ответа двух механик, а не один свой поверх них.
 *
 * Обёртка тонкая, и ответ у неё такой же: объявление отдаёт движок
 * (`DeclareSupplyOutcome`), применение — прогон (`DoorResult`), и оба лежат
 * здесь целыми. Слить их в одну структуру значило бы предъявить ответ, которого
 * не считала ни одна из механик, — ровно то, чего не делает и `renderText` с
 * планами двух обвесов (`result.ts`).
 */
export interface AddResult {
  /** Версия формы ответа консоли — тот же номер, что у прогона. */
  readonly doorSchemaVersion: number;
  /**
   * Что случилось с объявлением локации; `null` — способность отказала.
   *
   * Отказ при этом лежит в `problems`, а не здесь: «объявления нет» и «объявить
   * не вышло» — разные состояния, и различать их пустотой поля значило бы
   * заставить читателя гадать по соседнему списку.
   */
  readonly declared: DeclareSupplyOutcome | null;
  /**
   * Применение; `null` — до него не дошло.
   *
   * Дойти оно может не всегда: отказавшая способность оставляет локацию
   * нетронутой, и применять там нечего. Пустой `DoorResult` на этом месте
   * рассказал бы про прогон, которого не было.
   */
  readonly door: DoorResult | null;
  /**
   * Отказы, которым больше негде лежать: способности и сброса объявления.
   *
   * Отказы применения живут в `door.problems` и сюда не копируются: вторая
   * правда об одном событии расходится с первой молча.
   */
  readonly problems: readonly DoorProblem[];
  /**
   * Спаны фаз КОНСОЛИ — здесь ровно один: сброс объявления на диск.
   *
   * Своё отдельно от чужого, тем же правилом, что у прогона: трейс способности
   * лежит в `declared.trace`, трейс применения — в `door.trace`. Свести их в
   * один список значило бы, что прогон, подорожавший на складе, указывает на
   * «где-то в add».
   */
  readonly trace: readonly TraceSpan[];
}

/**
 * Объявить поставку в локации и применить.
 *
 * Бросков наружу не делает: сбой — тоже ответ, как и у прогона (`run.ts`).
 */
export async function add(options: AddOptions): Promise<AddResult> {
  const repo = readRepo(options.cwd);
  const tree = createRepoTree(repo.root);
  const trace = createTrace();

  // Вход уезжает способности КАК ЕСТЬ. Ни проверки пары «метка + номер», ни
  // нормализации имени пакета здесь нет намеренно: и то, и другое — решения, а
  // решения принимает движок. Необязательные поля не подставляются пустыми —
  // «не названо» и «названо пустым» это разные утверждения.
  const input: DeclareSupplyInput = {
    use: options.use,
    ...(options.channel === undefined ? {} : { channel: options.channel }),
    ...(options.version === undefined ? {} : { version: options.version }),
  };

  const declared = declareSupply.run(tree, input);
  if (!declared.ok) {
    // Способность пишет в виртуальное дерево, а сбрасывает его этот файл: на
    // диск не ушло ничего, применения не было, локация не тронута.
    return {
      doorSchemaVersion: DOOR_SCHEMA_VERSION,
      declared: null,
      door: null,
      problems: declared.problems,
      trace: trace.snapshot(),
    };
  }

  try {
    trace.span('add.flush', () => tree.flush(), {
      at: declared.value.at,
      change: declared.value.change,
    });
  } catch (cause) {
    // Тот же код, что у сброса прогона: событие одно и то же — дерево не легло
    // на диск. Своего второго слова для него консоль не заводит.
    return {
      doorSchemaVersion: DOOR_SCHEMA_VERSION,
      declared: declared.value,
      door: null,
      problems: [
        {
          code: 'flush-failed',
          at: declared.value.at,
          message:
            `объявление на диск не легло: ${describe(cause)}. ` +
            'Применения не было — локация осталась такой же, какой была',
        },
      ],
      trace: trace.snapshot(),
    };
  }

  // Применение читает объявление с ДИСКА — там же, где его прочитает человек и
  // следующий прогон. Передать его прогону в памяти значило бы применить не то,
  // что лежит в локации, а то, что консоль подумала.
  const door = await run({
    command: 'apply',
    cwd: repo.root,
    ...(options.cache === undefined ? {} : { cache: options.cache }),
  });

  return {
    doorSchemaVersion: DOOR_SCHEMA_VERSION,
    declared: declared.value,
    door,
    problems: [],
    trace: trace.snapshot(),
  };
}

/**
 * Код возврата `add` — производная от двух ответов, а не третий признак.
 *
 * Словарь тот же, что у прогона (`exitCodeOf`): применение отвечает за себя
 * само, а до применения не дошло — значит вход непригоден, и это `2`. Своего
 * числа `add` не заводит: гейт, которому пришлось бы знать четвёртый код ради
 * одной команды, разбирал бы их по одному на догадку.
 */
export function addExitCode(result: AddResult): number {
  return result.door === null ? 2 : exitCodeOf(result.door);
}

function describe(cause: unknown): string {
  return cause instanceof Error ? cause.message : String(cause);
}
