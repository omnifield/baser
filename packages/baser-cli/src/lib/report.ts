/**
 * ЧТО ОСТАЁТСЯ ЧЕЛОВЕКУ — ЖАНР, а не одно сообщение (`tasker:BASER2-99`).
 *
 * Место, где консоль говорит, чего она не сделает сама: прогон верный, а работа
 * остаётся. Половин у блока две, и приходят они с РАЗНЫХ сторон:
 *
 * - **слово самого обвеса** про своё применение в этой локации (`renderWarning`,
 *   последнее звено шва `tasker:BASER2-226`) — причину знает только он;
 * - **пересоздание запущенного и обещание соседям** (`renderRebuild`) — это
 *   консоль знает сама и говорит своим голосом.
 *
 * Заголовок у них ОДИН, потому что событие одного рода: «сделано верно, но тебе
 * ещё предстоит». Два заголовка подряд читались бы как два разных исхода
 * прогона, а исход один.
 *
 * Блок печатается там, где есть ПРЕДМЕТ: пусты обе половины — нет и блока.
 * Заголовок-заготовка на каждом прогоне за неделю перестаёт читаться, и
 * обесценивает он не себя, а то предупреждение, ради которого однажды
 * напечатается (`tasker:BASER2-135`).
 */
function renderRemains(run: SourceRun): string[] {
  const remains = [...renderWarning(run), ...renderRebuild(run)];
  if (remains.length === 0) {
    return [];
  }
  return ['', REMAINS_HEAD, ...remains];
}

const REMAINS_HEAD =
  'остаётся человеку — консоль этого не делает и делать не начнёт:';

/** Есть ли у прогона этот блок — и, значит, есть ли на что ссылаться итоговой строке. */
function hasRemains(run: SourceRun): boolean {
  return renderRemains(run).length > 0;
}

/**
 * ПЕРЕСОЗДАНИЕ ЗАПУЩЕННОГО И ОБЕЩАНИЕ СОСЕДЯМ — половина, которую консоль знает
 * сама (`tasker:BASER2-99`).
 *
 * Дверь кладёт файл. Старый контейнер после применения остаётся под старым
 * именем, и его надо пересоздать; соседей, ходивших на прежний сетевой алиас,
 * надо поправить. Обвес сделать этого не может — **это не его работа и не
 * работа станка** (`kb:BASER2-2` §6: пульт и триггеры запуска не наши), — но
 * молчать об этом он не вправе: обещание в тексте такой же контракт, как код.
 *
 * Здесь названо ПРАВИЛО, а не список: что именно у человека запущено по этому
 * файлу, дверь не знает и знать не может. Она называет то, что знает точно, —
 * границу собственной работы.
 *
 * Печатается ровно там, где работа остаётся: прогон переписывает файл, который
 * УЖЕ ЛЕЖИТ, — значит по нему уже что-то живёт. На первой укладке этой половины
 * нет: пересоздавать нечего. Слово обвеса при этом на первой укладке БЫВАЕТ, и
 * условия у половин поэтому свои (`tasker:BASER2-234`).
 *
 * Стоит НИЖЕ слова обвеса, и это не вкусовщина: обвес говорит про эту локацию и
 * этот прогон, а здесь названо стоячее правило про запущенное. Частное перед
 * общим — иначе фраза, ради которой заводился весь шов, оказалась бы под
 * абзацем, который человек читал вчера и позавчера.
 *
 * ## Половина СОРАЗМЕРНА тому, что поехало (`tasker:BASER2-135`)
 *
 * Двух половин у него разная цена. Пересоздание остаётся человеку ВСЕГДА, когда
 * переписывается уже лежащий файл, — это про запущенное, а не про значения.
 * Обещание соседям — про значение, видное СНАРУЖИ, и предмет у него есть только
 * там, где движение значений названо. У weber не переехало ни одно, а абзац про
 * соседей пришёл целиком и прочитался как заготовка; заготовка на месте
 * предупреждения обесценивает и само предупреждение.
 *
 * Условие сжатия — то, что дверь ЗНАЕТ ТОЧНО: назвала ли она в этом прогоне хоть
 * одно переезжающее значение. Утверждать «снаружи ничего не поехало» она не
 * вправе — прежний конец бывает недоказуем, и молчание `previous.ts` остаётся
 * молчанием (`tasker:BASER2-38`). Поэтому сжатая форма говорит именно про
 * названное, а не про репозиторий: убрать нельзя, соврать тем более.
 *
 * ## Перед пересборкой — закоммитить и ЗАПУШИТЬ (`tasker:BASER2-180`)
 *
 * Пересоздание среды человек делает руками, и блок выше уже говорит ему об этом.
 * Чего он не говорил — что пересборка меняет саму МОДЕЛЬ рабочего каталога: у
 * среды, поднимающейся клонированием в том, рабочая папка после пересборки
 * другая, и незапушенное остаётся в прежней. На первом живом переезде это стоило
 * получаса работы (2026-08-04) и худшего из исходов: человек видит чистый клон и
 * считает работу потерянной, хотя она цела в каталоге, из которого он вышел.
 *
 * **Говорит это дверь, а не сводка расхождений.** Предупреждение обязано стоять в
 * тот момент, когда человек подходит к пересборке; сводка показывается раньше —
 * там он ещё решает, применять ли, и последствие читается как описание, а не как
 * указание к следующему шагу. У двери этот жанр уже есть: она называет цену
 * изменения и границу своей работы, и предупреждение встаёт в тот же ряд.
 *
 * **Названо ПРАВИЛО, а не факт про эту локацию**, и это то же ограничение, что и
 * у всего блока. Модель рабочего каталога не выражена ни в объявлении обвеса, ни
 * в артефакте, который дверь кладёт; в git дверь не смотрит вовсе. Значит сказать
 * «тебя пересадит» она не вправе — она называет случай, при котором это
 * происходит, и цену проверки, которая дешевле потери в любом случае.
 *
 * Адресность у этого предупреждения та же, что у половины: пересборка предстоит
 * там, где переписывается уже лежащий артефакт. На первой укладке пересоздавать
 * нечего — и предупреждения нет, иначе оно приклеилось бы к каждому применению
 * и за неделю перестало бы читаться.
 */
function renderRebuild(run: SourceRun): string[] {
  if (!rewritesPlaced(run)) {
    return [];
  }

  // Названное движение — прежний конец, доказанный побайтово, либо посчитанное
  // от него слово. Ни одного — про обещание соседям говорить не о чем.
  const moved =
    run.settings.some((setting) => setting.placed !== undefined) ||
    run.derived.length > 0;

  if (!moved) {
    return [
      '  докер консоль не зовёт и контейнерами не управляет: контейнер, поднятый по прежнему',
      '  содержимому, пересоздаёшь ты. Переезжающих значений этот прогон не назвал.',
      ...BEFORE_REBUILD,
    ];
  }

  return [
    '  применение переписывает ФАЙЛ, а не то, что по нему уже запущено. Контейнер, поднятый',
    '  по прежнему содержимому, живёт под прежним именем, пока ты сам его не пересоздашь:',
    '  докер консоль не зовёт и контейнерами не управляет — это не её работа и не работа станка.',
    '  Значение, которое видно СНАРУЖИ (имя, адрес, сетевой алиас), — обещание соседям, а не',
    '  подпись для себя: сменив его, поправь и тех, кто ходил на прежнее.',
    ...BEFORE_REBUILD,
  ];
}

/**
 * СЛОВО САМОГО ОБВЕСА — последнее звено шва `tasker:BASER2-226`.
 *
 * У обвеса до формы 7 была одна громкость: бросок резолвера, валивший весь
 * прогон локации у всех обвесов сразу, — то есть выбор между «промолчать» и
 * «сломать всё». Форма завела вторую (`warningFrom`), движок донёс её планом,
 * а печатает консоль — и печатает СЮДА, а не в новый жанр: «прогон верный, но
 * человеку надо что-то знать» это ровно то, про что блок и заведён.
 *
 * ## Что здесь чьё
 *
 * Рамка — консоли, текст — обвеса, и видно это отступом: слово обвеса стоит на
 * этаж глубже и приезжает ДОСЛОВНО. Консоль его не сочиняет, не сокращает и не
 * переносит по своей ширине — она не знает ни причины, ни цены этой фразы (про
 * `core.hooksPath` знает обвес, движок про конкретные обвесы не знает по
 * построению — `kb:BASER3-34`). Отступ при этом не редактура: он про раскладку
 * страницы, а не про слова.
 *
 * **Обвес назван поимённо**, хотя блок и так стоит внутри его прогона: обвесов
 * бывает несколько (`kb:BASER2-4`), у части из них предупреждение есть, у части
 * нет, и «чьё это» обязано читаться из самой строки, а не из расстояния до
 * заголовка выше.
 *
 * ## `failed` печатается ТОЖЕ, и печатается бедой ОБСТАНОВКИ
 *
 * Проглоченная беда выглядит как исправно молчащий обвес — то самое молчание,
 * против которого поле заведено: автор обвеса считал бы, что его предупреждение
 * работает, а человек не видел бы ничего. Но и отказом она не становится: код
 * возврата считается от `status` (`result.ts`), а `status` про предупреждение не
 * знает — виновата обстановка, локацию за неё не наказывают.
 *
 * Сам отказ печатается контрактным `describeProblems`, тем же, что печатает
 * настоящие отказы: своей второй правды о чужом событии консоль не заводит. В
 * список `отказов: N` он при этом НЕ попадает — там живёт то, из-за чего прогон
 * не поехал.
 */
function renderWarning(run: SourceRun): string[] {
  const warning = run.plan?.warning;
  if (warning === undefined || warning.kind === 'none') {
    return [];
  }

  if (warning.kind === 'said') {
    return [
      `  говорит САМ обвес "${run.source.id}" — про своё применение в этой локации. Прогон при`,
      '  этом верный: предупреждение не отказ и кода возврата не меняет. Слово его, дословно:',
      // Пустая строка внутри чужого текста остаётся пустой, а не превращается в
      // отступ без слов: это тоже часть того, как обвес разбил свою мысль.
      ...warning.text
        .trimEnd()
        .split('\n')
        .map((line) => (line.trim() === '' ? '' : `    ${line}`)),
    ];
  }

  return [
    `  обвес "${run.source.id}" собирался что-то сказать и НЕ СМОГ. Это беда ОБСТАНОВКИ, а не`,
    '  отказ локации: прогон верный, код возврата прежний, а предупреждения ты не увидел —',
    '  чинится оно там, куда показывает адрес, и чинит это автор обвеса, а не ты:',
    `    ${describeProblems([warning.problem])}`,
  ];
}

/**
 * ЧТО ИЗ ЧУЖОГО ФАЙЛА НЕ ВОСПРОИЗВЕДЁТСЯ — построчно (`tasker:BASER2-112`).
 *
 * Стоит ПОСЛЕ плана, а не выше: этот блок объясняет его отказы — он читается
 * как их подробность, а вклиненный между значениями и шагами он оторвал бы
 * причину от следствия. Человеку он всё равно достаётся до решения:
 * подтверждения ещё не было, и отказ ниже прямо на него ссылается.
 *
 * Форма подачи — усечённая. Дифф бывает длинным, и вывалить чужой файл целиком
 * в лицо каждому, кто ставит обвес в живой репозиторий, значило бы сделать
 * вывод нечитаемым; поэтому показывается начало, а остаток НАЗВАН счётчиком и
 * достаётся по `--difference`. Молча обрезанный список читается как полный.
 *
 * **Слово «чужой» стоит здесь, а не только в справке** (`tasker:BASER2-135`).
 * Оно несущее: «что из твоего файла не воспроизведётся» читается как «файл в
 * твоём репозитории», тогда как речь про файл, которым обвес НЕ ВЛАДЕЕТ. Пока
 * определение жило в `--help`, текст плана отвечал на этот вопрос только тому,
 * кто уже сходил в справку.
 */
function renderDifferences(
  differences: readonly ArtifactDifference[],
): string[] {
  if (differences.length === 0) {
    return [];
  }

  const lines = [
    '',
    `чужое не воспроизведётся: ${differences.length} — чужой здесь тот файл, ` +
      'которым обвес НЕ владеет; построчно, формат при этом не разбирается',
  ];

  for (const difference of differences) {
    if (!difference.measured) {
      // «Не считали» и «расхождений нет» — разные утверждения, и второе на
      // месте первого сказало бы человеку «ничего не потеряешь» там, где дверь
      // не смотрела.
      lines.push(
        `  ${difference.dest} — расхождение НЕ СЧИТАЛОСЬ: файл двоичный либо слишком длинный`,
      );
      continue;
    }

    lines.push(
      `  ${difference.dest} — не воспроизведётся строк: ${difference.goneCount}, ляжет своих: ${difference.comesCount}`,
      ...shown(difference.gone, difference.goneCount, '-'),
      ...shown(difference.comes, difference.comesCount, '+'),
    );
  }

  return lines;
}

/**
 * ФЛАГ ЗАДАЛ ВОПРОС — ОТВЕТ ОБЯЗАН БЫТЬ (`tasker:BASER2-135`).
 *
 * `--difference` снимает усечение показа, и там, где чужой файл есть, отвечает
 * сам блок выше. А там, где чужого нет, прогон с флагом печатался БАЙТ В БАЙТ
 * так же, как без флага, — и читался как невыполненное обещание. Ответ нашёлся в
 * `--help`, но текст двери обязан отвечать сам: справка рядом с терминалом не
 * лежит.
 *
 * Печатается ТОЛЬКО по флагу — то есть тому, кто спросил. Строка «чужого нет» на
 * каждом прогоне была бы ровно тем предупреждением-заготовкой, которое за неделю
 * перестаёт читаться; но молчать в ответ на прямой вопрос — хуже.
 *
 * Условие берётся из ответа, а не из аргументов: `renderText` не видит ничего,
 * кроме `DoorResult`, и вопрос живёт там же полем `difference`.
 */
function renderDifferenceAsked(result: DoorResult): string[] {
  if (
    !result.difference ||
    result.runs.some((run) => run.differences.length > 0)
  ) {
    return [];
  }

  return [
    '',
    '--difference: показывать нечего — расхождение считается только для ЧУЖОГО файла, то есть',
    '  такого, которым обвес НЕ владеет. В этом прогоне таких нет: файл, уже взятый обвесом',
    '  во владение, чужим не считается, и расхождение по нему не считалось.',
  ];
}

/** Показанные строки одной стороны плюс честный хвост про непоказанные. */
function shown(
  lines: readonly string[],
  total: number,
  mark: string,
): string[] {
  return [
    ...lines.map((line) => `    ${mark} ${line}`),
    ...(total > lines.length
      ? [
          `    ${mark} … ещё ${total - lines.length}: целиком — тот же прогон с "--difference"`,
        ]
      : []),
  ];
}

/** Откуда значение приехало и поедет ли оно дальше за нами. */
function trace(setting: SettingMovement): string {
  const steps = setting.chain.map(source).join(', затем ');
  return setting.ours
    ? `${steps} — поедет за выпуском обвеса`
    : `${steps} — не поднимется никогда`;
}

function source(link: SettingLink): string {
  switch (link.kind) {
    case 'default':
      return 'дефолт обвеса';
    case 'computed':
      return `дефолт обвеса, посчитанный ${link.resolver}`;
    case 'preset':
      return `пресет ${link.preset}`;
    case 'filled':
      return 'заполнено тобой';
  }
}

function value(setting: SettingLink['value']): string {
  return JSON.stringify(setting);
}

function indent(text: string): string {
  return text
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');
}

