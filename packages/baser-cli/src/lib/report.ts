// ПРИВЯЗКА ПОСТАВКИ: add (`tasker:BASER2-201`)
// ───────────────────────────────────────────────────────────────────────────

/**
 * ТЕКСТ `add` — ДВА рассказа подряд, а не третий поверх них.
 *
 * Команда складывает две механики: объявление (способность движка) и применение
 * (прогон). Значит и текст складывается из их же слов — смену объявления
 * называет `describeSupplyChange` движка, прогон печатает `renderText`. Свой
 * пересказ поверх них был бы второй правдой ровно там, где обёртка обязана быть
 * тонкой.
 *
 * Своё здесь одно, и сказать это больше некому: **что стало с объявлением, когда
 * применение не прошло**. Ни движок, ни прогон об этом не знают — движок не
 * видел применения, прогон не видел объявления.
 */
export function renderAdd(result: AddResult): string {
  const lines: string[] = [];

  if (result.declared !== null) {
    lines.push(describeSupplyChange(result.declared));
  }

  if (result.problems.length > 0) {
    lines.push(
      '',
      `отказов: ${result.problems.length}`,
      indent(describeProblems(result.problems as readonly FormProblem[])),
    );
  }

  if (result.door === null) {
    // Применения не было, и человек обязан знать, ЧТО осталось в локации:
    // «отказ» без этого читается одинаково и там, где не тронуто ничего, и там,
    // где объявление уже легло.
    lines.push(
      '',
      result.declared === null
        ? 'применения не было, и на диск не ушло НИЧЕГО: объявление считается в памяти, ' +
            'а отказ назван до всякой записи — локация такая же, какой была'
        : 'применения не было: объявление на диск не легло, и причина названа выше',
    );
    return lines.join('\n');
  }

  lines.push('', renderText(result.door));
  lines.push(...remainsDeclared(result));
  return lines.join('\n');
}

/**
 * ОБЪЯВЛЕНИЕ ОСТАЁТСЯ, И ЭТО СКАЗАНО ВСЛУХ.
 *
 * Применение отказало, а запись поставки на диске лежит — молча это читалось бы
 * как след неудавшегося прогона, который человек пойдёт убирать руками. Между
 * тем откат здесь неверен: конфликт владения чинится подтверждением, а
 * подтверждение адресуется УЖЕ объявленной поставке (`add.ts`). Убрав запись,
 * консоль сделала бы починку невозможной.
 *
 * Печатается ровно там, где предмет есть, — на отказе и на конфликте. Приклеенное
 * к удачному прогону, это объяснение за неделю перестало бы читаться, как и всякое
 * предупреждение-заготовка (`tasker:BASER2-135`).
 */
function remainsDeclared(result: AddResult): string[] {
  const door = result.door;
  if (
    door === null ||
    result.declared === null ||
    (door.status !== 'refused' && door.status !== 'blocked')
  ) {
    return [];
  }

  return [
    '',
    `объявление ОСТАЁТСЯ в "${result.declared.at}" — это не след неудачи:`,
    '  сказанное тобой «поставь это» ошибкой ввода не было, отказало применение. Почини',
    '  названную выше причину и повтори тот же вызов — второй записи от этого не появится.',
    '  Конфликт владения разрешается подтверждением ("baser apply --confirm <путь>"), и',
    '  адресуется оно ОБЪЯВЛЕННОЙ поставке: снятое объявление сделало бы починку',
    `  невозможной. Передумал — убери запись из "${result.declared.at}" руками.`,
  ];
}

// ───────────────────────────────────────────────────────────────────────────
// ПОДГОТОВКА ОБВЕСА К ВЫДАЧЕ: check · pack · bundle
//
// Те же правила, что и у рендера прогона. Механики живут в соседних зонах, и
// дверь их ответы НЕ пересказывает: коды и адреса печатаются как есть тем же
// `describeProblems` контрактов, каким печатает свои. Второй рендер для чужих
// отказов означал бы вторую правду об одном событии.
//
// Итог слоя — НЕ исключение из этого правила, а его исполнение
// (`tasker:BASER2-155`). Пересказа тут нет: дверь не переименовывает событие и не
// заводит поверх него своей семантики, а РИСУЕТ человеку то же самое состояние
// его словом. Второй правды не появляется — статус в ответе один и прежний, по
// нему ветвятся снаружи; появляется рендер, которого до этого не было вовсе:
// машинный токен печатался человеку как есть.
//
// Объём сверки печатается всегда. `check` и `pack` считают его сами (`stages`
// со счётчиком), и ровно ради того, чтобы зелёный прогон, ничего не сверивший,
// был виден — прятать этот счётчик в человеческом выводе значило бы вернуть
// ему возможность быть незамеченным.
// ───────────────────────────────────────────────────────────────────────────

/** Строка шага: имя, состояние, объём. Форма общая у всех трёх механик. */
interface RenderedStage {
  readonly name: string;
  readonly status: string;
  readonly counted: number;
  readonly reason?: string;
}

/**
 * ЧТО ЕДЕТ ПО ПРОВОДУ И ЧТО ВИДИТ ЧЕЛОВЕК — РАЗНЫЕ СЛОВА (`tasker:BASER2-155`).
 *
 * Статус слоя машинный: по нему ветвятся снаружи — `baser-pack` считает им
 * сверенные слои, по нему же зеленеет гейт. Трогать его нельзя, это ломающее
 * для соседа (проверено при `tasker:BASER2-130`). Но дверь печатала его человеку
 * КАК ЕСТЬ, и в колонке итога `skipped` читается как несделанная работа: слово
 * говорит «пропущено», а причина рядом объясняет, что ничего не пропущено —
 * ответ верный, порядок неверный.
 *
 * ## Слово одно, потому что различать их НЕЧЕМ — и это находка, а не выбор
 *
 * Пропуск сегодня несёт три разных смысла (`tasker:BASER2-130`): мерить было
 * нечего (зелёный прогон, ПОЛНЫЙ ответ слоя) · сверять нечем на красном прогоне ·
 * состав решает не мы. Разные слова на них дверь дать не может, и вот почему:
 *
 * | что есть в ответе  | различает ли смыслы                                 |
 * | ------------------ | --------------------------------------------------- |
 * | `status`           | нет: одно слово на все три, в этом и предмет задачи |
 * | `counted`          | нет: у пропуска он `0` всегда                       |
 * | `ok` всего ответа  | нет: слой с полным ответом бывает и на красном      |
 * | `reason`           | ДА — но это свободный текст соседней зоны           |
 *
 * Различие несёт только причина, и разбирать её дверь не станет: чужая проза как
 * машинный признак — это вторая правда о чужом событии, и рассыпется она от
 * первой правки формулировки у соседа. Значит слово должно быть ОДНО и верное во
 * всех трёх случаях.
 *
 * `нет предмета` — итог, а не наша нерадивость: рендеримых записей не было ·
 * манифест не прочитан, разбирать нечего · состав никто не объявлял · нагрузка не
 * собрана, бандла из негодного обвеса не бывает. Ни в одном случае оно не
 * противоречит причине, которая стоит на той же строке, — а «пропущено»
 * противоречило.
 *
 * `ok` и `failed` остаются как есть: вопроса они не порождают, и переписывать их
 * заодно значило бы менять то, что не сломано.
 *
 * ## Отдан наружу модуля — чтобы шов сторожили СЛОВАРЁМ, а не копией фразы
 *
 * Шов «человеческое слово не течёт в машинный ответ» сторожит проба, и слово ей
 * знать обязательно. Взяв его копией — строкой в тексте пробы, — она сторожила
 * бы РОВНО ЭТУ фразу: заведи мы завтра второе человеческое слово, шов остался бы
 * открытым, а проба зелёной (`tasker:BASER2-197`). Отсюда экспорт: словарь один,
 * и проба судит по нему, а не по его вчерашнему снимку.
 *
 * Наружу ПАКЕТА он при этом не уезжает (`src/index.ts` его не перечисляет):
 * снаружи по тексту не ветвятся, там ветвятся по `status`.
 */
export const HUMAN_VERDICT: Readonly<Record<string, string>> = {
  skipped: 'нет предмета',
};

function verdictOf(status: string): string {
  return HUMAN_VERDICT[status] ?? status;
}

/**
 * Ширина колонки итога ПОСТОЯННАЯ, а не по самому длинному в этом прогоне.
 *
 * Два прогона одной команды человек читает столбцами — и прогон со пропуском не
 * должен разъезжаться с прогоном без него.
 */
const VERDICT_WIDTH = Math.max(
  ...['ok', 'failed', ...Object.values(HUMAN_VERDICT)].map(
    (word) => word.length,
  ),
);

function renderStages(stages: readonly RenderedStage[]): string[] {
  const width = Math.max(...stages.map((stage) => stage.name.length));
  return stages.map((stage) => {
    const tail = stage.reason === undefined ? '' : `  — ${stage.reason}`;
    return `  ${stage.name.padEnd(width)}  ${verdictOf(stage.status).padEnd(
      VERDICT_WIDTH,
    )} ${String(stage.counted).padStart(4)}${tail}`;
  });
}

function renderProblems(
  problems: readonly { code: string; at: string; message: string }[],
): string[] {
  if (problems.length === 0) {
    return [];
  }
  return [
    '',
    `отказов: ${problems.length}`,
    indent(describeProblems(problems as readonly FormProblem[])),
  ];
}

export function renderCheck(report: CheckReport): string {
  const lines = [
    `baser check · ${report.root}`,
    report.packageName === null
      ? '  пакет не назван'
      : `  пакет ${report.packageName}${
          report.packageVersion === null ? '' : `@${report.packageVersion}`
        }`,
  ];

  if (report.declaration !== null) {
    lines.push(
      `  обвес ${report.declaration.source.id} — ${report.declaration.source.title}`,
    );
  }

  lines.push(
    '',
    `проверено (слой · итог · сверено):`,
    ...renderStages(report.stages),
  );
  lines.push(...renderProblems(report.problems));
  lines.push(
    '',
    // Словарь канона (`kb:BASER2-9`, поправлен 2026-07-29): обвес подходит
    // ПОСАДОЧНОМУ МЕСТУ. Прежняя пара слов была расхождением внутри канона, а
    // не самодеятельностью зоны, — поэтому зона приведена следом за ним, а не
    // закрепила одно из двух чтений молча. Сама отменённая пара названа в
    // README зоны (§ «Словарь»): объяснение живёт в доке, а в уезжающих
    // потребителю модулях отменённых слов нет вовсе — это сторожит
    // `vocabulary.spec.ts`.
    report.ok
      ? 'обвес подходит посадочному месту'
      : 'обвес посадочному месту не подходит — причины выше',
  );
  return lines.join('\n');
}

export function renderPack(report: PackReport): string {
  const lines = [`baser pack · ${report.source} → ${report.target}`];

  const manifest = report.manifest;
  if (manifest !== null) {
    lines.push(
      `  обвес ${manifest.source.id} · пакет ${manifest.source.package.name}${
        manifest.source.package.version === null
          ? ''
          : `@${manifest.source.package.version}`
      }`,
      `  файлов ${manifest.files.length} · артефактов ${manifest.artifacts.length}`,
      // Состояние «не могу сказать» доезжает до человека, а не растворяется в
      // «годен»: его назвала проверка, и снял его не разбор, а npm.
      `  состав: ${manifest.shipping.claim} (решил ${manifest.shipping.decidedBy})${
        manifest.shipping.reason === undefined
          ? ''
          : ` — ${manifest.shipping.reason}`
      }`,
    );
  }

  lines.push(
    '',
    'собрано (шаг · итог · сверено):',
    ...renderStages(report.stages),
  );
  lines.push(...renderProblems(report.problems));
  lines.push(
    '',
    report.ok
      ? `нагрузка собрана: ${report.payloadRoot ?? ''}`
      : 'нагрузка не собрана — причины выше',
  );
  return lines.join('\n');
}

export function renderBundle(report: BundleReport): string {
  const lines = [`baser bundle · ${report.source} → ${report.target}`];

  if (report.runtime.length > 0) {
    const bytes = report.runtime.reduce((sum, item) => sum + item.bytes, 0);
    lines.push(
      `  вложено пакетов ${report.runtime.length}, ${Math.round(bytes / 1024)} КБ:`,
      ...report.runtime.map(
        (item) =>
          `    ${item.name}${item.version === null ? '' : `@${item.version}`}` +
          ` — ${item.files} ф., ${Math.round(item.bytes / 1024)} КБ`,
      ),
    );
  }

  lines.push(
    '',
    'собрано (шаг · итог · сверено):',
    ...renderStages(report.stages),
  );

  // Отказ упаковки печатается ЕЁ рендером: бандл его не пересказывает.
  if (!report.pack.ok) {
    lines.push('', indent(renderPack(report.pack)));
  }

  lines.push(...renderProblems(report.problems));
  lines.push(
    '',
    report.ok
      ? `бандл собран — унеси папку и прочти ${report.target}/INSTALL.md`
      : 'бандл не собран — причины выше',
  );
  return lines.join('\n');
}
