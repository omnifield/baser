/**
 * ФАЙЛ НАСТРОЕК ОБВЕСА — то, что заполняет человек, и то, что дверь ему родила.
 *
 * `baser.json` говорит, ЧТО ПОСТАВЛЕНО. `.omnifield/<поставщик>-<обвес>.yaml` —
 * КАК НАСТРОЕНО (`tasker:BASER2-10` §3). Имя файла считается из личности обвеса,
 * ссылки на него в `baser.json` нет намеренно: второе место для одного факта
 * могло бы разъехаться, а правило разъехаться не может.
 *
 * Здесь три обязательства двери, и каждое легко нарушить незаметно.
 *
 * **1. YAML читает дверь.** Контракты не читают ничего и не исполняют ничего
 * (`packages/baser-contracts/README.md`), поэтому зависимость на разборщик стоит
 * тут, а туда приезжает уже разобранное значение (`parseSourceConfig`). Формат
 * выбран человеком и ради человека: файл заполняет он, а ему нужны комментарии —
 * `title` и `description` каждой настройки обязаны лежать в файле, который он
 * открывает, а не в доке, которую он не открывает.
 *
 * **2. Дверь рождает файл ОДИН РАЗ, если его нет, и значений не пишет НИКОГДА.**
 * Родила — с закомментированными дефолтами и описаниями. После рождения не пишет
 * ни при каких условиях: на этом стоит инвариант `kb:BASER2-5` — «заполненное не
 * поднимается, потому что движку писать сюда некуда». Записать в файл посчитанный
 * дефолт значило бы заморозить его молча: обвес выпустился бы с новым, а у
 * человека остался бы вчерашний, и он бы даже не узнал, что выбирал.
 *
 * **3. Зарезервирован ровно один ключ — `baser`.** Всё остальное в файле
 * принадлежит самому инструменту: у плагина агентов там зоны, модели и адреса
 * сервисов. Дверь их не открывает и об их полях молчит — опечатки называются
 * вслух только внутри `baser.settings`. Один файл, два читателя, конфликта нет:
 * пишет в него человек, а не два поставщика.
 *
 * Файл настроек **не запись раскладки**: в паспорте укладки он не числится и
 * сиротой не бывает. Владеть тут нечем — это конфиг человека, а не наш артефакт.
 */

import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';
import {
  parseSourceConfig,
  sourceConfigPath,
  SOURCE_CONFIG_KEY,
  type SourceConfig,
  type SourceDeclaration,
} from '@omnifield/baser-contracts';
import { DoorProblemLog } from './problems.js';
import type { Repo } from './repo.js';
import type { SettingMovement } from './values.js';

/** Файл настроек одного обвеса: где он и что в нём. */
export interface SourceConfigState {
  /** Путь относительно корня репозитория — он же адрес в сообщениях. */
  readonly path: string;
  /** Файл лежал на диске до прогона. */
  readonly existed: boolean;
  /**
   * Разобранный ключ `baser`; `null` — файл есть, но непригоден.
   *
   * Отказ не отменяет остального рассказа: путь и факт существования доезжают до
   * ответа и тогда, когда разбор не удался, — иначе человек чинит вслепую.
   */
  readonly config: SourceConfig | null;
}

/**
 * Читает файл настроек обвеса. Файла нет — это не отказ, а «ничего не выбрано».
 *
 * Отсутствие означает ровно дефолты обвеса: вопросов у двери не бывает
 * (`tasker:BASER2-18`), и «не заполнено» — рабочее состояние, а не пробел.
 * Родится файл ниже по прогону, и содержимое его будет закомментировано целиком.
 */
export function readSourceConfig(
  repo: Repo,
  declaration: SourceDeclaration,
  log: DoorProblemLog,
): SourceConfigState {
  const path = sourceConfigPath(declaration.source.id);
  const absolute = join(repo.root, path);

  if (!existsSync(absolute)) {
    return { path, existed: false, config: parseEmpty(path) };
  }

  let document: unknown;
  try {
    document = parse(readFileSync(absolute, 'utf-8'));
  } catch (cause) {
    // Отказ разборщика — свой код двери: YAML читает она, и сказать про
    // сломанный отступ больше некому. Форма о существовании файла не знает.
    log.add(
      'source-config-unreadable',
      path,
      `файл настроек не разбирается как YAML: ${describe(cause)}. ` +
        'Пока он непригоден, дверь не может отличить «ничего не выбрано» от ' +
        'выбранного и молча работать по дефолтам не станет',
    );
    return { path, existed: true, config: null };
  }

  const parsed = parseSourceConfig(document, path);
  if (!parsed.ok) {
    log.addAll(parsed.problems);
    return { path, existed: true, config: null };
  }
  return { path, existed: true, config: parsed.value };
}

/**
 * Родившийся файл — весь из комментариев, кроме служебной структуры.
 *
 * Значения не пишутся ни одного: `presets` и каждая настройка стоят
 * закомментированными вместе со своим `title`, `description` и дефолтом обвеса.
 * Раскомментировать значение — это и есть заполнить настройку, и оно обязано
 * разбираться после этого без единой правки, поэтому сами строки **печатаются
 * разборщиком YAML**, а не склеиваются руками: кавычки, списки и `null` —
 * его работа, а не наши догадки о ней.
 *
 * Отступ у комментария стоит ПОСЛЕ структурного, а не в начале строки, ровно по
 * этой же причине: сняв `# `, человек получает строку на своём уровне вложенности.
 *
 * **Обещание дано БЛОКОМ, а не строкой, и это правка по следам карты**
 * (`tasker:BASER2-116`). У скаляра значение занимает одну строку, и «раскомментируй
 * строку» было верно буквально. У карты и списка оно занимает несколько, и та же
 * фраза стала неправдой: сняв решётку с одной первой строки, человек получает ключ
 * без значения (`null`), с одной вложенной — отступ, которому не к чему
 * относиться. Обещание в тексте есть контракт, поэтому исправлено оно, а не
 * человек, который ему поверил.
 *
 * Дефолт берётся из ПЕРВОГО звена движения — конца «дефолт обвеса»
 * (`values.ts`). У новорождённого файла оно же и последнее: пресетов не выбрано,
 * заполненного нет. Брать разрешённое значение было бы тем же самым сегодня и
 * враньём завтра — стоит появиться пресету по умолчанию.
 */
export function renderSourceConfig(
  declaration: SourceDeclaration,
  movements: readonly SettingMovement[],
): string {
  const { source } = declaration;
  const lines: string[] = [
    `# ${source.title} — настройки обвеса ${source.id}.`,
    '#',
    '# Файл родила дверь, потому что его здесь не было. Дальше он твой: дверь в',
    '# него не пишет НИКОГДА, поэтому заполненное не поднимается за выпусками',
    '# обвеса — писать сюда некому, кроме тебя.',
    '#',
    `# Имя файла считается из личности обвеса (${source.id}); ссылки на него в`,
    '# baser.json нет намеренно — правило разъехаться не может, ссылка могла бы.',
    '#',
    `# Ключ "${SOURCE_CONFIG_KEY}" читает дверь. Всё, что вне него, принадлежит самому`,
    '# инструменту, и дверь этого не открывает.',
    '',
    `${SOURCE_CONFIG_KEY}:`,
    ...renderPresets(declaration),
    '',
    ...renderSettings(declaration, movements),
  ];

  return `${lines.join('\n')}\n`;
}

/**
 * Пресеты — списком объявленных, но НЕ выбранными.
 *
 * Выбор пресета это значение: пресет двигает настройки, и записать его за
 * человека значило бы выбрать за него. Поэтому объявленные перечислены
 * комментарием с их назначением, а пример выбора закомментирован.
 */
function renderPresets(declaration: SourceDeclaration): string[] {
  const names = Object.keys(declaration.presets).sort();

  if (names.length === 0) {
    return ['  # Пресетов обвес не объявлял.'];
  }

  return [
    '  # Ходовые положения регулировок; следующий пресет бьёт предыдущего.',
    '  # Объявлены обвесом:',
    ...names.map(
      (name) => `  #   ${name} — ${declaration.presets[name].title}`,
    ),
    ...comment(stringify({ presets: names.slice(0, 1) }), '  '),
  ];
}

function renderSettings(
  declaration: SourceDeclaration,
  movements: readonly SettingMovement[],
): string[] {
  if (movements.length === 0) {
    return ['  # Настроек обвес не объявлял — регулировать здесь нечего.'];
  }

  const lines = [
    '  settings:',
    '    # Ничего не заполнено, и это рабочее состояние: вопросов у двери не бывает.',
    '    # Раскомментируй значение — и оно перестанет ездить за выпусками обвеса.',
    '    # Значение из НЕСКОЛЬКИХ строк (карта, список) снимается блоком целиком:',
    '    # с одной первой строки останется ключ без значения, то есть null, а с',
    '    # одной вложенной — отступ, которому не к чему относиться.',
  ];

  for (const movement of movements) {
    const spec = declaration.settings[movement.key];
    const origin = movement.chain[0];

    lines.push('', `    # ${spec.title}`);
    for (const line of (spec.description ?? '').split('\n')) {
      if (line.trim() !== '') {
        lines.push(`    # ${line.trim()}`);
      }
    }
    if (origin.kind === 'computed') {
      // Человек имеет право знать, что дефолт не написан в объявлении, а
      // посчитан обвесом: значение, которое «взялось само», иначе выглядит
      // случайным, и его заполняют, чтобы «зафиксировать», теряя обновления.
      lines.push(`    # Дефолт считает сам обвес (${origin.resolver}).`);
    }
    lines.push(...comment(stringify({ [movement.key]: origin.value }), '    '));
  }

  return lines;
}

/**
 * Комментирует готовый кусок YAML, сохраняя его отступ ОТНОСИТЕЛЬНО структуры.
 *
 * `# ` ставится после структурного отступа, а не в начале строки: человек снимет
 * ровно эти два символа и получит строку на своём уровне вложенности. Комментарий
 * с нулевым отступом заставил бы его ещё и досчитывать пробелы — а ошибка в них
 * в YAML не читается глазами.
 *
 * Держится это построчно, и потому обещание про БЛОК выполнимо: у многострочного
 * значения снятие тех же двух символов с КАЖДОЙ его строки оставляет вложенность
 * целой — внутренний отступ печатал разборщик, и в комментарий он уехал как есть.
 */
function comment(yaml: string, indent: string): string[] {
  return yaml
    .replace(/\n$/, '')
    .split('\n')
    .map((line) => `${indent}# ${line}`);
}

function parseEmpty(path: string): SourceConfig {
  // Через ту же форму, что и настоящий файл: «пустой конфиг» — её слово, а не
  // второе представление того же состояния на стороне двери.
  const parsed = parseSourceConfig(undefined, path);
  return parsed.ok ? parsed.value : { presets: [], settings: {} };
}

function describe(cause: unknown): string {
  return cause instanceof Error ? cause.message : String(cause);
}
