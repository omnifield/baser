/**
 * Отказы ДВЕРИ — данные, а не исключения.
 *
 * Форма отказа взята у контрактов целиком (`FormProblem`: код, адрес, текст) и
 * не переизобретается: дверь склеивает отказы формы, отказы движка и свои
 * собственные в один список, и потребителю, который по ним ветвится, разные
 * формы на один предмет были бы ровно тем же «двумя языками», от которого
 * избавлялась зона движка (`tasker:BASER2-23`).
 *
 * Здесь объявлены ТОЛЬКО коды, которых нет ни у формы, ни у движка. Всё, что
 * умеет назвать соседняя зона, дверь пробрасывает её кодом — своей семантики
 * поверх чужой она не изобретает (`tasker:BASER2-20`).
 */

import type { FormProblem, FormProblemCode } from '@omnifield/baser-contracts';
import type { EngineProblemCode } from '@omnifield/baser-materialize';

/**
 * Что не так на стороне двери.
 *
 * Ветвиться потребителю — по коду, не по тексту.
 *
 * **Снято в схеме двери 2: `multiple-sources`** (`tasker:BASER2-55`). Дверь
 * отказывала, когда обвесов в конфиге больше одного, и отказ был верен: план
 * строился по одной декларации, а сироты искались по всем записям манифеста —
 * второй прогон снял бы артефакты первого. Код снят ВМЕСТЕ С ПРИЧИНОЙ: движок
 * ведёт владение по каждому обвесу отдельно (`tasker:BASER2-7`), и дверь гоняет
 * прогон по каждому вместо отказа на втором. Подавления тут нет — подавить отказ
 * значило бы вернуть тихую порчу.
 *
 * Столкновение двух обвесов на один путь никуда не делось и говорит ЧУЖИМИ
 * кодами, а не своим: `artifact-shared` контрактов — когда оба ОБЪЯВИЛИ один
 * `dest`; `cross-source-dest` движка — когда путь уже числится за соседом в
 * паспорте укладки. Своего кода дверь сюда не заводит: сказать про столкновение
 * есть кому.
 */
export type DoorProblemCode =
  /** `baser.json` есть, но это не JSON. */
  | 'config-unreadable'
  /** Манифест пакета обвеса не читается или не JSON. */
  | 'package-manifest-unreadable'
  /** Пакет, названный в `use`, не резолвится из репозитория потребителя. */
  | 'package-not-found'
  /**
   * Служебной записи `baser.lock.json` нет, а конфиг потребителя есть — значит
   * раскладка здесь скорее всего уже была, а запись пропала.
   *
   * Движок этого сказать не может: для него «записи нет» — одно состояние, и он
   * честно объявляет артефакты чужими. Различает состояния конфиг потребителя —
   * сигнал, которого у движка нет и быть не должно.
   *
   * Признак не абсолютен (конфиг можно написать руками), и сообщение это
   * называет вслух, отдавая человеку дешёвую проверку вместо второй догадки.
   */
  | 'manifest-missing'
  /**
   * ПЕРВАЯ УСТАНОВКА В НЕПУСТОЙ РЕПОЗИТОРИЙ: ни конфига, ни записи, а файлы на
   * местах, куда целится обвес, уже лежат. Они не наши — они лежали до нас.
   *
   * Отдельный код, а не оттенок предыдущего: человек не потерял ничего и чинить
   * ему нечего, он выбирает. Одно сообщение на оба состояния уже соврало на
   * живом репозитории (`tasker:BASER2-28`), послав искать в истории запись,
   * которой там никогда не было.
   */
  | 'first-install'
  /**
   * Файл настроек обвеса есть, но не разбирается как YAML.
   *
   * Свой код, а не чужой: YAML читает ДВЕРЬ (`tasker:BASER2-53`) — контракты не
   * читают ничего и о существовании файла не знают, поэтому сказать про
   * сломанный отступ больше некому. Молчаливого «считаем, что ничего не
   * выбрано» тут быть не может: оно превратило бы настроенный обвес в
   * дефолтный ровно в тот момент, когда человек ошибся в своём же файле.
   */
  | 'source-config-unreadable'
  /** Шаблон объявлен раскладкой, но не читается с диска. */
  | 'template-unreadable'
  /** Подстановка значений сорвалась: шаблон не собрался. */
  | 'render-failed'
  /** Дверь не смогла вложить в бандл себя или свои зависимости. */
  | 'bundle-runtime-failed'
  /**
   * В бандле есть импорт, который резолвится наружу либо не резолвится вовсе.
   *
   * Проверяется на СЛОЖЕННОМ бандле, а не по списку зависимостей: список — это
   * ожидание, а унесённый бандл падает от реальных импортов.
   */
  | 'bundle-not-self-contained'
  /** Сброс дерева на реальную ФС сорвался. */
  | 'flush-failed'
  /**
   * Дверь сорвалась исключением там, где отказа не предусмотрено.
   *
   * Названо кодом, а не стеком в поток: прогон в CI обязан отдавать разбираемый
   * ответ даже когда дверь сломалась сама.
   */
  | 'door-failed';

/**
 * Код отказа в ответе двери: свой либо чужой, но всегда машинный.
 *
 * Коды соседних зон принимаются КАК ЕСТЬ, а не переупаковываются в один общий
 * «отказ движка». Переупаковка означала бы, что дверь держит вторую правду о
 * чужом событии: `manifest-unreadable` и `plan-blocked` — это разные починки в
 * разных местах, и склеить их в один код значило бы сказать «что-то не так»
 * (`tasker:BASER2-24`).
 */
export type ProblemCode = DoorProblemCode | FormProblemCode | EngineProblemCode;

/**
 * Отказ в ответе двери.
 *
 * Структурно совместим с `FormProblem` контрактов — отказы формы кладутся сюда
 * без переупаковки, а `describeProblems` рендерит и те, и другие.
 */
export interface DoorProblem extends Omit<FormProblem, 'code'> {
  readonly code: ProblemCode;
}

/** Копилка отказов двери. Разбор идёт дальше, а не встаёт на первом. */
export class DoorProblemLog {
  readonly #problems: DoorProblem[] = [];

  add(code: ProblemCode, at: string, message: string): void {
    this.#problems.push({ code, at, message });
  }

  /**
   * Принимает отказы как есть — код и адрес уже машинные.
   *
   * Принимает и `FormProblem` соседней зоны, и собственные: коды двери шире
   * кодов формы, поэтому чужой отказ ложится сюда без переупаковки, а свой не
   * требует второго метода.
   */
  addAll(problems: readonly (FormProblem | DoorProblem)[]): void {
    this.#problems.push(...problems);
  }

  get empty(): boolean {
    return this.#problems.length === 0;
  }

  list(): readonly DoorProblem[] {
    return this.#problems;
  }
}
