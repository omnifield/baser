/**
 * Отказы ДВЕРИ — данные, а не исключения.
 *
 * Форма отказа взята у контрактов целиком (`FormProblem`: код, адрес, текст) и
 * не переизобретается: дверь склеивает отказы формы, отказы движка и свои
 * собственные в один список, и потребителю, который по ним ветвится, разные
 * формы на один предмет были бы ровно тем же «двумя языками», от которого
 * избавлялась зона движка (`tasker:BASER2-23`).
 *
 * Здесь объявлены ТОЛЬКО коды, которых нет ни у формы, ни у движка. Всё, что
 * умеет назвать соседняя зона, дверь пробрасывает её кодом — своей семантики
 * поверх чужой она не изобретает (`tasker:BASER2-20`).
 */

import type { FormProblem, FormProblemCode } from '@omnifield/baser-contracts';

/**
 * Что не так на стороне двери.
 *
 * Ветвиться потребителю — по коду, не по тексту.
 */
export type DoorProblemCode =
  /** `baser.json` есть, но это не JSON. */
  | 'config-unreadable'
  /** Манифест пакета обвеса не читается или не JSON. */
  | 'package-manifest-unreadable'
  /** Пакет, названный в `use`, не резолвится из репозитория потребителя. */
  | 'package-not-found'
  /**
   * Источник обвеса лежит вне дерева потребителя, и движок этой формы ещё не
   * понимает. Шов, а не деталь реализации — см. `README.md` § «Шов contentRoot».
   */
  | 'source-outside-tree'
  /**
   * Обвесов поставлено больше одного. Форма это допускает с первого дня, а
   * движок сегодня — нет: план строится ПО ОДНОЙ декларации, а сироты ищутся
   * сканом всего дерева, поэтому два прогона подряд сняли бы артефакты друг
   * друга как потерявшие объявление. Отказ, а не тихая порча (A5).
   */
  | 'multiple-sources'
  /** Шаблон объявлен раскладкой, но не читается с диска. */
  | 'template-unreadable'
  /** Подстановка значений сорвалась: шаблон не собрался. */
  | 'render-failed'
  /** Движок отверг поданный вход целиком (`DeclarationError`). */
  | 'engine-refused'
  /** Сброс дерева на реальную ФС сорвался. */
  | 'flush-failed'
  /**
   * Дверь сорвалась исключением там, где отказа не предусмотрено.
   *
   * Названо кодом, а не стеком в поток: прогон в CI обязан отдавать разбираемый
   * ответ даже когда дверь сломалась сама.
   */
  | 'door-failed';

/** Код отказа в ответе двери: свой либо чужой, но всегда машинный. */
export type ProblemCode = DoorProblemCode | FormProblemCode;

/**
 * Отказ в ответе двери.
 *
 * Структурно совместим с `FormProblem` контрактов — отказы формы кладутся сюда
 * без переупаковки, а `describeProblems` рендерит и те, и другие.
 */
export interface DoorProblem extends Omit<FormProblem, 'code'> {
  readonly code: ProblemCode;
}

/** Копилка отказов двери. Разбор идёт дальше, а не встаёт на первом. */
export class DoorProblemLog {
  readonly #problems: DoorProblem[] = [];

  add(code: ProblemCode, at: string, message: string): void {
    this.#problems.push({ code, at, message });
  }

  /**
   * Принимает отказы как есть — код и адрес уже машинные.
   *
   * Принимает и `FormProblem` соседней зоны, и собственные: коды двери шире
   * кодов формы, поэтому чужой отказ ложится сюда без переупаковки, а свой не
   * требует второго метода.
   */
  addAll(problems: readonly (FormProblem | DoorProblem)[]): void {
    this.#problems.push(...problems);
  }

  get empty(): boolean {
    return this.#problems.length === 0;
  }

  list(): readonly DoorProblem[] {
    return this.#problems;
  }
}
