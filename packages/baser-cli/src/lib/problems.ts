/**
 * Отказы ДВЕРИ — данные, а не исключения.
 *
 * Форма отказа взята у контрактов целиком (`FormProblem`: код, адрес, текст) и
 * не переизобретается: дверь склеивает отказы формы, отказы движка и свои
 * собственные в один список, и потребителю, который по ним ветвится, разные
 * формы на один предмет были бы ровно тем же «двумя языками», от которого
 * избавлялась зона движка (`tasker:BASER2-23`).
 *
 * Здесь объявлены ТОЛЬКО коды, которых нет ни у формы, ни у движка. Всё, что
 * умеет назвать соседняя зона, дверь пробрасывает её кодом — своей семантики
 * поверх чужой она не изобретает (`tasker:BASER2-20`).
 */

import type { FormProblem, FormProblemCode } from '@omnifield/baser-contracts';
import type {
  CapabilityProblemCode,
  EngineProblemCode,
} from '@omnifield/baser-materialize';

/**
 * Что не так на стороне двери.
 *
 * Ветвиться потребителю — по коду, не по тексту.
 *
 * **Снято в схеме двери 2: `multiple-sources`** (`tasker:BASER2-55`). Дверь
 * отказывала, когда обвесов в конфиге больше одного, и отказ был верен: план
 * строился по одной декларации, а сироты искались по всем записям манифеста —
 * второй прогон снял бы артефакты первого. Код снят ВМЕСТЕ С ПРИЧИНОЙ: движок
 * ведёт владение по каждому обвесу отдельно (`tasker:BASER2-7`), и дверь гоняет
 * прогон по каждому вместо отказа на втором. Подавления тут нет — подавить отказ
 * значило бы вернуть тихую порчу.
 *
 * Столкновение двух обвесов на один путь никуда не делось и говорит ЧУЖИМИ
 * кодами, а не своим: `artifact-shared` контрактов — когда оба ОБЪЯВИЛИ один
 * `dest`; `cross-source-dest` движка — когда путь уже числится за соседом в
 * паспорте укладки. Своего кода дверь сюда не заводит: сказать про столкновение
 * есть кому.
 *
 * **Снято вместе с копией резолва: `package-not-found` и
 * `package-manifest-unreadable`** (`tasker:BASER2-128`). Резолв по имени уехал в
 * контракты, и оба случая называет теперь он сам — `package-not-installed` и
 * `package-manifest-unreadable` кодами формы. Своё имя тому же событию дверь не
 * оставляет: это ровно та вторая правда о чужом факте, которую верхний абзац
 * запрещает. `package-manifest-unreadable` из ответа не пропал — он приходит из
 * `FormProblemCode` и живёт в `ProblemCode` как прежде; `package-not-found`
 * заменён на `package-not-installed`, и это ЛОМАЮЩЕЕ изменение поверхности:
 * потребитель, ветвившийся по старому коду, обязан узнать об этом красным, а не
 * молчаливым «условие больше не срабатывает».
 */
export type DoorProblemCode =
  /** `baser.json` есть, но это не JSON. */
  | 'config-unreadable'
  /**
   * Служебной записи `baser.lock.json` нет, а конфиг потребителя есть — значит
   * раскладка здесь скорее всего уже была, а запись пропала.
   *
   * Движок этого сказать не может: для него «записи нет» — одно состояние, и он
   * честно объявляет артефакты чужими. Различает состояния конфиг потребителя —
   * сигнал, которого у движка нет и быть не должно.
   *
   * Признак не абсолютен (конфиг можно написать руками), и сообщение это
   * называет вслух, отдавая человеку дешёвую проверку вместо второй догадки.
   */
  | 'manifest-missing'
  /**
   * ПЕРВАЯ УСТАНОВКА В НЕПУСТОЙ РЕПОЗИТОРИЙ: ни конфига, ни записи, а файлы на
   * местах, куда целится обвес, уже лежат. Они не наши — они лежали до нас.
   *
   * Отдельный код, а не оттенок предыдущего: человек не потерял ничего и чинить
   * ему нечего, он выбирает. Одно сообщение на оба состояния уже соврало на
   * живом репозитории (`tasker:BASER2-28`), послав искать в истории запись,
   * которой там никогда не было.
   */
  | 'first-install'
  /**
   * СЛУЖЕБНАЯ ЗАПИСЬ ЕСТЬ И ВЕРНА, а этих путей в ней нет: по ним baser здесь
   * ещё не раскладывал, и файлы на этих местах не наши.
   *
   * Третье состояние «файлы оказались чужими», и до `tasker:BASER2-134` дверь не
   * называла его никак. Два соседних кода привязаны к РЕПОЗИТОРИЮ — «нет ни
   * конфига, ни записи» и «конфиг есть, записи нет», — а это состояние про
   * ПУТИ: запись на месте, владение по ней доказано, просто в неё не входят те
   * адреса, в которые целится обвес. Живой случай — второй обвес в репозитории,
   * где первый работает давно (`tasker:BASER2-133`).
   *
   * Отсюда и разница в починке, ради которой код заведён отдельным. У
   * `manifest-missing` верное действие — восстановить запись из истории; здесь
   * восстанавливать НЕЧЕГО, и тот же текст послал бы человека искать в истории
   * то, что лежит у него перед глазами. Уверенный указатель не туда хуже
   * отсутствующего — это у нас уже случалось (`tasker:BASER2-28`).
   *
   * Перенастроить на этот случай `first-install` было нельзя: он выпущен со
   * смыслом «репозиторий девственный», и сменить смысл выпущенного слова значило
   * бы обмануть его читателя молча. Новое слово в перечислении — прибавление, и
   * выпущенных читателей оно не трогает.
   *
   * Как и оба соседа, отказ НАЗЫВАЕТ КЛАСС каждого спорного пути: цена
   * подтверждения у классов разная, и без неё человек либо не решается
   * подтвердить, либо подтверждает с испугом (`tasker:BASER2-123`).
   */
  | 'unrecorded-dest'
  /**
   * Файл настроек обвеса есть, но не разбирается как YAML.
   *
   * Свой код, а не чужой: YAML читает ДВЕРЬ (`tasker:BASER2-53`) — контракты не
   * читают ничего и о существовании файла не знают, поэтому сказать про
   * сломанный отступ больше некому. Молчаливого «считаем, что ничего не
   * выбрано» тут быть не может: оно превратило бы настроенный обвес в
   * дефолтный ровно в тот момент, когда человек ошибся в своём же файле.
   */
  | 'source-config-unreadable'
  /**
   * СКЛАД НЕ ОТВЕТИЛ либо доступа к нему нет: поставку достать нечем.
   *
   * Своё слово, а не пробрасывание чужого: `npm` на этом месте говорит про
   * сокет и прокси, и человеку из этого не следует ни адрес его склада, ни то,
   * что сделать. Форма сообщения взята с постсоздания девбокса, где она уже
   * прожита на живом (`tasker:BASER2-125`): адрес склада, чего не хватает,
   * команда проверки руками и команда починки.
   *
   * Отдельно от `supply-not-published` потому, что чинятся они в разных местах:
   * здесь — токен и связь, там — имя и версия в перечне.
   */
  | 'supply-unreachable'
  /**
   * СКЛАД ОТВЕТИЛ, что такой поставки у него нет.
   *
   * Не «нет доступа» и не «нет сети»: склад на связи и говорит `404`. Чинится
   * правкой перечня (имя пакета, закреплённая версия) либо адресом склада — у
   * скоупа он свой и бьёт общий, а «ходили не туда» выглядит ровно как «нет
   * такого пакета».
   */
  | 'supply-not-published'
  /**
   * СКЛАД ЗНАЕТ ПАКЕТ, а МЕТКИ КАНАЛА у него нет.
   *
   * Отдельный код, потому что тихого отката тут быть не должно
   * (`kb:BASER3-26`): взять «последнюю стабильную» вместо ненайденного
   * дев-канала значило бы разложить локацию не тем, что у неё написано, и
   * назвать это успехом. Человек просил движущийся указатель — он либо есть,
   * либо его нет.
   *
   * От `supply-not-published` отличается тем, ЧЕГО нет: там нет пакета или
   * версии (чинится именем и адресом склада), здесь — метки у существующего
   * пакета. Второе чинится в двух местах, и оба названы в сообщении: метка в
   * перечне либо выпуск в этот канал. Поэтому отказ и перечисляет метки,
   * которые у пакета есть, — «dev» вместо «development» видно сразу.
   */
  | 'supply-channel-unknown'
  /**
   * Достать поставку не вышло, и причина не разложилась ни на один из двух
   * соседних случаев.
   *
   * Отдельный код, а не «уронить как есть»: прогон в конвейере обязан отдавать
   * разбираемый ответ, и слова менеджера едут ВНУТРИ сообщения, а не вместо
   * него. Слепить это с `supply-unreachable` значило бы утверждать про склад то,
   * чего мы не знаем.
   */
  | 'supply-fetch-failed'
  /**
   * ДЕВ-ПЕТЛЯ: каталог поставки назван, а поставки в нём нет.
   *
   * Свой код потому, что чинится он в командной строке, а не на складе: человек
   * назвал не тот путь. Отправить его в этот момент настраивать токен значило бы
   * дать уверенный указатель не туда.
   */
  | 'supply-local-missing'
  /**
   * `npm` в среде не нашёлся, а поставку достаёт дверь — и достаёт им.
   *
   * Дефект СРЕДЫ, а не локации: дверь ставится в среду один раз и вместе с
   * менеджером (`kb:BASER2-22`). Поэтому сообщение зовёт чинить среду и называет
   * дев-петлю — единственный путь, который работает и без склада.
   */
  | 'package-manager-missing'
  /** Шаблон объявлен раскладкой, но не читается с диска. */
  | 'template-unreadable'
  /** Подстановка значений сорвалась: шаблон не собрался. */
  | 'render-failed'
  /** Дверь не смогла вложить в бандл себя или свои зависимости. */
  | 'bundle-runtime-failed'
  /**
   * В бандле есть импорт, который резолвится наружу либо не резолвится вовсе.
   *
   * Проверяется на СЛОЖЕННОМ бандле, а не по списку зависимостей: список — это
   * ожидание, а унесённый бандл падает от реальных импортов.
   */
  | 'bundle-not-self-contained'
  /**
   * ПАСПОРТ УКЛАДКИ ЛЕЖИТ, А ЗАПИСАТЬ В НЕГО НЕЧЕМ: прав нет.
   *
   * Отдельный код, а не оттенок соседнего, потому что предмет другой и цена
   * другая. `path-unwritable` говорит про ЭТОТ прогон — какие артефакты не
   * лягут; здесь речь про сам инструмент: паспорт дверь переписывает КАЖДЫМ
   * применением (`tasker:BASER2-52`), и пока в него не пишется, в этой локации
   * не применится НИЧЕГО и никогда. Поэтому и спрашивается он раньше всего
   * прочего — до склада, до шаблонов, до плана.
   *
   * Живой случай — `tasker:BASER2-190`: паспорт остался под другим
   * пользователем, а сессия шла от своего. Дверь про это молчала, и цена
   * всплыла позже, на соседней механике, чужим голосом.
   *
   * Владение дверь при этом НЕ ВЫРАВНИВАЕТ: она пишет файлы, а не
   * администрирует машину, и тихая смена владельца — сюрприз хуже отказа.
   */
  | 'manifest-unwritable'
  /**
   * В ЭТИ ПУТИ ДВЕРЬ ПИСАТЬ НЕ СМОЖЕТ — сказано ДО применения, поимённо.
   *
   * Раньше это узнавалось в момент записи и говорилось чужим голосом: `EACCES`
   * из библиотеки посреди сброса, без имени виноватого файла и без причины
   * (`tasker:BASER2-190`). Теперь вопрос задаётся там же, где и прочие входные,
   * — по списку того, что этот прогон собирается записать, — и отказ называет
   * КАЖДЫЙ путь и причину рядом с ним: чужое владение либо биты прав.
   *
   * Отказывают обе команды одинаково. `plan` не пишет ничего, но и отвечает он
   * не про себя, а про то, что случится при применении: узнать про невозможность
   * записи после того, как план прочитан и принят, — ровно та поздняя правда, от
   * которой уходит эта работа.
   *
   * Сброс это НЕ ЗАМЕНЯЕТ: `flush-failed` остаётся на месте и ловит то, что
   * изменилось между проверкой и записью. Здесь — отчёт, там — гарантия.
   */
  | 'path-unwritable'
  /** Сброс дерева на реальную ФС сорвался. */
  | 'flush-failed'
  /**
   * Дверь сорвалась исключением там, где отказа не предусмотрено.
   *
   * Названо кодом, а не стеком в поток: прогон в CI обязан отдавать разбираемый
   * ответ даже когда дверь сломалась сама.
   */
  | 'door-failed';

/**
 * Код отказа в ответе двери: свой либо чужой, но всегда машинный.
 *
 * Коды соседних зон принимаются КАК ЕСТЬ, а не переупаковываются в один общий
 * «отказ движка». Переупаковка означала бы, что дверь держит вторую правду о
 * чужом событии: `manifest-unreadable` и `plan-blocked` — это разные починки в
 * разных местах, и склеить их в один код значило бы сказать «что-то не так»
 * (`tasker:BASER2-24`).
 *
 * **Коды СПОСОБНОСТЕЙ движка входят сюда тем же правилом** (`tasker:BASER2-201`).
 * Команда `add` зовёт способность «объявить поставку», и её отказы приезжают в
 * ответ консоли как есть — `pin-ambiguous` в том числе. Своего слова про
 * названное дважды закрепление консоль не заводит: решение о нём принимает
 * движок, и второе такое же, принятое здесь, разошлось бы с первым молча.
 */
export type ProblemCode =
  | DoorProblemCode
  | FormProblemCode
  | EngineProblemCode
  | CapabilityProblemCode;

/**
 * Отказ в ответе двери.
 *
 * Структурно совместим с `FormProblem` контрактов — отказы формы кладутся сюда
 * без переупаковки, а `describeProblems` рендерит и те, и другие.
 */
export interface DoorProblem extends Omit<FormProblem, 'code'> {
  readonly code: ProblemCode;
}

/** Копилка отказов двери. Разбор идёт дальше, а не встаёт на первом. */
export class DoorProblemLog {
  readonly #problems: DoorProblem[] = [];

  add(code: ProblemCode, at: string, message: string): void {
    this.#problems.push({ code, at, message });
  }

  /**
   * Принимает отказы как есть — код и адрес уже машинные.
   *
   * Принимает и `FormProblem` соседней зоны, и собственные: коды двери шире
   * кодов формы, поэтому чужой отказ ложится сюда без переупаковки, а свой не
   * требует второго метода.
   */
  addAll(problems: readonly (FormProblem | DoorProblem)[]): void {
    this.#problems.push(...problems);
  }

  get empty(): boolean {
    return this.#problems.length === 0;
  }

  list(): readonly DoorProblem[] {
    return this.#problems;
  }
}
