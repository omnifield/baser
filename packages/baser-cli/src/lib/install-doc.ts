import { basename } from 'node:path';
import { sourceConfigPath } from '@omnifield/baser-contracts';
import type { PackReport, PayloadArtifact } from '@omnifield/baser-pack';

/**
 * ЦЕНА ПОДТВЕРЖДЕНИЯ — по классам из ОПИСИ, а не одним обещанием на оба.
 *
 * Дока обещала «подтверждённый файл заменяется целиком», и для `placed-once`
 * это неправда: подтверждение регистрирует такой артефакт в паспорте укладки,
 * не трогая содержимое (`tasker:BASER2-123`, находка первого чужого обвеса).
 * Читающий буквально либо не решается подтвердить и застревает на конфликте,
 * либо подтверждает, готовясь потерять свой файл. Оба исхода от одной строки.
 *
 * Класс берётся из ОПИСИ — она и существует для того, чтобы узнавать груз, не
 * вскрывая его (`baser-pack`, `manifest.ts`). Заглядывать за неё в объявление
 * обвеса значило бы завести вторую правду о том же грузе.
 *
 * Дублем разбора класса у отказов прогона это НЕ является (`tasker:BASER2-143`).
 * Там дверь берёт класс словом движка, потому что движок его сказал; здесь
 * движка нет в разговоре вовсе — бандл собирается без единого прогона по
 * репозиторию потребителя, и спросить, кроме описи, некого.
 */
function confirmationPrice(artifacts: readonly PayloadArtifact[]): string {
  const once = artifacts.filter((item) => item.class === 'placed-once');
  const regenerated = artifacts.filter((item) => item.class !== 'placed-once');

  const replaced =
    'файл заменяется целиком и дальше ведётся обвесом — правки руками в нём не ' +
    'переживут следующего обновления';
  const adopted =
    '**содержимое не изменится** — обвес объявил такой файл человеческим, и ' +
    'подтверждение только записывает его в паспорт укладки: ни этот прогон, ни ' +
    'следующие в него не пишут';

  if (once.length === 0) {
    return `- **regenerated** (все артефакты этого обвеса): ${replaced}.`;
  }
  if (regenerated.length === 0) {
    return `- **placed-once** (все артефакты этого обвеса): ${adopted}.`;
  }
  return [
    `- **regenerated** (${list(regenerated)}): ${replaced};`,
    `- **placed-once** (${list(once)}): ${adopted}.`,
  ].join('\n');
}

function list(artifacts: readonly PayloadArtifact[]): string {
  return artifacts.map((item) => `\`${item.dest}\``).join(', ');
}

/**
 * `INSTALL.md` — инструкция под КОНКРЕТНЫЙ обвес, а не шаблон с плейсхолдерами.
 *
 * Имя пакета, версия и список артефактов берутся из описи: человек, открывший
 * бандл, читает про то, что у него в руках, а не про абстрактный обвес. Имя
 * каталога бандла — тоже настоящее: команду из доки копируют целиком, и
 * плейсхолдер в ней означал бы ошибку с первого движения.
 *
 * ## Почему первой командой идёт контейнер
 *
 * Инструмент, который затаскивает проект в контейнер, требовал Node НА ХОСТЕ —
 * а по канону (`kb:FUND-4`, containers-only) хост держит только докер и файлы
 * (`tasker:BASER2-34`). Мы этого не видели, потому что все прогоны шли внутри
 * девбоксов, где Node есть по умолчанию: предусловие выполнялось само собой и
 * поэтому не было названо нигде.
 *
 * Лечится это ДОКОЙ, а не запускалкой в бандле: шелл-скрипт добавил бы в
 * поставку предположение про докер ради экономии одной команды.
 */
export function installDoc(packed: PackReport, target: string): string {
  const manifest = packed.manifest;
  const name = manifest?.source.package.name ?? 'обвес';
  const version = manifest?.source.package.version;
  const artifacts = manifest?.artifacts ?? [];
  /** Файл настроек этого обвеса — считается из его личности, а не из ссылки. */
  const tuning = sourceConfigPath(manifest?.source.id ?? '<поставщик>/<обвес>');
  /** Как папка называется у человека в руках — так она и зовётся в командах. */
  const here = basename(target);
  /**
   * Путь для примера с `--confirm` — из ОПИСИ, а не прибитый.
   *
   * Здесь стоял литерал `.devcontainer/devcontainer.json`, и на девбоксе это
   * было незаметно: прибитый путь совпадал с настоящим. Для плагина агентов
   * (живой случай `tasker:BASER2-44`) дока предлагала бы подтвердить путь,
   * которого никто не кладёт, — человек получил бы `confirmation-unused` вместо
   * снятого отказа. Шапка обещает инструкцию под КОНКРЕТНЫЙ обвес, значит и
   * подсказка обязана быть его.
   */
  const someArtifact = artifacts[0]?.dest ?? null;

  /**
   * Оболочка контейнера: Node появляется на время прогона и исчезает с ним.
   *
   * ## Почему монтируется под `basename "$PWD"`, а не в `/repo`
   *
   * Здесь стояла оговорка про имя девбокса от имени каталога с пометкой
   * «временная, уедет с `tasker:BASER2-32`». `BASER2-32` смержен, оговорку
   * сняли верно — и вместе с ней уехало монтирование под настоящим именем, на
   * `/repo`. Это была потеря, а не упрощение (`tasker:BASER2-71`, находка
   * ревью).
   *
   * Имя репозитория обвес берёт из `origin` — идентичности, одинаковой у всех
   * клонов; точка монтирования на неё не влияет никак. Но `origin` есть не
   * всегда: свежий `git init` до первого пуша (живой случай — прогон нового
   * продукта, `tasker:BASER2-44`) его не имеет, и тогда обвес читает **имя
   * каталога** — запасной вариант, заведённый нарочно («как назвал человек»,
   * `baser-devbox/defaults.mjs`).
   *
   * Внутри контейнера имя каталога — это и есть точка монтирования: `--cwd`
   * докерная команда не передаёт, корнем становится рабочий каталог. Поэтому
   * `/repo` не нейтрален — он **стирает вход, который читает запасной вариант**,
   * и всякий репозиторий без `origin` называется одинаково. Монтирование под
   * своим именем ничего не подпирает: оно просто не выбрасывает то, что человек
   * уже сказал, назвав папку.
   */
  const inContainer = (...args: string[]): string =>
    `docker run --rm --user "$(id -u):$(id -g)" \\
  -v "$PWD":"/$(basename "$PWD")" -w "/$(basename "$PWD")" node:22 \\
  node ${here}/install.mjs${args.length > 0 ? ` ${args.join(' ')}` : ''}`;

  return `# Установка: ${name}${version === null || version === undefined ? '' : `@${version}`}

${manifest?.source.title ?? ''}

Эта папка самодостаточна: в ней лежит обвес, консоль и всё, что консоли нужно.
Доставать из сети ничего не придётся.

**На хосте Node не нужен** — и не должен быть нужен: на машине живут докер и
файлы, а исполняется всё в контейнерах. Поэтому первая команда ниже — не
\`node\`, а одноразовый контейнер: Node появляется в нём на время прогона и
исчезает вместе с ним. Установленного на хост не остаётся ничего.

## Сухой прогон — посмотреть, что будет

Положи эту папку (\`${here}/\`) в корень своего репозитория — иначе из
контейнера её не видно, — и оттуда же запускай:

\`\`\`bash
${inContainer('--plan')}
\`\`\`

\`--user\` — чтобы файлы остались твоими: без него из контейнера прилетают
root-овы, и разгребать их придётся руками.

Репозиторий монтируется под СВОИМ именем (\`basename "$PWD"\`), а не в
\`/repo\`. Для того, что бежит внутри, точка монтирования и есть корень
репозитория: обвес, который считает что-нибудь от имени каталога, увидит именно
её. Монтирование в \`/repo\` заставило бы твой репозиторий зваться \`repo\` —
молча и одинаково у всех. Имя папки менять не надо: достаточно не выбрасывать
его по дороге.

Если Node на хосте уже есть, то же самое без контейнера:

\`\`\`bash
node install.mjs --plan --cwd /путь/к/репозиторию
\`\`\`

Бит исполнения на \`install.mjs\` стоит, поэтому работает и \`./install.mjs\`.
Права переживают \`tar\` и обычное копирование, но не всякую дорогу: если бандл
ехал через архиватор или выгрузку, которые прав не несут, зови через \`node\` —
этот путь от прав не зависит вовсе.

## Что прогон трогает, и что после него остаётся

**Обвес в твой репозиторий не кладётся вообще.** Он лежит в этой папке, и консоль
берёт его прямо отсюда — установщик называет ей каталог поставки
(\`--source ${name}=<эта папка>/payload\`). Значит после прогона у тебя не
появляется ни склада, ни \`package.json\`, ни строки в нём, ни чужого лока:
трогаются только сами артефакты, паспорт укладки и твой файл настроек.

Раньше здесь было иначе: обвес копировался в \`node_modules\` и на время прогона
объявлялся зависимостью, а установщик убирал за собой. Убирать больше нечего —
поставку достаёт консоль, и названный каталог для неё такой же законный источник,
как склад.

\`pnpm-lock.yaml\` не трогается никогда: чужой лок-формат — чужие внутренности.

## Установка

\`\`\`bash
${inContainer()}
\`\`\`

Разложит артефакты и запишет служебную запись. Что именно ляжет:

${artifacts.map((item) => `- \`${item.dest}\``).join('\n')}

## Где это настраивается

Регулировки этого обвеса живут в \`${tuning}\` — твоём файле настроек. Консоль
создаёт его ОДИН РАЗ, если его нет, и кладёт туда все регулировки
закомментированными, вместе с их описаниями и дефолтами.
Значений она не пишет никогда: раскомментируй строку — и значение станет твоим,
а незаполненное продолжит ездить за выпусками обвеса.

Файл рождается только тогда, когда обвесу есть что в него положить: объявлена
хоть одна настройка или пресет. Нечего — файла не будет, и это не пропажа: он
появится в том выпуске обвеса, где появится первая регулировка. Существующий
файл консоль не трогает и не удаляет ни при каких условиях.

Имя файла считается из личности обвеса, поэтому у каждого инструмента он свой, а
ссылки на него в \`baser.json\` нет. Всё, что ты допишешь в этот файл ВНЕ ключа
\`baser\`, — дело самого инструмента: консоль туда не смотрит.

## Если такой файл у тебя уже есть

**Ничего не будет затёрто.** Консоль откажется трогать файл, которого она не
клала, и скажет об этом: это первая установка в непустой репозиторий, а не
поломка. Дальше решаешь ты:
${
  someArtifact === null
    ? `
Подтверждение выглядит как \`--confirm <путь>\`, и путь берётся из отказа: он
называет каждый спорный артефакт поимённо. Готового примера здесь нет — этот
обвес не объявил ни одного артефакта, и подставлять в команду выдуманный путь
значило бы дать подсказку, которая не сработает.
`
    : `
\`\`\`bash
${inContainer('--confirm', someArtifact)}
\`\`\`
`
}
Подтверждение поимённое: согласие на один файл не становится согласием на
соседний. Хочешь оставить своё — просто не подтверждай.
${
  artifacts.length === 0
    ? ''
    : `
Подтверждение отдаёт файл во ВЛАДЕНИЕ обвесу. Что при этом станет с
содержимым, решает класс, которым обвес держит артефакт:

${confirmationPrice(artifacts)}
`
}
## Что коммитить, а что нет

| Путь | Куда |
|---|---|
| разложенные артефакты (см. список выше) | **в git** — это файлы твоего репозитория |
| \`baser.json\` | **в git** — перечень поставленных обвесов |
| \`${tuning}\` | **в git**, когда он появится — твои настройки этого обвеса |
| \`baser.lock.json\` | **в git, обязательно** |
| \`${here}/\` (эта папка) | **не коммить** — удали или унеси после установки |

Ни склада, ни \`package.json\`, ни лока пакетного менеджера в этом списке нет
намеренно: прогон их не создаёт и не трогает. Если твоя локация не на ноде — в
ней после установки ничего от ноды и не появится.

Сама папка бандла в репозитории не нужна: она понадобилась на прогон и после
него остаётся лишним каталогом в \`git status\`. Разложенное живёт своей жизнью
и от неё не зависит.

\`baser.lock.json\` — служебная запись: по ней консоль знает, какие файлы положила
она, а какие твои. **Без неё следующий прогон объявит все артефакты чужими** и
упрётся в отказы по всему дереву. Это не каприз: без записи владение
недоказуемо.

Если \`.gitignore\` у тебя игнорирует что-то из списка артефактов — проверь
заранее, иначе положенное не доедет до остальных.

## Дальше

Повторный прогон — тем же установщиком, хоть \`--plan\`, хоть без него: он снова
покажет консоли каталог поставки в этой папке.

Рядом лежит \`baser.mjs\` — та же консоль, вызываемая напрямую. Каталог поставки
ей надо назвать самому — это ровно то, что делает за тебя \`install.mjs\`:

\`\`\`bash
node ${here}/baser.mjs plan --cwd /путь/к/репозиторию --source ${name}=${here}/payload
\`\`\`

Без \`--source\` консоль пойдёт за поставкой на склад — и не найдёт её там, пока
обвес не выпущен. Отказ при этом будет названный: адрес склада, чего не хватает
и что сделать.

Когда обвес выйдет на склад, эта папка станет не нужна вовсе: консоль достанет
поставку сама, в свой кэш снаружи твоего репозитория, а версию возьмёт из
\`baser.json\` — закреплённую (\`sources[].version\`), стоящую сегодня за меткой
канала (\`sources[].channel\`), записанную паспортом укладки либо последнюю
доступную. Любой из этих выборов план называет до применения.
`;
}
