/**
 * ПОСЧИТАННОЕ ОТ ЗНАЧЕНИЯ ПЕРЕЕЗЖАЕТ ВМЕСТЕ С НИМ — и это дверь обязана назвать.
 *
 * `tasker:BASER2-38` научил план называть оба конца движения: `imageUser "node"
 * → "vscode"`, прежнее прочитано из разложенного артефакта и доказано побайтово
 * (`previous.ts`). Половина осталась неназванной, и нашлась она глазами
 * потребителя (`tasker:BASER2-98`): **значение человек выбрал сам, а адрес тома
 * от него только СЧИТАЕТСЯ.** Тома `omnifield-secrets` и `omnifield-pnpm-store`
 * уезжают с `/home/node/…` на `/home/vscode/…` — вместе с настройкой и без
 * единого слова про это. В томах при этом лежит то, что человек клал руками:
 * креды, стор.
 *
 * Это ровно тот класс, что закрыт в `tasker:BASER2-38`: **план обязан называть
 * последствия движения, а не только само движение.** Там был сетевой алиас —
 * обещание соседям; здесь адрес тома — обещание содержимому.
 *
 * ── ЧТО ДВЕРЬ МОЖЕТ СКАЗАТЬ, НЕ ЗНАЯ НИ ОДНОГО СЛОВА ПРО ТОМА ───────────────
 *
 * Про тома дверь не знает и знать не должна: что такое `target=` и почему он
 * важен, знает обвес. Но у двери в руках оба конца САМОГО АРТЕФАКТА — лежащий
 * (`step.previous`) и тот, который ляжет (`step.content`), — и названные
 * движения значений. Значит она может показать не «что такое том», а факт:
 *
 * ```
 * source=omnifield-secrets,target=/home/node/.secrets,type=volume
 *   → source=omnifield-secrets,target=/home/vscode/.secrets,type=volume
 * ```
 *
 * Человек, увидевший это, узнаёт свою потерю сам — и узнаёт её ДО применения.
 *
 * ── ПОЧЕМУ СЛОВО, А НЕ СТРОКА ЦЕЛИКОМ ───────────────────────────────────────
 *
 * Показывать расходящиеся строки артефакта целиком было бы проще, но неверно:
 * строка `"remoteUser": "node"` не несёт человеку НИЧЕГО нового — движение
 * `imageUser "node" → "vscode"` план уже назвал строкой выше, и повтор
 * обесценил бы блок ровно там, где он должен быть коротким и страшным.
 *
 * Поэтому единица здесь — **слово**: то, что стоит между пробелами, без
 * окаймляющих знаков (`"`, `,`, `:` и прочая пунктуация формата — она
 * принадлежит формату, а не значению). Разбирать формат при этом не нужно и не
 * делается: дверь не знает, JSON перед ней, YAML или строка шелла.
 *
 * | слово в лежащем артефакте          | что это                     | говорим  |
 * | ---------------------------------- | --------------------------- | -------- |
 * | `node`                             | само значение               | молчим   |
 * | `weber-live-devbox`                | значение ДРУГОЙ настройки   | молчим   |
 * | `/home/node/.secrets`              | ПОСЧИТАНО от значения       | называем |
 * | `mcr…/typescript-node:1-22`        | содержит `node` случайно    | молчим*  |
 *
 * \* — не потому, что дверь разбирает смысл, а потому, что утверждение
 * ДОКАЗЫВАЕТСЯ (ниже). Подстановка `node → vscode` дала бы
 * `typescript-vscode:1-22`, а такого слова в новом артефакте нет — значит и
 * говорить нечего.
 *
 * ── НИ ОДНОГО НЕДОКАЗАННОГО СЛОВА (то же правило, что у `previous.ts`) ───────
 *
 * Слово называется переехавшим, только когда выполнены ОБА условия:
 *
 * 1. подстановка нового значения на место прежнего даёт слово, которое **есть**
 *    в новом содержимом;
 * 2. прежнего слова в новом содержимом **нет**.
 *
 * Не выполнилось — дверь молчит. Ошибиться в сторону молчания механизм может (и
 * будет: слово, случайно уцелевшее в новом артефакте, названо не будет),
 * соврать — нет. Уверенный указатель не туда хуже отсутствующего.
 */

/** Названное движение значения: оба конца, оба строки. */
export interface NamedMove {
  readonly key: string;
  /** С чем артефакт уже разложен — прежний конец, доказанный `previous.ts`. */
  readonly from: string;
  /** Что поедет в шаблон сейчас. */
  readonly to: string;
}

/** Слово артефакта, переезжающее ВМЕСТЕ с названным значением. */
export interface DerivedMove {
  /** Настройка, от которой это слово посчитано. */
  readonly key: string;
  /** Артефакт, в котором слово найдено, — он же доказательство. */
  readonly dest: string;
  /** Как стоит сейчас. */
  readonly placed: string;
  /** Как станет после применения. */
  readonly comes: string;
}

export interface DerivedInput {
  readonly dest: string;
  /** Содержимое, лежащее на диске: `step.previous`. */
  readonly placed: string;
  /** Содержимое, которое ляжет: `step.content`. */
  readonly comes: string;
  /** Движения, которые план уже назвал. Пустой список — искать не от чего. */
  readonly moved: readonly NamedMove[];
}

/**
 * Предел размера артефакта, на котором работает разбор.
 *
 * Стоит не как тюнинг, а чтобы отказ был предсказуем: артефакты обвеса живут в
 * килобайтах, а на мегабайтном файле разбор по словам перестал бы быть дешёвым
 * ровно там, где человек ждёт план. Упёрлись — молчим, и это то же молчание,
 * что и у недоказанного слова.
 */
const MAX_BYTES = 512 * 1024;

/**
 * Знаки, которые снимаются с краёв слова.
 *
 * Это НЕ разбор формата: дверь не решает, JSON перед ней или шелл. Это
 * утверждение про слово — кавычка, запятая и двоеточие принадлежат тому, кто
 * записывает значение, а не самому значению.
 *
 * Точка снимается ТОЛЬКО с конца: в начале она часть имени (`.secrets`), а в
 * конце — знак препинания живого текста. Без этого одно и то же слово,
 * попавшее и в комментарий, и в поле, называлось бы дважды: `/home/node/.secrets.`
 * и `/home/node/.secrets` — два разных слова для человека, читающего один файл.
 */
const EDGES = /^[«"'`([{<,;:]+|[»"'`)\]}>,;:.]+$/g;

/**
 * Слова артефакта, переезжающие вместе с названными значениями.
 *
 * Порядок — тот, в котором слова стоят в лежащем артефакте: человек читает
 * рассказ про свой файл, и переставлять его порядком настроек значило бы путать
 * без причины.
 */
export function derivedMoves(input: DerivedInput): readonly DerivedMove[] {
  const moved = input.moved.filter(
    (move) => move.from !== '' && move.to !== '' && move.from !== move.to,
  );
  if (moved.length === 0 || input.placed.length > MAX_BYTES) {
    return [];
  }

  // Значения, названные планом. Слово, равное любому из них, — это само
  // движение, а его человек уже прочитал строкой выше.
  const named = new Set(moved.map((move) => move.from));
  const seen = new Set<string>();
  const found: DerivedMove[] = [];

  for (const word of input.placed.split(/\s+/)) {
    const bare = word.replace(EDGES, '');
    if (bare === '' || named.has(bare) || seen.has(bare)) {
      continue;
    }
    seen.add(bare);

    for (const move of moved) {
      if (!bare.includes(move.from)) {
        continue;
      }
      const comes = bare.split(move.from).join(move.to);
      // ── ДОКАЗАТЕЛЬСТВО. Пока его нет, всё выше — гипотеза.
      if (
        comes === bare ||
        !input.comes.includes(comes) ||
        input.comes.includes(bare)
      ) {
        continue;
      }
      found.push({ key: move.key, dest: input.dest, placed: bare, comes });
      break;
    }
  }

  return found;
}
