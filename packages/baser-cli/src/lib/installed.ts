/**
 * ШОВ `contentRoot` — единственное, что осталось у двери от «поставленного обвеса».
 *
 * Обвес объявляет корень содержимого ОТНОСИТЕЛЬНО СВОЕГО ПАКЕТА, а движок
 * адресует источник путём ОТНОСИТЕЛЬНО ДЕРЕВА ПОТРЕБИТЕЛЯ. Перевод одного в
 * другое возможен только здесь — и он не всегда возможен вовсе
 * (`locateContentRoot`).
 *
 * ── РЕЗОЛВ ПО ИМЕНИ УЕХАЛ В КОНТРАКТЫ ───────────────────────────────────────
 *
 * `resolveInstalledPackage` жил здесь и был вторым экземпляром одного и того же
 * резолва: тот же вопрос — «по ИМЕНИ пакета: где он у потребителя и что в его
 * манифесте» — держали контракты (`tasker:BASER2-122`). Дублировалось не слово,
 * а ПОВЕДЕНИЕ, и расхождение таких копий молчаливое: обе стороны отработали бы
 * успешно, просто на разных пакетах, и дверь разложила бы артефакты из одного, а
 * хук обвеса прочитал бы свой эталон из другого.
 *
 * Факт отдан наружу владельцем нижней зоны (`tasker:BASER2-127`) и зовётся
 * теперь одним входом — `locatePackage` из `@omnifield/baser-contracts/locate`.
 * Дверь его ЗОВЁТ, а не повторяет: экземпляр резолва в продукте один
 * (`tasker:BASER2-128`).
 *
 * Вопрос СВЕРХУ у двери при этом свой и никуда не делся: контракты спрашивают
 * «где содержимое обвеса с такой ЛИЧНОСТЬЮ» (вход для чужого рантайм-кода у
 * потребителя), дверь — «какие обвесы объявлены и что каждый объявляет». Личность
 * против имени живёт этажом ВЫШЕ резолва, у вызывающих.
 *
 * Вместе с копией снят и гейт `resolve-seam.spec.ts`: он держал две стороны на
 * одном ответе, пока сторон было две. Проба, которая больше не может покраснеть,
 * уезжает вместе с причиной.
 */

import { existsSync, realpathSync } from 'node:fs';
import { isAbsolute, relative, resolve, sep } from 'node:path';

/**
 * Где лежит источник шаблонов относительно дерева потребителя.
 *
 * Движок адресует источник репо-относительным путём и этим же путём защищается
 * от записи в собственный источник (`dest-in-content-root`, `scan.exclude`).
 * Когда пакет поставлен внутрь дерева (`node_modules/…` — штатная раскладка),
 * такой путь есть, дверь подаёт его как есть, и защита настоящая.
 *
 * Когда пакет лежит ВНЕ дерева (кэш поставок снаружи локации — штатный путь с
 * `tasker:BASER2-146`, каталог дев-петли, hoisting на корень workspace,
 * `npm link`), репо-относительного пути не существует вовсе. Подделать его
 * нельзя: подделка выглядела бы как защита, а защищала бы пустоту — и настоящий
 * источник, окажись он потом внутри дерева по другому пути, остался бы
 * незакрытым. Поэтому факт называется формой, а не заменяется правдоподобием.
 *
 * Движку это положение подаётся АДРЕСОМ (`{ outside }`, `tasker:BASER2-150`), а
 * не пустотой: он утверждает пустое пересечение по адресу, который обязан быть
 * невыразим репо-относительным путём. Отказом второе положение быть перестало —
 * с тех пор как поставка забирается в кэш, источник снаружи это НОРМА.
 */
export type SourceLocation =
  /** Источник внутри дерева: путь есть, защита движка работает в полную силу. */
  | { readonly kind: 'in-tree'; readonly path: string }
  /**
   * Источника в этом дереве нет — и адрес его известен.
   *
   * Пересечение с деревом пусто ПО ПОСТРОЕНИЮ, а не по недосмотру: писать вне
   * корня дерева движок не может вообще. Абсолютный адрес здесь не украшение —
   * им это и утверждается: движок проверяет, что репо-относительным путём он
   * невыразим (`{ outside }`, `tasker:BASER2-150`).
   */
  | { readonly kind: 'outside-tree'; readonly absolute: string };

export function locateContentRoot(
  repoRoot: string,
  packageRoot: string,
  contentRoot: string,
): SourceLocation {
  const templates = resolve(packageRoot, contentRoot);
  // Симлинки снимаются с обеих сторон: pnpm кладёт пакет ссылкой в
  // `node_modules`, и сравнение ссылки с реальным корнем разъехалось бы на
  // ровном месте. Путь, которого ещё нет, сравнивается как есть — его
  // непригодность назовёт движок отказом `missing-source` по своей записи.
  const real = (path: string): string =>
    existsSync(path) ? realpathSync(path) : path;

  const inside = relative(real(repoRoot), real(templates));

  if (
    inside === '' ||
    isAbsolute(inside) ||
    inside === '..' ||
    inside.startsWith(`..${sep}`)
  ) {
    return { kind: 'outside-tree', absolute: templates };
  }

  return { kind: 'in-tree', path: inside.split(sep).join('/') };
}
