/**
 * ПОДГОТОВКА — ОДНА НА ПРОГОН, и её нет ни в одном бюджете пробы.
 *
 * Заход `tasker:BASER2-189`. Три пробы зоны упали в конвейере по таймауту и
 * прошли на перезапуске БЕЗ ЕДИНОЙ ПРАВКИ. Смотрели не на «пробы медленные», а
 * на то, ЧТО именно они платят, — и совпадение оказалось точным: упавшие три
 * были ПЕРВОЙ пробой своего файла (`acceptance.spec.ts:90`,
 * `many-tools.spec.ts:158`, `supply.spec.ts:151`).
 *
 * Первая проба платила за подготовку обвеса: сборка тарбола была ленивой и
 * памятилась на модуль, а модульный реестр у vitest свой на каждый файл. Значит
 * из десяти файлов зоны, которые ставят девбокс, каждый собирал тарбол заново —
 * и всегда в бюджете того, кто начался первым.
 *
 * ```
 * первая installDevbox = 264 мс, вторая = 1 мс        (девбокс, 4 ядра, 2026-08-05)
 * npm pack + tar: 254 · 274 · 255 мс в одиночку, 480 … 739 мс — восемь разом
 * ```
 *
 * Лечится это не сроком ожидания: ждать нечего, работа настоящая. Лечится тем,
 * что общего ресурса не остаётся — тарбол собирается один раз на прогон, до
 * первой пробы (`packed.setup.ts`). Тот же способ, которым зона уже лечила этот
 * класс (`tasker:BASER2-156`).
 *
 * ── ЧТО СУДИТСЯ ЗДЕСЬ ───────────────────────────────────────────────────────
 *
 * Не длительность: проба, судящая миллисекунды, сама становится лотереей —
 * ровно тем, от чего этот заход уходит. Судятся ПРИЧИНЫ, и все они машинные:
 * подготовка приезжает прогоном · собирать её пробам нечем · порог назван в
 * конфиге, а не достался дефолтом.
 */

import { describe, expect, inject, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LIB = dirname(fileURLToPath(import.meta.url));
const ZONE = resolve(LIB, '../..');

describe('обвес готов ДО первой пробы, а не в ней', () => {
  it('прогон отдаёт собранный обвес — и это тарбол, а не каталог монорепы', () => {
    const packed = inject('packedDevbox');

    expect(existsSync(join(packed, 'package.json'))).toBe(true);
    // Настоящая поставка: шаблоны и резолверы на месте.
    expect(existsSync(join(packed, 'template'))).toBe(true);
    expect(existsSync(join(packed, 'defaults.mjs'))).toBe(true);
    // И ровно то, что уедет потребителю: пробы самого обвеса в тарбол не
    // входят — между «лежит в репозитории» и «приехало» стоит `files`.
    expect(existsSync(join(packed, 'test'))).toBe(false);
  });

  it('собрать его в пробе нечем: у фикстуры нет входа к процессам', () => {
    // Пока сборка жила в фикстуре, её звала первая проба — по построению, а не
    // по невнимательности. Вернуть её обратно теперь нечем: у фикстуры
    // установки нет входа к внешним процессам вовсе, а другого входа в зоне не
    // существует (`sealed.spec.ts` сторожит это по всей зоне).
    const fixture = readFileSync(join(LIB, 'devbox.fixture.ts'), 'utf-8');

    expect(fixture).not.toMatch(/from '\.\/sealed\.fixture\.js'/);
  });

  it('подготовка объявлена прогоном, а не позвана из пробы', () => {
    const config = readFileSync(join(ZONE, 'vitest.config.mts'), 'utf-8');

    expect(config).toMatch(/globalSetup:\s*\['\.\/src\/lib\/packed\.setup\.ts'\]/);
    // И файл, на который она указывает, существует: снятая регистрация
    // покраснела бы и без этого (пробам стало бы неоткуда взять обвес), а вот
    // переименованный файл — молча.
    expect(existsSync(join(ZONE, 'src/lib/packed.setup.ts'))).toBe(true);
  });
});

describe('порог назван, а не достался по умолчанию', () => {
  it('зона объявляет свой срок и для проб, и для хуков', () => {
    // Дефолт vitest (5000 мс проба, 10 000 мс хук) выбран для проб над чистыми
    // функциями. Пробы этой зоны ходят на диск и зовут пакетный менеджер, и
    // молча взятый чужой порог — это порог, который никто не выбирал.
    const config = readFileSync(join(ZONE, 'vitest.config.mts'), 'utf-8');

    expect(config).toMatch(/testTimeout:\s*\d/);
    expect(config).toMatch(/hookTimeout:\s*\d/);
    // И названо, почему именно столько: число без причины через полгода снимут
    // как случайное.
    expect(config).toContain('2848');
  });
});
