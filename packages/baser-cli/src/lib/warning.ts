/**
 * ПРЕДУПРЕЖДЕНИЕ ОБВЕСА — консоль его СЧИТАЕТ, а печатает потом (`report.ts`).
 *
 * Последнее звено шва `tasker:BASER2-226`. Форма объявила поле `warningFrom` и
 * разбирает то, что резолвер вернул (`baser-contracts`, `warning.ts`); движок
 * несёт посчитанное до ответа (`baser-materialize`, `warning.ts`); резолвер
 * ГРУЗИТ И ЗОВЁТ консоль — у неё одной есть файловая система и распакованный
 * пакет обвеса. Тот же порядок, что у значений настроек.
 *
 * Живой случай, ради которого всё: локация с заданным `core.hooksPath` получает
 * хук в `.git/hooks` — он ляжет верно и НЕ СРАБОТАЕТ, потому что git смотрит в
 * другой каталог. Прогон при этом верный, отказывать не за что, но человек
 * обязан услышать (`tasker:BASER2-208`). Про `core.hooksPath` консоль не знает
 * и знать не должна: условие и текст объявляет обвес, консоль печатает.
 *
 * ## Здесь НЕТ ни одного решения — и это главное свойство модуля
 *
 * Годен ли ответ резолвера, чем называется пустота, что делать с броском —
 * решено в контрактах, целиком и один раз. Своей ветки «а если он вернул не
 * то» консоль не заводит: вторая правда про чужой ответ разошлась бы с первой
 * молча, и разошлась бы в ту сторону, где обвес считает, что предупреждение
 * работает, а человек его не видит.
 *
 * Отсюда и вызов `resolveWarning` БЕЗ порта на молчащем обвесе: «поля нет —
 * сказать нечего» тоже решение формы, и повторять его здесь условием значило бы
 * завести второе место, где живёт то же правило.
 *
 * ## Прогон это не останавливает НИКОГДА
 *
 * Ни бросок резолвера, ни отсутствующий модуль, ни негодный ответ. Всё
 * случившееся приезжает состоянием `SourceWarning` (`failed` с кодом и адресом)
 * и печатается как БЕДА ОБСТАНОВКИ, а не как отказ локации: код возврата
 * прогона от предупреждения не зависит вовсе — он считается от `status`
 * (`result.ts`, `exitCodeOf`), а `status` про предупреждение не знает.
 */

import {
  resolveWarning,
  type SourceDeclaration,
  type SourceWarning,
} from '@omnifield/baser-contracts';
import type { LocatedPackage } from '@omnifield/baser-contracts/locate';
import type { Repo } from './repo.js';
import { loadResolvers } from './resolvers.js';

/**
 * Что обвес говорит про своё применение В ЭТОЙ локации.
 *
 * Считается ДО плана и от плана не зависит: предупреждение — про обстановку, а
 * не про работу, и обвес, которому нечего класть, говорит его ровно так же, как
 * обвес с десятью артефактами.
 */
export async function loadWarning(
  declaration: SourceDeclaration,
  pkg: LocatedPackage,
  repo: Repo,
): Promise<SourceWarning> {
  const ref = declaration.warningFrom;
  if (ref === undefined) {
    // Молчащий обвес не платит за поле ничем: ни импорта, ни чтения диска.
    return resolveWarning(declaration);
  }

  const port = await loadResolvers([ref], declaration, pkg, repo);
  return resolveWarning(declaration, (asked) => port.call(asked));
}
