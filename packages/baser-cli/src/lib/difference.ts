/**
 * ЧТО ИЗ ЧУЖОГО ФАЙЛА НЕ ВОСПРОИЗВЕДЁТСЯ — построчно и не разбирая формат.
 *
 * План печатает свои значения и молчит о том, что было у человека и не
 * воспроизведётся (`tasker:BASER2-112`). `tasker:BASER2-106` научил отказ
 * говорить, что **твой файл не прочитан**, — и это половина правды: человек
 * знает, что подстановки не будет, но по-прежнему не знает, ЧЕГО именно
 * лишится. Читать `devcontainer.json` глазами и сверять с блоком значений —
 * работа, которую мы переложили на него.
 *
 * ── ЧТО ДВЕРЬ МОЖЕТ, НЕ ЗАЛЕЗАЯ В СЕМАНТИКУ ─────────────────────────────────
 *
 * Артефакт бывает любым файлом, и разбирать его формат дверь не должна и не
 * будет. Но она держит в руках ОБА КОНЦА: файл, который лежит, и файл, который
 * ляжет. Значит может показать **построчное расхождение** — честно и для любого
 * формата. Человек, увидевший в нём исчезающие `features`, `containerEnv` и
 * `forwardPorts`, узнает свою потерю сам, и узнает её ДО подтверждения, а не
 * первым `git commit`.
 *
 * **Это не «умный перенос».** Дверь не угадывает, во что превратить чужие
 * ключи, и ничего не переносит: она показывает разницу, решает человек.
 *
 * ── ПРАВИЛА СРАВНЕНИЯ, И ОНИ НАЗВАНЫ ────────────────────────────────────────
 *
 * **Единица — строка целиком, как есть.** Ни отступ, ни кавычки не
 * нормализуются: строка, отличающаяся отступом, — другая строка, и утверждать
 * обратное значило бы начать разбирать формат с самого мелкого его конца.
 *
 * **Порядок не учитывается, кратность — да.** Строка, переехавшая на другое
 * место, не потеряна, и называть её потерей значило бы кричать на
 * форматирование. А строка, встречавшаяся дважды и оставшаяся одна, названа
 * исчезнувшей один раз.
 *
 * **Пустая строка не содержимое** и в сравнение не берётся вовсе: расхождение
 * из четырёх пустых строк рассказывает человеку ровно ничего, а место в выводе
 * занимает наравне с настоящей потерей.
 *
 * ── ЧЕГО РАСХОЖДЕНИЕ НЕ СЧИТАЕТ, И ЭТО ВИДНО В ОТВЕТЕ ───────────────────────
 *
 * Файл длиннее `MAX_LINES` строк либо содержащий нулевой байт (то есть двоичный)
 * не сверяется: `measured: false`. Не «расхождений нет» — именно «не считали».
 * Тихо отдать пустой список значило бы сказать «ничего не потеряешь» там, где
 * дверь не смотрела.
 *
 * **Усечение тоже названо.** В показ идёт не больше `limit` строк на сторону, а
 * `goneCount` и `comesCount` говорят, сколько их всего: молча обрезанный список
 * читается как полный, и это ровно то умолчание, от которого вся эта работа.
 */

/** Построчное расхождение по одному артефакту. */
export interface ArtifactDifference {
  readonly dest: string;
  /** Строки лежащего файла, которых в новом содержимом нет. Усечены до `limit`. */
  readonly gone: readonly string[];
  /** Строки нового содержимого, которых нет в лежащем файле. */
  readonly comes: readonly string[];
  /** Сколько строк не воспроизводится ВСЕГО — до усечения. */
  readonly goneCount: number;
  /** Сколько строк появится ВСЕГО — до усечения. */
  readonly comesCount: number;
  /**
   * Расхождение считалось.
   *
   * `false` — файл двоичный либо длиннее предела, и пустые списки здесь значат
   * «не смотрели», а не «потерь нет».
   */
  readonly measured: boolean;
}

export interface DifferenceInput {
  readonly dest: string;
  /** Содержимое, лежащее на диске. */
  readonly placed: string;
  /** Содержимое, которое ляжет на его место. */
  readonly comes: string;
  /** Сколько строк показывать на сторону; `null` — целиком. */
  readonly limit: number | null;
}

/**
 * Предел длины файла, на котором расхождение считается.
 *
 * Артефакты обвеса живут в сотнях строк. Предел стоит не как тюнинг, а чтобы
 * человек, у которого на пути обвеса оказался мегабайтный файл, получил
 * названное «не считали» вместо подвисшего плана.
 */
const MAX_LINES = 2000;

export function differenceOf(input: DifferenceInput): ArtifactDifference {
  const shell = { dest: input.dest, gone: [], comes: [], measured: false };

  if (!measurable(input.placed) || !measurable(input.comes)) {
    return { ...shell, goneCount: 0, comesCount: 0 };
  }

  const placed = content(input.placed);
  const comes = content(input.comes);
  const gone = only(placed, comes);
  const arriving = only(comes, placed);

  return {
    dest: input.dest,
    gone: cut(gone, input.limit),
    comes: cut(arriving, input.limit),
    goneCount: gone.length,
    comesCount: arriving.length,
    measured: true,
  };
}

/** Содержательные строки текста: пустые не содержимое (см. шапку). */
function content(text: string): readonly string[] {
  return text.split('\n').filter((line) => line.trim() !== '');
}

/**
 * Строки, которых во втором тексте нет, — С УЧЁТОМ КРАТНОСТИ.
 *
 * Счётчик, а не множество: строка, стоявшая дважды и оставшаяся одна, потеряна
 * ровно один раз, и сказать «потеряна» или «цела» было бы одинаково неверно.
 */
function only(
  from: readonly string[],
  other: readonly string[],
): readonly string[] {
  const left = new Map<string, number>();
  for (const line of other) {
    left.set(line, (left.get(line) ?? 0) + 1);
  }

  const found: string[] = [];
  for (const line of from) {
    const held = left.get(line) ?? 0;
    if (held > 0) {
      left.set(line, held - 1);
      continue;
    }
    found.push(line);
  }
  return found;
}

function cut(
  lines: readonly string[],
  limit: number | null,
): readonly string[] {
  return limit === null ? lines : lines.slice(0, limit);
}

/** Текст, который вообще можно сверять построчно. */
function measurable(text: string): boolean {
  return !text.includes('\0') && text.split('\n').length <= MAX_LINES;
}
