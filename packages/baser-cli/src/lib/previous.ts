/**
 * ПРЕЖНИЙ КОНЕЦ ДВИЖЕНИЯ — прочитанный из разложенного артефакта и ДОКАЗАННЫЙ.
 *
 * Дверь называла движение значений наполовину: `diverged` и новое значение.
 * Прежнего конца не было нигде — ни в конфиге (там только заполненное), ни в
 * паспорте укладки (он помнит, ЧТО положено, а не с какими значениями). Человек
 * читал план и не узнавал, что именно у него сменится и на что
 * (`tasker:BASER2-38`).
 *
 * Цена этой половины — не абстрактная. Смена резолвера имени репозитория
 * (`tasker:BASER2-32`) двигает у потребителя, который имя не настраивал, имя
 * контейнера и **сетевой алиас**. Алиас есть обещание СОСЕДЯМ: сосед ходит на
 * `http://weber:3000`, и смена адреса ломает не наш контейнер, а чужие.
 *
 * ── ГДЕ ПАМЯТЬ, И ПОЧЕМУ ИМЕННО ТАМ ─────────────────────────────────────────
 *
 * Прежние значения нигде не записаны — но они ОТПЕЧАТАНЫ: разложенный артефакт
 * и есть результат подстановки прежних значений в шаблон. Он лежит на диске, он
 * наш (владение доказано паспортом укладки), и движок отдаёт его содержимое
 * шагом плана (`step.previous`). Значит второй конец можно не хранить, а
 * прочитать.
 *
 * Альтернатива — класть значения в паспорт укладки — была бы изменением ФОРМЫ
 * ЗАПИСИ, то есть шва между зонами. Платить связностью за то, что уже лежит
 * рядом, незачем; там, где отпечатка не хватает, дверь молчит (см. ниже), и
 * молчание честнее чужой формы, изменённой на всякий случай.
 *
 * ── КАК ЧИТАЕТСЯ (и почему это не догадка) ──────────────────────────────────
 *
 * 1. Шаблон рендерится ещё раз, но каждое строковое значение подменяется
 *    МЕТКОЙ — уникальной на настройку. Получается отпечаток с дырами ровно там,
 *    куда эти значения приземляются.
 * 2. Разложенный артефакт прикладывается к отпечатку: неизменные куски обязаны
 *    совпасть подряд и целиком, а дыры дают кандидатов в прежние значения.
 * 3. **Кандидаты доказываются.** Шаблон рендерится третий раз — уже с ними, — и
 *    результат обязан совпасть с лежащим артефактом БАЙТ В БАЙТ. Не совпал —
 *    дверь не говорит ничего.
 *
 * Шаг 3 и делает это утверждением, а не эвристикой: назван не «похожий»
 * кандидат, а значение, которым лежащий файл воспроизводится целиком. Ошибиться
 * в пользу молчания механизм может (и будет — см. границы), соврать не может.
 *
 * ── ЧЕГО МЕХАНИЗМ НЕ ВОССТАНОВИТ, И ЭТО НАЗВАНО ─────────────────────────────
 *
 * - **Шаблон уехал вместе со значениями.** Прежний артефакт не воспроизводится
 *   НИ ОДНИМ набором значений нового шаблона — доказать нечем.
 * - **Артефакт правили руками.** То же самое, и план говорит про это своим
 *   `diverged`, а не выдуманным движением настройки.
 * - **Списки и флаги.** Строка ложится в текст подстрокой, и её видно. Список
 *   разворачивается шаблоном в структуру, флаг — в ветку: «прежнего места» у
 *   них в тексте нет вовсе, и подменять их меткой значило бы рендерить не то,
 *   что рендерилось.
 *
 * Во всех трёх случаях защита не пропадает: расхождение артефакта названо
 * планом, как и раньше. Пропадает только рассказ, которому нечем быть правдой.
 */

import type { SettingValue } from '@omnifield/baser-contracts';

/** Прежнее значение и артефакт, которым оно доказано. */
export interface PlacedValue {
  readonly value: SettingValue;
  /** `dest` артефакта, воспроизводящегося этим значением байт в байт. */
  readonly provenBy: string;
}

export interface RecoverInput {
  /** Значения, с которыми артефакт ляжет сейчас. */
  readonly values: Readonly<Record<string, SettingValue>>;
  /** Содержимое, лежащее на диске: отпечаток прежних значений. */
  readonly placed: string;
  /** Адрес этого артефакта — он же будущее доказательство. */
  readonly dest: string;
  /** Пересчёт ЭТОГО артефакта на других значениях (`render.ts`). */
  readonly rerender: (
    values: Readonly<Record<string, SettingValue>>,
  ) => string | null;
}

/**
 * Метка на настройку — печатная латиница с нонсенсом на конце.
 *
 * Первым здесь стоял нулевой байт: «символ, которого в тексте не бывает».
 * Красиво и неверно. Значение попадает в артефакт не только напрямую, но и
 * через `JSON.stringify` — так девбокс собирает `runArgs`, список расширений и
 * `postCreateCommand`, — а тот экранирует управляющие символы: метка приезжала
 * в отпечаток шестью печатными знаками и переставала быть меткой. Дыра
 * находилась не везде, отпечаток не сходился, и механизм молчал ровно там, где
 * обязан был говорить.
 *
 * Отсюда требование к метке: **пережить сериализацию неизменной.** Печатная
 * латиница с дефисами проходит как есть и через `JSON.stringify`, и через
 * кавычки шелла.
 *
 * Совпасть с настоящим содержимым она теоретически может — тогда дыра найдётся
 * не там. Ценой будет молчание, а не враньё: подобранное значение не
 * воспроизведёт лежащий артефакт, и доказательство не сойдётся.
 */
function mark(index: number): string {
  return `baser-placed-${index}-e3b0c44298fc`;
}

const MARK = /baser-placed-(\d+)-e3b0c44298fc/g;

/**
 * Сколько дыр разбирается за раз.
 *
 * Каждая дыра — ленивая группа в выражении, и на сотнях дыр разбор перестаёт
 * быть дешёвым. Настоящие обвесы держатся в единицах: предел стоит не как
 * тюнинг, а чтобы отказ был предсказуем и назывался молчанием, а не подвисшим
 * планом.
 */
const MAX_SLOTS = 64;

/**
 * Прежние значения, которыми лежащий артефакт воспроизводится побайтово.
 *
 * Пустая карта — восстановить не удалось либо восстанавливать нечего. Разницы
 * для вызывающего нет: и там, и там утверждать нечего.
 */
export function recoverPlacedValues(
  input: RecoverInput,
): ReadonlyMap<string, PlacedValue> {
  const empty = new Map<string, PlacedValue>();

  // Подменяются только строки: см. границы в шапке.
  const strings = Object.keys(input.values).filter(
    (key) => typeof input.values[key] === 'string',
  );
  if (strings.length === 0) {
    return empty;
  }

  const target = input.rerender(input.values);
  if (target === null) {
    return empty;
  }

  const keys = strings.filter((key) =>
    substitutes(key, strings.indexOf(key), input, target),
  );
  if (keys.length === 0) {
    return empty;
  }

  const marked: Record<string, SettingValue> = { ...input.values };
  for (const key of keys) {
    marked[key] = mark(strings.indexOf(key));
  }

  const stencil = input.rerender(marked);
  if (stencil === null) {
    return empty;
  }

  const slots = readSlots(stencil, strings);
  if (slots === null) {
    return empty;
  }

  const candidates = matchStencil(slots, input.placed);
  if (candidates === null) {
    return empty;
  }

  // Двигалось ли хоть что-то. Совпало — артефакт разошёлся не значениями (или
  // не разошёлся вовсе), и переезд называть не о чем.
  const moved = [...candidates].filter(
    ([key, value]) => value !== input.values[key],
  );
  if (moved.length === 0) {
    return empty;
  }

  // ── ДОКАЗАТЕЛЬСТВО. Пока его нет, всё выше — гипотеза.
  const proof = input.rerender({
    ...input.values,
    ...Object.fromEntries(moved),
  });
  if (proof !== input.placed) {
    return empty;
  }

  return new Map(
    moved.map(([key, value]) => [key, { value, provenBy: input.dest }]),
  );
}

/**
 * Настройка ПОДСТАВЛЯЕТСЯ, а не участвует в решении шаблона.
 *
 * Метка обязана быть только подстановкой. Значение, от которого шаблон
 * ВЕТВИТСЯ, под меткой меняет не текст, а структуру, и отпечаток перестаёт быть
 * отпечатком этого артефакта. Живой пример из девбокса: форматтер редактора сам
 * дописывается в список расширений, если его там нет, — под меткой он там не
 * находится и дописывается лишней строкой.
 *
 * Проверка прямая: рендерим с одной меткой и вставляем значение обратно на её
 * места. Совпало с целевым содержимым — метка была подстановкой и ничем больше.
 * Не совпало — настройка в отпечаток не берётся, и её прежний конец останется
 * неназванным. Это ровно тот случай, когда молчание честнее рассказа.
 */
function substitutes(
  key: string,
  index: number,
  input: RecoverInput,
  target: string,
): boolean {
  const token = mark(index);
  const alone = input.rerender({ ...input.values, [key]: token });
  return (
    alone !== null &&
    alone.split(token).join(String(input.values[key])) === target
  );
}

/** Отпечаток, разобранный на неизменные куски и дыры под значения. */
interface Stencil {
  /** Куски текста между дырами: `literals[i]` идёт перед `slots[i]`. */
  readonly literals: readonly string[];
  /** Настройка, чьё значение стоит в этой дыре. */
  readonly slots: readonly string[];
}

function readSlots(stencil: string, keys: readonly string[]): Stencil | null {
  const literals: string[] = [];
  const slots: string[] = [];
  let cursor = 0;

  MARK.lastIndex = 0;
  for (
    let found = MARK.exec(stencil);
    found !== null;
    found = MARK.exec(stencil)
  ) {
    literals.push(stencil.slice(cursor, found.index));
    slots.push(keys[Number(found[1])]);
    cursor = found.index + found[0].length;
  }

  if (slots.length === 0 || slots.length > MAX_SLOTS) {
    // Ни одна настройка в артефакт не приземляется — восстанавливать нечего.
    return null;
  }
  literals.push(stencil.slice(cursor));

  return { literals, slots };
}

/**
 * Прикладывает отпечаток к лежащему тексту и вынимает содержимое дыр.
 *
 * Неизменные куски обязаны совпасть ЦЕЛИКОМ и подряд — от первого символа до
 * последнего. Совпадение «где-то в середине» означало бы, что мы читаем чужой
 * файл по своему шаблону, а это ровно та уверенность не туда, которой здесь
 * быть не должно.
 *
 * Одна настройка может приземляться в артефакт несколько раз (имя девбокса —
 * и в комментарии, и в поле): все её дыры обязаны дать ОДНО значение, иначе
 * прочитано не то.
 */
function matchStencil(
  stencil: Stencil,
  placed: string,
): Map<string, SettingValue> | null {
  const pattern = new RegExp(
    `^${stencil.literals.map(escape).join('([\\s\\S]*?)')}$`,
  );
  const found = pattern.exec(placed);
  if (found === null) {
    return null;
  }

  const values = new Map<string, SettingValue>();
  for (const [index, key] of stencil.slots.entries()) {
    const value = found[index + 1];
    const seen = values.get(key);
    if (seen !== undefined && seen !== value) {
      return null;
    }
    values.set(key, value);
  }
  return values;
}

function escape(literal: string): string {
  return literal.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
