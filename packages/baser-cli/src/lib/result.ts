/**
 * ОТВЕТ ДВЕРИ — данные. Текст поверх них — рендер, а не вторая правда.
 *
 * Потребитель прогона это скрипт, гейт и пульт, а не только человек в терминале
 * (`tasker:BASER2-20`), поэтому команда сначала СОБИРАЕТ вот эту структуру и
 * лишь потом что-то печатает. `renderText` принимает её целиком и больше ничего:
 * то, чего нет здесь, человеку показать физически нечем — так «текст — рендер
 * поверх тех же данных» держится формой, а не дисциплиной.
 *
 * Своей семантики поверх соседних зон здесь нет: план, отчёт применения и их
 * коды приезжают от движка как есть, отказы формы — с кодами контрактов. Дверь
 * добавляет ровно то, чего не знает ни та, ни другая зона: где она работала,
 * что прочитала, какое движение значений назвала и что легло на диск.
 *
 * ## Обвесов много, ответ один (`tasker:BASER2-55`)
 *
 * Несколько инструментов в одном репозитории — норма по построению
 * (`kb:BASER2-4`), а движок считает план по ОДНОЙ декларации. Значит прогонов
 * столько же, сколько обвесов, и они лежат в `runs` — по одному на обвес, с его
 * планом, его значениями и его отчётом применения.
 *
 * **Планы НЕ сводятся в один.** Сложить шаги двух прогонов в объект типа движка
 * значило бы предъявить план, которого движок не считал: у конфликта нет поля
 * «чей», у снятия нет записи, и владение в таком плане перестало бы читаться —
 * ровно то различение, ради которого писался `tasker:BASER2-7`.
 *
 * **Один здесь — ОТВЕТ:** `status`, `problems`, `writes`, код возврата и итог
 * прогона общие на все обвесы. Применение проходит целиком либо никак, поэтому
 * второго исхода у прогона быть не может, сколько бы инструментов ни стояло.
 */

import type {
  ApplyReport,
  MaterializationPlan,
  TraceSpan,
} from '@omnifield/baser-materialize';
import type { DerivedMove } from './derived.js';
import type { ArtifactDifference } from './difference.js';
import type { DoorProblem } from './problems.js';
import type { SourceLocation } from './installed.js';
import type { SettingMovement } from './values.js';

export type DoorCommand = 'plan' | 'apply';

/**
 * Чем кончился прогон.
 *
 * Сходимость отделена от пустоты по той же причине, что у движка: гейт,
 * зеленеющий на нерешённом конфликте, опаснее отсутствующего. Отделён и отказ
 * ДВЕРИ от отказа ДВИЖКА — чинить их идут в разные места: непригодный конфиг
 * правит пользователь, конфликт владения решает подтверждение или раскладка.
 */
export type DoorStatus =
  /** Обвесов не поставлено — раскладывать нечего. Это не ошибка. */
  | 'no-sources'
  /**
   * Делать нечего: ни шага у движка, ни конфига, который дверь родила бы.
   *
   * Именно это спрашивает гейт, поэтому мерится прогон ЦЕЛИКОМ, а не один
   * план: конфиг движок своим шагом не считает и считать не может.
   */
  | 'converged'
  /** Работа есть и она применима; команда `plan` её не применяла. */
  | 'pending'
  /** Шаги применены и сброшены на диск. */
  | 'applied'
  /** Движок отказал конфликтами владения — не применено ничего. */
  | 'blocked'
  /**
   * Плана нет: прогон отказал на входе.
   *
   * Отказать могла дверь (непригодный конфиг, шаблон на чужом языке) или движок
   * до плана (битая служебная запись, непригодная структура). Отделять их
   * статусом незачем — чинить идут по АДРЕСУ отказа, и он у каждого свой; а вот
   * приписать в статусе отказ не тому значило бы отправить человека не туда.
   */
  | 'refused';

export interface RepoReport {
  readonly root: string;
  readonly name: string;
}

export interface ConfigReport {
  readonly path: string;
  /** Файл лежал на диске до прогона. */
  readonly existed: boolean;
  /**
   * Этот прогон рождает конфиг.
   *
   * Настоящее время, а не прошедшее: у `plan` это НАМЕРЕНИЕ (он не пишет), у
   * `apply` — факт. Что действительно легло на диск, говорит `writes`, и только
   * он: поле «created» на плане читалось бы как «файл уже есть», а гейт,
   * поверивший в это, разошёлся бы с репозиторием.
   */
  readonly creates: boolean;
  /** Версия формы конфига: её проставляет дверь, пользователь не вводит ничего. */
  readonly formVersion: number;
}

export interface SourceReport {
  /** Идентичность обвеса — не имя пакета. */
  readonly id: string;
  readonly title: string;
  readonly packageName: string;
  /**
   * Версия пакета обвеса; `null` — обвес её не назвал.
   *
   * Тот же факт уезжает в паспорт укладки (`ManifestRecord.version`), и место у
   * него ОДНО — манифест пакета: дверь его читает, показывает человеку и подаёт
   * движку. Второго поля в объявлении нет и не будет (`kb:BASER2-2`).
   */
  readonly packageVersion: string | null;
  /** Абсолютный корень распакованного пакета. */
  readonly packageRoot: string;
  /** Корень содержимого, как объявил обвес: путь ВНУТРИ его пакета. */
  readonly contentRoot: string;
  /** Тот же корень глазами движка: путь в дереве потребителя либо его отсутствие. */
  readonly location: SourceLocation;
}

/**
 * Состоявшаяся запись в реальную ФС.
 *
 * Список включает конфиг потребителя, которого нет в плане движка: движок о нём
 * не знает и знать не должен. У `plan` он ПУСТ по построению — план не пишет, а
 * то, что ляжет, читается из `runs[].plan.steps` и `config.creates`.
 */
export interface WriteReport {
  readonly path: string;
  readonly kind: 'CREATE' | 'UPDATE' | 'DELETE';
}

/**
 * Файл настроек обвеса у потребителя — `.omnifield/<поставщик>-<обвес>.yaml`.
 *
 * Версии формы тут нет и не будет: файл не самостоятельная форма, а вторая
 * половина той же — версию несёт `baser.json`, и второй номер на одну форму
 * означал бы, что половинки могут разъехаться, чего им никто не обещал.
 */
export interface SourceConfigReport {
  /** Путь относительно корня репозитория; считается из личности обвеса. */
  readonly path: string;
  /** Файл лежал на диске до прогона. */
  readonly existed: boolean;
  /**
   * Обвес объявил хоть одну настройку или пресет — то есть регулировать ЕСТЬ ЧТО.
   *
   * `null` — до этого вопроса прогон не дошёл (отказал раньше разбора
   * объявления). Не `false`: «регулировать нечего» это утверждение об обвесе, и
   * делать его, не заглянув в объявление, дверь не вправе.
   *
   * `false` — законное состояние, а не пробел: форма прямо разрешает обвесу не
   * объявлять ни `settings`, ни `presets`. Именно оно и решает, родится ли файл
   * (`tasker:BASER2-124`).
   */
  readonly tunable: boolean | null;
  /**
   * Этот прогон РОЖДАЕТ файл: его не было И обвесу есть что в него положить.
   *
   * Настоящее время, как и у `ConfigReport.creates`: у `plan` это намерение (он
   * не пишет), у `apply` — факт. Рождение бывает ровно одно на файл; дальше
   * дверь в него не пишет ни при каких условиях, и `creates` у неё больше
   * никогда не станет `true` (`kb:BASER2-5`).
   *
   * `existed: false` вместе с `creates: false` — не противоречие, а третье
   * состояние: файла нет и в этом прогоне не будет, потому что класть в него
   * нечего (`tunable: false`).
   */
  readonly creates: boolean;
}

/**
 * Прогон ПО ОДНОМУ обвесу — то, что дверь посчитала и применила его декларацией.
 *
 * Отдельная запись на обвес, а не общий котёл: план и отчёт применения приходят
 * от движка, а он работает по одной декларации за прогон. Приписать шаг не тому
 * обвесу здесь физически нечем — каждый лежит под своим.
 */
export interface SourceRun {
  readonly source: SourceReport;
  /**
   * Файл настроек ЭТОГО обвеса: где он и родит ли его этот прогон.
   *
   * Отдельно от `DoorResult.config`, потому что файлов два и они про разное:
   * `baser.json` говорит, что поставлено, а этот — как настроено
   * (`tasker:BASER2-10` §3). Свести их в один отчёт значило бы, что «создан»
   * относится неизвестно к какому из двух.
   */
  readonly config: SourceConfigReport;
  /**
   * Движение значений ЭТОГО обвеса, названное ДО применения (`kb:BASER2-5`).
   *
   * Стоит выше плана намеренно: это то, чего движок сказать не может, и то, что
   * человек обязан прочитать раньше, чем решит применять.
   */
  readonly settings: readonly SettingMovement[];
  /**
   * ПОСЧИТАННОЕ от переехавших значений — то, что переедет вместе с ними.
   *
   * Движение выше называет значение; здесь — его последствия в самом артефакте:
   * адрес тома, посчитанный от имени пользователя образа, уезжает вместе с ним,
   * а в томе лежит то, что человек клал руками (`tasker:BASER2-98`). Дверь при
   * этом не знает ни про тома, ни про формат — она называет слово артефакта,
   * которое исчезнет, и слово, которое встанет на его место (`derived.ts`).
   */
  readonly derived: readonly DerivedMove[];
  /**
   * ПОСТРОЧНОЕ РАСХОЖДЕНИЕ с чужим файлом — что из него не воспроизведётся.
   *
   * Только там, где на месте артефакта лежит НЕ НАШЕ: первая установка в
   * непустой репозиторий, потерянная служебная запись, подтверждённое взятие во
   * владение. План печатал свои значения и молчал о том, что было у человека
   * (`tasker:BASER2-112`); здесь названы обе стороны, и формат при этом не
   * разбирается (`difference.ts`).
   *
   * Пусто и у сошедшегося прогона, и у того, где чужого файла нет вовсе.
   */
  readonly differences: readonly ArtifactDifference[];
  /** План движка; `null` — до плана этот обвес не дошёл. */
  readonly plan: MaterializationPlan | null;
  /**
   * Отчёт применения; `null` у `plan` ВСЕГДА.
   *
   * Виртуальное дерево команда `plan` доводит до конца — иначе план второго
   * обвеса считался бы по состоянию, которого не будет. Но на диск не уходит
   * ничего, и назвать это «применено» значило бы отчитаться о работе, которой в
   * репозитории не было.
   */
  readonly applied: ApplyReport | null;
}

export interface DoorResult {
  /** Версия формы ответа ДВЕРИ. */
  readonly doorSchemaVersion: number;
  /** Версия формы объявления и конфига — из контрактов. */
  readonly formVersion: number;
  /** Версия схемы вывода движка — из движка. */
  readonly outputSchemaVersion: number;
  readonly command: DoorCommand;
  readonly status: DoorStatus;
  readonly repo: RepoReport;
  readonly config: ConfigReport;
  /**
   * Прогоны по каждому поставленному обвесу, в порядке конфига потребителя.
   *
   * Пуст, пока дверь не дошла до разбора объявлений; частичен, если отказ
   * случился на середине набора — отказ не обнуляет рассказ про то, что дверь
   * успела узнать про остальные.
   */
  readonly runs: readonly SourceRun[];
  readonly writes: readonly WriteReport[];
  /**
   * Спаны фаз ДВЕРИ: чтение конфига, разбор объявления, значения, подстановка,
   * сброс на диск.
   *
   * Отдельный список, а не общий с движком: `plan.trace` и `applied.trace`
   * принадлежат его зоне и мерят его работу. Свести их в один означало бы, что
   * потребитель, увидевший медленный прогон, не отличит разбор записи от чтения
   * десятка шаблонов, — а это разные починки в разных пакетах.
   *
   * Телеметрия, а не печать в поток: в текстовый рендер трейсы не идут.
   */
  readonly trace: readonly TraceSpan[];
  readonly problems: readonly DoorProblem[];
}

/**
 * Прогон ЕДИНСТВЕННОГО обвеса из ответа двери.
 *
 * Обвесов в ответе столько же, сколько поставлено (`tasker:BASER2-55`), а
 * спрашивают у ответа часто про один: гейт девбокса, проба, скрипт. Молчаливое
 * `runs[0]` в таком месте однажды начинает отвечать про первый из двух и
 * зеленеть на половине ответа, поэтому «не один» здесь — бросок с перечислением
 * того, что нашлось.
 *
 * **Публичная поверхность, а не тестовый хелпер.** Жил в фикстуре, и соседняя
 * зона держалась за него глубоким путём в наш `src/lib` (`tasker:BASER2-59`):
 * приёмка соседа была прибита к раскладке наших тестовых файлов, а сигнала об
 * этой зависимости у нас не было. Утверждение при этом — о ФОРМЕ ОТВЕТА
 * («обвес один — вот его прогон»), а форма ответа наша и публичная.
 */
export function soleRun(result: DoorResult): SourceRun {
  if (result.runs.length !== 1) {
    throw new Error(
      `ожидался ровно один прогон, а их ${result.runs.length}: ` +
        result.runs.map((run) => run.source.id).join(' · '),
    );
  }
  return result.runs[0];
}

/**
 * Код возврата процесса — производная от `status`, а не отдельный признак.
 *
 * Набор короткий намеренно: гейт в CI ветвится по нему, а разбирать полтора
 * десятка чисел никто не станет — подробности лежат в ответе данными.
 *
 * | код | что                                                     |
 * | --- | ------------------------------------------------------- |
 * | 0   | сделано либо нечего делать                              |
 * | 1   | движок отказал: конфликт владения, решать потребителю   |
 * | 2   | дверь отказала: вход непригоден, чинить конфиг/обвес    |
 */
export function exitCodeOf(result: DoorResult): number {
  switch (result.status) {
    case 'blocked':
      return 1;
    case 'refused':
      return 2;
    default:
      return 0;
  }
}
