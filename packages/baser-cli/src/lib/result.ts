/**
 * ОТВЕТ ДВЕРИ — данные. Текст поверх них — рендер, а не вторая правда.
 *
 * Потребитель прогона это скрипт, гейт и пульт, а не только человек в терминале
 * (`tasker:BASER2-20`), поэтому команда сначала СОБИРАЕТ вот эту структуру и
 * лишь потом что-то печатает. `renderText` принимает её целиком и больше ничего:
 * то, чего нет здесь, человеку показать физически нечем — так «текст — рендер
 * поверх тех же данных» держится формой, а не дисциплиной.
 *
 * Своей семантики поверх соседних зон здесь нет: план, отчёт применения и их
 * коды приезжают от движка как есть, отказы формы — с кодами контрактов. Дверь
 * добавляет ровно то, чего не знает ни та, ни другая зона: где она работала,
 * что прочитала, какое движение значений назвала и что легло на диск.
 */

import type {
  ApplyReport,
  MaterializationPlan,
  TraceSpan,
} from '@omnifield/baser-materialize';
import type { DoorProblem } from './problems.js';
import type { SourceLocation } from './installed.js';
import type { SettingMovement } from './values.js';

export type DoorCommand = 'plan' | 'apply';

/**
 * Чем кончился прогон.
 *
 * Сходимость отделена от пустоты по той же причине, что у движка: гейт,
 * зеленеющий на нерешённом конфликте, опаснее отсутствующего. Отделён и отказ
 * ДВЕРИ от отказа ДВИЖКА — чинить их идут в разные места: непригодный конфиг
 * правит пользователь, конфликт владения решает подтверждение или раскладка.
 */
export type DoorStatus =
  /** Обвесов не поставлено — раскладывать нечего. Это не ошибка. */
  | 'no-sources'
  /**
   * Делать нечего: ни шага у движка, ни конфига, который дверь родила бы.
   *
   * Именно это спрашивает гейт, поэтому мерится прогон ЦЕЛИКОМ, а не один
   * план: конфиг движок своим шагом не считает и считать не может.
   */
  | 'converged'
  /** Работа есть и она применима; команда `plan` её не применяла. */
  | 'pending'
  /** Шаги применены и сброшены на диск. */
  | 'applied'
  /** Движок отказал конфликтами владения — не применено ничего. */
  | 'blocked'
  /** Дверь отказала ДО движка: вход собрать не из чего. */
  | 'refused';

export interface RepoReport {
  readonly root: string;
  readonly name: string;
}

export interface ConfigReport {
  readonly path: string;
  /** Файл лежал на диске до прогона. */
  readonly existed: boolean;
  /**
   * Этот прогон рождает конфиг.
   *
   * Настоящее время, а не прошедшее: у `plan` это НАМЕРЕНИЕ (он не пишет), у
   * `apply` — факт. Что действительно легло на диск, говорит `writes`, и только
   * он: поле «created» на плане читалось бы как «файл уже есть», а гейт,
   * поверивший в это, разошёлся бы с репозиторием.
   */
  readonly creates: boolean;
  /** Версия формы конфига: её проставляет дверь, пользователь не вводит ничего. */
  readonly formVersion: number;
}

export interface SourceReport {
  /** Идентичность обвеса — не имя пакета. */
  readonly id: string;
  readonly title: string;
  readonly packageName: string;
  readonly packageVersion: string;
  /** Абсолютный корень распакованного пакета. */
  readonly packageRoot: string;
  /** Корень содержимого, как объявил обвес: путь ВНУТРИ его пакета. */
  readonly contentRoot: string;
  /** Тот же корень глазами движка: путь в дереве потребителя либо его отсутствие. */
  readonly location: SourceLocation;
}

/**
 * Состоявшаяся запись в реальную ФС.
 *
 * Список включает конфиг потребителя, которого нет в плане движка: движок о нём
 * не знает и знать не должен. У `plan` он ПУСТ по построению — план не пишет, а
 * то, что ляжет, читается из `plan.steps` и `config.created`.
 */
export interface WriteReport {
  readonly path: string;
  readonly kind: 'CREATE' | 'UPDATE' | 'DELETE';
}

export interface DoorResult {
  /** Версия формы ответа ДВЕРИ. */
  readonly doorSchemaVersion: number;
  /** Версия формы объявления и конфига — из контрактов. */
  readonly formVersion: number;
  /** Версия схемы вывода движка — из движка. */
  readonly outputSchemaVersion: number;
  readonly command: DoorCommand;
  readonly status: DoorStatus;
  readonly repo: RepoReport;
  readonly config: ConfigReport;
  readonly source: SourceReport | null;
  /**
   * Движение значений, названное ДО применения (`kb:BASER2-5`).
   *
   * Стоит в ответе выше плана намеренно: это то, чего движок сказать не может, и
   * то, что человек обязан прочитать раньше, чем решит применять.
   */
  readonly settings: readonly SettingMovement[];
  readonly plan: MaterializationPlan | null;
  readonly applied: ApplyReport | null;
  readonly writes: readonly WriteReport[];
  /**
   * Спаны фаз ДВЕРИ: чтение конфига, разбор объявления, значения, подстановка,
   * сброс на диск.
   *
   * Отдельный список, а не общий с движком: `plan.trace` и `applied.trace`
   * принадлежат его зоне и мерят его работу. Свести их в один означало бы, что
   * потребитель, увидевший медленный прогон, не отличит скан дерева от чтения
   * десятка шаблонов, — а это разные починки в разных пакетах.
   *
   * Телеметрия, а не печать в поток: в текстовый рендер трейсы не идут.
   */
  readonly trace: readonly TraceSpan[];
  readonly problems: readonly DoorProblem[];
}

/**
 * Код возврата процесса — производная от `status`, а не отдельный признак.
 *
 * Набор короткий намеренно: гейт в CI ветвится по нему, а разбирать полтора
 * десятка чисел никто не станет — подробности лежат в ответе данными.
 *
 * | код | что                                                     |
 * | --- | ------------------------------------------------------- |
 * | 0   | сделано либо нечего делать                              |
 * | 1   | движок отказал: конфликт владения, решать потребителю   |
 * | 2   | дверь отказала: вход непригоден, чинить конфиг/обвес    |
 */
export function exitCodeOf(result: DoorResult): number {
  switch (result.status) {
    case 'blocked':
      return 1;
    case 'refused':
      return 2;
    default:
      return 0;
  }
}
