/**
 * ВИРТУАЛЬНОЕ ДЕРЕВО НАД РЕАЛЬНОЙ ФС — порт, который дверь держит сама.
 *
 * Движок работает только с `Tree` и файловой системы не касается вовсе; кто
 * подаёт ему дерево и кто потом сбрасывает изменения на диск — работа раннера
 * (`packages/baser-materialize/README.md`). Раньше дверь брала для этого `FsTree`
 * из `nx`, и это работало, пока дверь жила в монорепе.
 *
 * ## Почему своя реализация, а не `FsTree`
 *
 * Ручная выдача уносит дверь в чужой репозиторий папкой в руках
 * (`tasker:BASER2-29`), и всё, что она несёт, обязано быть переносимым. `nx` —
 * 21 МБ и платформенные нативные модули (`@nx/nx-linux-x64-gnu` и соседи):
 * бандл с ними перестал бы работать при переносе на другую платформу, то есть
 * ровно там, где обещано «унесли и заработало».
 *
 * Цена вопроса — ШЕСТЬ МЕТОДОВ. Движок зовёт `read` · `write` · `exists` ·
 * `isFile` · `children` · `delete`, и больше ничего; `@nx/devkit` остаётся
 * зависимостью ТИПА, а в рантайме двери его нет. Тащить двадцать мегабайт ради
 * шести методов — не размен, а недосмотр.
 *
 * ## Седьмой член: режим артефакта (`tasker:BASER2-215`)
 *
 * Раскладка объявляет исполняемость (`layout[].executable`, форма 6), движок
 * доносит объявленное отдельным НЕОБЯЗАТЕЛЬНЫМ членом порта — `setExecutable`,
 * а не третьим параметром `write` (`packages/baser-materialize/src/lib/tree.ts`).
 * Форма выбрана так не по вкусу: наш мешок опций столкнулся бы с чужим
 * `{ mode?: Mode }` девкита, чью форму это дерево держит, — то есть покрасило бы
 * ровно нашу сборку.
 *
 * Здесь этот член РЕАЛИЗОВАН, и от этого меняется не только диск: движок видит
 * наличие члена и говорит в трейсе `apply.executable`, донеслось ли объявленное
 * до раннера (`port: "accepts"` против `"blind"`). Консоль перестала быть
 * слепым раннером — объявленное доезжает до бита.
 *
 * **Кладётся БИТ, а не режим целиком.** Объявление отвечает на один вопрос —
 * «программа или данные», — и отвечать за него на второй («кому читать») нельзя:
 * файл с правами `600`, объявленный программой, обязан стать `700`, а не
 * общедоступным `755`. Исполняемость поэтому ложится поверх сложившегося
 * режима, и ложится по праву чтения (`programMode`).
 *
 * **Режим — часть расхождения с диском, а не довесок к записи.** Файл, чьё
 * содержимое совпало, а режим объявленному противоречит, — это расхождение, и
 * прогон обязан назвать его работой: иначе «сошлось» значило бы «содержимое
 * сошлось», и шов, ради которого всё это затевалось (`tasker:BASER2-208`),
 * закрылся бы наполовину. Бита, который не держит файловая система, здесь не
 * боимся: исполнение у нас контейнерное (`kb:FUND-4`), и диск под ним свой.
 *
 * ## Режим БЕЗ содержимого — четвёртое слово (`tasker:BASER2-223`)
 *
 * Паспорт укладки помнит теперь не только содержимое, но и то, ЧТО BASER СДЕЛАЛ
 * с файлом (`kb:BASER3-36`, форма паспорта 3). Отсюда расхождение нового вида:
 * содержимое сошлось, а бит разошёлся — и движок рождает на него **свой шаг,
 * `chmod`**, у которого содержимого нет вовсе. Порт зовётся на пути, который
 * этот прогон НЕ ПИШЕТ, и дерево обязано привести режим лежащему файлу, не
 * переписывая его. Дерево, требующее записи рядом, на таком шаге падало — это и
 * был замер, с которого началась задача.
 *
 * Поэтому у списка изменений появилось четвёртое слово — **`CHMOD`**, и это не
 * украшение: человек читает `writes` глазами, и «UPDATE» на файле, содержимое
 * которого не менялось, отправил бы его искать несуществующую правку
 * (`kb:BASER3-36` §3). Ценой стало расхождение с девкитом: его `FileChange`
 * знает три слова, наше — четыре. Расходимся ровно здесь и осознанно
 * (`RepoTree extends Omit<Tree, 'listChanges'>`): шесть методов по-прежнему
 * сверены с чужой формой компилятором, а список изменений — наш и говорит на
 * нашем словаре. Порт, который на самом деле обязан подойти, — не девкитовский,
 * а движковый (`packages/baser-materialize/src/lib/tree.ts`), и его соблюдение
 * проверяется каждым вызовом `computePlan`/`applyPlan` в `run.ts`.
 *
 * **Снимаем не всякий бит.** Что делать с режимом, решает не только объявление,
 * но и СЛЕД в паспорте (`kb:BASER3-36` §2), и решает это движок: инвариант
 * «baser никогда не снимает бит, которого не записал, что ставил» живёт там.
 * Дерево исполняет то, что ему сказали, и не гадает: не позвали — не тронули.
 *
 * ## Восьмой член: ЧИТАЮЩИЙ (`tasker:BASER2-225`)
 *
 * Режим — состояние, а не команда, и читается он той же рукой, что и пишется:
 * `isExecutable` рядом с `setExecutable`, как `read` рядом с `write`. Пары
 * «объявлено × след» движку хватало, пока бит менялся только нами; бит, сбитый
 * СНАРУЖИ, в неё не попадал вовсе — и прогон отвечал «сошлось» файлу, который
 * перестал работать (`tasker:BASER2-190`, правка через `\\wsl.localhost`).
 *
 * Дисковую сторону это дерево знало и раньше — `executableOnDisk` считал по ней
 * расхождения, — но наружу её не отдавало. С этим членом движок получает ТРЕТЬЮ
 * величину, сверяет тройку и говорит в трейсе `plan.executable`, чем сверялся:
 * `port: "reads"` вместо `"blind"`. Своего мнения о том, каким режим ДОЛЖЕН
 * быть, у дерева при этом не прибавилось ни на грамм: оно отвечает, какой он
 * ЕСТЬ. Этим членом шов `tasker:BASER2-221` закрывается целиком.
 *
 * ## Что здесь важно не переизобрести
 *
 * Дерево виртуально: изменения копятся в памяти и уезжают на диск ОДНИМ
 * броском (`flush`). Отсюда два инварианта, которые держит этот файл:
 *
 * **Изменение — это расхождение с диском, а не факт вызова `write`.** Запись,
 * совпавшая с тем, что уже лежит, изменением не является: иначе прогон, который
 * ничего не поменял, рапортовал бы работу, а «сошлось» перестало бы значить
 * «делать нечего».
 *
 * **Снятия идут раньше записей.** Артефакт, переобъявленный из файла в каталог,
 * освобождает путь именно снятием; выполнив запись первой, сброс упёрся бы в
 * занятый путь — и упал бы уже ВНЕ журнала отката движка.
 */

import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import type { Mode } from 'node:fs';
import type { Tree } from '@nx/devkit';

/**
 * Вид изменения. Три слова про содержимое плюс одно про режим.
 *
 * `CHMOD` — содержимое файла СОВПАЛО, разошёлся бит: приводим режим и ничего не
 * переписываем (`kb:BASER3-36` §3). Своё слово, а не `UPDATE`, потому что этот
 * список читает человек: «обновлён» на файле, в котором ничего не изменилось,
 * отправляет искать правку, которой нет.
 */
export type ChangeKind = 'CREATE' | 'UPDATE' | 'DELETE' | 'CHMOD';

/**
 * Изменение дерева: что легло бы на диск и с каким режимом.
 *
 * Своя форма, а не девкитовский `FileChange`: у того три слова, у нас четыре, и
 * четвёртое несёт `executable`. Совместимость, которая нам действительно нужна,
 * — с портом ДВИЖКА, а не с девкитом; она и проверяется вызовами движка.
 */
export interface RepoChange {
  readonly path: string;
  readonly type: ChangeKind;
  /** Содержимое к записи; `null` — снятие либо чистый `CHMOD`. */
  readonly content: Buffer | null;
  /** Режим числом — форма девкита (`write(..., { mode })`); движок ею не ходит. */
  readonly options?: { mode?: Mode };
  /** Приводимая исполняемость; поля нет — режим не трогаем. */
  readonly executable?: boolean;
}

/**
 * Дерево потребителя плюс то, что нужно раннеру: список и сброс.
 *
 * `Omit<…, 'listChanges'>` — единственное место, где мы РАСХОДИМСЯ с формой
 * девкита: его список изменений не знает слова `CHMOD`. Шесть методов, которые
 * зовёт движок, остаются сверены с чужой формой компилятором.
 */
export interface RepoTree extends Omit<Tree, 'listChanges'> {
  /** Сбрасывает накопленное на реальную ФС. Снятия — раньше записей. */
  flush(): void;
  /** Расхождения с диском — включая объявленный режим (`RepoChange`). */
  listChanges(): RepoChange[];
  /**
   * Объявленный раскладкой режим артефакта: программа (`true`) или данные
   * (`false`). Зовёт движок — сразу за записью того же пути и только там, где
   * раскладка режим НАЗВАЛА.
   */
  setExecutable(filePath: string, executable: boolean): void;
  /**
   * ИСПОЛНЯЕМ ЛИ ЛЕЖАЩИЙ ФАЙЛ; `null` — сказать нечего (файла нет).
   *
   * Пара к `setExecutable`: режим — состояние, а не команда, и читается он той
   * же рукой, что и пишется (`tasker:BASER2-225`).
   */
  isExecutable(filePath: string): boolean | null;
}

/** Биты исполняемости — владельцу, группе и остальным. */
const EXECUTABLE_BITS = 0o111;

/**
 * Запись, ожидающая сброса: содержимое либо `null` для снятия.
 *
 * Режима здесь нет НАМЕРЕННО, хотя раньше он тут лежал. Приведение режима
 * бывает и без записи содержимого (шаг `chmod`), то есть это отдельное
 * накопление, а не поле записи; сложив их в одну структуру, пришлось бы заводить
 * запись «без содержимого, но и не снятие» — третье значение `content: null`,
 * которое молча путалось бы со снятием во всех читателях сразу.
 *
 * `mode` остаётся: это чужая форма (`write(..., { mode })` девкита), режим
 * ЧИСЛОМ, и с объявленной исполняемостью у неё общего только слово.
 */
interface Pending {
  readonly content: Buffer | null;
  readonly mode?: Mode;
}

/**
 * Дерево над каталогом репозитория потребителя.
 *
 * Чтение идёт «сначала накопленное, потом диск»: движок обязан видеть то, что
 * сам же записал в этом прогоне, иначе его собственный журнал отката не смог бы
 * вернуть прежнее состояние.
 */
export function createRepoTree(root: string): RepoTree {
  const absolute = resolve(root);
  const pending = new Map<string, Pending>();
  /**
   * Приводимая исполняемость по путям — рядом с записями, а не внутри них.
   *
   * Отдельное накопление, потому что режим приезжает и к пути, который этот
   * прогон не пишет (шаг `chmod`), и к тому, который пишет (`write` +
   * `setExecutable` одним шагом). Одно место на оба случая значит, что порядок
   * вызовов роли не играет: сводит их `listChanges`, а не очерёдность.
   */
  const modes = new Map<string, boolean>();

  const full = (path: string): string => join(absolute, path);

  const fileOnDisk = (path: string): boolean => {
    try {
      return statSync(full(path)).isFile();
    } catch {
      return false;
    }
  };

  const bytesOnDisk = (path: string): Buffer | null => {
    try {
      return readFileSync(full(path));
    } catch {
      return null;
    }
  };

  /** Исполняем ли лежащий файл; `null` — файла на диске нет. */
  const executableOnDisk = (path: string): boolean | null => {
    try {
      return (statSync(full(path)).mode & EXECUTABLE_BITS) !== 0;
    } catch {
      return null;
    }
  };

  const tree = {
    root: absolute,

    read(path: string, encoding?: BufferEncoding): Buffer | string | null {
      const key = repoPath(path);
      const held = pending.get(key);
      const content = held !== undefined ? held.content : bytesOnDisk(key);
      if (content === null) {
        return null;
      }
      return encoding === undefined ? content : content.toString(encoding);
    },

    write(
      path: string,
      content: Buffer | string,
      options?: { mode?: Mode },
    ): void {
      pending.set(repoPath(path), {
        content: Buffer.isBuffer(content) ? content : Buffer.from(content),
        ...(options?.mode === undefined ? {} : { mode: options.mode }),
      });
    },

    /**
     * ПРИВЕСТИ РЕЖИМ — и вместе с записью, и БЕЗ НЕЁ.
     *
     * Два случая, и второй тут главный:
     *
     * · путь пишется этим же прогоном (`create`/`update`) — режим ляжет следом
     *   за содержимым, одной работой;
     * · путь этим прогоном НЕ пишется (шаг `chmod`, `tasker:BASER2-223`) —
     *   содержимое файла уже целевое, разошёлся только бит. Дерево приводит
     *   режим лежащему файлу и содержимого не касается.
     *
     * До формы 3 паспорта второй случай был невозможен, и дерево на нём
     * ОТКАЗЫВАЛО — с полным основанием: режим без записи тогда означал бы, что
     * движок сказал про файл, которого не трогает. Теперь это законный шаг, и
     * отказ стал бы ровно тем молчаливым «лежит, но не работает», ради снятия
     * которого шов и затевался.
     *
     * Не позвали — не тронули: чего движок не сказал, того дерево не делает.
     * Решение «снимать или не снимать» принимается ПАСПОРТОМ и живёт в движке
     * (`kb:BASER3-36` §2), дерево его не переигрывает и не угадывает.
     */
    setExecutable(path: string, executable: boolean): void {
      modes.set(repoPath(path), executable);
    },

    /**
     * ИСПОЛНЯЕМ ЛИ ЛЕЖАЩИЙ ФАЙЛ — та же рука, что и пишет режим.
     *
     * Этим членом закрывается шов (`tasker:BASER2-221`): движку нужна ТРЕТЬЯ
     * величина расхождения — факт с диска. Пары «объявлено × след» хватало,
     * пока бит менялся только нами; бит, сбитый снаружи (правка через
     * `\\wsl.localhost` — `tasker:BASER2-190`), в неё не попадал вовсе, и прогон
     * отвечал «сошлось» файлу, который перестал работать. Своего мнения о том,
     * каким режим ДОЛЖЕН быть, дерево при этом по-прежнему не имеет: оно
     * отвечает, какой он ЕСТЬ, а решает движок.
     *
     * Порядок ответа тот же, что у `read`: **сначала накопленное, потом диск**.
     * Иначе дерево соврало бы про собственную работу — сказало бы «бита нет» о
     * файле, которому само же его в этом прогоне и назначило.
     *
     * `null` — сказать нечего: файла нет ни в накопленном, ни на диске. Не
     * `false`: «файла нет» и «файл не программа» это разные ответы, и движок
     * различает их сам (`packages/baser-materialize/src/lib/tree.ts`).
     */
    isExecutable(path: string): boolean | null {
      const key = repoPath(path);

      // Снятое перестаёт существовать до всякого сброса — режима у него нет.
      if (pending.get(key)?.content === null) {
        return null;
      }

      const wanted = modes.get(key);
      if (wanted !== undefined) {
        return wanted;
      }

      return executableOnDisk(key);
    },

    delete(path: string): void {
      pending.set(repoPath(path), { content: null });
    },

    exists(path: string): boolean {
      const key = repoPath(path);
      const held = pending.get(key);
      if (held !== undefined) {
        return held.content !== null;
      }
      return existsSync(full(key));
    },

    isFile(path: string): boolean {
      const key = repoPath(path);
      const held = pending.get(key);
      if (held !== undefined) {
        return held.content !== null;
      }
      return fileOnDisk(key);
    },

    /**
     * Дети каталога: реальные плюс появившиеся в этом прогоне, минус снятые.
     *
     * Накопленное учитывается наравне с диском, потому что движок проверяет по
     * этому списку достижимость объявленного состояния: каталог, который весь
     * снимается этим же планом, препятствием не является, а созданный этим же
     * планом файл — является.
     */
    children(path: string): string[] {
      const base = repoPath(path);
      const names = new Set<string>();

      const directory = base === '' ? absolute : full(base);
      try {
        if (statSync(directory).isDirectory()) {
          for (const name of readdirSync(directory)) {
            names.add(name);
          }
        }
      } catch {
        // Каталога на диске нет — значит все дети только накопленные.
      }

      const prefix = base === '' ? '' : `${base}/`;
      for (const [key, held] of pending) {
        if (held.content === null || !key.startsWith(prefix)) {
          continue;
        }
        const rest = key.slice(prefix.length);
        if (rest !== '') {
          names.add(rest.split('/')[0]);
        }
      }

      // Снятое ребёнком больше не считается. Снимаются только файлы: каталог
      // движок целиком не удаляет, поэтому проверять его содержимое здесь не за
      // чем — а если начнёт, это увидит `flush`, а не молчаливый пропуск.
      for (const name of [...names]) {
        const key = base === '' ? name : `${base}/${name}`;
        if (pending.get(key)?.content === null) {
          names.delete(name);
        }
      }

      return [...names];
    },

    /**
     * Накопленные изменения — РАСХОЖДЕНИЯ С ДИСКОМ, а не журнал вызовов.
     *
     * Считается лениво и от текущего состояния: запись, вернувшая файлу
     * прежнее содержимое (журнал отката движка делает ровно это), изменением не
     * является и в список не попадает.
     */
    listChanges(): RepoChange[] {
      const changes: RepoChange[] = [];
      for (const [path, held] of pending) {
        const before = bytesOnDisk(path);
        const wanted = modes.get(path);

        // Режим едет вместе со своей записью: сбрасывает его тот же `flush`,
        // который кладёт содержимое, и знать о нём он может только отсюда.
        const declared = {
          ...(held.mode === undefined ? {} : { options: { mode: held.mode } }),
          ...(wanted === undefined ? {} : { executable: wanted }),
        };

        if (held.content === null) {
          // Снятие того, чего на диске не было, — не изменение, а отмена
          // собственной записи (откат создавшего шага). Режим снятому файлу ни
          // к чему: снятие — утверждение сильнее, файла после него не будет.
          if (before !== null) {
            changes.push({ path, type: 'DELETE', content: null });
          }
          continue;
        }

        if (before === null) {
          changes.push({
            path,
            type: 'CREATE',
            content: held.content,
            ...declared,
          });
          continue;
        }

        if (!before.equals(held.content)) {
          changes.push({
            path,
            type: 'UPDATE',
            content: held.content,
            ...declared,
          });
          continue;
        }

        // СОДЕРЖИМОЕ СОШЛОСЬ, А РЕЖИМ — НЕТ. Работа есть, но она не про
        // содержимое, и называется своим словом: писать тут нечего.
        if (wanted !== undefined && executableOnDisk(path) !== wanted) {
          changes.push({
            path,
            type: 'CHMOD',
            content: null,
            executable: wanted,
          });
        }
      }

      // ПРИВЕДЕНИЕ РЕЖИМА БЕЗ ЗАПИСИ — шаг `chmod` движка. Пути, которых этот
      // прогон не пишет вовсе: файл лежит целевым, разошёлся только бит.
      // Сошедшийся бит работой не является — иначе прогон рапортовал бы её на
      // каждом объявленном артефакте, ничего при этом не меняя.
      for (const [path, wanted] of modes) {
        if (pending.has(path)) {
          continue;
        }
        if (executableOnDisk(path) !== wanted) {
          changes.push({
            path,
            type: 'CHMOD',
            content: null,
            executable: wanted,
          });
        }
      }

      return changes.sort((left, right) => (left.path < right.path ? -1 : 1));
    },

    flush(): void {
      const changes = tree.listChanges();

      // Снятия раньше записей: путь, освобождаемый снятием, обязан
      // освободиться до того, как на него что-то ляжет.
      for (const change of changes) {
        if (change.type === 'DELETE') {
          rmSync(full(change.path), { force: true, recursive: true });
        }
      }
      for (const change of changes) {
        if (change.type === 'DELETE') {
          continue;
        }

        // РЕЖИМ БЕЗ СОДЕРЖИМОГО: файл лежит на месте и переписан не будет.
        // Перезаписать его «заодно» было бы проще, но это неправда: содержимое
        // сошлось, а лишняя запись меняет время правки у потребителя и врёт
        // всему, что за этим временем следит.
        if (change.type === 'CHMOD') {
          if (change.executable === undefined) {
            throw new Error(
              `изменение CHMOD "${change.path}" без режима — дерево повреждено: ` +
                'приводить нечего, а слово сказано',
            );
          }
          chmodSync(
            full(change.path),
            programMode(full(change.path), change.executable),
          );
          continue;
        }

        if (change.content === null) {
          continue;
        }
        mkdirSync(dirname(full(change.path)), { recursive: true });
        writeFileSync(full(change.path), change.content);
        if (change.options?.mode !== undefined) {
          chmodSync(full(change.path), change.options.mode);
        }
        // Объявленный режим — ПОСЛЕДНИМ и поверх сложившегося.
        if (change.executable !== undefined) {
          chmodSync(
            full(change.path),
            programMode(full(change.path), change.executable),
          );
        }
      }
    },

    /**
     * Переименование и смена прав движку не нужны — он их не зовёт.
     *
     * Отказ, а не тихая заглушка: молчаливый no-op на смене прав отдал бы
     * потребителю файл с неверным режимом и не сказал бы об этом ни слова. Если
     * движок когда-нибудь их позовёт, это будет видно сразу.
     *
     * Исполняемость сюда не относится: её объявляет раскладка, и доезжает она
     * своим членом порта (`setExecutable`), а не сменой прав по чужому вызову.
     */
    rename(): never {
      throw new Error(
        'дерево консоли не умеет rename: движок его не зовёт. ' +
          'Появилась нужда — реализуй явно, а не молчаливой заглушкой',
      );
    },

    changePermissions(): never {
      throw new Error(
        'дерево консоли не умеет changePermissions: движок его не зовёт. ' +
          'Права задаются при записи (`write(..., { mode })`), а объявленная ' +
          'исполняемость — своим членом порта (`setExecutable`)',
      );
    },
  };

  return tree as unknown as RepoTree;
}

/**
 * РЕЖИМ ФАЙЛА ПОСЛЕ ОБЪЯВЛЕНИЯ: исполняемость идёт туда, где уже есть чтение.
 *
 * Обвес объявляет один предмет — «программа или данные», — и права доступа
 * этим объявлением не переписываются: файл `600`, объявленный программой,
 * становится `700`, а не общедоступным `755`. Кому его читать, обвес не
 * говорил, и решать за него консоль не станет.
 *
 * Бит ставится по маске чтения (`r` → `x`), а не всем трём классам подряд, и
 * это не косметика: право выполнить скрипт без права его прочитать
 * бессмысленно — интерпретатор читает файл. Раздачу бита сужает и сам рынок:
 * `chmod +x` без явного класса режется `umask`, а не ставит `x` всем троим
 * (сверено 2026-08-07). Снятие маской проще постановки: «не программа» — это
 * ровно отсутствие трёх бит, и вопроса «у кого» там нет.
 */
function programMode(file: string, executable: boolean): number {
  const now = statSync(file).mode & 0o777;
  return executable ? now | ((now & 0o444) >> 2) : now & ~EXECUTABLE_BITS;
}

/**
 * Репо-относительный путь в каноничной форме.
 *
 * Написание приводится здесь по той же причине, по которой его приводит движок:
 * один и тот же файл, записанный как `./a.json` и `a.json`, оказался бы двумя
 * разными ключами — и прогон потерял бы собственную запись.
 */
function repoPath(path: string): string {
  return path
    .replace(/\\/g, '/')
    .replace(/^\.\/+/, '')
    .replace(/\/+/g, '/')
    .replace(/^\/+|\/+$/g, '');
}
