#!/usr/bin/env node
/**
 * ДВЕРЬ ИЗ БАНДЛА — та же команда, что и у поставленного пакета.
 *
 * Уезжает в бандл рядом с установщиком. Нужна после установки: обвес уже лежит
 * в `node_modules` репозитория, а звать `plan`/`apply` человеку по-прежнему
 * нечем — из монорепы бандл унесли, а из npm он не ставился.
 *
 * Своей логики здесь нет и быть не должно: всё, что можно проверить тестом,
 * живёт в `cli()`. Иначе у двери завелось бы второе поведение — «как в бандле»,
 * — и расходиться они начали бы в первый же выпуск.
 */

import { cli } from '@omnifield/baser-cli';

const outcome = await cli(process.argv.slice(2), process.cwd());

process.stdout.write(outcome.stdout);
process.exitCode = outcome.exitCode;
