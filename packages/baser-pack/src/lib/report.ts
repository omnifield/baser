/**
 * ОТВЕТ УПАКОВКИ — данные. Текст поверх них рисует дверь, а не эта зона.
 *
 * Потребитель ответа — дверь, гейт в CI и пульт, а человек в терминале только
 * один из них. Поэтому упаковка отдаёт структуру и НИЧЕГО не печатает.
 *
 * В ответе лежат ОБА вердикта проверки целиком и без пересказа: и по исходному
 * каталогу, и по собранной нагрузке. Это не избыточность — это два разных
 * утверждения. Первое отвечает «стоит ли вообще паковать», второе — «годно ли
 * то, что собралось». Второе не выводится из первого: между ними стоит npm со
 * своими правилами упаковки, и разойтись они могут молча.
 *
 * Объём сделанного назван в `stages` по той же причине, что и у проверки:
 * зелёная сборка, которая ничего не собрала, читается как успешная.
 */

import type { CheckReport } from '@omnifield/baser-check';

import type { PayloadManifest } from './manifest.js';
import type { PackProblem } from './problems.js';

/**
 * Версия формы ОТВЕТА упаковки.
 *
 * Отдельная от версии формы объявления, формы ответа проверки и формы описи:
 * едут они по разным причинам и в разном темпе, а несовместимость обязана быть
 * видимой, а не выясняться по симптомам у того, кто по ответу ветвится.
 */
export const PACK_SCHEMA_VERSION = 1;

/** Какой шаг сборки отчитывается. */
export type PackStageName =
  /** Обвес подходит посадочному месту — иначе не пакуем вовсе. */
  | 'check'
  /** Место выдачи: куда кладём и можно ли туда класть. */
  | 'target'
  /** Состав поставки — перечислен npm. */
  | 'contents'
  /** Состав скопирован в нагрузку. */
  | 'payload'
  /** Собранная нагрузка проверена заново — как чужой каталог обвеса. */
  | 'verify'
  /** Опись выдачи написана рядом с нагрузкой. */
  | 'manifest';

export type PackStageStatus =
  /** Сделано, отказов нет. */
  | 'ok'
  /** Сделано, отказы названы. */
  | 'failed'
  /** НЕ сделано — и сказано почему. Не то же самое, что «сделано и чисто». */
  | 'skipped';

export interface PackStage {
  readonly name: PackStageName;
  readonly status: PackStageStatus;
  /** Сколько единиц прошло через шаг: файлов, слоёв, записей описи. */
  readonly counted: number;
  /** Пояснение к состоянию. Обязательно при `skipped` — иначе это молчание. */
  readonly reason?: string;
}

/**
 * Один замер (perf-лог), тремя полями.
 *
 * Форма намеренно совпадает со спаном проверки и движка, чтобы дверь могла
 * сложить спаны всех зон в один список. Тип при этом свой: складывать спаны —
 * работа двери, и ответ упаковки не должен зависеть от того, как соседи назвали
 * свою запись из трёх полей.
 */
export interface PackSpan {
  readonly name: string;
  readonly ms: number;
  readonly detail?: Readonly<Record<string, unknown>>;
}

export interface PackReport {
  /** Версия формы этого ответа. */
  readonly packSchemaVersion: number;
  /**
   * Собрана ли нагрузка и годна ли она к выдаче: ни одного отказа.
   *
   * Производная от `problems`, а не отдельный признак: два источника правды о
   * пригодности разошлись бы на первой же ветке.
   */
  readonly ok: boolean;
  /** Абсолютный корень каталога обвеса, из которого собирали. */
  readonly source: string;
  /** Абсолютный корень каталога выдачи, куда просили положить. */
  readonly target: string;
  /**
   * Корень собранной нагрузки — или `null`, если выдавать нечего.
   *
   * `null` не значит «где-то лежит недособранное»: отказ означает, что после
   * него на диске не остаётся ничего, что можно было бы принять за готовую
   * выдачу.
   */
  readonly payloadRoot: string | null;
  /**
   * Путь описи выдачи — или `null`, если описи на диске нет.
   *
   * `null` и при отказе НА записи: оборванная опись убрана вместе с нагрузкой,
   * и называть её путь значило бы указывать на пустое место.
   */
  readonly manifestPath: string | null;
  /** Опись выдачи, та же, что записана файлом. */
  readonly manifest: PayloadManifest | null;
  /**
   * Проверка ИСХОДНОГО каталога — как есть, без пересказа.
   *
   * Есть всегда: даже когда каталога нет вовсе, отказ об этом принадлежит
   * проверке, а не упаковке.
   */
  readonly check: CheckReport;
  /** Проверка СОБРАННОЙ нагрузки — как есть. `null`, если до неё не дошло. */
  readonly verify: CheckReport | null;
  readonly stages: readonly PackStage[];
  /** Все отказы списком: свои и приехавшие от проверки, вперемешку по порядку. */
  readonly problems: readonly PackProblem[];
  /** Телеметрия шагов. Данные вне ответа человеку — их печатает не упаковка. */
  readonly trace: readonly PackSpan[];
}
