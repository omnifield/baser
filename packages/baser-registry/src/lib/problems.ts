/**
 * ОТКАЗЫ МАГАЗИНА — данные, а не исключения.
 *
 * Форма та же, что у двери и у контрактов: **код, адрес, текст**. Код — часть
 * публичного контракта и не меняется вместе с формулировкой; текст — человеку.
 * Ветвиться по тексту не должен никто и никогда (`kb:BASER3-10`).
 *
 * Адрес (`at`) обязателен по той же причине, по которой он обязателен у формы:
 * человек чинит отказ в КОНКРЕТНОМ месте, и «порт занят» без имени файла и ключа
 * отправляет его искать, где же этот порт назначен.
 *
 * Отказы копятся, а не бросаются: разбор конфига идёт до конца, и человек
 * получает все опечатки разом, а не по одной за прогон.
 */

/**
 * Что не так. Набор закрытый: незнакомый код у потребителя — это красное, а не
 * «ну, наверное, что-то новое».
 */
export type ShopProblemCode =
  /** `config.yml` есть, но это не YAML. */
  | 'config-unreadable'
  /** `config.yml` разобрался, но это не набор ключей (список, строка, число). */
  | 'config-not-mapping'
  /**
   * Настройки лежат в ПРЕЖНЕМ месте — `.baser-registry/config.yml`.
   *
   * Отдельный код, а не молчание, и это главное решение переезда. Молча взять
   * дефолты, увидев заполненный человеком файл, — худший из возможных исходов:
   * магазин поднимется на другом порту, полезет не к тому апстриму и ничего об
   * этом не скажет. Про переезд человек обязан узнать из отказа, а не из того,
   * что его настройки перестали действовать.
   *
   * Переносить файл за него мы не станем: в конфиг человека инструмент не
   * пишет (`kb:BASER3-6`), а «мы сами всё перенесли» отличается от «мы
   * перезаписали ваш файл» только удачей.
   */
  | 'config-in-old-place'
  /**
   * Ключ, которого магазин не знает.
   *
   * Назван вслух намеренно. Файл наш целиком — в отличие от `.omnifield/*.yaml`,
   * где рядом законно живут ключи чужих инструментов и молчать о них правильно
   * (`kb:BASER3-6`). Здесь чужих ключей нет, поэтому опечатка в имени настройки
   * иначе означала бы молча работающий дефолт: человек написал `ports: 4900`,
   * магазин поднялся на 4873, и объяснить это будет нечем.
   */
  | 'setting-unknown'
  /** Значение не того типа, который эта настройка принимает. */
  | 'setting-type'
  /** Порт вне диапазона, который вообще бывает у TCP. */
  | 'port-out-of-range'
  /**
   * Адрес занят — на нём уже кто-то отвечает, и это не наш магазин.
   *
   * Отдельно от «магазин уже поднят»: то не отказ вовсе (`up` идемпотентен), а
   * это чужой процесс, и лечится он сменой настройки, а не повтором команды.
   */
  | 'address-busy'
  /**
   * Процесс запущен и умер, не начав отвечать.
   *
   * Адрес отказа — лог магазина: единственное место, где лежит причина, и
   * человека надо отправить туда, а не в наш вывод.
   */
  | 'shop-died'
  /** Процесс живёт, а раздача так и не ответила за отпущенный срок. */
  | 'shop-silent'
  /** Просили погасить — процесс не умер даже после жёсткого сигнала. */
  | 'shop-immortal'
  /** Публиковать просили, а магазин закрыт: класть товар некуда. */
  | 'shop-closed'
  /** В каталоге публикации нет `package.json`. */
  | 'manifest-missing'
  /** `package.json` есть, но это не JSON либо в нём нет имени или версии. */
  | 'manifest-unreadable'
  /**
   * Пакету нужен `pnpm`, а его нет.
   *
   * Отдельный код, а не «публикация не удалась»: `npm` такой пакет опубликует
   * УСПЕШНО и сломанным — с `workspace:*` в манифесте, который не ставится
   * нигде. Тихий успех здесь хуже отказа, поэтому отказ.
   */
  | 'pnpm-required'
  /**
   * Менеджер собрался публиковать НЕ в наш магазин.
   *
   * Ловится сухим прогоном ДО живой команды: уехавшее в чужой реестр обратно не
   * забирается. Сюда же попадает случай, когда назначение вообще не удалось
   * прочитать: публиковать на удачу мы не станем.
   */
  | 'wrong-destination'
  /** Менеджер отказал на самой публикации — причина в его выводе. */
  | 'publish-failed'
  /** Команды с таким именем у магазина нет. */
  | 'unknown-command'
  /** Флага с таким именем у команды нет. */
  | 'unknown-flag';

export interface ShopProblem {
  readonly code: ShopProblemCode;
  /** Где чинить: путь к файлу, ключ настройки, адрес. */
  readonly at: string;
  /** Человеку. Машине — `code`. */
  readonly message: string;
}

/** Копилка отказов: разбор идёт дальше, а не встаёт на первом. */
export class ShopProblemLog {
  readonly #problems: ShopProblem[] = [];

  add(code: ShopProblemCode, at: string, message: string): void {
    this.#problems.push({ code, at, message });
  }

  get empty(): boolean {
    return this.#problems.length === 0;
  }

  list(): readonly ShopProblem[] {
    return [...this.#problems];
  }
}
