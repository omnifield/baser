/**
 * ТРИ ДЕЙСТВИЯ ПУБЛИКАЦИИ — выпуск · отгрузка · объявление.
 *
 * Отдельный файл, а не поле в форме ответа, потому что это отдельная вещь мира
 * (`kb:WORLD-34`), а не подробность нашей структуры. Здесь и типы шагов, и
 * сборка их отчётов: где заводится словарь, там и его конструкторы — иначе
 * каждый зовущий соберёт свою версию «шага, до которого не дошли».
 */

import type { ShopProblemCode } from './problems.js';

/**
 * ПУБЛИКАЦИЯ — ТРИ ДЕЙСТВИЯ, А НЕ ОДНА КНОПКА (`kb:WORLD-34`).
 *
 * | действие         | что происходит                    | чем говорит «нет»                            |
 * | ---------------- | --------------------------------- | -------------------------------------------- |
 * | **выпуск**       | вещь замерзает и получает номер   | номер занят чужим содержимым · правишь выпущенное |
 * | **отгрузка**     | попадает на склад по адресу       | до склада нет дороги · вход закрыт · назначение не то |
 * | **объявление**   | появляется на витрине             | витрины у нас нет вовсе → тишина, а не отказ  |
 *
 * Склеенные в одно слово, они дают отказ, по которому непонятно, что сломалось:
 * ровно так «уже на складе» и «правишь выпущенное» год приезжали человеку одним
 * успехом с кодом 0 (`tasker:BASER2-287`). Разведённые — отказ сразу называет шаг.
 *
 * Порядок здесь — порядок исполнения, и он не случаен: номер судится ДО того,
 * как что-то поехало. Уехавшее со склада не возвращается.
 */
export type PublishStep = 'release' | 'shipment' | 'announcement';

/**
 * Что сказал ОДИН шаг.
 *
 * `nothing-to-do` и `silent` — разные вещи, и путать их нельзя: первое означает
 * «работа уже сделана раньше», второе — «этой работы у нас нет вовсе». Склад без
 * витрины — рабочее состояние, а не недоделка (`kb:WORLD-34`), и объявление при
 * ней обязано ПРИСУТСТВОВАТЬ и молчать: разница между «мы этого не делаем» и «мы
 * про это не подумали» видна потребителю только так.
 */
export type StepOutcome =
  /** Шаг сделал работу. */
  | 'done'
  /** Состояние уже достигнуто — делать было нечего. Успех. */
  | 'nothing-to-do'
  /** Шага здесь нет вовсе, и это законно. Названная тишина, а не отказ. */
  | 'silent'
  /** Шаг сказал «нет». Код — в `reason`, текст к нему — в `problems`. */
  | 'refused'
  /** До шага не дошли: отказал предыдущий либо разбор входа. */
  | 'skipped';

/**
 * Чем названа ТИШИНА шага — отдельно от отказов, потому что это не отказ.
 *
 * Сегодня значение одно: витрины у магазина локации нет, и брать её нам неоткуда
 * — витрину как вещь взял другой продукт. Появится витрина — здесь появится
 * второе значение («манифеста нет — нечего показать»), а `silent` перестанет
 * быть единственным исходом объявления.
 */
export type StepSilence = 'no-storefront';

/** Что сказал шаг — и чем именно. */
export interface StepReport {
  readonly step: PublishStep;
  readonly outcome: StepOutcome;
  /**
   * Код, которым шаг объяснил свой исход; `null` — сверх `outcome` сказать
   * нечего.
   *
   * Отказ называется кодом ИЗ ТОГО ЖЕ перечня, что и `problems`: там же лежит
   * человеческий текст и место, где чинить. Второго словаря отказов мы не
   * заводим — разъехавшись, они заставили бы потребителя знать оба.
   */
  readonly reason: ShopProblemCode | StepSilence | null;
}

/**
 * Три действия одного прогона (или одного пакета партии) — все три и всегда.
 *
 * Отсутствующий шаг и промолчавший шаг — разные ответы, и первого здесь не
 * бывает по построению: поле обязательное, а «до нас не дошло» называется
 * исходом `skipped`, а не пропуском в структуре.
 */
export interface PublicationSteps {
  readonly release: StepReport;
  readonly shipment: StepReport;
  readonly announcement: StepReport;
}

/** Один шаг: что он и что сказал. */
export function said(
  step: PublishStep,
  outcome: StepOutcome,
  reason: ShopProblemCode | StepSilence | null = null,
): StepReport {
  return { step, outcome, reason };
}

/**
 * ОБЪЯВЛЕНИЕ — ЗАКОННАЯ ТИШИНА, и она одна на все прогоны.
 *
 * Витрины у магазина локации нет вовсе, и это рабочее состояние, а не
 * недоделка: склад отдаёт тому, кто знает имя, витрина показывает тому, кто не
 * знает, — и второе нам просто не нужно (`kb:WORLD-34`). Появиться в ответе шаг
 * при этом ОБЯЗАН: разницу между «мы этого не делаем» и «мы про это не
 * подумали» потребитель видит только так.
 *
 * Самое дешёвое из трёх действий и самое лёгкое забыть — поэтому оно здесь
 * константой, а не собирается на каждом вызове по памяти.
 */
export const ANNOUNCEMENT_SILENT: StepReport = said(
  'announcement',
  'silent',
  'no-storefront',
);

/**
 * До трёх действий не дошли: вход разобрать не удалось.
 *
 * Не «шага не было», а «шаг не начинался» — и сказано это исходом, а не
 * отсутствием поля. Объявление здесь тоже `skipped`, а не `silent`: молчать
 * может только шаг, до которого дошли.
 */
export function stepsNotReached(): PublicationSteps {
  return {
    release: said('release', 'skipped'),
    shipment: said('shipment', 'skipped'),
    announcement: said('announcement', 'skipped'),
  };
}

/**
 * СВОДКА ПАРТИИ: три шага прогона из трёх шагов каждого пакета.
 *
 * Правило одно — **худшее слово побеждает**, и порядок «худшести» ниже. Иначе
 * партия, где один пакет уехал, а второму отказал выпуск, называла бы прогон
 * успешным: конвейеру нужно знать, идти ли разбираться, а с чем именно — он
 * прочитает построчно.
 */
export function rollUp(all: readonly PublicationSteps[]): PublicationSteps {
  return {
    release: worst('release', all),
    shipment: worst('shipment', all),
    announcement: worst('announcement', all),
  };
}

/**
 * Порядок «худшести» исходов шага.
 *
 * `refused` впереди всего: один отказ красит прогон. `skipped` перед `done`,
 * потому что недошедший шаг — это незакрытый вопрос, а не сделанная работа.
 * `nothing-to-do` и `silent` — самые спокойные и не перебивают `done`: партия,
 * где один пакет уехал, а второй уже лежал, всё-таки отгружалась.
 */
const SEVERITY: readonly StepOutcome[] = [
  'refused',
  'skipped',
  'done',
  'nothing-to-do',
  'silent',
];

function worst(
  step: PublishStep,
  all: readonly PublicationSteps[],
): StepReport {
  const each = all.map((one) => one[step]);
  if (each.length === 0) return said(step, 'skipped');

  for (const outcome of SEVERITY) {
    const found = each.find((one) => one.outcome === outcome);
    if (found) return found;
  }
  return each[0];
}

