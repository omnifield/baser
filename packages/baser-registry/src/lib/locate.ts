/**
 * ГДЕ КОРЕНЬ ПОСТРОЙКИ — вопрос, на который команда обязана отвечать сама.
 *
 * Постройка — это клон репозитория, главный объект локации (`kb:WORLD-14`).
 * Магазин ей больше не принадлежит: он вещь ЛОКАЦИИ и живёт на своём уровне
 * (`location.ts`). Корень постройки нужен для другого — назвать в ответе, ОТКУДА
 * работали, и найти прежние места настроек, если они там остались.
 *
 * Команда ставится глобально и зовётся откуда угодно — из `src/`, из
 * `packages/что-нибудь`, из любого места дерева. Считать постройкой текущий
 * каталог значило бы называть в ответе не то место и искать старые настройки не
 * там, где они лежат.
 *
 * ПОРЯДОК ПРИЗНАКОВ:
 *
 * 1. `.git/` — постройка это клон, и её граница проходит по нему.
 * 2. Ни одного — корнем остаётся каталог вызова. Законное состояние: пустая
 *    папка без git тоже годится, публиковать из неё можно.
 *
 * Признак «заведённый магазин» отсюда СНЯТ вместе со своей причиной: раньше
 * папка магазина лежала в постройке и была сильнейшим признаком её корня.
 * Теперь магазина в постройке нет, и искать по нему нечего.
 */

import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

/** Как именно нашёлся корень постройки. */
export type BuildingOrigin = 'git' | 'cwd';

export interface LocatedBuilding {
  readonly root: string;
  readonly origin: BuildingOrigin;
}

/**
 * Ищет корень постройки вверх от каталога вызова.
 *
 * Найденное НАЗЫВАЕТСЯ (`origin`), а не только используется: команда, молча
 * работающая двумя уровнями выше, чем думает человек, — это тот же класс, что
 * молча поднятый дефолт.
 */
export function locateBuilding(from: string): LocatedBuilding {
  const start = resolve(from);

  for (let at = start; ; at = dirname(at)) {
    if (existsSync(join(at, '.git'))) {
      return { root: at, origin: 'git' };
    }
    if (dirname(at) === at) break;
  }

  return { root: start, origin: 'cwd' };
}
