/**
 * ГДЕ КОРЕНЬ ЛОКАЦИИ — вопрос, на который команда обязана отвечать сама.
 *
 * Магазин ставится ГЛОБАЛЬНО (`npm i -g`), как git и ассистент, и зовут его
 * откуда угодно — из `src/`, из `packages/что-нибудь`, из любого места дерева.
 * Если считать корнем текущий каталог, то `up` из подкаталога заведёт ВТОРОЙ
 * магазин со своим складом, а лог и папка лягут там, где человек случайно
 * стоял. Ровно этот мусор поймало ревью первого коммита
 * (`tasker:BASER2-249`), и лечится он здесь — в причине, а не в путях каждого
 * файла по отдельности.
 *
 * ПОРЯДОК ПРИЗНАКОВ, и он не произвольный:
 *
 * 1. `.baser-registry/` — магазин у этой локации УЖЕ ЕСТЬ. Сильнейший признак:
 *    спорить с тем, что человек однажды завёл, команде нечем.
 *    2. `.git/` — граница локации в общем случае. Локация это репозиторий, и
 *    магазин заводится ей целиком, а не одному её каталогу.
 * 3. Ни того, ни другого — корнем остаётся каталог вызова. Это законное
 *    состояние: пустая папка без git — тоже локация, и `up` в ней осмыслен.
 *
 * Так же ищут свой корень git и pre-commit, и человек этого поведения ждёт.
 */

import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { SHOP_DIRECTORY } from './layout.js';

/** Как именно нашёлся корень — уезжает в ответ, чтобы «почему тут» не гадали. */
export type RootOrigin = 'shop' | 'git' | 'cwd';

export interface LocatedRoot {
  readonly root: string;
  readonly origin: RootOrigin;
}

/**
 * Ищет корень локации вверх от каталога вызова.
 *
 * Найденное НАЗЫВАЕТСЯ (`origin`), а не только используется: команда, молча
 * работающая на два уровня выше, чем думает человек, — это тот же класс, что
 * молча поднятый дефолт.
 */
export function locateRoot(from: string): LocatedRoot {
  const start = resolve(from);

  // Первый проход ищет сильнейший признак — заведённый магазин.
  for (let at = start; ; at = dirname(at)) {
    if (existsSync(join(at, SHOP_DIRECTORY))) {
      return { root: at, origin: 'shop' };
    }
    if (dirname(at) === at) break;
  }

  // Второй — границу локации. Отдельным проходом, а не одним циклом с двумя
  // проверками: иначе `.git` ближайшего подрепозитория обошёл бы магазин,
  // заведённый выше, и порядок признаков перестал бы соблюдаться.
  for (let at = start; ; at = dirname(at)) {
    if (existsSync(join(at, '.git'))) {
      return { root: at, origin: 'git' };
    }
    if (dirname(at) === at) break;
  }

  return { root: start, origin: 'cwd' };
}
