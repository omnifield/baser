/**
 * КОНФИГ РАЗДАЧИ — АРТЕФАКТ, который собирается целиком на каждом `up`.
 *
 * Магазин мы не пишем сами: раздача пакетов — инфраструктурный узел, и он взят с
 * рынка (verdaccio; сверка с рынком и разбор альтернатив — `tasker:BASER2-248`,
 * зависимость разрешена architect'ом отдельным решением). Наша работа —
 * жизненный цикл вокруг него и одна честная настройка поверх, а не свой реестр.
 *
 * ПОЧЕМУ СОБИРАЕТСЯ ЦЕЛИКОМ, А НЕ ПРАВИТСЯ. Файл человека — `config.yml`, и в нём
 * несколько наших настроек. Этот — производный от него, и владеем им мы:
 * перезаписывается на каждом запуске без спроса. Дать человеку править его
 * значило бы предложить правку, которая исчезнет на следующем `up`, — ровно то,
 * что канон называет дефектом поставщика (`kb:BASER3-5`).
 *
 * ПРОКСИ, А НЕ ВТОРОЙ РЕЕСТР РЯДОМ. Чего нет на складе — магазин берёт наверху и
 * кэширует, поэтому потребителю хватает ОДНОГО адреса (`kb:BASER3-9`).
 * Альтернатива — два адреса и список, что откуда, — возвращает человеку ручную
 * маршрутизацию имён, ради устранения которой магазин и заводится.
 */

import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';
import type { ShopLayout } from './layout.js';
import type { ShopSettings } from './settings.js';

/**
 * Скоуп, который идёт через магазин целиком (решение `tasker:BASER2-41`).
 *
 * Назван отдельным правилом ВЫШЕ общего, хотя общее его и так покрывает: правило
 * читается человеком, который полез разбираться, и «наши пакеты ходят через свой
 * магазин» должно быть видно в файле, а не выводиться из порядка масок.
 */
const OWN_SCOPE = '@omnifield/*';

const ACCESS = {
  access: '$all',
  publish: '$all',
  unpublish: '$all',
  proxy: 'upstream',
} as const;

/**
 * Собирает конфиг раздачи из настроек человека и нашей раскладки.
 *
 * Чистая функция: диска не трогает, время не читает. Иначе два запуска подряд
 * давали бы разные файлы, и «перезаписывается целиком» превратилось бы в
 * бесконечную правку.
 */
export function verdaccioConfig(
  settings: ShopSettings,
  layout: ShopLayout,
  logFile: string,
): string {
  const body = stringify({
    // Пути абсолютные намеренно: процесс запускается с рабочим каталогом,
    // который мы не контролируем, а относительный путь склада означал бы товар,
    // разложенный там, откуда позвали команду.
    storage: layout.storage,
    uplinks: {
      upstream: {
        url: settings.uplink,
        // Кэшируем то, что притащили сверху: ради этого прокси и ставится —
        // локация переживает падение апстрима на том, что уже спрашивала.
        cache: true,
      },
    },
    packages: {
      [OWN_SCOPE]: { ...ACCESS },
      '**': { ...ACCESS },
    },
    log: {
      type: 'file',
      path: logFile,
      format: 'json',
      level: 'warn',
    },
    publish: {
      // Публиковать можно и без связи с апстримом: магазин локации обязан
      // работать, когда мира нет вовсе.
      allow_offline: true,
    },
  });

  return [
    '# СОБРАН МАГАЗИНОМ. Правки здесь исчезнут на следующем `baser-registry up`.',
    `# Настройки раздачи живут в ${layout.config} — правьте там.`,
    '',
    body,
  ].join('\n');
}

/**
 * ФАЙЛ, КОТОРЫЙ СПАВНИТСЯ, ЧТОБЫ ПОДНЯТЬ РАЗДАЧУ, — НАШ, а не чужой.
 *
 * Было `resolve('verdaccio/bin/verdaccio')` — подпуть чужого пакета, который тот
 * никогда не объявлял публичным. У потребителя приезжала другая сборка (замер:
 * 6.9.2 против 6.8.0 в монорепе), в ней появилось поле `exports` — и `up` падал
 * с `ERR_PACKAGE_PATH_NOT_EXPORTED` (`tasker:BASER2-251`). Разбор целиком —
 * в `serve.ts`.
 *
 * Теперь резолвится СОСЕДНИЙ НАШ ФАЙЛ: он лежит в нашем же `dist`, приезжает
 * тем же тарболом и не может разойтись с нами по версии. Всё, что осталось от
 * чужого пакета, — его главный вход, и он объявлен в `exports`.
 *
 * `import.meta.url`, а не `process.cwd()` и не корень локации: магазин ставится
 * глобально и работает в чужих деревьях, где своего `node_modules` нет и быть не
 * должно.
 */
export function shopEntry(): string {
  // У ПОТРЕБИТЕЛЯ раскладка одна: `dist/lib/verdaccio.js` и `dist/lib/serve.js`
  // лежат рядом, приехав одним тарболом.
  const shipped = fileURLToPath(new URL('./serve.js', import.meta.url));
  if (existsSync(shipped)) return shipped;

  // В МОНОРЕПЕ пробы бегут из исходников (`src/lib/verdaccio.ts`), и рядом
  // лежит `serve.ts`, который спавнить нечем. Значит берём собранный файл
  // своего же пакета.
  //
  // Это не запасной путь «на всякий случай», а вторая настоящая раскладка, в
  // которой мы живём. Названа она здесь ровно потому, что прошлый выпуск
  // сломался на молчаливом предположении о единственной раскладке: в монорепе
  // резолвилось, у потребителя нет, и узнали мы об этом от человека. Свежесть
  // этой сборки обеспечена связкой целей (`test` зависит от `build` в манифесте
  // пакета), а не надеждой.
  return fileURLToPath(new URL('../../dist/lib/serve.js', import.meta.url));
}
