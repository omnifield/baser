/**
 * ОРГАН РЕШЕНИЯ ПОСТРОЙКИ — нужен ли ей магазин, что она отгружает, куда.
 *
 * Правило мира (`kb:WORLD-34`, ответ `tasker:BASER2-273`) разводит две вещи,
 * которые у нас были склеены:
 *
 * ```
 * ЧТО ОТГРУЖАЕМ И КУДА  → СХЕМА постройки (этот файл)  — переживает пересоздание контейнера
 * СКЛАД, ПРОЦЕСС, ПОРТ  → ЛОКАЦИЯ (config.yml магазина) — переживает остановку
 * ```
 *
 * Проверка принадлежности — сносом: снеси локацию, и магазин уйдёт с ней;
 * перечерти производство, и магазин останется. Отсюда и разделение: **товар в
 * магазин — да, отдел продаж в магазин — нет.** Склад мы держим на локации
 * (`tasker:BASER2-254`), и это остаётся в силе; а решения о том, что и куда
 * отгружать, до сих пор не жили НИГДЕ — они были в голове того, кто настраивал
 * контейнер, и пересоздание поднимало склад без единого решения.
 *
 * ── ФАЙЛА МАГАЗИНУ НИКТО НЕ РОДИТ ───────────────────────────────────────────
 *
 * Магазин — не обвес: в `baser.json` он не объявляется, класть в постройку ему
 * нечего, и дверь про него ничего не знает. Значит и файл решений он читает
 * САМ — ровно так же, как читает настройки участка. Писать в него инструмент не
 * станет никогда (`kb:BASER3-6`): это файл человека.
 *
 * ── ОТСУТСТВИЕ ФАЙЛА — ЗАКОННОЕ СОСТОЯНИЕ, А НЕ ПРОБЕЛ ──────────────────────
 *
 * Постройка, которая ничего не отгружает, органа продаж не заводит. Отказать ей
 * значило бы соврать про намерение владельца, а родить ей пустой файл — обещать
 * регулировку, которой она не просила. Поэтому «файла нет» читается как «не
 * продаём», и все команды работают ровно как раньше.
 *
 * ── ИМЁН ЗДЕСЬ НЕТ ОТДЕЛЬНЫМ КЛЮЧОМ, И ЭТО РЕШЕНИЕ ──────────────────────────
 *
 * У имени два регистра (`kb:MECH-15`): внутри контура — `@<продукт>/<инструмент>`,
 * в комьюнити — `@<бренд>/<продукт>-<инструмент>`. Регистров два ПОТОМУ, что
 * магазинов два, — значит регистр это следствие адреса, а не отдельный выбор
 * (`tasker:BASER2-272`). А карта публичных имён уже объявлена репозиторием один
 * раз (`packages/baser-release/public-names.json`), и второй такой карты быть не
 * должно: разъехавшись, они отправят наружу имя, которого никто не выбирал.
 * Поэтому «под какими именами» здесь ОТВЕЧЕНО — полем `names` в ответе, — но не
 * спрошено ещё раз.
 *
 * ── ПУТЬ ТОТ ЖЕ, ЧТО БЫЛ У СТАРЫХ НАСТРОЕК, И СТАРОЕ ЛОВИТСЯ ПО КЛЮЧАМ ──────
 *
 * `.omnifield/omnifield-registry.yaml` когда-то держал настройки РАЗДАЧИ, и они
 * уехали на уровень локации. Теперь путь занят решениями постройки, то есть тем,
 * чему в схеме место. Старое содержимое опознаётся не по наличию файла, а по
 * КЛЮЧАМ: `port`/`host`/`uplink`/`log` решениями не являются ни при каком
 * толковании, и молча их проглотить — тот же тихий эффект, от которого уходили.
 */

import { parse } from 'yaml';
import type { ShopProblemLog } from './problems.js';
import { DEFAULT_SETTINGS } from './settings.js';

/**
 * Где лежит орган решения — в схеме постройки, рядом с настройками остальных
 * инструментов. Путь относительный: считается от корня клона.
 */
export const DECISIONS_PATH = '.omnifield/omnifield-registry.yaml';

/**
 * Куда постройка отгружает партию.
 *
 * Сегодня адрес один — магазин ЭТОЙ локации, и назван он словом, а не URL'ом:
 * адрес раздачи считается из настроек участка (порт, интерфейс), и повторять его
 * в схеме значило бы завести второе место для того же числа. Схема отвечает на
 * вопрос «куда» именем места, а не его координатами.
 *
 * Второй адрес (общий магазин комьюнити) — следующий этап роадмапа: отгрузка
 * наружу необратима и разводится на три действия отдельно (`tasker:BASER2-272`).
 */
export type ShipTo = 'location';

export const LOCATION: ShipTo = 'location';

/**
 * Регистр, в котором едет имя. Следствие адреса, а не отдельное решение:
 * регистров два потому, что магазинов два (`kb:MECH-15`).
 */
export type NameRegister = 'internal' | 'public';

/** Решения постройки: то, что переживает пересоздание контейнера. */
export interface BuildingDecisions {
  /**
   * Нужен ли ЭТОЙ постройке магазин локации.
   *
   * Отдельно от партии, потому что это разные вопросы: постройка может брать со
   * склада, ничего туда не кладя, — и тому, кто поднимает локацию, нужен ответ
   * именно на первый. Вывести его из непустой партии значило бы объявить
   * потребителя без магазина.
   */
  readonly shop: boolean;
  /**
   * ПАРТИЯ — что именно постройка отгружает. Пути пакетов от корня постройки.
   *
   * Партия, а не «всё, что собралось»: наружу уходит выбранное, и «у меня есть,
   * но я это не отдаю» — решение владельца, а не недоделка. Пусто — постройка
   * пользуется магазином, но не отгружает; это законное состояние.
   *
   * Пути, а не имена пакетов: публикуют каталог, и путь — то же, что человек уже
   * называет рукой в `publish <папка>`. Имя лежит в манифесте по этому пути, и
   * второго места для него мы не заводим.
   */
  readonly batch: readonly string[];
  /** Куда отгружаем. */
  readonly address: ShipTo;
  /** В каком регистре едет имя по этому адресу — вычислено, а не спрошено. */
  readonly names: NameRegister;
}

/** Чем решения оказываются, если файл есть, но в нём не сказано ничего. */
export const DEFAULT_DECISIONS: BuildingDecisions = {
  // Файл заведён — значит про магазин думали. Дефолт «не нужен» превратил бы
  // заведённый орган в отказ от продаж, чего никто не просил.
  shop: true,
  batch: [],
  address: LOCATION,
  names: registerOf(LOCATION),
};

/** Что постройка вправе решить — единственный перечень, из него же дока. */
interface DecisionDeclaration {
  readonly key: keyof Omit<BuildingDecisions, 'names'>;
  readonly title: string;
  readonly description: string;
}

export const DECISION_DECLARATIONS: readonly DecisionDeclaration[] = [
  {
    key: 'shop',
    title: 'Нужен ли этой постройке магазин локации',
    description:
      'true — постройка пользуется раздачей своей локации: ставит из неё, ' +
      'кладёт на её склад или и то и другое. false — не пользуется вовсе. ' +
      'Вопрос отдельный от партии: брать со склада можно, ничего туда не кладя.',
  },
  {
    key: 'batch',
    title: 'Партия — что эта постройка отгружает',
    description:
      'Список путей пакетов от корня постройки. Отгружается ровно названное, ' +
      'а не всё, что собралось: «есть, но не отдаю» — решение владельца. ' +
      'Пусто или ключа нет — постройка не отгружает ничего.',
  },
  {
    key: 'address',
    title: 'Куда отгружаем',
    description:
      'location — магазин этой локации, единственный адрес, до которого ' +
      'сегодня построена дорога. Координаты (порт, интерфейс) лежат в настройках ' +
      'магазина и здесь не повторяются: схема называет место, а не его адрес.',
  },
];

/**
 * Ключи, по которым опознаётся СТАРОЕ содержимое этого пути.
 *
 * Настройки раздачи берутся перечнем из самого их объявления: снятая настройка
 * перестанет ловиться здесь сама, а добавленная начнёт — второго списка,
 * который разъедется с первым, мы не заводим. `baser` — ключ обвесной формы:
 * файл с ним родила дверь, когда магазин ещё пытались объявить поставкой.
 */
const LOCATION_KEYS: readonly string[] = [
  ...Object.keys(DEFAULT_SETTINGS),
  'baser',
];

/**
 * Читает орган решения постройки. Диска не трогает — текст приходит снаружи.
 *
 * `null` на выходе — решений нет: либо файла нет вовсе (законно), либо он
 * непригоден и об этом сказано отказом. Отличать эти два случая по возврату
 * незачем: непригодный вход и так останавливает прогон до первого действия.
 */
export function readDecisions(
  text: string | null,
  at: string,
  locationConfig: string,
  problems: ShopProblemLog,
): BuildingDecisions | null {
  if (text === null) {
    // Постройка ничего не объявила. Это «не продаём», а не «не настроено».
    return null;
  }

  let parsed: unknown;
  try {
    parsed = parse(text);
  } catch (error) {
    problems.add(
      'decisions-unreadable',
      at,
      `решения об отгрузке не разбираются как YAML: ${(error as Error).message}`,
    );
    return null;
  }

  if (parsed === null || parsed === undefined) {
    return DEFAULT_DECISIONS;
  }

  if (typeof parsed !== 'object' || Array.isArray(parsed)) {
    problems.add(
      'decisions-unreadable',
      at,
      'решения об отгрузке — это набор ключей; здесь лежит ' +
        (Array.isArray(parsed) ? 'список' : typeof parsed),
    );
    return null;
  }

  const raw = parsed as Record<string, unknown>;

  // СТАРЫЕ НАСТРОЙКИ РАЗДАЧИ по этому пути — отказ, а не молчание. Прочитать их
  // как решения нельзя (они не решения), а сделать вид, что файла нет, значило
  // бы уехать на дефолтах мимо заполненного человеком файла.
  const stale = LOCATION_KEYS.filter((key) => Object.hasOwn(raw, key));
  if (stale.length > 0) {
    problems.add(
      'config-in-old-place',
      at,
      `в ${at} теперь живут решения об отгрузке этой постройки, а ключи ` +
        `${stale.join(' · ')} — это настройки раздачи, и раздача принадлежит ` +
        `локации, а не одному её клону. Перенесите их в ${locationConfig} и ` +
        `уберите отсюда`,
    );
    return null;
  }

  const known = new Set<string>(DECISION_DECLARATIONS.map((one) => one.key));
  for (const key of Object.keys(raw)) {
    if (!known.has(key)) {
      problems.add(
        'decision-unknown',
        `${at}#${key}`,
        `решения "${key}" у магазина нет; есть: ${[...known].join(' · ')}`,
      );
    }
  }

  const shop = readShop(raw['shop'], at, problems);
  const batch = readBatch(raw['batch'], at, problems);
  const address = readAddress(raw['address'], at, problems);

  // ДВА РЕШЕНИЯ, КОТОРЫЕ СПОРЯТ ДРУГ С ДРУГОМ, — отказ. «Магазин не нужен» и
  // «отгружаю вот это» вместе не значат ничего: исполнить можно только одно, и
  // выбирать за человека, какое из двух он имел в виду, мы не станем.
  if (!shop && batch.length > 0) {
    problems.add(
      'decision-conflict',
      at,
      `постройка объявила shop: false и при этом отгружает партию ` +
        `(${batch.length} шт.). Одно из двух: магазин не нужен — партия пуста; ` +
        `партия есть — магазин нужен`,
    );
    return null;
  }

  return { shop, batch, address, names: registerOf(address) };
}

function readShop(
  value: unknown,
  at: string,
  problems: ShopProblemLog,
): boolean {
  if (value === undefined || value === null) {
    return DEFAULT_DECISIONS.shop;
  }
  if (typeof value !== 'boolean') {
    problems.add(
      'decision-type',
      `${at}#shop`,
      `shop — это да или нет (true/false), а здесь ${describe(value)}`,
    );
    return DEFAULT_DECISIONS.shop;
  }
  return value;
}

/**
 * Разбирает партию.
 *
 * Путь обязан оставаться ВНУТРИ постройки, и проверяется это здесь, а не при
 * отгрузке: партия — объявление о собственном товаре, и `../соседний-клон` в
 * ней означает либо опечатку, либо отгрузку чужого под своим именем. Оба случая
 * чинит человек, а не мы догадкой.
 */
function readBatch(
  value: unknown,
  at: string,
  problems: ShopProblemLog,
): readonly string[] {
  if (value === undefined || value === null) {
    return DEFAULT_DECISIONS.batch;
  }
  if (!Array.isArray(value)) {
    problems.add(
      'decision-type',
      `${at}#batch`,
      `партия — список путей, а здесь ${describe(value)}`,
    );
    return DEFAULT_DECISIONS.batch;
  }

  const batch: string[] = [];
  for (const [index, one] of value.entries()) {
    const spot = `${at}#batch[${index}]`;
    if (typeof one !== 'string' || one.trim() === '') {
      problems.add(
        'decision-type',
        spot,
        `в партии — пути пакетов от корня постройки, а здесь ${describe(one)}`,
      );
      continue;
    }
    const path = one.trim();
    if (path.startsWith('/') || path.split('/').includes('..')) {
      problems.add(
        'decision-type',
        spot,
        `"${path}" уводит за пределы постройки; в партии называют своё — путь ` +
          `от корня клона, например packages/моя-штука`,
      );
      continue;
    }
    batch.push(path);
  }
  return batch;
}

function readAddress(
  value: unknown,
  at: string,
  problems: ShopProblemLog,
): ShipTo {
  if (value === undefined || value === null) {
    return DEFAULT_DECISIONS.address;
  }
  if (typeof value !== 'string' || value.trim() === '') {
    problems.add(
      'decision-type',
      `${at}#address`,
      `адрес отгрузки — слово, а здесь ${describe(value)}`,
    );
    return DEFAULT_DECISIONS.address;
  }
  const named = value.trim();
  if (named !== LOCATION) {
    // Не «неизвестное значение», а названная граница: адрес есть, дороги до
    // него ещё нет. Отгрузка наружу необратима и разводится на три действия
    // отдельным этапом — молча повезти туда партию было бы худшим из исходов.
    problems.add(
      'address-not-built',
      `${at}#address`,
      `отгружать можно только в "${LOCATION}" — магазин этой локации. ` +
        `Адрес "${named}" означает отгрузку наружу, а она необратима и ` +
        `отдельными действиями пока не построена`,
    );
    return DEFAULT_DECISIONS.address;
  }
  return LOCATION;
}

/**
 * В каком регистре едет имя по этому адресу.
 *
 * Свой магазин — внутреннее имя, то самое, что лежит в манифесте пакета.
 * Общий магазин комьюнити — публичное, и берётся оно из объявленной карты
 * репозитория, а не собирается по дороге.
 */
export function registerOf(address: ShipTo): NameRegister {
  switch (address) {
    case LOCATION:
      return 'internal';
  }
}

function describe(value: unknown): string {
  if (value === null) return 'null';
  if (value === undefined) return 'ничего';
  if (Array.isArray(value)) return 'список';
  return `${typeof value} (${JSON.stringify(value)})`;
}
