/**
 * ЗАПУСКАТЕЛЬ РАЗДАЧИ — наш файл, который поднимает чужой сервер.
 *
 * Это тот самый процесс, который остаётся жить после того, как `up` кончился.
 * Отдельный файл нужен по одной причине: `runServer` поднимает сервер В СВОЁМ
 * процессе, а магазин обязан пережить команду, которая его завела. Значит нужен
 * процесс, который можно спавнить, — и он должен быть НАШИМ.
 *
 * ── ПОЧЕМУ НЕ `bin` ЧУЖОГО ПАКЕТА (и чем это оплачено) ──────────────────────
 *
 * Первый выпуск спавнил `require.resolve('verdaccio/bin/verdaccio')`. Способ был
 * взят не с потолка: так делает `@nx/js`, и ровно так написано в доке verdaccio
 * («using fork from child_process»). Тем не менее у потребителя он упал:
 *
 *     ERR_PACKAGE_PATH_NOT_EXPORTED: Package subpath './bin/verdaccio'
 *     is not defined by "exports"
 *
 * Замер 2026-08-08: в 6.8.0 (наша монорепа) поля `exports` у verdaccio НЕТ
 * ВОВСЕ — поэтому резолвился любой подпуть; в 6.9.2 (то, что приезжает
 * потребителю по диапазону `^6.3.2`) объявлены ровно `.` и `./package.json`, и
 * подпуть закрылся. То есть работало не «почти правильно», а на пакете без
 * объявленных границ: контрактом это не было никогда, и наш зелёный прогон
 * означал лишь совпадение раскладки.
 *
 * ── ЧТО ВЗЯТО ВМЕСТО ЭТОГО ──────────────────────────────────────────────────
 *
 * `runServer` из ГЛАВНОГО входа — он объявлен в `exports` и он же прямо
 * рекомендован вендором: «recommend use runServer for future compatibility»
 * (verdaccio.org/docs/verdaccio-programmatically, сверено 2026-08-08). Замер на
 * 6.9.2: сервер поднимается, `/-/ping` отвечает 200.
 *
 * Опора теперь ровно на то, что чужой пакет ОБЪЯВИЛ публичным. Закроют и это —
 * узнаем красной приёмкой по выпущенному пакету, а не письмом от человека,
 * у которого не поднялся магазин.
 *
 * ── ОШИБКИ УЕЗЖАЮТ В ЛОГ, И ЭТО НЕ НЕБРЕЖНОСТЬ ──────────────────────────────
 *
 * Здесь ничего не ловится намеренно: процесс отвязан от команды, и печатать
 * человеку ему уже некуда. Его поток целиком направлен в лог магазина
 * (`shop.ts`), а команда, не дождавшись ответа, скажет `shop-died` и назовёт
 * путь к этому логу. Причина попадает туда, где её будут искать.
 */

import { runServer } from 'verdaccio';

const [configPath, host, port] = process.argv.slice(2);

const app = await runServer(configPath);

app.listen(Number(port), host);
