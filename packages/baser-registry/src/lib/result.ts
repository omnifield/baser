/**
 * ОТВЕТ МАГАЗИНА — данные. Текст поверх них — рендер, а не вторая правда.
 *
 * Потребитель здесь не только человек в терминале: это скрипт подъёма среды,
 * конвейер и devopser. Инструмент, который «печатает результат», к ним не
 * подключается — его разбирают регулярками и переписывают (`kb:BASER3-10`).
 * Поэтому команда сперва СОБИРАЕТ вот эту структуру и лишь потом что-то
 * печатает, а `renderText` принимает её целиком и больше ничего: чего нет
 * здесь, человеку показать физически нечем.
 *
 * ДВА РАЗНЫХ ВОПРОСА РАЗВЕДЕНЫ ПОЛЯМИ, и это главное решение файла:
 * `state` — что с магазином СЕЙЧАС, `outcome` — что сделал ЭТОТ прогон. Слить их
 * было бы дешевле на одно поле и дороже на весь смысл: `up` при уже поднятом
 * магазине не сделал ничего и это успех, а не «работает» без различения того,
 * подняли его мы или он и так стоял.
 */

import type { ShopProblem } from './problems.js';
import type { RootOrigin } from './locate.js';
import type { TraceSpan } from './trace.js';

export type ShopCommand = 'up' | 'down' | 'status';

/**
 * ЧТО С МАГАЗИНОМ СЕЙЧАС — по факту, а не по заявке.
 *
 * Состояний два, и промежуточных нет намеренно: раздача либо отвечает, либо её
 * нет. «Заявка есть, а ответа нет» — не третье состояние, а закрытый магазин с
 * протухшей записью, и путать эти вещи означало бы отвечать «наверное работает»
 * на вопрос, который задают ровно для того, чтобы знать точно.
 */
export type ShopState = 'running' | 'closed';

/** Что сделал этот прогон. */
export type ShopOutcome =
  /** Раздача поднята этим прогоном. */
  | 'started'
  /** Магазин уже работал — делать было нечего. Это успех, а не отказ. */
  | 'already-running'
  /** Раздача остановлена этим прогоном. */
  | 'stopped'
  /** Магазин и так был закрыт. Тоже успех: `down` идемпотентен. */
  | 'already-closed'
  /** Ничего не делали — спрашивали. */
  | 'reported'
  /** Просили изменить состояние, и не вышло. */
  | 'failed'
  /** Вход непригоден: до попытки не дошли. */
  | 'refused';

/** Где команда работала и почему именно там. */
export interface LocationReport {
  readonly root: string;
  /**
   * Чем корень опознан. Уезжает в ответ, чтобы «почему тут» не выяснялось на
   * глаз: команда ставится глобально и зовётся откуда угодно.
   */
  readonly origin: RootOrigin;
  readonly home: string;
}

/** Сам магазин: где, по какому адресу и чем поднят. */
export interface ShopReport {
  /**
   * Адрес, по которому в магазин ходят, — тот, что подставляют в `--registry`.
   *
   * Не то же, что слушаемый интерфейс: `0.0.0.0` слушать можно, ходить по нему
   * нельзя (`settings.ts`).
   */
  readonly address: string;
  /** Что процесс слушает: `host:port` как есть. */
  readonly listen: string;
  /** У кого магазин спрашивает то, чего нет на складе. */
  readonly uplink: string;
  /** Процесс раздачи; `null` — магазин закрыт либо держит его не наша заявка. */
  readonly pid: number | null;
  /**
   * Заявка о запуске лежала на диске.
   *
   * Отдельно от `state`, потому что вместе они отвечают на вопрос про
   * ПЕРЕЗАПУСК КОНТЕЙНЕРА: `claimed: true` и `closed` — магазин не пережил
   * остановку, и это ожидаемое состояние, а не поломка. Одним полем такого не
   * сказать.
   */
  readonly claimed: boolean;
  /** Куда магазин пишет лог — единственный след упавшего старта. */
  readonly log: string;
}

/** Товар: то, ради чего магазин переживает остановку. */
export interface StockReport {
  readonly storage: string;
  /**
   * Сколько имён лежит на складе.
   *
   * Имён, а не версий и не файлов: человек спрашивает «сколько у меня товара»,
   * и ответ в штуках пакетов — единственный, который он может сверить глазами.
   */
  readonly packages: number;
}

/**
 * ЧУЖОЙ АДРЕС, КОТОРЫЙ ПЕРЕБИВАЕТ НАШ, — названный факт, а не сюрприз.
 *
 * Скоуп-специфичная настройка npm (`@скоуп:registry`) БЬЁТ флаг `--registry`, и
 * бьёт молча: команда выглядит правильной, код возврата нулевой, а товар уезжает
 * в чужой реестр. На этом мы уже обожглись живьём — публикация пробы ушла в
 * GitHub Packages организации вместо локального магазина (`tasker:BASER2-249`).
 *
 * Поэтому магазин не советует «как надо», а СМОТРИТ, что настроено у человека, и
 * называет расхождение данными: вот скоуп, вот куда он сейчас указывает, вот
 * адрес, который перебьёт его для этой команды. Совет без замера здесь был бы
 * ровно той же ловушкой второго порядка.
 */
export interface ScopeConflict {
  /** Скоуп целиком, вместе с собакой: `@omnifield`. */
  readonly scope: string;
  /** Куда он указывает сейчас — по эффективному конфигу npm. */
  readonly registry: string;
}

/**
 * ЧЕМ ХОДИТЬ В ЭТОТ МАГАЗИН — готовые строки npm-конфига, а не совет словами.
 *
 * Два факта, каждый из которых мы оплатили живым прогоном:
 *
 * 1. **Без токена npm не публикует вовсе** (`ENEEDAUTH`), даже когда раздача
 *    разрешает запись всем: решение принимает КЛИЕНТ, до похода на сервер.
 *    Значение токена при этом любое непустое — магазин локации его не проверяет,
 *    потому что прав доступа в первом выпуске нет по решению ТЗ.
 * 2. **Скоуп-настройка бьёт `--registry` молча.** Значит строка на скоуп нужна
 *    отдельно от общей, и нужна ровно там, где скоуп уже настроен мимо нас.
 *
 * Едет структурой, а не текстом, чтобы обещание можно было ПРОВЕРИТЬ: приёмка
 * берёт эти строки буквально, кладёт в конфиг и публикует ими. Совет, который
 * никто не прогонял, протухает молча — и человек идёт по нему в тупик.
 */
export interface AccessReport {
  /** Строки для `.npmrc` — в том порядке, в котором их кладут в файл. */
  readonly npmrc: readonly string[];
}

export interface ShopResult {
  /**
   * Версия формы ответа.
   *
   * Схема вывода версионируется, потому что скрипты и devopser переживают
   * эволюцию инструмента только предсказуемой сменой формы (`kb:BASER3-10`).
   */
  readonly schemaVersion: number;
  readonly command: ShopCommand;
  readonly outcome: ShopOutcome;
  readonly state: ShopState;
  readonly location: LocationReport;
  readonly shop: ShopReport;
  readonly stock: StockReport;
  /**
   * Скоупы, настроенные мимо этого магазина.
   *
   * Пусто — расхождений нет. Непусто — публикация и установка по этим скоупам
   * уедут не сюда, пока адрес не назван явно.
   */
  readonly scopeConflicts: readonly ScopeConflict[];
  /** Чем ходить в этот магазин — готовые строки конфига. */
  readonly access: AccessReport;
  /** Что легло на диск этим прогоном. */
  readonly writes: readonly WriteReport[];
  /** Телеметрия. В текстовый рендер не идёт. */
  readonly trace: readonly TraceSpan[];
  readonly problems: readonly ShopProblem[];
}

export interface WriteReport {
  readonly path: string;
  readonly kind: 'CREATE' | 'UPDATE' | 'DELETE';
}

/** Текущая версия формы ответа. Поднимается вместе с изменением структуры. */
export const SCHEMA_VERSION = 1;

/**
 * Код возврата — производная от исхода, а не отдельный признак.
 *
 * Набор короткий намеренно: конвейер ветвится по нему, а подробности лежат в
 * ответе данными.
 *
 * | код | что                                                          |
 * | --- | ------------------------------------------------------------ |
 * | 0   | сделано либо делать было нечего                              |
 * | 1   | просили изменить состояние — не вышло; чинить по логу        |
 * | 2   | вход непригоден: настройка или занятый адрес, чинит человек  |
 */
export function exitCodeOf(result: ShopResult): number {
  switch (result.outcome) {
    case 'failed':
      return 1;
    case 'refused':
      return 2;
    default:
      return 0;
  }
}
