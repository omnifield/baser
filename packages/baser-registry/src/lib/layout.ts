/**
 * ЧТО ОСТАЁТСЯ ОТ МАГАЗИНА В ЛОКАЦИИ — и что из этого переживает остановку.
 *
 * Папка одна и лежит в корне рядом с `.git` и `.claude`: магазин — свойство
 * ЛОКАЦИИ, а не одного каталога внутри неё, и искать его по дереву человек не
 * должен.
 *
 * ```
 * .baser-registry/
 *   config.yml   настройки этой локации — файл ЧЕЛОВЕКА
 *   storage/     товар — то, что опубликовали
 *   runtime/     служебное текущего запуска
 * ```
 *
 * ── РАЗДЕЛЕНИЕ, РАДИ КОТОРОГО ВСЁ И ЗАТЕВАЛОСЬ ──────────────────────────────
 *
 * Обещание инструмента звучит так: контейнер остановился — магазин закрыт,
 * ТОВАР ОСТАЛСЯ. Значит внутри папки проходит граница: `config.yml` и `storage/`
 * переживают остановку и переезд, `runtime/` — нет. Смешать их в одном каталоге
 * было бы дешевле на один путь и дороже на весь класс дефектов: чистка
 * служебного унесла бы товар, а `pid` протухшего запуска лежал бы рядом с
 * настройками человека и читался бы как часть его конфига.
 *
 * `runtime/` — целиком наш и целиком одноразовый: его содержимое
 * перерождается на каждом `up` и не переживает остановку контейнера
 * осмысленно (см. `shop.ts` — заявка о запуске проверяется фактом, а не
 * принимается на веру).
 *
 * ── ПОЧЕМУ КОНФИГ VERDACCIO ЛЕЖИТ В `runtime/`, А НЕ РЯДОМ С ЧЕЛОВЕЧЕСКИМ ───
 *
 * У магазина два конфига, и они разной природы. `config.yml` — файл человека:
 * несколько наших настроек, которые он вправе поменять. `runtime/verdaccio.yaml`
 * — АРТЕФАКТ: он собирается нами целиком на каждом запуске из настроек человека
 * и наших дефолтов. Положить их рядом значило бы предложить человеку править
 * то, что перезапишется на следующем `up` без предупреждения, — ровно та
 * «правка руками вместо настройки», которую канон называет дефектом поставщика
 * (`kb:BASER3-5`).
 */

import { join } from 'node:path';

/** Имя папки магазина в корне локации — единственное место, где оно названо. */
export const SHOP_DIRECTORY = '.baser-registry';

/** Адреса всего, что магазин держит в локации. */
export interface ShopLayout {
  /** Корень локации — каталог, в котором позвали команду. */
  readonly root: string;
  /** Папка магазина целиком. */
  readonly home: string;
  /** Настройки этой локации — файл человека. Переживает остановку. */
  readonly config: string;
  /** Товар: то, что опубликовали. Переживает остановку — ради этого всё. */
  readonly storage: string;
  /** Служебное текущего запуска. Остановку не переживает. */
  readonly runtime: string;
  /** Конфиг verdaccio — артефакт, собирается целиком на каждом `up`. */
  readonly generatedConfig: string;
  /** Заявка о запуске: pid, адрес, чем поднято. Проверяется фактом. */
  readonly claim: string;
  /** Куда магазин пишет свой лог: единственный след упавшего старта. */
  readonly log: string;
}

/** Считает адреса от корня локации. Диска не трогает — это чистая функция. */
export function shopLayout(root: string): ShopLayout {
  const home = join(root, SHOP_DIRECTORY);
  const runtime = join(home, 'runtime');
  return {
    root,
    home,
    config: join(home, 'config.yml'),
    storage: join(home, 'storage'),
    runtime,
    generatedConfig: join(runtime, 'verdaccio.yaml'),
    claim: join(runtime, 'shop.json'),
    log: join(runtime, 'shop.log'),
  };
}
