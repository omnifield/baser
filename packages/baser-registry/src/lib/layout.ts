/**
 * ЧТО ОСТАЁТСЯ ОТ МАГАЗИНА — и на КАКОМ уровне мира это лежит.
 *
 * ```
 * ЛОКАЦИЯ (контейнер)
 *   <корень магазина>/        ← весь магазин: одна вещь на весь участок
 *     config.yml              настройки раздачи — файл ЧЕЛОВЕКА
 *     storage/                товар — то, что опубликовали
 *     runtime/                состояние текущего запуска
 *
 *   ПОСТРОЙКА (клон репозитория)
 *     .omnifield/             настройки построек; магазина среди них больше нет
 * ```
 *
 * ── ВЕЩЬ ЖИВЁТ НА ОДНОМ УРОВНЕ, А НЕ НА ДВУХ ────────────────────────────────
 *
 * Процесс и порт принадлежат контейнеру по построению: адрес раздачи один на
 * всю локацию. Значит склад и настройки раздачи обязаны лежать там же — иначе
 * вещь разложена по двум уровням, и это не теория: товар одной постройки уезжал
 * на склад другой, а команда отвечала `failed` (`tasker:BASER2-254`).
 *
 * Разбор уровня — в `location.ts`, там же выбор конкретного места и его цена.
 *
 * ── ЧТО ОСТАЁТСЯ ПОСТРОЙКЕ ──────────────────────────────────────────────────
 *
 * Настройки ПУБЛИКАЦИИ — то, что именно эта постройка кладёт на общий склад.
 * Сегодня таких настроек нет ни одной, поэтому файла у постройки тоже нет:
 * заводить пустой ради симметрии значило бы обещать регулировку, которой не
 * существует. Место известно и названо (`.omnifield/` клона) — появится
 * настройка, появится и файл.
 *
 * ── ПОЧЕМУ КОНФИГ VERDACCIO ЛЕЖИТ В `runtime/` ─────────────────────────────
 *
 * Он не файл человека, а АРТЕФАКТ: собирается нами целиком на каждом `up` из
 * настроек человека и наших дефолтов. Положить его к человеческим значило бы
 * предложить править то, что перезапишется на следующем запуске без
 * предупреждения (`kb:BASER3-5`).
 */

import { join } from 'node:path';
import { shopHome, type ShopHome } from './location.js';

/**
 * Прежние места настроек — только чтобы их ЗАМЕТИТЬ и сказать вслух.
 *
 * Оба лежали в постройке, и оба были неверным уровнем. Читать их мы не станем:
 * молча подхватить настройки, которые человек писал для другой раскладки, —
 * это тот же тихий эффект, от которого уходим.
 */
export const LEGACY_SHOP_DIRECTORY = '.baser-registry';
export const LEGACY_SETTINGS_PATH = '.omnifield/omnifield-registry.yaml';

/** Адреса всего, что магазин держит в локации. */
export interface ShopLayout {
  /** Корень магазина этой локации и то, чем он определился. */
  readonly home: ShopHome;
  /** Настройки раздачи — файл человека, один на локацию. */
  readonly config: string;
  /** Товар: то, что опубликовали. Переживает остановку — ради этого всё. */
  readonly storage: string;
  /** Состояние текущего запуска. Остановку не переживает осмысленно. */
  readonly runtime: string;
  /** Конфиг verdaccio — артефакт, собирается целиком на каждом `up`. */
  readonly generatedConfig: string;
  /** Заявка о запуске: pid, адрес, чем поднято. Проверяется фактом. */
  readonly claim: string;
  /** Куда магазин пишет лог: единственный след упавшего старта. */
  readonly log: string;
}

/** Что от прежних раскладок могло остаться в ПОСТРОЙКЕ. */
export interface BuildingLayout {
  /** Корень постройки — клон репозитория, из которого позвали команду. */
  readonly root: string;
  /** Прежнее место настроек, самое первое. */
  readonly legacyShopConfig: string;
  /** Прежнее место настроек, предыдущее. */
  readonly legacySettings: string;
}

/** Считает адреса магазина локации. Диска не трогает — чистая функция. */
export function shopLayout(
  environment: NodeJS.ProcessEnv = process.env,
): ShopLayout {
  const home = shopHome(environment);
  const runtime = join(home.path, 'runtime');
  return {
    home,
    config: join(home.path, 'config.yml'),
    storage: join(home.path, 'storage'),
    runtime,
    generatedConfig: join(runtime, 'verdaccio.yaml'),
    claim: join(runtime, 'shop.json'),
    log: join(runtime, 'shop.log'),
  };
}

/** Считает адреса прежних мест внутри постройки. */
export function buildingLayout(root: string): BuildingLayout {
  return {
    root,
    legacyShopConfig: join(root, LEGACY_SHOP_DIRECTORY, 'config.yml'),
    legacySettings: join(root, LEGACY_SETTINGS_PATH),
  };
}
