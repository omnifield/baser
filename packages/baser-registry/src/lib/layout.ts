/**
 * ЧТО ОСТАЁТСЯ ОТ МАГАЗИНА В ЛОКАЦИИ — и почему это ДВА разных места.
 *
 * ```
 * .omnifield/
 *   omnifield-registry.yaml   настройки этой локации — файл ЧЕЛОВЕКА
 *
 * .baser-registry/            только МАШИННОЕ
 *   storage/                  товар — то, что опубликовали
 *   runtime/                  состояние текущего запуска
 * ```
 *
 * ── ДЕЛЕНИЕ ПРОХОДИТ ПО ПРИРОДЕ, А НЕ ПО ИНСТРУМЕНТУ ────────────────────────
 *
 * Раньше настройки лежали внутри папки магазина, вместе с товаром. Так удобнее
 * писать инструмент и хуже жить человеку: то, что он правит, обязано лежать
 * там же, где всё остальное, что он правит в этой локации (`kb:BASER3-5`), —
 * рядом с `harness.yaml` и настройками соседних инструментов.
 *
 * Цена смешения предъявлена живьём: папка магазина закрыта в `.gitignore` — и
 * это ВЕРНО для двух десятков мегабайт товара и НЕВЕРНО для конфига, который
 * человек обязан видеть и коммитить. Один игнор не обслуживает две природы, и
 * никакая формулировка правила этого не исправит — исправляет только раскладка.
 *
 * Отсюда обе половины:
 *
 * - **`.omnifield/`** — человеческое: переживает обновление, едет в репозиторий,
 *   правится руками. Наш файл там ничем не выделяется среди соседей, и это
 *   свойство, а не совпадение: инструмент отдают другим продуктам, и каждый из
 *   них должен искать настройки там же, где искал бы у любого другого.
 * - **`.baser-registry/`** — машинное целиком, и потому целиком годится под один
 *   игнор. `storage/` переживает остановку контейнера (ради этого весь
 *   инструмент), `runtime/` — нет.
 *
 * ── ПОЧЕМУ КОНФИГ VERDACCIO ЛЕЖИТ В `runtime/` ─────────────────────────────
 *
 * Он не файл человека, а АРТЕФАКТ: собирается нами целиком на каждом `up` из
 * настроек человека и наших дефолтов. Положить его к человеческим значило бы
 * предложить править то, что перезапишется на следующем запуске без
 * предупреждения, — ровно та «правка руками вместо настройки», которую канон
 * называет дефектом поставщика (`kb:BASER3-5`).
 */

import { join } from 'node:path';

/** Имя папки магазина в корне локации — единственное место, где оно названо. */
export const SHOP_DIRECTORY = '.baser-registry';

/**
 * Папка, где локация держит ВСЁ, что настраивает человек.
 *
 * Не наша: в ней уже лежат `harness.yaml`, `omnifield-devbox.yaml`,
 * `omnifield-git.yaml`. Человек ходит в одно место, а не ищет по дереву, где
 * что настраивается (`kb:BASER3-5`).
 */
export const SETTINGS_DIRECTORY = '.omnifield';

/**
 * Имя нашего файла настроек — по той же конвенции, что у обвесов.
 *
 * Дверь считает его из личности обвеса: `omnifield/devbox` →
 * `omnifield-devbox.yaml` (`sourceConfigPath` в контрактах). Магазин обвесом не
 * является, но личность у него та же по форме — `omnifield/registry`, — и имя
 * файла обязано читаться человеком так же, как соседние. Конвенция повторена
 * здесь, а не импортирована: тянуть контракты станка в глобально ставящийся
 * инструмент значило бы везти потребителю пол-производства ради одной строки.
 */
export const SETTINGS_FILE = 'omnifield-registry.yaml';

/** Адреса всего, что магазин держит в локации. */
export interface ShopLayout {
  /** Корень локации — каталог, в котором позвали команду. */
  readonly root: string;
  /** Папка магазина целиком: только машинное. */
  readonly home: string;
  /**
   * Настройки этой локации — файл человека, в ОБЩЕЙ папке локации.
   *
   * Лежит вне папки магазина намеренно: деление проходит по природе, а не по
   * инструменту. То, что правит человек, живёт рядом с остальными его
   * настройками, переживает обновление и едет в репозиторий; товар и состояние
   * прогона не едут никуда.
   *
   * Живое доказательство, что смешивать нельзя: `.baser-registry/` закрыт в
   * `.gitignore` — верно для товара и неверно для конфига, который человек
   * обязан видеть и коммитить. Один игнор не обслуживает две природы.
   */
  readonly config: string;
  /**
   * Прежнее место настроек — `.baser-registry/config.yml`.
   *
   * Нужен не для чтения, а чтобы ЗАМЕТИТЬ его и сказать вслух: локация, где
   * человек заполнил старый файл, не должна молча поехать на дефолтах.
   */
  readonly legacyConfig: string;
  /** Товар: то, что опубликовали. Переживает остановку — ради этого всё. */
  readonly storage: string;
  /** Служебное текущего запуска. Остановку не переживает. */
  readonly runtime: string;
  /** Конфиг verdaccio — артефакт, собирается целиком на каждом `up`. */
  readonly generatedConfig: string;
  /** Заявка о запуске: pid, адрес, чем поднято. Проверяется фактом. */
  readonly claim: string;
  /** Куда магазин пишет свой лог: единственный след упавшего старта. */
  readonly log: string;
}

/** Считает адреса от корня локации. Диска не трогает — это чистая функция. */
export function shopLayout(root: string): ShopLayout {
  const home = join(root, SHOP_DIRECTORY);
  const runtime = join(home, 'runtime');
  return {
    root,
    home,
    config: join(root, SETTINGS_DIRECTORY, SETTINGS_FILE),
    legacyConfig: join(home, 'config.yml'),
    storage: join(home, 'storage'),
    runtime,
    generatedConfig: join(runtime, 'verdaccio.yaml'),
    claim: join(runtime, 'shop.json'),
    log: join(runtime, 'shop.log'),
  };
}
