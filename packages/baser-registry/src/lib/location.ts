import { homedir } from 'node:os';
import { join, resolve } from 'node:path';

/** Переменная, которой локация называет своё место для магазина. */
export const HOME_VARIABLE = 'BASER_REGISTRY_HOME';

/** Имя каталога магазина внутри общего места данных. */
export const SHOP_DIRECTORY = 'baser-registry';

/** Чем определился корень — уезжает в ответ, чтобы «почему тут» не гадали. */
export type ShopHomeOrigin = 'variable' | 'xdg' | 'home';

export interface ShopHome {
  readonly path: string;
  readonly origin: ShopHomeOrigin;
}

/**
 * Корень магазина этой локации.
 *
 * Окружение читается снаружи, а не из `process.env` напрямую: так пробы
 * задают его без правки глобального состояния, а поведение остаётся одним и
 * тем же кодом.
 */
export function shopHome(
  environment: NodeJS.ProcessEnv = process.env,
): ShopHome {
  const named = environment[HOME_VARIABLE];
  if (typeof named === 'string' && named.trim() !== '') {
    return { path: resolve(named.trim()), origin: 'variable' };
  }

  const data = environment['XDG_DATA_HOME'];
  if (typeof data === 'string' && data.trim() !== '') {
    return { path: join(resolve(data.trim()), SHOP_DIRECTORY), origin: 'xdg' };
  }

  return {
    path: join(homedir(), '.local', 'share', SHOP_DIRECTORY),
    origin: 'home',
  };
}
