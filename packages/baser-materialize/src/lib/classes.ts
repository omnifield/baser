/**
 * КЛАСС АРТЕФАКТА — чем движок держит положенный файл.
 *
 * Станок даёт инструменту руки, а не решения (`kb:BASER2-2` §4): он замечает и
 * называет, а что делать с файлом при обновлении — знает обвес. Класс и есть то
 * слово, которым обвес это говорит; движок его ИСПОЛНЯЕТ и не выводит сам —
 * разбираться в семантике чужих файлов станку незачем.
 *
 * **Перечисление, а не флаг.** `once: true` выразил бы ровно два состояния, а
 * третий класс уже описан у соседей (`kb:WEBER-4`).
 *
 * ## Почему слово здесь СВОЁ, а не импортировано из контракта
 *
 * То же самое слово объявлено в `@omnifield/baser-contracts` (`classes.ts`), и
 * это НЕ второе место для одного факта, а та же развязка, что уже стоит на
 * `LayoutEntry` (`declaration.ts`): вход движка — готовая структура, а не форма,
 * и подать её вправе не только наша дверь. Зависеть от разбора формы ради
 * двухзначного перечисления значило бы связать движок с той дверью, которую он
 * специально не знает.
 *
 * Расхождение при этом ловится, а не молчит: класс, которого движок не знает, —
 * НАЗВАННЫЙ отказ (`unknown-artifact-class`), а не тихо взятое умолчание.
 * Приедет третий класс — движок скажет об этом вслух на первом же прогоне.
 * Словарь общий, объявления два — как у `source` · `layout` · `src` · `dest`.
 */

export type ArtifactClass =
  /**
   * Артефакт наш и перегенерируется целиком (`kb:BASER2-2` §4, модель A).
   * Правка руками не переводит владение — план называет будущее затирание
   * вслух и перекладывает файл целиком.
   */
  | 'regenerated'
  /**
   * Станок кладёт файл в объявленном месте и дальше его не трогает.
   *
   * Что это значит для движка (`tasker:BASER2-51`):
   *   - **хеш не пишется вовсе** — записанный и никогда не сравниваемый хеш это
   *     половина имитации, а она хуже отсутствия;
   *   - **содержимое не сверяется** — правка человека расхождением не считается
   *     и шага не порождает: файл задумывался человеческим;
   *   - **запись, потерявшая объявление, НЕ уходит сиротой молча** — она
   *     называется извещением и снимается только поимённым подтверждением;
   *   - **пропал сам артефакт — кладём заново**: это «объявленное место
   *     пустое», а не «человек удалил, уважим».
   */
  | 'placed-once';

/** Перечень классов — для сообщений и для проверки поданной структуры. */
export const ARTIFACT_CLASSES: readonly ArtifactClass[] = [
  'regenerated',
  'placed-once',
];

/**
 * Умолчание: класс не назван — артефакт наш.
 *
 * Форму разбирает дверь и класс проставляет ОНА (`baser-contracts`), поэтому
 * здесь это не второе умолчание, а то же самое: структура без класса означает
 * ровно то, что означала раскладка формы 1, — `regenerated`. Держать вместо
 * умолчания отказ значило бы требовать от всякого, кто строит вход руками
 * (тест, чужая дверь), повторять уже решённое.
 */
export const DEFAULT_ARTIFACT_CLASS: ArtifactClass = 'regenerated';

export function isArtifactClass(value: unknown): value is ArtifactClass {
  return (
    typeof value === 'string' &&
    (ARTIFACT_CLASSES as readonly string[]).includes(value)
  );
}
