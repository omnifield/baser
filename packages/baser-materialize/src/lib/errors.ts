/**
 * Ошибки движка материализации.
 *
 * Правило: движок никогда не «падает молча» и никогда не перезаписывает молча —
 * всё, что он отказался сделать, он обязан НАЗВАТЬ. Поэтому каждая ошибка несёт
 * адрес (файл/поле), причину человеческим текстом и МАШИННЫЙ КОД.
 *
 * Код нужен соседней зоне: дверь склеивает отказы формы, движка и свои в один
 * список и ветвится по кодам, а не по тексту (`packages/baser-cli`,
 * `tasker:BASER2-24`). Пока кода не было, дверь угадывала причину по типу
 * ошибки плюс собственному знанию о раскладке — то есть держала вторую правду
 * о чужом событии.
 */

/** Код отказа движка. Ветвиться потребителю — по нему, не по тексту. */
export type EngineProblemCode =
  /** Поданная структура непригодна: нет раскладки, нет корня содержимого. */
  | 'declaration-invalid'
  /** Источник обвеса лежит вне дерева потребителя. */
  | 'source-outside-tree'
  /** Манифест материализации не читается или не той формы. */
  | 'manifest-unreadable'
  /** Сбой применения; дерево откачено. */
  | 'apply-failed'
  /** План неприменим: есть конфликты владения. */
  | 'plan-blocked';

/** Общий предок ошибок зоны — позволяет потребителю отличить «наше» от чужого. */
export class BaserMaterializeError extends Error {
  /** Машинный код отказа; переопределяется наследниками. */
  readonly code: EngineProblemCode = 'declaration-invalid';

  constructor(message: string, options?: { cause?: unknown }) {
    super(message, options);
    this.name = new.target.name;
  }
}

/** Поданная движку структура не годится для работы. */
export class DeclarationError extends BaserMaterializeError {
  override readonly code: EngineProblemCode = 'declaration-invalid';
}

/**
 * Источник обвеса лежит вне дерева потребителя.
 *
 * Шаблоны физически живут в установленном пакете, и это норма; но движок
 * адресует источник репо-относительным путём и ИМ ЖЕ защищается от записи в
 * собственный источник. Когда источника в дереве нет, защите не за что
 * зацепиться — и движок называет это сам, вместо того чтобы вырождаться в
 * молчаливое «проверка ничего не нашла» (`tasker:BASER2-24`).
 */
export class SourceOutsideTreeError extends BaserMaterializeError {
  override readonly code: EngineProblemCode = 'source-outside-tree';
}
