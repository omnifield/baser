/**
 * ВИРТУАЛЬНОЕ ДЕРЕВО — ПОРТ, А НЕ ЧУЖОЙ ТИП.
 *
 * Движок файловой системы не касается вовсе: он читает и пишет через дерево, а
 * кто это дерево подаёт и кто потом сбрасывает накопленное на диск — работа
 * раннера (`README.md`, «Модель»). Раньше форма этого порта бралась готовой —
 * `Tree` из `@nx/devkit`, — и вместе с формой в поставку уезжала чужая сборочная
 * система.
 *
 * ## Почему свой тип, а не `@nx/devkit`
 *
 * Тип нужен движку ТОЛЬКО как тип: ни одного значения из `@nx/devkit` в рантайме
 * зоны нет (все обращения — `import type`). Но объявление типа в публичной
 * поверхности (`computePlan`, `applyPlan`, `readManifest`, `createTreeSource`)
 * уезжает в `.d.ts`, а вместе с ним — требование иметь этот пакет у себя.
 * Выражалось оно `peerDependencies`, и пакетные менеджеры ставят peer сами:
 * потребитель двери получал `nx` — 21 МБ и платформенные нативные модули
 * (`tasker:BASER2-181`).
 *
 * Дверь эту же цену уже отказалась платить и держит СВОЮ реализацию дерева на
 * шести методах (`packages/baser-cli/src/lib/tree.ts`). Здесь — вторая половина
 * того же решения: движок называет шесть методов, которые зовёт, и на этом его
 * знание о дереве заканчивается.
 *
 * ## Ровно то, что движок зовёт
 *
 * Порт не «подмножество `Tree` для экономии», а перечень зовомого: `read` ·
 * `write` · `exists` · `isFile` · `children` · `delete` — и `setExecutable`,
 * который движок зовёт только там, где раскладка объявила режим. Метода,
 * которого движок не зовёт, здесь нет — объявленный и никем не зовомый метод
 * стал бы требованием к каждому раннеру и не был бы проверен ни одной пробой.
 *
 * **Двоичной формы здесь нет по той же причине.** Движок читает текстом
 * (`read(path, 'utf-8')`) и пишет строку — содержимого он не трогает вовсе.
 * Объявить `Buffer` значило бы притянуть в публичную поверхность `@types/node`:
 * до этого порта она была самодостаточна типово, и менять один чужой пакет на
 * другой смысла нет. Раннер, умеющий больше (и `FsTree`, и дерево двери умеют),
 * порту подходит: шире — не мешает.
 *
 * **Совместимость структурная и проверяемая.** Сигнатуры взяты у дерева devkit,
 * поэтому и `FsTree` из Nx, и дерево двери подходят порту без обёрток и
 * приведений. Утверждение это не на словах: пробы зоны гоняют движок на
 * настоящем дереве Nx (`createTreeWithEmptyWorkspace`, `workspace.fixture.ts`),
 * и разъехавшаяся сигнатура уронит `typecheck` проб, а не прогон потребителя.
 *
 * ## Режим артефакта — СЕДЬМОЙ ЧЛЕН, а не третий параметр `write`
 *
 * Раскладка объявляет исполняемость (`layout[].executable`, форма 6,
 * `tasker:BASER2-213`), и объявленное обязано доехать до того, кто пишет
 * (`tasker:BASER2-214`). Напрашивался третий параметр `write(path, content,
 * { executable })` — так режим носят и рынок, и оба существующих раннера:
 * `fs.writeFile(path, data, { mode })` в Node, `write(path, content, { mode })` у
 * дерева Nx и у дерева двери, `git update-index --chmod=+x` в git — где режим
 * файла и вовсе один бит, как у нас (сверено 2026-08-07).
 *
 * **Эта форма отпадает не по вкусу, а по замеру.** Наш мешок опций
 * (`{ executable?: boolean }`) не имеет ни одного общего поля с чужим
 * (`{ mode?: Mode }`), и TypeScript на таком отказывает в обе стороны — «has no
 * properties in common». Замер: дерево Nx перестаёт подходить порту, а вместе с
 * ним и дерево двери (`RepoTree extends Tree` из devkit), то есть правка в этой
 * зоне красит чужую сборку. Приёмка задачи требует ровно обратного: раннер, не
 * знающий про режим, продолжает работать.
 *
 * Поэтому режим едет ОТДЕЛЬНЫМ НЕОБЯЗАТЕЛЬНЫМ членом порта. Необязательность —
 * не послабление, а то самое требование приёмки: у старого дерева члена нет, оно
 * подходит порту как подходило. Различить «раннер режим принял» и «раннер про
 * режим не знает» движок при этом МОЖЕТ — член либо есть, либо его нет, — и
 * говорит об этом в трейсе (`apply.executable`). Мешок опций такой возможности
 * не оставлял вовсе: чужое дерево молча проглотило бы незнакомый ключ, и
 * «объявлено исполняемым» разошлось бы с «лежит исполняемым» ровно так же
 * молча, как разошлось в `tasker:BASER2-208`, с которого всё и началось.
 */

/**
 * Дерево, с которым работает движок.
 *
 * Виртуальное: изменения копятся у раннера и уезжают на диск за пределами
 * движка — отсюда §2 контракта «применение проходит целиком либо не проходит
 * вовсе» (`apply.ts`).
 */
export interface Tree {
  /**
   * Содержимое файла текстом; `null` — файла нет.
   *
   * Кодировка названа литералом, а не `BufferEncoding`: движок зовёт ровно
   * `'utf-8'` и ничего другого, а `BufferEncoding` — тип `@types/node`, то есть
   * ещё один чужой пакет в поверхности ради значения, которое здесь одно.
   */
  read(filePath: string, encoding: 'utf-8'): string | null;
  /** Кладёт содержимое по пути, создавая недостающие каталоги. */
  write(filePath: string, content: string): void;
  /** Есть ли что-то по пути — файл или каталог. */
  exists(filePath: string): boolean;
  /** Файл ли по пути (каталог — нет). */
  isFile(filePath: string): boolean;
  /** Имена детей каталога; путь `''` — корень дерева. */
  children(dirPath: string): string[];
  /** Снимает файл по пути. */
  delete(filePath: string): void;
  /**
   * ОБЪЯВЛЯЕТ РЕЖИМ УЛОЖЕННОГО АРТЕФАКТА: программа (`true`) или данные
   * (`false`). Зовётся сразу после `write` того же пути и только тогда, когда
   * раскладка режим НАЗВАЛА.
   *
   * **Три состояния, а не два.** Не названный режим сюда не доезжает вовсе —
   * метод не зовётся, и раннер оставляет файлу тот режим, который у него и был.
   * Это не то же самое, что `executable: false`: там обвес СКАЗАЛ «не
   * программа», и раннер вправе это утвердить. Умолчания движок не
   * подставляет — подставленное умолчание превратило бы молчание обвеса в
   * утверждение, которого он не делал.
   *
   * **Булево, а не режим числом** — то же решение, что и у формы объявления
   * (`tasker:BASER2-212`): различение, которое нужно, ровно одно. Восьмеричный
   * режим обещал бы то, что не держится на всех системах; КАК исполняемость
   * ложится на диск (или не ложится — Windows), решает раннер, и это его
   * обязательство, а не движка.
   *
   * **Необязателен, и это требование приёмки, а не послабление**
   * (`tasker:BASER2-214`): раннер, написанный до режима, порту подходит как
   * подходил и работает как работал. Движок отсутствие ВИДИТ и называет его в
   * трейсе (`apply.executable`), а не делает вид, что объявленное доехало.
   *
   * Откат применения режим не переигрывает: журнал отката возвращает содержимое,
   * а прочитать нынешний режим порт не умеет — и не будет, движку это знание
   * незачем. Дерево, пережившее откат, на диск не сбрасывается вовсе
   * («полуобновлённого дерева не бывает», `apply.ts`).
   */
  setExecutable?(filePath: string, executable: boolean): void;
}
