/**
 * ФОРМА СПОСОБНОСТИ — что запустить · описание · именованные параметры.
 *
 * Правило целиком — `kb:BASER3-33`. Коротко: способность, у которой есть все три
 * части, одинаково доступна человеку, агенту и пульту, и **их не надо
 * программировать под каждую способность отдельно**. Пульт покажет то, чего в
 * него не зашивали; агент позовёт то, чего не знал.
 *
 * Отсюда же следует, почему форма живёт ЗДЕСЬ, а не в консоли: консоль — один из
 * фронтов. Способность, написанная в ней, пульту не достанется — её придётся
 * писать второй раз, и две реализации разъедутся на первой правке.
 *
 * ## Описание рядом с вызовом, а не в справке
 *
 * `title` и `description` — поля, а не строки справки консоли: справку читает
 * только человек в терминале, а описание нужно ровно тем троим, что перечислены
 * выше. Ровно та же механика с другой стороны уже работает у настроек обвеса —
 * обвес привозит `title`/`description`/`type`/`default` и этим сам рисует свою
 * форму настройки (`kb:BASER3-34`). Здесь себя описывает действие, там —
 * настройка.
 *
 * ## Дверь оставлена открытой, но в неё не идём
 *
 * Сегодня способности принадлежат сборщику: обвес привозит только то, что у него
 * можно НАСТРОИТЬ. Понадобится, чтобы обвес привозил и свои действия, — это
 * делается ЭТОЙ ЖЕ формой, отдельного механизма не потребуется (`kb:BASER3-34`,
 * решение 2026-08-06 — сейчас не строим).
 *
 * ## Каталога здесь нет
 *
 * Перечень способностей собирается отдельным этапом (`Э3`), и заготовки под него
 * тут не лежит: реестр из одного элемента ничего не доказывает, а форму
 * перечисления назовёт тот, кто будет каталог строить. Машинночитаемость,
 * которой требует приёмка, даёт сама способность — она несёт свой `spec`.
 */

import type { FormProblemCode } from '@omnifield/baser-contracts';
import type { Tree } from './tree.js';
import type { TraceRecorder } from './trace.js';

/**
 * Тип значения параметра.
 *
 * Перечень — РОВНО ТО, ЧТО СЕГОДНЯ ЗОВУТ, а не «словарь на вырост»: у
 * единственной способности все параметры строковые. Тот же принцип, что у порта
 * дерева (`tree.ts`): объявленный и никем не используемый тип стал бы
 * требованием к каждому фронту и не был бы проверен ни одной пробой. Приедет
 * способность с числом или флагом — слово добавится вместе с ней.
 */
export type CapabilityParameterType = 'string';

/**
 * Один именованный параметр.
 *
 * Именованный, а не позиционный: порядок аргументов живёт в голове того, кто
 * писал вызов, и пульту с агентом не достаётся вовсе.
 */
export interface CapabilityParameter {
  /** Имя, которым параметр подаётся. */
  readonly name: string;
  /** Короткое человеческое имя — подпись поля на пульте. */
  readonly title: string;
  /** Что этот параметр значит и что будет, если его не подать. */
  readonly description: string;
  readonly type: CapabilityParameterType;
  /** Обязателен ли. Необязательный обязан объяснять в `description`, что значит его отсутствие. */
  readonly required: boolean;
}

/** Способность, как её видит тот, кто её ещё не звал: имя, описание, параметры. */
export interface CapabilitySpec {
  /** Чем позвать — стабильное машинное имя. */
  readonly name: string;
  /** Короткое человеческое имя. */
  readonly title: string;
  /** Что способность делает — рядом с вызовом, а не в отдельной доке. */
  readonly description: string;
  readonly parameters: readonly CapabilityParameter[];
}

/**
 * Код отказа способности.
 *
 * Словарь формы взят ЦЕЛИКОМ (`FormProblemCode` из контрактов) и дополнен тем,
 * чего в нём нет по построению. Причина — не экономия: отказы формы способность
 * не пересказывает, а пропускает наружу как есть, вместе с адресом и текстом.
 * Завести им свои синонимы значило бы держать вторую правду об одном событии, и
 * потребителю пришлось бы знать оба словаря.
 */
export type CapabilityProblemCode = FormProblemCode | 'pin-ambiguous';

/**
 * Отказ способности — ДАННЫЕ, а не исключение (`kb:BASER3-10`).
 *
 * Форма совпадает с отказом контрактов (`FormProblem`) поле в поле, и это
 * намеренно: дверь склеивает отказы формы, движка и свои в один список, и список
 * не имеет права состоять из записей разной формы.
 */
export interface CapabilityProblem {
  /** Ветвиться потребителю — по нему, не по тексту. */
  readonly code: CapabilityProblemCode;
  /** Адрес: поле разбираемого файла либо параметр вызова. */
  readonly at: string;
  /** Человеческим текстом и самодостаточно — без «см. выше». */
  readonly message: string;
}

/** Способность отработала либо назвала, почему не взялась. Броска нет ни в одном случае. */
export type CapabilityResult<Outcome> =
  | { readonly ok: true; readonly value: Outcome }
  | { readonly ok: false; readonly problems: readonly CapabilityProblem[] };

export interface CapabilityRunOptions {
  /** Приёмник замеров; не подан — способность заводит свой (`trace.ts`). */
  readonly trace?: TraceRecorder;
}

/**
 * Способность целиком: описание плюс то, чем её запускают.
 *
 * Дерево первым аргументом — по той же причине, что у плана и применения: движок
 * файловой системы не касается вовсе, а локация это и есть дерево, которое ему
 * подали (`tree.ts`).
 */
export interface Capability<Input, Outcome> extends CapabilitySpec {
  run(
    tree: Tree,
    input: Input,
    options?: CapabilityRunOptions,
  ): CapabilityResult<Outcome>;
}
