/**
 * ВЕРСИЯ СХЕМЫ МАШИННОЧИТАЕМОГО ВЫВОДА.
 *
 * Потребитель материализации — не человек в терминале, а скрипт, CI и панель
 * управления, поэтому вывод машинночитаем в первую очередь, человекочитаем — во
 * вторую (`README.md` § «Вывод — данные, текст — рендер поверх»). План,
 * конфликты, извещения, отчёт и трейсы — структурированные данные со стабильной
 * схемой; текст (`describePlan`) — рендер поверх них.
 *
 * Схема версионируется, чтобы панель и скрипты переживали эволюцию движка:
 * потребитель читает `schemaVersion` и знает, с какой формой ответа имеет дело.
 * Версия поднимается при НЕСОВМЕСТИМОМ изменении формы (удалено/переименовано
 * поле, изменился смысл кода); добавление нового кода или необязательного поля
 * версию не поднимает.
 *
 * **2** — снят трёхсторонний мердж (`tasker:BASER2-3`): из вывода ушли шаг
 * `release`, конфликты `ownership-narrowing` · `unknown-mode` · `strategy`,
 * извещения `product-owned` · `baseline-missing` и поля `mode` · `ownership`
 * шагов, конфликтов и извещений. Форма несовместима с 1 — потребитель,
 * ветвившийся по снятым кодам, обязан это увидеть, а не молча промахнуться.
 *
 * **3** — движок принимает готовый вход и говорит словарём контракта
 * (`tasker:BASER2-23`). Несовместимо: `frame` → `layout` и `contentRoot` →
 * `source.contentRoot` во входной структуре, снято чтение декларации
 * (`readDeclaration` · `parseDeclaration` · `DECLARATION_BLOCK` ·
 * `DEFAULT_DECLARATION_PATH`), `detail.resolution` переименован
 * `drop-frame-entry` → `drop-layout-entry`, спан трейса `plan.frame` →
 * `plan.layout`. Добавлен конфликт `invalid-path` — добавление кода само по
 * себе версию не поднимает, но здесь она поднята за переименования.
 *
 * **4** — служебная запись уехала из артефактов в манифест сбоку
 * (`tasker:BASER2-4`). Несовместимо: план и отчёт несут `manifestPath` и
 * `manifest`, у шага появилось поле `record` и вид `record`, снят конфликт
 * `unmarkable-dest` (класс файла больше не условие владения) и извещение
 * `scan-scope-narrowed` вместе со сканом дерева, из `PlanOptions` ушёл `scan`.
 * Потребитель, ветвившийся по снятым кодам или читавший владение из содержимого
 * артефакта, обязан это увидеть, а не молча промахнуться.
 *
 * **4, без подъёма** — владение по каждому обвесу отдельно
 * (`tasker:BASER2-7`). Добавлены конфликт `cross-source-dest`, поле
 * `detail.ownedBy` и значение извещения `not-applicable`; ни один код не снят и
 * не переименован, форма ответа прежняя. Сузилась ОБЛАСТЬ, а не схема: сиротой
 * считается запись своего обвеса, а не всякая запись без объявления. Потребитель
 * на снятые коды не ветвился и промахнуться не может — промахивался движок.
 *
 * **5** — класс артефакта и версия обвеса в паспорте укладки
 * (`tasker:BASER2-51`, `tasker:BASER2-52`). Несовместимо ровно в одном месте, и
 * его достаточно: у `ManifestRecord` поле `hash` стало НЕОБЯЗАТЕЛЬНЫМ — у
 * `placed-once` его нет вовсе. Потребитель, читавший `record.hash` как строку,
 * обязан это увидеть, а не получить `undefined` в рантайме. Заодно у записи
 * появились `class` и `version`, у шага — `restated`, добавлены конфликт
 * `unknown-artifact-class` и извещение `placed-once-retained`; сами по себе
 * добавления версию не поднимают.
 *
 * **5, без подъёма** — отказ `foreign-dest` называет класс спорного артефакта
 * (`tasker:BASER2-141`). Добавлено НЕОБЯЗАТЕЛЬНОЕ поле `class` у `PlanConflict`;
 * ни один код не снят, не переименован и смысла не сменил, форма ответа прежняя.
 * Потребитель, не знающий про поле, читает план ровно как читал: прибавление
 * ответа на вопрос «что сделает подтверждение» ничего у него не ломает. Заодно
 * сменился текст `message` у `foreign-dest` и строка шага `record` в
 * `describePlan` — `message` и рендер версией не покрыты вовсе: ветвиться по ним
 * нельзя ни гейту, ни панели, и это сказано в контракте, а не подразумевается.
 *
 * **5, без подъёма** — источник вне дерева принимается по построению
 * (`tasker:BASER2-150`). Изменился ВХОД, а не форма ответа: `source.contentRoot`
 * принимает третье значение — `{ outside: "<адрес>" }`, — и это добавление, а не
 * замена: строка и `null` означают ровно то, что означали. В выводе не появилось
 * и не исчезло ни одного кода; `dest-in-content-root` продолжает срабатывать
 * ровно там, где источник внутри дерева.
 *
 * Область отказа `source-outside-tree` при этом СУЗИЛАСЬ: до него доходит только
 * неназванное положение источника (`contentRoot: null`), а лежащий заведомо
 * снаружи принимается. Смысл кода от этого не перевернулся — «движок не берётся
 * работать с этим источником» осталось им же, — и потребитель, ветвившийся по
 * коду, ветвится так же; сузилось то, что до отказа доходит. Тот же случай, что
 * у «4, без подъёма»: сузилась ОБЛАСТЬ, а не схема. Текст отказа сменился, а
 * `message` версией не покрыт вовсе — ветвиться по нему нельзя ни гейту, ни
 * панели.
 *
 * Добавлено событие трейса `plan.source` — положение источника и то, чем держится
 * защита от записи в него. Трейс — данные о прогоне, а не форма ответа: события
 * в нём прибавляются, и потребитель, читающий свои спаны по имени, не промахнётся.
 *
 * **5, без подъёма** — у движка появились способности (`tasker:BASER2-200`).
 * `DeclareSupplyOutcome` несёт ту же `schemaVersion`, потому что это тот же
 * контракт с пультом: одна форма ответа движка, а не вторая рядом. Ни один код
 * плана, конфликта или извещения при этом не снят, не переименован и смысла не
 * сменил — ПРИБАВИЛСЯ новый вид ответа, и потребитель, про способности не
 * знающий, читает план ровно как читал.
 *
 * Отказы способностей версией НЕ покрыты и покрыты быть не могут: они говорят
 * словарём формы (`FormProblemCode` из контрактов), а он версионируется своим
 * номером формы объявления. Держать здесь второй номер на тот же словарь значило
 * бы обещать совместимость, которой мы не распоряжаемся.
 *
 * **5, без подъёма** — объявленный режим артефакта доезжает до порта
 * (`tasker:BASER2-214`). У `PlanStep` появилось НЕОБЯЗАТЕЛЬНОЕ поле `executable`,
 * у `plan.layout` — счётчик `executable`, у применения — событие
 * `apply.executable`. Ни один код не снят, не переименован и смысла не сменил;
 * потребитель, про режим не знающий, читает план ровно как читал.
 *
 * Отсутствие поля у шага значимо и версией НЕ покрывается формально, а держится
 * пробой: `executable` нет вовсе, когда обвес режим не назвал, — и это не то же
 * самое, что `false`. Потребитель, читающий поле как булево с умолчанием,
 * получит `undefined` и обязан это увидеть; поле новое, и читать его так с
 * прошлой версии никто не мог.
 *
 * **5, без подъёма** — паспорт укладки помнит режим (`kb:BASER3-36`,
 * `tasker:BASER2-222`). Прибавились вид шага `chmod` (режим приводится, а
 * содержимое не трогается) и поле записи `executable` в перечне `restated`; ни
 * один код не снят, не переименован и смысла не сменил. Потребитель, про режим
 * не знающий, читает план как читал, — но ветвление `switch` по видам шага у
 * него станет неполным, и это ровно то, что должно быть видно: `chmod` меняет
 * файл, и молча считать его `record`'ом нельзя.
 *
 * Граница шва, названная прошлым заходом, ЗАКРЫТА: смена объявленного режима на
 * сошедшемся содержимом теперь расхождение, шаг и работа.
 *
 * **5, без подъёма** — движок читает РЕЖИМ ЛЕЖАЩЕГО ФАЙЛА (`tasker:BASER2-224`).
 * Прибавились причина шага `executable-drifted` (бит на диске разошёлся с
 * объявленным — содержимое и запись при этом могут быть в порядке) и событие
 * трейса `plan.executable`. Ни один код не снят, не переименован и смысла не
 * сменил; форма ответа прежняя.
 *
 * Изменилось при этом ПОВЕДЕНИЕ, и это не покрывается схемой вовсе: артефакт,
 * у которого бит сбит на диске, раньше давал `converged`, а теперь даёт шаг.
 * Схема версионирует форму ответа, а не то, что движок в этой форме говорит, —
 * потребитель, читавший «сошлось» как «работы нет», получает правду, а не другую
 * форму.
 *
 * Форма манифеста версионируется ОТДЕЛЬНО (`MANIFEST_VERSION`): это файл на
 * диске у потребителя, а не форма ответа панели, и переживают они разное. С
 * формой 3 движок читает ДВЕ формы (`MIN_READABLE_MANIFEST_VERSION`), а пишет
 * одну — старый паспорт правки на диске не требует.
 */
export const OUTPUT_SCHEMA_VERSION = 5;

export type OutputSchemaVersion = typeof OUTPUT_SCHEMA_VERSION;
