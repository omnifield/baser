/**
 * Источник канона — откуда движок берёт содержимое `layout[].src`.
 *
 * Носитель канона — опубликованный версионированный пакет, который потребитель
 * ставит себе (`kb:BASER2-2`, «Кор — в пакете, внешнее — в репозитории»), поэтому
 * по умолчанию источник читается из того же виртуального дерева (в реальном
 * прогоне это установленный пакет внутри рабочего дерева). Порт оставлен
 * открытым: подмена источника — дело раннера, а не движка.
 *
 * УМОЛЧАНИЕ ЕСТЬ ТОЛЬКО У ИСТОЧНИКА ВНУТРИ ДЕРЕВА. Поставка, забранная в кэш
 * снаружи локации (`tasker:BASER2-146`), лежит вне дерева, а файловой системы
 * движок не касается вовсе — читать ему нечем. Такой источник обязан приехать
 * портом, и отсутствие порта движок называет отказом, а не изображает
 * ненайденными шаблонами на каждой записи (`plan.ts`, `defaultSource`).
 */

import type { Tree } from '@nx/devkit';
import { joinRepoPath } from './paths.js';

export interface CanonSource {
  /** Содержимое `src` относительно `contentRoot`; `null` — источника нет. */
  read(src: string): string | null;
  /** Адрес источника для сообщений (план обязан быть читаемым). */
  describe(src: string): string;
}

/** Источник поверх виртуального дерева — дефолт движка. */
export function createTreeSource(
  tree: Tree,
  contentRoot: string,
): CanonSource {
  return {
    read(src) {
      return tree.read(joinRepoPath(contentRoot, src), 'utf-8');
    },
    describe(src) {
      return joinRepoPath(contentRoot, src);
    },
  };
}

