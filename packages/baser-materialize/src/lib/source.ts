/**
 * Источник канона — откуда движок берёт содержимое `frame[].src`.
 *
 * Носитель канона — опубликованный версионированный пакет, который продукт
 * опт-инит (`kb:BASER-3`), поэтому по умолчанию источник читается из того же
 * виртуального дерева (в реальном прогоне это распакованный пакет внутри
 * рабочего дерева). Порт оставлен открытым: подмена источника — дело раннера,
 * а не движка.
 */

import type { Tree } from '@nx/devkit';
import { joinRepoPath } from './paths.js';

export interface CanonSource {
  /** Содержимое `src` относительно `contentRoot`; `null` — источника нет. */
  read(src: string): string | null;
  /** Адрес источника для сообщений (план обязан быть читаемым). */
  describe(src: string): string;
  /**
   * Версия канона, из которой материализуем; `null` — источник версию не назвал.
   *
   * Движок её не выводит и не хранит: он лишь ЗАПИСЫВАЕТ её в маркер артефакта,
   * чтобы по ней потом восстанавливалась база мерджа (`kb:BASER-5`, «база
   * трёхстороннего мерджа»). Версии пакетов знает раннер, а не движок.
   */
  readonly version: string | null;
}

/** Источник поверх виртуального дерева — дефолт движка. */
export function createTreeSource(
  tree: Tree,
  contentRoot: string,
  version: string | null = null,
): CanonSource {
  return {
    read(src) {
      return tree.read(joinRepoPath(contentRoot, src), 'utf-8');
    },
    describe(src) {
      return joinRepoPath(contentRoot, src);
    },
    version,
  };
}

/**
 * База трёхстороннего мерджа — «прошлая версия канона» из контракта
 * (`kb:BASER-5`, раздел «База трёхстороннего мерджа: где она живёт»).
 *
 * Решение контракта: база НЕ хранится копией. Артефакт несёт в маркере версию
 * канона, из которой материализован, а база = содержимое `src` В ТОЙ ВЕРСИИ
 * источника. Восстанавливает её сторона, у которой есть доступ к версиям пакета
 * (раннер/гейт), и подаёт движку через этот порт — движок версиями не владеет.
 *
 * Дефолт — «базы нет»: тогда мердж НЕ трёхсторонний, и план обязан НАЗВАТЬ это
 * извещением `baseline-missing`, а не молча выродиться в двухсторонний.
 */
export interface CanonBaseline {
  /**
   * Содержимое `src` в версии `version` канона; `null` — база недоступна
   * (версия не публикуется, пакет не скачан, источник не хранит историю).
   */
  read(src: string, version: string): string | null;
}

/** Базы нет — дефолт движка. */
export const EMPTY_BASELINE: CanonBaseline = {
  read: () => null,
};
