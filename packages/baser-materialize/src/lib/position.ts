/**
 * ПОЛОЖЕНИЕ ИСТОЧНИКА относительно дерева потребителя.
 *
 * Движок пишет ТОЛЬКО внутрь дерева и адресует всё репо-относительным путём.
 * Источник же лежит там, куда его положила доставка: внутри дерева (обвес
 * поставлен в `node_modules`, каталог обвеса в той же монорепе) либо ЗАВЕДОМО
 * СНАРУЖИ — в кэше, который дверь держит вне локации (`tasker:BASER2-146`).
 * Одним репо-относительным путём эти два положения не выражаются.
 *
 * Раньше второе называлось отказом целиком (`tasker:BASER2-24`): защита «не пишу
 * в собственный источник» цеплялась за репо-относительный путь, а его нет — и
 * движок отказывался, вместо того чтобы выродиться в молчаливое «проверка ничего
 * не нашла». Решение было верным, а случай изменился: с тех пор как поставка
 * забирается в кэш снаружи локации, источник вне дерева стал НОРМОЙ ПО
 * ПОСТРОЕНИЮ.
 *
 * ЗАЩИТУ НЕ СНИМАЮТ — ЕЁ УТВЕРЖДАЮТ (`tasker:BASER2-150`). Внутри дерева
 * пересечение считается по путям, как считалось. Снаружи оно ПУСТО ПО
 * ПОСТРОЕНИЮ: движок пишет только внутрь дерева, источник лежит снаружи, общих
 * точек нет.
 *
 * Утверждение это ПРОВЕРЯЕМОЕ, и проверяется оно здесь: адрес, объявленный
 * внешним, обязан быть невыразим репо-относительным путём. Иначе «снаружи» было
 * бы словом, которым защиту выключают изнутри дерева, — объявил `template`
 * внешним, и движок кладёт артефакты поверх собственных шаблонов, ничего при
 * этом не заметив. Разница между «проверка пропущена» и «пересечение пусто»
 * держится этой проверкой, а не обещанием в комментарии.
 *
 * Рынок делит те же две области так же (сверено 2026-08-03): Nx читает шаблоны
 * генератора с диска по абсолютному пути, а пишет в виртуальное дерево — области
 * чтения и записи разные, и пересечение пусто по построению; cookiecutter держит
 * шаблоны в кэше домашнего каталога и отдельно ТРЕБУЕТ `input_dir != output_dir`,
 * то есть непересечение утверждает, а не подразумевает.
 */

import type { MaterializationSource } from './declaration.js';
import { DeclarationError, SourceOutsideTreeError } from './errors.js';
import { toRepoPath } from './paths.js';

/**
 * Где лежит содержимое источника — разобранное положение, а не строка.
 *
 * Перечислением, а не парой необязательных полей: положений ровно два, и оба
 * влияют на то, ЧЕМ движок держит защиту от записи в собственный источник.
 * Необязательные поля позволили бы состояние «ни то, ни другое», которого не
 * бывает, — а компилятор перестал бы требовать ответа на второй случай.
 */
export type SourcePosition =
  /** Источник внутри дерева: пересечение считается по путям. */
  | { readonly kind: 'in-tree'; readonly contentRoot: string }
  /** Источник заведомо снаружи: пересечение с деревом пусто по построению. */
  | { readonly kind: 'outside-tree'; readonly at: string };

/**
 * Разбирает `source.contentRoot` в положение источника.
 *
 * Три ответа на три состояния, и они не сводятся к двум:
 *   — строка → источник внутри дерева, защита работает по пути;
 *   — `{ outside }` → источник заведомо снаружи, пересечение пусто и УТВЕРЖДЕНО;
 *   — `null` → положение НЕ НАЗВАНО, и вот тут отказ остаётся живым: утверждать
 *     нечего — ни пути внутри дерева, ни адреса снаружи, — а молча ослабить
 *     проверку значит потерять её ровно там, где она написана.
 */
export function resolveSourcePosition(
  source: MaterializationSource,
): SourcePosition {
  const { contentRoot } = source;

  // Положение не названо. Отличается от отсутствия поля намеренно: пропущенное
  // поле — структура не той формы (её собирает дверь), а `null` — названное
  // состояние входа, и отвечает движок на него своим отказом.
  if (contentRoot === null) {
    throw new SourceOutsideTreeError(
      `положение источника обвеса "${source.id}" не названо: contentRoot подан ` +
        'как null. Движок пишет только внутрь дерева и обязан утверждать, что ' +
        'не пишет в собственный источник, — а утверждать не из чего: ни ' +
        'репо-относительного пути внутри дерева, ни адреса снаружи. Назови ' +
        'положение: строкой — корень содержимого внутри дерева; ' +
        '{ outside: "<адрес>" } — источник заведомо снаружи',
    );
  }

  if (typeof contentRoot === 'string') {
    // Вырожденный корень («.», «/», пустая строка) означает, что источником
    // объявлено ВСЁ дерево. Тогда защита отваливается — пересечение становится
    // всем деревом, а `isInside` от такого корня ложна, — и прогон затирает
    // шаблон, из которого сам же читает. Отказ вместо тихой порчи источника.
    if (!toRepoPath(contentRoot).ok) {
      throw new DeclarationError(
        `корень содержимого "${contentRoot}" непригоден: ` +
          'источником объявлено бы всё дерево, и движок писал бы поверх ' +
          'собственных шаблонов. Нужен путь к каталогу шаблонов внутри пакета',
      );
    }
    return { kind: 'in-tree', contentRoot };
  }

  if (
    typeof contentRoot !== 'object' ||
    typeof (contentRoot as { outside?: unknown }).outside !== 'string'
  ) {
    throw new DeclarationError(
      'движку подана структура не той формы: source.contentRoot — ожидалась ' +
        'строка с корнем содержимого внутри дерева, { outside: "<адрес>" } для ' +
        'источника заведомо снаружи либо null, если положение не названо. ' +
        'Собрать вход из объявления обвеса и конфига потребителя — забота двери',
    );
  }

  const at = contentRoot.outside.trim();
  if (at === '') {
    throw new DeclarationError(
      `источник обвеса "${source.id}" объявлен лежащим вне дерева, а адрес ` +
        'подан пустой строкой: пустота утверждает не «снаружи», а «неизвестно». ' +
        'Неизвестное положение подаётся null — это состояние движок называет вслух',
    );
  }

  // ВОТ ГДЕ УТВЕРЖДЕНИЕ СТАНОВИТСЯ ПРОВЕРКОЙ. Адрес, выразимый репо-относительным
  // путём, описывает место ВНУТРИ дерева: пересечение с деревом там не пусто, и
  // слово «снаружи» выключило бы защиту по ложному признаку — молча и ровно один
  // раз, потому что второй раз шаблоны читать будет уже неоткуда.
  if (toRepoPath(at).ok) {
    throw new DeclarationError(
      `источник обвеса "${source.id}" объявлен лежащим вне дерева, но адрес ` +
        `"${at}" — репо-относительный путь, то есть место ВНУТРИ дерева. ` +
        'Пересечение с деревом там не пусто, и защита «не пишу в собственный ' +
        'источник» выключилась бы по ложному признаку. Источник внутри дерева ' +
        'называется строкой — тогда защита работает по пути',
    );
  }

  return { kind: 'outside-tree', at };
}

/**
 * Пишет ли этот `dest` в собственный источник — и КУДА ИМЕННО.
 *
 * Возвращает корень содержимого, в который попал бы `dest`, либо `null`. Строкой,
 * а не флагом: отказ обязан назвать корень, а собрать его повторно на стороне
 * вызывающего значило бы завести второе место, знающее про положение источника.
 *
 * Снаружи ответ `null` — это НЕ «проверка пропущена». Каждый `dest` приведён к
 * репо-относительному пути раньше (`toRepoPath` в фазе плана), а адрес внешнего
 * источника таким путём невыразим по проверке в `resolveSourcePosition`. Двух
 * непересекающихся множеств хватает, чтобы пересечение было пустым, — и
 * утверждение это держится двумя проверками, а не умолчанием.
 */
export function writesIntoSource(
  position: SourcePosition,
  dest: string,
): string | null {
  if (position.kind === 'outside-tree') {
    return null;
  }
  const root = position.contentRoot.replace(/\/+$/, '');
  return root !== '' && (dest === root || dest.startsWith(`${root}/`))
    ? position.contentRoot
    : null;
}

/** Адрес источника для телеметрии и сообщений — одно написание на оба положения. */
export function describePosition(position: SourcePosition): string {
  return position.kind === 'in-tree' ? position.contentRoot : position.at;
}
