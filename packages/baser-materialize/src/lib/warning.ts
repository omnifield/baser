/**
 * ПРЕДУПРЕЖДЕНИЕ ОБВЕСА ЕДЕТ ЧЕРЕЗ ДВИЖОК — второе звено шва `tasker:BASER2-226`.
 *
 * У обвеса до формы 7 была одна громкость: бросок резолвера, валивший весь
 * прогон локации у всех обвесов сразу. Форма завела вторую — текст, который
 * обвес говорит человеку про СВОЁ ПРИМЕНЕНИЕ ЗДЕСЬ, не отказывая
 * (`packages/baser-contracts`, `warning.ts`). Живой случай: хук, который ляжет
 * верно и не сработает, потому что локация смотрит в другой каталог. Прогон
 * при этом верный, отказывать не за что, но человек обязан услышать.
 *
 * ## Что делает движок и чего он НЕ делает
 *
 * Он НЕСЁТ уже посчитанное. Резолвер зовёт дверь: у неё файловая система и
 * распакованный пакет обвеса, у движка нет ни того, ни другого — он не читает
 * файлов и не грузит чужих модулей вовсе (`index.ts`). Тот же порядок, что у
 * значений настроек: разрешает их дверь (`resolveSettings`), движку приезжает
 * готовое.
 *
 * Тогда зачем движок в этой цепи? Затем, что **машинный ответ прогона — это
 * план**: у него `schemaVersion`, его читают пульт и гейт, и он же уезжает в
 * `--json` целиком. Предупреждение обязано быть видимо обоим читателям, человеку
 * и агенту (`kb:BASER3-33`), — значит оно обязано лежать в ответе, а не только
 * в тексте, который дверь напечатает.
 *
 * ## Почему у ИСТОЧНИКА, а не у записи раскладки
 *
 * Решение владельца формы (`tasker:BASER2-232`), и оно про носителя тоже:
 * `executable` описывает САМ артефакт — он программа, куда его ни положи;
 * предупреждение артефакт не описывает — файл побайтно тот же, меняется лишь
 * то, сработает ли он здесь. Это свойство ИСТОЧНИКА В ЭТОЙ ОБСТАНОВКЕ, и носим
 * мы его так же: поле у `source` на входе, поле у плана на выходе.
 *
 * Отсюда же ответ про несколько обвесов: прогон движка идёт по ОДНОЙ декларации
 * (`plan.ts`), обвесов в репозитории сколько угодно (`kb:BASER2-4`), и планов
 * ровно столько же. Каждый несёт своё предупреждение и знает своего обвеса —
 * складывать их в общий перечень было бы вторым местом, где живёт то же знание.
 *
 * ## Здесь НЕ отказывают. Ни при какой беде
 *
 * Форма уже сказала это про себя, и на носителе правило то же: `ok: false`
 * читается всеми зонами как «прогон не поедет», а предупреждение такого права
 * не имеет. Упавший резолвер приезжает сюда состоянием `failed` — с кодом и
 * адресом, — и план от него не блокируется, не теряет шагов и не меняет
 * `status`. Виновата обстановка, а не локация; локацию за это не наказывают.
 *
 * **Поэтому непригодное значение здесь НАЗЫВАЕТСЯ, а не отвергается** — в
 * отличие от `source.version` и `layout[].executable`, где движок бросает
 * `DeclarationError`. Разница не в строгости, а в том, чем кончается ошибка:
 * бросок на негодной версии оставляет прогон без паспорта укладки, а бросок на
 * негодном предупреждении уронил бы прогон РАДИ ФРАЗЫ — то есть завёл бы вторую
 * громкость, ведущую себя как первая. Молчать при этом нельзя тем более: дверь
 * считала бы, что её предупреждение работает, а оно бы исчезало.
 */

import type { FormProblem, SourceWarning } from '@omnifield/baser-contracts';
import { describeValue } from '@omnifield/baser-contracts';
import type { MaterializationSource } from './declaration.js';

/**
 * Названное отсутствие — одно на весь движок.
 *
 * «Предупреждения нет» имеет ровно одно написание и всегда приезжает объектом:
 * потребитель ответа не обязан отличать `undefined` от `{ kind: 'none' }`, а
 * ветка на пропущенное поле у него разошлась бы с нашей молча.
 */
const NOTHING: SourceWarning = { kind: 'none' };

/**
 * Что обвес сказал про своё применение здесь — в том виде, в каком это уедет в
 * план и в машинный ответ.
 *
 * Значение приходит от двери уже посчитанным (`resolveWarning` из контрактов);
 * движок сверяет форму и несёт дальше. Сверка нужна потому, что вход подаёт не
 * только наша дверь: структура плана — открытый контракт, и подать её вправе
 * чужой вызывающий (`README.md`, «Вход: готовая структура»).
 */
export function carriedWarning(source: MaterializationSource): SourceWarning {
  const carried: unknown = source.warning;
  if (carried === undefined || carried === null) {
    return NOTHING;
  }

  if (typeof carried === 'object') {
    const { kind } = carried as { kind?: unknown };

    if (kind === 'none') {
      return NOTHING;
    }

    if (kind === 'said') {
      const { text } = carried as { text?: unknown };
      // Пустая строка не проезжает и здесь, и по той же причине, по которой её
      // не пропустила форма: печатать её некуда, а от исправной работы она
      // неотличима.
      if (typeof text === 'string' && text.trim() !== '') {
        // Текст переносится ДОСЛОВНО: движок не редактирует того, что обвес
        // сказал человеку, и не обрезает чужую фразу под свою строку отчёта.
        return { kind: 'said', text };
      }
      return malformed(
        source,
        `состояние "said" без текста (${describeValue(text)})`,
      );
    }

    if (kind === 'failed') {
      const { problem } = carried as { problem?: unknown };
      if (isProblem(problem)) {
        return { kind: 'failed', problem };
      }
      return malformed(
        source,
        `состояние "failed" без названного отказа (${describeValue(problem)})`,
      );
    }
  }

  return malformed(source, `${describeValue(carried)} на месте состояния`);
}

/** Отказ формы, пригодный для печати: код, адрес и текст — все три на месте. */
function isProblem(value: unknown): value is FormProblem {
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  const { code, at, message } = value as Record<string, unknown>;
  return (
    typeof code === 'string' &&
    typeof at === 'string' &&
    typeof message === 'string'
  );
}

/**
 * Предупреждение подано не в той форме — и это НАЗВАНО тем же состоянием, каким
 * форма называет упавший резолвер.
 *
 * Адрес свой (`<обвес>.warning`, а не `.warningFrom`): у формы отказывает
 * резолвер обвеса, здесь — то, что подал вызывающий. Один адрес на два разных
 * места отправил бы чинить объявление обвеса туда, где объявление ни при чём.
 */
function malformed(
  source: MaterializationSource,
  problem: string,
): SourceWarning {
  return {
    kind: 'failed',
    problem: {
      code: 'wrong-type',
      at: `${source.id}.warning`,
      message:
        `движку подано предупреждение не той формы: ${problem}. ` +
        'Считать его обязана дверь — resolveWarning из контрактов, — и она ' +
        'отдаёт состояние { kind }. Прогон это не остановило: предупреждение ' +
        'не отказ',
    },
  };
}
