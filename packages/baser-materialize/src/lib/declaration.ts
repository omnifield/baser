/**
 * ВХОД ДВИЖКА — готовая структура, а не файл.
 *
 * Движок ничего не читает сам. Настоящая декларация размазана по ТРЁМ файлам, и
 * каждый отвечает на свой вопрос (`tasker:BASER2-10` §3, `kb:BASER2-5`):
 *   - `package.json` → блок `baser` пакета-поставщика — что обвес ОБЪЯВЛЯЕТ:
 *     раскладку, настройки, пресеты;
 *   - `baser.json` в репозитории потребителя — ЧТО поставлено, перечень
 *     инструментов и только он: значений и пресетов здесь больше нет;
 *   - `.omnifield/<поставщик>-<обвес>.yaml` — КАК настроено, по файлу на
 *     инструмент, и имя файла считается из личности обвеса.
 *
 * Склеить их может только дверь: у неё есть все три, и у неё же разрешение
 * значений настроек (`packages/baser-contracts/README.md`).
 *
 * Поэтому здесь нет ни чтения манифеста, ни знания про блок в нём, ни разбора
 * формы. Разбор формы — валидаторы объявления, настроек, пресетов, проверка
 * столкновений — зона контрактов; движку подают уже собранное.
 *
 * Словарь — общий с контрактом (`tasker:BASER2-19`): `source` · `layout` ·
 * `src` · `dest` · `class`. Двух языков на один предмет не держим.
 */

import type { ArtifactClass } from './classes.js';

/**
 * Источник, лежащий ЗАВЕДОМО ВНЕ дерева потребителя.
 *
 * Обёрткой, а не голой строкой рядом с репо-относительной: у одного поля два
 * разных смысла — «путь внутри дерева» и «адрес снаружи», — и различить их по
 * виду строки нельзя. Тот, кто знает положение, называет его сам; движок
 * проверяет названное, а не угадывает по написанию.
 *
 * `outside` — адрес источника КАК ЕСТЬ: абсолютный путь кэша, каталог за корнем
 * дерева. Движок его не разбирает и содержимое по нему не читает — читает порт
 * `CanonSource`. Адрес нужен, чтобы положение было названо в трейсе и в отказах:
 * «источник снаружи» без адреса — утверждение, которое нечем проверить.
 */
export interface OutsideTree {
  readonly outside: string;
}

/**
 * Источник артефактов — обвес, который их принёс.
 *
 * `id` — идентичность вида `<поставщик>/<обвес>`, НЕ имя npm-пакета: пакет это
 * доставка, `id` это личность. Движок его не интерпретирует и в артефакты не
 * пишет (запись владения — A2, `tasker:BASER2-4`); он часть общего словаря, на
 * котором говорят все три зоны.
 */
export interface MaterializationSource {
  readonly id: string;
  /**
   * ГДЕ ЛЕЖИТ СОДЕРЖИМОЕ — три состояния, а не два (`tasker:BASER2-150`).
   *
   * Движок пишет только внутрь дерева и обязан утверждать, что не пишет в
   * собственный источник. Утверждение опирается на положение источника, и
   * положений ровно три:
   *
   *   — **строка** — корень содержимого относительно корня дерева: обвес
   *     поставлен в `node_modules`, лежит каталогом в той же монорепе. Защита
   *     работает по пути, как работала (`dest-in-content-root`);
   *   — **`{ outside }`** — источник ЗАВЕДОМО СНАРУЖИ дерева: дверь забрала
   *     поставку в кэш вне локации (`tasker:BASER2-146`). Репо-относительного
   *     пути к нему не существует, и он не нужен: пересечение с деревом пусто по
   *     построению, и движок это утверждает — адрес обязан быть невыразим
   *     репо-относительным путём (`position.ts`). Содержимое подаётся портом
   *     `PlanOptions.source`: за пределы дерева движок не ходит сам;
   *   — **`null`** — положение НЕ НАЗВАНО. Утверждать не из чего, и движок
   *     отвечает названным отказом (`SourceOutsideTreeError`,
   *     `tasker:BASER2-24`), а не тихо ослабленной проверкой.
   *
   * Подделать путь вместо `{ outside }` нельзя: это была бы защита, защищающая
   * пустоту. Назвать `{ outside }` местом внутри дерева — тоже: движок такой
   * адрес отвергает, иначе «снаружи» стало бы словом, выключающим защиту изнутри.
   */
  readonly contentRoot: string | OutsideTree | null;
  /**
   * Версия обвеса, которым кладём, — та, что стоит в манифесте его пакета.
   *
   * **Второго места для версии нет** (`tasker:BASER2-10` §1): в объявлении
   * обвеса поля `version` не существует, версия живёт в `package.json` рядом с
   * `name`, дверь её оттуда читает и подаёт сюда. Движок версию не
   * интерпретирует и не сравнивает по правилам semver — он её ХРАНИТ в паспорте
   * укладки, чтобы потом можно было сказать «между твоей версией и новой было
   * ломающее изменение» (`tasker:BASER2-52`).
   *
   * `null` либо отсутствие — **источник версии не назвал**. Решение овнера
   * зоны, названное вслух: в паспорт укладки ложится именно `null`, и это
   * НАЗВАННОЕ отсутствие — ключ в файле стоит и говорит «неизвестно». Тот же
   * `null` уходит в трейс (`plan.owned`), так что «каким обвесом и какой версии
   * шёл прогон» читается из телеметрии.
   *
   * **Пустая строка сюда не пролезает** — она была бы молчаливой пустотой,
   * выдающей себя за версию: `DeclarationError`, а не тихая запись.
   *
   * Отдельного извещения на прогон здесь НЕТ и не будет — решение architect.
   * Дело не в шуме, а в том, ЧЬЁ это событие: версию знает манифест пакета,
   * читает его дверь, и сказать «обвес версии не объявил» может только она.
   * Движку известно ровно то, что ему подали, — его извещение было бы пересказом
   * чужого знания, то есть второй правдой об одном событии.
   */
  readonly version?: string | null;
}

/** Единица раскладки: один артефакт `dest` из одного шаблона `src`. */
export interface LayoutEntry {
  /** Путь внутри `source.contentRoot`. */
  readonly src: string;
  /** Путь артефакта в репозитории потребителя — он же единица владения. */
  readonly dest: string;
  /**
   * Чем станок держит этот артефакт (`classes.ts`).
   *
   * Отсутствие = `regenerated`: класс проставляет разбор формы у двери, а
   * структура без класса означает ровно то, что означала раскладка формы 1.
   * Незнакомое значение умолчанием НЕ подменяется — это названный отказ
   * `unknown-artifact-class`.
   */
  readonly class?: ArtifactClass;
}

/**
 * Что движку раскладывать и откуда.
 *
 * Настроек и пресетов здесь нет: значения разрешает дверь, а подстановку их в
 * содержимое делает тот, кто отдаёт движку шаблон, — порт `CanonSource`
 * (`source.ts`). Движок получает содержимое уже готовым и кладёт его целиком.
 */
export interface Declaration {
  readonly source: MaterializationSource;
  readonly layout: readonly LayoutEntry[];
}
